#    클로드가 **문서 하나만 grep 하고 "정한 적 없다"** 고 답했다.
#    정답은 `docs/자산현황-자동집계.md` §정원 대조 ＋ `scripts/asset-map.mjs` 의 `QUOTA`
#    (캐릭터 = 계절 12 · 기본 24) 였고 **`npm run assets` 한 번이면 나왔다.**
#
# ⛔⛔ **장치가 세 개나 있었는데 하나도 안 떴다** — 전부 «조건을 좁혀놨기» 때문이다.
#    · evidence-guard  = 저장소 «밖» 주제만        → 이번은 저장소 «안»
#    · latest-guard    = 주제어 목록에 있는 문서만  → 「정원」이 목록에 없었다
#    · submission-guard= 밖으로 나가는 글만        → 글 쓰는 게 아니었다
#    📌 「시끄러운 게이트는 죽은 게이트」라며 계속 좁혔는데,
#       **놓쳐서 치른 값이 시끄러워서 치를 값보다 훨씬 컸다.**
#
# ⭐⭐ 그래서 이건 **조건이 없다. 창업자가 무엇을 쓰든 «언제나» 뜬다.**
#    창업자 2026-08-03: *"**다다다다다 뜨게해 뭐든 내가 묻는건 다 읽고 찾아보고 대답하라고!!!**"*
#    ⛔ 「말에 물음표가 있을 때만」처럼 좁히지 말 것 — 좁히는 순간 또 빠져나간다.
#       (실제로 이번 사고 때 세 장치가 전부 «조건에 안 걸려서» 조용했다)
#    ⚠️ 이건 «검사»가 아니라 «상기»다. 배포를 막지도, 창업자를 귀찮게 하지도 않는다.
#       읽는 건 클로드고, 시끄러워도 되는 쪽이다.

# ⭐⭐ **[2026-09-03] 「무조건 뜬다」는 그대로. «길이»만 세션 첫 판 뒤로 줄인다.**
#    📮 창업자 = *"토큰을 덜 쓰게 할 수 있는 방법이 있어??"*
#    🔢 실측 = 이 훅이 매 메시지 **1,928 B**. 100메시지면 193KB 가 아래 «사고 이야기»의 되풀이다.
#    ⛔ **조건을 좁힌 게 아니다** — 무엇을 쓰든 여전히 매번 뜬다(위 원문 그대로).
#       다만 사고 경위는 세션에 한 번이면 되고, **매번 나가야 하는 건 「무엇을 돌려라」 목록**이다.
HERE="$(cd "$(dirname "$0")" && pwd)"
IN=$(cat)
FIRST=$(printf '%s' "$IN" | "$HERE/_first-time.sh" ask 2>/dev/null || echo 처음)

if [ "$FIRST" != 처음 ]; then
  cat <<'SHORT'
