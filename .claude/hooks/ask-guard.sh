   **파일을 안 열고** 「그렇다」고 답했다. 샘플은 **콩국수**에 붙어 있었고 묵채엔 없었다.
   ⭐ 창업자가 «내가 만든 오해» 위에서 판정을 하게 된다 — 그게 제일 나쁘다.
   👉 `recipe.mjs --sample` 한 줄이면 그날 안 틀렸다. **확인이 기억보다 빠르다.**

