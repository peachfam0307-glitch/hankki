#!/usr/bin/env bash
# 📤📤 **도구가 뱉는 «답»이 대화 창을 한 번에 먹는 것을 막는다.**
#
# 📮 창업자 2026-09-03 = *"하루종일 이거 잡는중이었어. 컨텍스트 오류."*
#
# ⛔⛔ **그날 무슨 일이 났나 (실측 · 창업자 캡처 두 장)**
#      `/clear` 직후      6%  (58.8k / 1M)
#      «한 턴» 뒤        45%  (445.7k / 1M)      ← 한 번에 ≈390k 가 들어왔다
#      그 턴에 실패한 명령 = `measure doc sizes and tool output sizes`
#      **문서·도구 답 크기를 «재려던» 명령이, 재려던 것을 그대로 대화에 쏟았다.**
#      그날 아침 문서를 763KB → 172KB 로 줄여놨는데 명령 한 줄이 그 두 배를 한 번에 넣었다.
#
# ⭐⭐ **왜 기존 게이트가 다 통과시켰나 — 아무도 «답»을 안 봤다**
#      `bigread-guard` = 파일을 «통째로 여는 것»만 본다 (cat · Read). 오늘 범인은 파일을 안 열었다.
#      `docsize-guard` = 문서 «파일 크기»만 본다. 도구 답은 파일이 아니다.
#      PostToolUse 에 걸린 건 `wip-snap.sh` 하나뿐이고 그건 크기를 안 본다.
#      📌 「막는 게이트가 있다」가 아니라 «무엇을 보고 막는가»다.
#
# 🧭 **두 겹이다 — 둘이 하는 일이 다르다**
#    ① tool  (PreToolUse)  = «돌기 전»에 막는다.  ⭐이게 진짜 방패다.
#    ② after (PostToolUse) = 이미 뱉은 답을 «재서» 알린다. 자를 수는 없다 —
#       그때는 이미 대화에 들어간 뒤다. 대신 **그 턴에서 멈추게** 해서 다음 턴이 겹치는 걸 막는다.
#       (2026-09-03 에 손해가 커진 건 터진 뒤에도 계속 돌았기 때문이다)
#
# ⭐ **막다른 길이 아니다** — 상한 한 마디면 언제나 통과한다.
#      | head -40   ·   | head -c 60000   ·   | wc -l   ·   > 파일   ·   --for <주제>
#    ⛔ 상한을 올려서 통과시키지 말 것 — 그건 게이트를 끄는 것이다.
set -u
MODE="${1:-tool}"
INPUT=$(cat)
HERE=$(cd "$(dirname "$0")" && pwd)

# 상한 = 60,000 B. `bigread-guard` 와 «같은 문턱»으로 맞춘다 — 잣대가 둘이면 사람이 헷갈린다.
LIMIT=60000

# ──────────────────────────────────────────────────────────────
# ① 돌기 «전» — 답 길이를 모르는 명령에 상한이 없으면 막는다
# ──────────────────────────────────────────────────────────────
if [ "$MODE" = "tool" ]; then
  # ⛔ 변수 이름은 «반드시 ASCII» — bash 는 한글 변수명을 못 쓴다.
  #    `맞은=$(…)` 로 적었더니 「command not found」로 죽고, 그 뒤 판정이 통째로 무너져
  #    **모든 명령을 막는 막다른 길**이 됐다(2026-09-03 · 재현판이 9개 ❌로 잡았다).
  #    📌 함수 이름엔 한글이 되지만(면제()) 변수엔 안 된다 — 기존 훅이 HIT·PATHS 를 쓰는 이유다.
  HIT=$(printf '%s' "$INPUT" | python3 "$HERE/_bigout-cmd.py" 2>/dev/null)
  [ -n "$HIT" ] || exit 0
  {
    echo "📤📤 **이 명령은 답이 «얼마나 나올지 모른다» — 상한을 붙여라.**"
    echo ""
    echo "   ⛔ 걸린 자리 = \`$HIT\`"
    cat <<'MSG'

   👉 **한 마디만 붙이면 그대로 통과한다** (아무거나 하나)
      … | head -40              ← 줄 수로 자르기
      … | head -c 60000         ← 글자 수로 자르기
      … | wc -l                 ← 숫자만 필요할 때
      … > /tmp/…/결과.txt        ← 파일로 흘리고 필요한 데만 열기
      latest-map.mjs --for "<주제>"   ← 도구가 «좁혀 부르는 길»을 주는 경우

   ⛔⛔ 2026-09-03 = `/clear` 직후 6% 였던 창이 «한 턴» 만에 45% 가 됐다.
      「문서·도구 답 크기를 재는」 명령 하나가 ≈390k 토큰을 쏟았다. 하루가 날아갔다.
   ⛔ 상한을 올려서 통과시키지 말 것 — 그건 게이트를 끄는 것이다.
MSG
  } >&2
  exit 2
fi

# ──────────────────────────────────────────────────────────────
# ② 돌고 «난 뒤» — 실제로 나온 답을 재서, 크면 그 턴에서 멈추게 한다
#    ⛔ 자를 수는 없다(이미 대화에 들어갔다). 할 수 있는 건 «겹치지 않게» 하는 것뿐이다.
# ──────────────────────────────────────────────────────────────
# ──────────────────────────────────────────────────────────────
# ②-0 «턴 합계» — 2026-09-07 창업자 캡처(Messages 1.3M / 1M · 130%)로 알게 된 구멍
#    답 «하나»는 6만 B 아래여도 한 턴에 스무 번 돌면 1.2MB 가 그냥 지나간다.
#    그래서 «턴»마다 누적을 세고, 상한을 넘으면 그 턴에서 멈추게 한다.
#    · 표식 = /tmp/hankki-bigout-turn-<session_id>  (창업자가 말을 하면 `reset` 이 지운다)
#    · TURN_LIMIT 200,000 B ≈ 답 셋~넷 분량 · ⛔올려서 통과시키지 말 것
# ──────────────────────────────────────────────────────────────
TURN_LIMIT=200000
SID=$(printf '%s' "$INPUT" | python3 -c 'import sys,json
try: print(json.load(sys.stdin).get("session_id") or "nosid")
except Exception: print("nosid")' 2>/dev/null || echo nosid)
TURN_FILE="/tmp/hankki-bigout-turn-${SID}"
if [ "$MODE" = "reset" ]; then rm -f "$TURN_FILE"; exit 0; fi

SIZE=$(printf '%s' "$INPUT" | python3 "$HERE/_bigout-size.py" 2>/dev/null || echo 0)
case "$SIZE" in ''|*[!0-9]*) exit 0 ;; esac

PREV=$(cat "$TURN_FILE" 2>/dev/null || echo 0)
case "$PREV" in ''|*[!0-9]*) PREV=0 ;; esac
SUM=$((PREV + SIZE))
printf '%s' "$SUM" > "$TURN_FILE" 2>/dev/null || true
if [ "$SUM" -gt "$TURN_LIMIT" ] && [ "$SIZE" -le "$LIMIT" ]; then
  # 답 하나는 작은데 «합계»가 넘었다 — 한 번 알리고 계수기를 비운다(같은 말을 매번 반복하지 않게)
  rm -f "$TURN_FILE"
  {
    echo "📤📤 **이 턴에 도구 답이 «합쳐서» $(printf "%'d" "$SUM" 2>/dev/null || echo "$SUM") B 들어왔다 (턴 상한 $(printf "%'d" $TURN_LIMIT 2>/dev/null || echo $TURN_LIMIT) B)**"
    cat <<'MSG'

   ⛔ 답 하나하나는 작았지만 «턴 합계»가 넘었다 — 2026-09-07 창업자 캡처 = Messages 1.3M / 1M (130%).
   👉 여기서 멈추고 창업자에게 «지금까지»를 보고한다. 더 돌릴 게 남았으면 다음 턴에.
   👉 남은 것은 파일로 흘리고(… > 파일) 필요한 줄만 연다.
MSG
  } >&2
  exit 2
fi
[ "$SIZE" -gt "$LIMIT" ] || exit 0

{
  echo "📤📤 **방금 도구 답이 너무 컸다 — $(printf "%'d" "$SIZE" 2>/dev/null || echo "$SIZE") B (상한 $(printf "%'d" $LIMIT 2>/dev/null || echo $LIMIT) B)**"
  cat <<'MSG'

   ⛔ **이미 대화에 들어갔다 — 되돌릴 수 없다.** 그러니 «여기서 멈춘다».
   👉 같은 명령을 **다시 돌리지 말 것.** 범위를 좁혀서 한 번만 부른다.
   👉 창업자에게 알린다 — 창이 얼마나 찼는지 `/context` 로 볼 수 있다.

   📌 2026-09-03 에 손해가 커진 건 «터진 뒤에도 계속 돌았기» 때문이다.
      한 번은 사고고, 두 번째부터는 겹치기다.
MSG
} >&2
exit 2
