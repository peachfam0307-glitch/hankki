#!/bin/sh
# 🧪🧪 계측 캡처를 받았을 때 — «나누기 전에» 잣대를 돌리라고 띄운다 (2026-09-16)
#
# 📮 창업자 = *"이거 날짜가 중요해. 우리가 계속 수정을 했었고, 그 수정을 완료한 날 이후를 봐야하고
#    내가 테스트한 것도 섞여있나도 봐야해"*
#
# ⛔ 2026-09-16 사고 = GA4 캡처를 받자마자 「가져오기 43 → 7 (16%)」이라고 나눴다.
#    이벤트마다 심은 날이 달랐고(9/07·9/10·9/12·9/14), 9/13 22:13~9/15 18:56 은 자르기 안내가 안 뜨던
#    버그 기간이었고, 창업자 테스트가 안 빠져 있었다. 셋 다 안 보고 나눴다.
#
# ⛔ 이 훅은 «막지» 않는다 — 내가 하는 말은 훅이 못 막는다(규칙 26 한계). 그 턴에 눈앞에 놓는다.
# ⚠️ 창업자가 «그림만» 보내면 글자가 없어 못 뜬다 — 그건 못 잡는다(정직하게).
# ⛔ bash 변수명은 ASCII 로 (CLAUDE.md 규칙 24)
set -u
INPUT=$(cat 2>/dev/null || true)

# 「계측 캡처」 신호 ＋ 「나누기·분석」 신호가 같이 있을 때만 (시끄러운 게이트는 죽은 게이트)
echo "$INPUT" | grep -qE '애널리틱스|GA4|개요|클래스|이름 표|조회수|활성 사용자|이벤트 수|퍼널|깔때기' || exit 0
echo "$INPUT" | grep -qE '분석|비율|퍼센트|%|몇 명|얼마나|새|구멍|끊|나눠|저장했' || exit 0

cat <<'MSG'
🧪🧪 **계측 숫자를 나누기 «전»에 — 잣대부터 돌린다.** (창업자 2026-09-16 · 「16%」 사고)

   node hankki/scripts/계측-잣대.mjs --부터 YYYY-MM-DD --까지 YYYY-MM-DD --이벤트 a,b,c

   그러면 ① 이벤트마다 «심은 날»(git 이 센다) ② 장부의 «오염 구간» ③ **공정한 공통 구간**이 나온다.
   ⛔ 그 구간 «밖»의 값으로 비율을 말하지 않는다. 캡처 기간이 더 이르면 「그 전 값은 오염됐다」고 말한다.
   ⛔ 캡처의 «기간»을 모르면 먼저 묻는다 — 기간 없는 캡처(09-15 쿠팡)는 며칠치인지 모른다.
   ⛔ 창업자 테스트가 빠져 있나 — GA4 「내부 트래픽」 필터가 «활성»인지 창업자에게 확인 (딱지만으론 안 빠진다).
   📄 docs/계측-오염방지-설계-2026-09-16.md · docs/계측-오염장부.md
MSG
exit 0
