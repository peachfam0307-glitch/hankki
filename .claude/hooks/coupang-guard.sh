#!/bin/sh
# 🛒🛒 쿠팡 파트너스 — 「폰으로 눌러봐」라고 말하기 «전»에 반드시 붙일 말을 띄운다.
#    (절대원칙 · 창업자 2026-09-15 = *"절대원칙으로 꼭꼭 나한테 말해줘"*)
#
# ⛔ 왜 규칙이 아니라 장치인가 = 창업자 2026-07-31 *"규칙만 만들면 뭐해 안지키는데."*
#    이 훅은 «막지» 않는다 — 클로드가 그 말을 할 때 «잊지 않게» 띄운다.
#    📌 훅은 도구 호출만 막지 내가 하는 말은 못 막는다(규칙 26 과 같은 한계).
#       그래서 창업자 말에 쿠팡·테스트 신호가 보이면 «그 턴에» 눈앞에 띄우는 쪽으로 만들었다.
#
# ⛔ bash 변수명은 ASCII 로 (CLAUDE.md 규칙 24)
set -u
INPUT=$(cat 2>/dev/null || true)

# 「쿠팡 쪽 이야기」이면서 「눌러보기·확인」 신호가 같이 있을 때만 뜬다 (시끄러운 게이트는 죽은 게이트)
echo "$INPUT" | grep -qE '쿠팡|파트너스|사러가기|coupang' || exit 0
echo "$INPUT" | grep -qE '눌러|테스트|확인|열어|해봐|검사|폰으로' || exit 0

cat <<'MSG'
🛒🛒 **쿠팡 링크를 «폰으로» 눌러보라고 말하려 한다면 — 이것을 «반드시» 같이 준다.**

   ⭐⭐ **① 쿠팡 테스트는 «무조건 딸 아이폰»으로 한다.** (창업자 확정 2026-09-15)
        · 딸 아이폰 = **쿠팡 가입이 안 돼 있다** → 거기서 살 일이 없다 → 실적이 안 섞인다
        · 창업자 갤럭시 = **장보기 전용**. 클릭 기록이 안 남는다
        👉 기기를 아예 갈라 두면 **24시간을 신경 쓸 일이 사라진다.**
   ② **그래도 갤럭시로 눌렀다면** — 그 뒤 24시간 안에 «폰 쿠팡 앱»으로 개인 장보기를 하지 않는다.
      그날 장을 봐야 하면 **«컴퓨터»로** 본다 — 클릭 기록은 그 기기에만 남는다.

   🔢 왜 = 공식 가이드(2025-10-28 · 41쪽) *"접속시간 기준 24시간 내에 발생한 모든 구매액에 대해 수익이 집계"*
        ＋ *"본인 링크를 통한 자가 구매는 실적이 집계되지 않아요"*
        → 테스트로 한 번 누르면 **그 뒤 24시간의 개인 장보기가 통째로 실적에 섞이고, 제외 대상이 된다.**
   🔢 실제로 났다 = 2026-09-15 실적에 창업자 개인 구매 **672원**(파로·탈취제)이 붙었다.

   ⚠️ 「컴퓨터는 안전하다」는 **거의 확실하지만 100%는 아니다** — 쿠팡이 «계정»으로 기기를 이어 볼지는 모른다.
      ⛔ 「완전히 안전하다」고 단정하지 말 것.
   ⭐ 그리고 **대부분의 검사는 클로드가 스크립트로 한다** — 폰은 「쿠팡 앱이 진짜 열리나」에만 쓴다.

   📄 전문 = hankki/docs/쿠팡파트너스-공식가이드-정리-2026-09-15.md
MSG
exit 0
