#!/bin/sh
# 🛒🛒 쿠팡 파트너스 — 「폰으로 눌러봐」라고 말하기 «전»에 반드시 붙일 말을 띄운다.
#    (절대원칙 · 창업자 2026-09-15 = *"절대원칙으로 꼭꼭 나한테 말해줘"*)
#
# ⛔ 왜 규칙이 아니라 장치인가 = 창업자 2026-07-31 *"규칙만 만들면 뭐해 안지키는데."*
#    이 훅은 «막지» 않는다 — 클로드가 그 말을 할 때 «잊지 않게» 띄운다.
#    📌 훅은 도구 호출만 막지 내가 하는 말은 못 막는다(규칙 26 과 같은 한계).
#       그래서 창업자 말에 쿠팡·테스트 신호가 보이면 «그 턴에» 눈앞에 띄우는 쪽으로 만들었다.
#
# ⛔ bash 변수명은 ASCII 로 (CLAUDE.md 규칙 24)
set -u
INPUT=$(cat 2>/dev/null || true)

# 「쿠팡 쪽 이야기」이면서 「눌러보기·확인」 신호가 같이 있을 때만 뜬다 (시끄러운 게이트는 죽은 게이트)
echo "$INPUT" | grep -qE '쿠팡|파트너스|사러가기|coupang' || exit 0
echo "$INPUT" | grep -qE '눌러|테스트|확인|열어|해봐|검사|폰으로' || exit 0

cat <<'MSG'
🛒🛒 **쿠팡 링크를 눌러보라고 말하려 한다면 — 맨 먼저 이 한 줄부터.**

   ① 👧📱 **「딸 아이폰으로 눌러줘」** ＝ 창업자 확정 2026-09-15. ⛔창업자 폰으로 시키지 않는다.
      ⭐ 왜 = 딸 폰은 **쿠팡 계정이 없어서 살 수가 없다** → 본인·가족 구매가 애초에 안 일어난다.
         ＋ 그 폰으로 쿠팡 장을 볼 일이 없으니 **24시간 걱정도 없다.**
         ＋ 창업자 폰은 아예 안 건드리니 **창업자는 평소대로 장을 봐도 된다.**
      ⭐ 브라우저(사파리)로 열리는 것이 **맞는 모양**이다 — 우리 코드는 아이폰에서 앱으로 안 보낸다
         (`_repro-쿠팡문-0905.mjs` ④). **「그 제품으로 가나」는 브라우저로도 똑같이 보인다.**
      ⛔ 그래도 **한 링크당 한 번씩만** — 「누르기만 한 것」이 100% 무해한지는 공식 근거가 없다.

   ② ⛔ **혹시라도 창업자 폰으로 눌러야 한다면** — 이 두 줄을 «반드시» 같이 준다:
      · 누른 날은 **그 뒤 24시간 안에 그 폰 쿠팡으로 아무것도 사지 않는다**(무엇을 사든 섞인다)
      · 그날 장을 봐야 하면 **컴퓨터로** 본다 — 클릭 기록은 그 기기에만 남는다

   🚨 **「원래 사려던 것」이라는 예외는 «없다»** — 2026-09-15 에 내가 그렇게 말했다가 창업자가 잡았다.
      📜 원문 = *"**본인 링크를 통한 구매 활동**은 … **실적에서 제외**됩니다"* — **물건을 가리지 않는다.**
      ✅ 한 줄 = **「누르는 건 된다. 사는 건 안 된다.」**

   🟢 **담기는 마음껏** — 「담기」는 우리 앱 안의 목록일 뿐 쿠팡에 닿지 않는다. **「사러가기」만** 클릭이 난다.
   ⭐ **대부분의 검사는 클로드가 스크립트로 한다** — 폰이 필요한 건 「그 링크가 진짜 그 제품이냐」 하나뿐.

   🔢 왜 = 공식 가이드(2025-10-28 · 41쪽) *"접속시간 기준 24시간 내에 발생한 모든 구매액에 대해 수익이 집계"*
   🔢 실제로 났다 = 2026-09-15 실적에 창업자 개인 구매 **672원**(파로·탈취제)이 붙었다.
   📄 전문 = hankki/docs/쿠팡파트너스-공식가이드-정리-2026-09-15.md
MSG
exit 0
