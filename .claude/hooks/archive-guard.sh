#!/usr/bin/env bash
# 🔒🔒 보관소 접근 금지 — 창업자가 지시할 때만 연다. (창업자 절대원칙 2026-08-13)
#
# ⛔⛔ **이 머리말에 「🗄 ＋ 별표 둘 ＋ 보관소」를 쓰지 말 것.**
#   그게 이 훅이 «보관소 문서»를 알아보는 표시라, 훅이 **자기 자신을 막는다.**
#   → 훅을 고치려면 훅을 읽어야 하는데 못 읽는 **막다른 길**이 된다(2026-08-15 실제로 걸렸다).
#   📌 규칙 19 그대로 — 게이트를 만들면 «푸는 길»도 그 게이트를 통과하는지 확인한다.
#
#   📮 창업자 원문 = *"내가 지시하지 않으면 **옛날 보관소에는 접근금지.**"*
#      2026-08-15 재확인 = *"나눠서 반영구적으로 가둬. **내가 허락할때만 들어가도록.**"*
#                        · *"**완전히막아.** 내 승인하에만 열람할 수 있게 규칙만들고 강제해"*
#
# ⛔⛔ **왜 「읽기 목록에서 빼기」로는 모자란가**
#   CLAUDE.md 의 옛 버전 기록을 docs/_archive/ 로 옮기고 hello-read 목록에서 뺐다.
#   **그건 «권하지 않는 것»일 뿐이다.** grep 으로 걸리거나 그냥 Read 로 열면 그대로 옛 판을 읽는다.
#   📌 자리만 옮기고 위험은 그대로 — 똑같은 사고가 난다.
#
# ⭐ **판정은 두 가지** — 경로(_archive·_아껴둠·_구판) 또는 문서가 스스로 붙인 「🗄 보관소」 표시.
#   경로만 보면 새 보관소가 생길 때마다 여기를 고쳐야 하고 **반드시 낡는다.**
#   **붙이는 쪽이 아는 게 맞다** → 문서 앞 40줄에 표시를 둔다.
#
# ⚠️ **푸는 길이 이 게이트를 통과하는지 확인했다** (2026-08-13 하루에 두 번 밟은 실수)
#   허가 표식을 만드는 echo·printf 는 읽는 명령이 아니므로 «안 막힌다». 막다른 길이 아니다.
#   ⛔⛔ **[2026-08-18 정정] 바로 위 줄이 «틀렸었다» — 적어만 두고 돌려보지 않았다.**
#      창업자 *"청소해"* 로 표식을 만들려는데 **그 printf 가 막혔다.** 표식 «글»에 보관소 낱말이
#      들어 있고 뒤에 `cat` 이 붙어서 「보관소를 읽는다」로 잡힌 것이다.
#      ✅ `guard-targets.py` 에 echo·printf 리다이렉트를 지우는 줄을 넣어 고쳤고,
#         `_test-archive-guard.sh` 에 **그 명령 자체를 검사로 박았다**(다음엔 게이트가 잡는다).
#      📌 **「푸는 길을 확인했다」고 «적는 것»과 «돌려보는 것»은 다르다.** 이번이 그 자리 세 번째다.
#
# ⛔⛔ **첫 판이 «모든 .md 읽기»를 막았다 — bash 변수명에 한글을 썼기 때문이다.**
#   한글 대입이 «명령»으로 해석돼 판정이 한 줄도 안 돌고 늘 차단됐다.
#   📌 **bash 변수명은 ASCII 로.** 주석·메시지는 한글이어도 된다.
#
# ⭐⭐⭐ **[2026-08-15] 판정 코드를 «파일»로 뺐다 — 이게 오늘 제일 큰 고침이다.**
#   전엔 python 이 이 파일 안에 python3 -c 로 «큰따옴표에 싸여» 들어 있었다. 그 안에서는
#     · 백틱      → 명령으로 실행된다
#     · 큰따옴표  → 그 자리에서 블록이 닫힌다
#     · 달러표시  → 치환된다
#   ⛔ 그래서 **주석 한 줄에 큰따옴표를 쓴 것만으로 python 이 통째로 깨졌고, 훅은 조용히 통과했다.**
#      「가뒀다」고 말해 놓고 안 가둬진 것이다 — 창업자에게 그렇게 보고할 뻔했다.
#   ⭐ 파일로 빼면 bash 가 그 안을 «아예 안 본다». 지뢰가 사라진다.
#   📄 판정 = .claude/hooks/guard-targets.py
#
# ⛔⛔ **[2026-08-16] 그 판정 파일 이름이 `_archive-targets.py` 였다 — 훅이 «자기 부품»을 막았다.**
#   경로에 `_archive` 가 들어가서 Read 로 못 열었고, **훅을 고치려면 그 부품을 읽어야 하는데 못 읽었다.**
#   📌 규칙 19 그 자리를 «두 번째» 밟았다(첫 번째 = 이 파일 머리말의 「🗄 보관소」 표시).
#   ✅ 고침 = ⑴이름을 `guard-targets.py` 로 ⑵`.claude/hooks/` 아래는 판정 대상에서 제외.
#      **「하지 마라」보다 «할 수 없게» 만드는 쪽으로.**
#
# ⛔ **＋ 같은 날 구멍 하나를 메웠다** — `git show HEAD:docs/_archive/…` 로 **내용을 그대로 읽을 수 있었다.**
#   `cat` 은 막히는데 `git show` 는 통과했다 — 같은 일을 하는데 한쪽만 막혀 있었다(재현으로 잡음).

INPUT=$(cat)
HERE=$(dirname "$0")

TARGETS=$(printf '%s' "$INPUT" | python3 "$HERE/guard-targets.py" 2>/dev/null)

[ -n "$TARGETS" ] || exit 0

ALLOW=/tmp/hankki-보관소-허가
BLOCKED=""
while IFS= read -r f; do
  [ -n "$f" ] || continue
  for p in "$f" "/home/user/hankki/$f" "/home/user/hankki/hankki/$f"; do
    # ⚠️ Grep·Glob 의 path 는 «폴더»일 수 있다 — 파일만 보면 보관소 폴더째 검색이 새어 나간다
    [ -e "$p" ] || continue
    if [ -d "$p" ]; then
      case "$p" in *_archive*|*_아껴둠*|*_구판*|*_구버전*) BLOCKED="${BLOCKED}   ⛔ ${p}  (폴더)
" ;; esac
      break
    fi
    kind=""
    case "$p" in *_archive*|*_아껴둠*|*_구판*|*_구버전*) kind="경로" ;; esac
    if [ -z "$kind" ] && head -40 "$p" 2>/dev/null | grep -q '🗄 \*\*보관소'; then kind="표시"; fi
    [ -n "$kind" ] && BLOCKED="${BLOCKED}   ⛔ ${p}  (${kind})
"
    break
  done
done <<< "$TARGETS"

[ -n "$BLOCKED" ] || exit 0

if [ -f "$ALLOW" ]; then
  echo "🗄 보관소를 연다 — 창업자 지시: $(head -1 "$ALLOW")" >&2
  exit 0
fi

{
  echo "🗄🗄 **보관소다 — 창업자가 지시할 때만 연다.** (절대원칙 2026-08-13)"
  echo ""
  printf '%s' "$BLOCKED"
  echo ""
  echo "   📮 창업자 *\"내가 지시하지 않으면 옛날 보관소에는 접근금지.\"*"
  echo "      *\"완전히막아. 내 승인하에만 열람할 수 있게 규칙만들고 강제해\"* (2026-08-15)"
  echo ""
  echo "   ⛔ 여기 있는 건 **옛 판·끝난 기록**이다. 읽고 그대로 쓰면 «옛날꺼 읽어서 실수하는» 그 사고가 난다."
  echo "      📌 2026-08-15 실제 사고 — 반영이 끝난 초안 JSON 을 보고 「창업자 확인을 못 받았다」고"
  echo "         잘못 보고했다. 이미 답한 것을 또 묻게 만들 뻔했다."
  echo ""
  echo "   ✅ **지금 규칙·핀은 CLAUDE.md 에 있다.**  최신 문서 = node hankki/scripts/hello-read.mjs"
  echo "   ✅ 「이미 정한 것」을 찾는 거면 → node hankki/scripts/decided.mjs \"<핵심어>\""
  echo "   ✅ 레시피·개수·상수의 «현행»은 문서가 아니라 **코드**다 (src/data/basics.js 등)"
  echo ""
  echo "   👉 **창업자가 열라고 했다면** — 그 지시 원문을 적어 표식을 만든다(이 세션에만):"
  echo "      echo '<창업자 지시 원문>' > $ALLOW"
} >&2
exit 2
