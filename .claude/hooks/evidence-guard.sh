#!/usr/bin/env bash
# 🛑 근거 훅 — 창업자가 «중요한 것»을 물으면, 답하기 «전에» 관문을 들이민다.
#
# 왜 (창업자 2026-08-03, 프로덕션 반려 직후):
#   *"또 중요한 결정할때 서치안하고 니맘대로 대충 얘기하는거. (프로덕션+설문지)
#     오늘 나 정말 너무너무 화가났어. 앞으로 모든 일을 제안할때 **구조적으로** 니 추측이나
#     대충 넘겨짚어 못하게 하는 시스템을 만들어. … **이건 앞으로 모든 일에 절대원칙이야.**
#     … **실물을 보지않고 대답하는 거 금지 절대원칙!!**"*
#
# ⭐ 왜 «UserPromptSubmit» 인가 = 여기가 **내가 입을 열기 직전**이다.
#   PreToolUse 는 도구를 쓸 때만 걸린다. 그런데 「대충 말하기」는 도구를 안 쓴다 — 그냥 말한다.
#   그래서 창업자 말이 들어오는 이 자리에서 막아야 한다.
#
# ⛔ 시끄러운 게이트는 죽은 게이트다 → **저장소가 «절대» 모르는 주제**에서만 뜬다.
#   (레시피·스티커·코드처럼 파일로 확인되는 건 안 뜬다)
set -u
IN=$(cat)
TXT=$(printf '%s' "$IN" | python3 -c 'import sys,json;d=json.load(sys.stdin);print(d.get("prompt",""))' 2>/dev/null || true)
[ -z "$TXT" ] && exit 0

# 저장소 밖 = 파일에도 없고 내가 열 수도 없는 것. 여기선 «실물»이 유일한 근거다.
KEY='프로덕션|반려|심사|콘솔|플레이|테스터|비공개 테스트|AAB|스토어|신청서|설문|구글 폼|정책|약관|수수료|파트너스|커넥트|큐레이터|제휴|사업자|세무|홈택스|통신판매|PG|결제|정산|상표|출원|특허|법|환불|기한|버전 코드'
printf '%s' "$TXT" | grep -qE "$KEY" || exit 0

cat <<'MSG'

🛑 **근거 관문** — 이건 «저장소 밖» 주제다. 답하기 전에 통과할 것. (창업자 절대원칙 2026-08-03)

  ⛔ 실물을 보지 않고 대답하지 않는다. ⛔ 모르는 게 남으면 창업자를 움직이지 않는다.

  ① 여러 경로로 «최신» 서치 (공식 원문 우선 — 개인 블로그 요약은 근거가 아니다)
  ② 이 환경이 못 여는 곳(play.google.com·support.google.com = 403)이 근거면
     → **창업자에게 그 화면 캡처를 요청한다.** 캡처 오기 전엔 제안하지 않는다.
  ③ 리스크(틀리면 무슨 일이 나나)까지 확인
  ④ 통과시킨다:

     node hankki/scripts/evidence.mjs --주제 "…" --종류 창업자행동|내작업|사실보고 \
       --주장 "…" --출처 "실물:…|…" --출처 "url:…|날짜|공식" \
       --리스크 "…" --모르는것 "없음"

  📌 2026-08-02 반려 = 이걸 안 해서 났다. 「공식 확인 못 함」이라 적어놓고 2주를 시켰고,
     구글이 «테스터가 참여하지 않았다»로 반려했다. 2주를 통째로 잃었다.
MSG
exit 0
