#!/usr/bin/env bash
# 📤📤 제출물 훅 — 「밖으로 나가는 글」을 쓰기 «전에» 콘솔 실물부터 받게 한다.
#
# 왜 (창업자 2026-08-03 *"만들어 진짜 이건 절대원칙이야"*):
#   *"그래서 뭐가 문제라서 반려된거야? 너는 이걸 왜 이제야 파악해?
#     **미리 이런 걸 나한테 캡처하라고 해서 신청서 쓸 때 알려줘야 하는 거 아냐?**"*
#   → 맞는 말이다. 7/31 신청서를 쓸 때 콘솔을 «아예 안 물었다».
#     그래서 릴리즈가 일곱 판인 걸 몰랐고, 답할 수 있던 칸을 「모른다」로 비워 냈다. → 8/02 반려.
#
# ⭐⭐ 근거 훅(evidence-guard)과 자리가 다르다 — **둘 다 있어야 한다.**
#   · evidence-guard = 내가 «말하려 할 때»  → 틀린 말을 막는다
#   · 이 훅          = 내가 «글을 쓰기 전에» → **안 물어본 것**을 막는다
#   8/02 사고는 «틀린 말»이 아니라 «안 물어본 것»이라 근거 훅으로는 안 잡혔다.
#
# ⛔ 시끄러우면 죽는다 → **밖으로 나가는 제출물**을 쓰려는 신호에서만 뜬다.
#    (「프로덕션이 뭐야」 같은 질문은 근거 훅이 맡는다. 여기는 «쓴다/낸다»일 때만)
set -u
IN=$(cat)
TXT=$(printf '%s' "$IN" | python3 -c 'import sys,json;d=json.load(sys.stdin);print(d.get("prompt",""))' 2>/dev/null || true)
[ -z "$TXT" ] && exit 0

# ① 무엇을 = 구글·스토어가 «읽는» 글
WHAT='신청서|재신청|답변|9문항|설문|구글 폼|스토어 등록|등록정보|앱 이름|앱 설명|짧은 설명|데이터 보안|스크린샷|제출|지원팀|구글에|문의|티켓|메일'
# ② 어떻게 = 쓰거나 낸다는 신호  (⚠️ 둘 다 있어야 뜬다 — 한쪽만이면 시끄럽다)
DOING='써|쓰자|쓸|작성|초안|만들|정리해|채워|채우|넣어|올려|올리|내자|제출|보내|고쳐|수정|갱신|다시 쓰|물어|물을|물어볼|질문'

printf '%s' "$TXT" | grep -qE "$WHAT" || exit 0
printf '%s' "$TXT" | grep -qE "$DOING" || exit 0

cat <<'MSG'

📤 **제출물 관문** — 구글이 «읽는» 글이다. 쓰기 전에 콘솔 실물부터. (창업자 절대원칙 2026-08-03)

  ⛔ 저장소에 있는 것만으로 답을 만들지 않는다.
  ⛔ 「모른다」로 비워서 내지 않는다 — **물어보면 알 수 있는 것**이었다.

  ⭐ **구글 지원팀에 «물어볼 것»이면 → 이 칸이다** (2026-08-18 신설):
       node hankki/scripts/submission-gate.mjs --종류 지원팀문의 \
         --질문 "…"  --근거 "…실물…"  --바뀜 "답이 오면 우리 행동이 어떻게 갈리나"
     ⛔ 게이트가 «이미 정한 것»과 겹치면 죽는다 — 2026-08-18 에 8/17 확정을 또 물을 뻔했다.
     📮 창업자 규칙 = **도장(ASK-…) 없는 질문은 안 보낸다.**

  ① 그 밖의 제출물이면 뭘 받아야 하는지 먼저 본다:
       node hankki/scripts/submission-gate.mjs --종류 재신청|스토어등록|설문|데이터보안
  ② 그 목록을 **창업자에게 한 번에** 요청한다 (⛔한 장씩 여러 번 시키지 말 것 · 규칙 8)
  ③ 캡처에서 «읽은 값»을 넣어 통과시킨다:
       … --값 "활성기기30일=7/22 16 · 7/24 18 · 이후 0~2" --값 "출시내역=1,2,3,5,7,9,10"
  ④ 통과한 값이 **그대로** 답변에 들어간다. ⛔거기서 다시 짐작하지 말 것.

  📌 2026-08-02 반려 = 이 칸이었다. 콘솔을 안 물어보고 신청서를 썼고,
     릴리즈가 일곱 판인 것도·활성 기기가 「몰아서 며칠」인 것도 모른 채 냈다.
MSG
exit 0
