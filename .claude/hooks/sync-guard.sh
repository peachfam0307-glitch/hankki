#!/usr/bin/env bash
# 🔁🔁 저장소 동기화 «2차 그물» — 세션시작 훅이 놓쳐도 «첫 도구 호출»에서 잡는다. (2026-08-12 신설)
#
# 📮 창업자 2026-08-12 — *"저장소는 왜 어제 고쳤는데 또 그러는거야? 원인파악해서 그것부터 고치자."*
#    · *"시스템만들어. 원천적으로"*
#
# ⛔⛔ **어제 무엇이 모자랐나 (2026-08-12 아침 실측으로 확정)**
#    · 그날 아침 컨테이너가 **11분 전에 새로 떴고** 저장소는 **79커밋 뒤처져** 있었다(v10.21 · 8/9 상태).
#    · `repo-sync.sh` 는 **그 되감긴 판에도 173줄로 멀쩡히 있었고 `settings.json` 에 등록도 돼 있었다**
#      (`git show b7ec7d0:.claude/settings.json` 로 확인 — 짐작 아님).
#    · 그런데 **안 고쳐졌다.** 게다가 `/tmp/hankki-sync.log` 가 아예 없었다.
#    · 손으로 돌려보니 **1초 만에 정상 작동**했다 → **코드는 멀쩡하고 «세션 시작 때 안 불린» 것이다.**
#
# ⭐⭐ **그래서 뿌리는 「훅이 틀렸다」가 아니라 「기회가 한 번뿐이다」이다.**
#    `SessionStart` 는 세션당 **딱 한 번** 돈다. 그 한 번에
#      ⒜훅이 안 불리거나 ⒝컨테이너가 갓 떠서 네트워크·프록시가 아직 안 열렸거나
#      ⒞타임아웃이 나면 — **그 세션은 낡은 채로 끝까지 간다.**
#    ⚠️ ⒜⒝⒞ 중 어느 것인지는 **아직 모른다**(옛 판엔 로그가 없었다).
#    📌 **원천 해결은 「이유를 밝히는 것」이 아니라 「이유가 무엇이든 잡히게」 만드는 것이다.**
#
# ✅ **이 훅이 원천적인 이유 = 기회가 «여러 번» 온다.**
#    나는 무슨 일을 하든 **반드시 도구를 쓴다.** 그러니 도구를 쓸 때마다 기회가 생긴다.
#    · 표식(`/tmp/hankki-synced`)이 **있으면 즉시 통과**한다(≈1ms · 파일 존재 검사 하나).
#    · **없으면** `repo-sync.sh` 를 부른다 → 맞추고 표식을 남긴다.
#    · ⭐**네트워크가 아직 없으면 표식을 «안» 남긴다** → 다음 도구 호출에서 또 해본다
#      → **네트워크가 열리는 순간 잡힌다.** 세션시작 훅엔 없던 성질이 이것이다.
#    · ⭐표식을 `/tmp` 에 두는 이유 = **컨테이너와 생명주기가 같다.**
#      되감기면 `/tmp` 도 비므로 **표식이 저절로 사라져 다시 검사한다.** 손으로 지울 일이 없다.
#
# 🛡 **안전장치 — `repo-sync.sh` 의 것을 그대로 물려받는다**(로직을 복사하지 않는다).
#    버리기 전에 `hold/자동회수` 에 담고 · 담기에 실패하면 되돌리지 않고 · BEHIND==0 이면 손대지 않는다.
#    ⛔ 로직을 여기 베껴 쓰면 둘이 어긋난다 — **부르기만 한다.**
set -u

MARK="/tmp/hankki-synced"
[ -f "$MARK" ] && exit 0          # ⚡ 이미 확인했다 — 즉시 통과(거의 모든 호출이 여기서 끝난다)

REPO="${CLAUDE_PROJECT_DIR:-/home/user/hankki}"
LOG="/tmp/hankki-sync.log"
note() { printf '%s  %s\n' "$(TZ=Asia/Seoul date '+%m-%d %H:%M:%S' 2>/dev/null || date '+%m-%d %H:%M:%S')" "$1" >> "$LOG" 2>&1 || true; }

# 🔎 `repo-sync.sh` 를 «두 곳»에서 찾는다 — 저장소 안이 먼저, 없으면 git 밖 복사본.
#    ⛔ 저장소 «안»만 보면 브랜치를 옮기거나 되감겼을 때 못 찾는다(2026-08-10 base-guard 가 겪은 그것).
SYNC=""
for c in "$REPO/.claude/hooks/repo-sync.sh" "$HOME/.claude/hooks/repo-sync.sh"; do
  [ -x "$c" ] && { SYNC="$c"; break; }
done
# ⛔ 어디에도 없으면 표식을 안 남긴다 — 다음 기회에 다시 본다.
[ -n "$SYNC" ] || { note "· [2차그물] repo-sync.sh 를 두 곳 다 못 찾음 — 다음 기회에"; exit 0; }

cd "$REPO" 2>/dev/null || exit 0
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

# 🌐 **네트워크가 열렸나부터 본다.** 안 열렸으면 «표식을 안 남기고» 조용히 나간다.
#    ⭐ 이 한 줄이 이 그물의 핵심이다 — 갓 뜬 컨테이너는 프록시가 늦게 열린다.
if ! timeout 12 git ls-remote --exit-code origin HEAD >/dev/null 2>&1; then
  note "· [2차그물] 네트워크 아직 — 표식 안 남김(다음 도구 호출에서 재시도)"
  exit 0
fi

note "▶ [2차그물] 세션시작 훅이 안 돈 것으로 보임 — 지금 맞춘다"
printf '{"source":"net"}' | timeout 90 "$SYNC" >/dev/null 2>&1
RC=$?

# ✅ 여기까지 왔으면 «확인은 했다». 결과와 무관하게 표식을 남긴다 —
#    ⚠️ 안 그러면 fetch 가 매 도구 호출마다 돌아 느려진다(시끄러운 게이트는 죽은 게이트).
#    ⛔ 단 «네트워크가 없어서 못 한 경우»는 위에서 이미 빠져나갔으므로 여기 안 온다.
date '+%s' > "$MARK" 2>/dev/null || true

BEHIND="$(git rev-list --count HEAD..origin/claude/chatgpt-conversation-link-kvn5ph 2>/dev/null || echo '?')"
note "· [2차그물] 끝 (rc=$RC · 남은뒤처짐=$BEHIND)"

# 📣 되돌린 게 있으면 «한 줄만» 알린다 — 클로드가 낡은 판으로 판단하는 걸 막는 게 목적이다.
if [ "$BEHIND" = "0" ]; then
  exit 0
else
  cat <<EOF
⚠️ 저장소가 원격보다 $BEHIND 커밋 뒤처져 있고 자동 맞추기가 끝내지 못했다.
   먼저 확인할 것 → git fetch origin && git status
   (자세한 발자국 = $LOG)
EOF
  exit 0
fi
