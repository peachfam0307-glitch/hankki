#!/usr/bin/env bash
# 🔬 design-guard — 「남의 서비스에 붙는 코드」를 만들기 «전»에 알아봤나 (절대원칙 37)
#
# 📮 창업자 2026-09-04 = *"설계할때 읽고 시작 코드로 만들어서 박아둬"*
#    ⭐ 규칙으로 적으면 안 지킨다(창업자 2026-07-31 = *"규칙만 만들면 뭐해 안지키는데"*). 그래서 «막는다».
#
# ⛔⛔ 2026-09-04 사고 = 인스타 표지 뽑기에서 «같은 자리»를 세 번 틀렸다.
#    ⑴ "인스타는 표지를 안 준다"(틀림) ⑵ 태그 모양에 맞춤(못 집음) ⑶ 넓게 잡음(**로고를 집어 왔다**)
#    ⭐ 셋 다 뿌리가 같다 — 그 서비스가 «실제로 어떻게 생겼는지»를 안 알아보고 만들었다.
#
# ⛔⛔ **변수명은 ASCII 로.** 첫 판을 한글 변수명으로 썼더니 대입이 «명령»으로 해석돼
#    판정이 한 줄도 안 돌고 **조용히 통과**했다(만들자마자 돌려봐서 잡았다).
#    📌 CLAUDE.md 규칙 24 에 박혀 있는 함정인데 또 밟았다 — 그래서 여기 다시 적는다.
#
# 🚪 푸는 길 = node hankki/scripts/design-check.mjs --붙는곳 … --모양 … --닮은것 … --바뀌는것 … --막힘신호 …
#    ⭐ 표식이 /tmp 라 컨테이너가 되감기면 사라진다 → 그땐 다시 알아본다(그게 맞다).
#
# ⚠️ 시끄러우면 죽은 게이트다 — **새로 «만드는» 것만** 본다(이미 있는 파일 고치기는 안 막는다).

set -u
INPUT="$(cat)"

TOOL="$(printf '%s' "$INPUT" | sed -n 's/.*"tool_name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
[ "$TOOL" = "Write" ] || exit 0

FPATH="$(printf '%s' "$INPUT" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
[ -n "$FPATH" ] || exit 0
# 이미 있는 파일이면 «고치는» 것이다 — 안 막는다(그건 이미 알아보고 만든 것이다)
[ -e "$FPATH" ] && exit 0

BODY="$(printf '%s' "$INPUT" | sed -n 's/.*"content"[[:space:]]*:[[:space:]]*"\(.*\)"[[:space:]]*}.*/\1/p' | head -1)"
[ -n "$BODY" ] || BODY="$INPUT"

# 바깥을 부르는 코드인가 — fetch( 와 https:// 가 둘 다 있어야 한다
printf '%s' "$BODY" | grep -q 'fetch(' || exit 0
printf '%s' "$BODY" | grep -q 'https://' || exit 0

# 우리 것끼리 부르는 건 «남의 서비스»가 아니다
OUT="$(printf '%s' "$BODY" \
  | grep -o 'https://[a-zA-Z0-9._-]*' \
  | sed 's|https://||' \
  | grep -v 'peachfam0307-glitch\.github\.io' \
  | grep -v 'workers\.dev' \
  | grep -v 'localhost' \
  | grep -v '127\.0\.0\.1' \
  | sort -u | head -3)"
[ -n "$OUT" ] || exit 0

# 표식이 하나라도 있으면 통과 (알아본 뒤다)
for D in $OUT; do
  ROOT="$(printf '%s' "$D" | awk -F. '{ if (NF>=2) printf "%s.%s", $(NF-1), $NF; else print $0 }')"
  [ -f "/tmp/hankki-설계-$D" ] && exit 0
  [ -f "/tmp/hankki-설계-$ROOT" ] && exit 0
done

FIRST="$(printf '%s' "$OUT" | head -1)"
cat >&2 <<MSG
🔬🔬 **남의 서비스에 붙는 코드다 — 알아보고 시작한다** (절대원칙 37 · 창업자가 「제일 중요한」이라 못 박았다)

   만들려는 것 = $FPATH
   붙는 곳     = $OUT

⛔ 2026-09-04 에 인스타 표지 뽑기에서 «같은 자리»를 세 번 틀렸다.
   ⑴ "인스타는 표지를 안 준다"(틀림) ⑵ 태그 모양에 맞춤(못 집음) ⑶ 넓게 잡음(**로고를 집어 왔다**)
   ⭐ 셋 다 뿌리가 같다 — 그 서비스가 «실제로 어떻게 생겼는지»를 안 알아보고 만들었다.
   ⛔ 제일 나쁜 건 ⑶ 이다. 안 뜨면 유저는 「안 뜨네」 하지만,
      **엉뚱한 그림이 뜨면 «그게 그거인 줄» 안다.**

👉 넷을 알아보고 적으면 열린다:
   node hankki/scripts/design-check.mjs --붙는곳 "$FIRST" \\
     --모양     "원하는 걸 실제로 어떤 «모양»으로 내주나 (주소 규칙·필드 이름·만료)" \\
     --닮은것   "비슷하지만 «다른 것» — 오탐 후보" \\
     --바뀌는것 "그쪽이 바꿀 만한 것 / 잘 안 바꾸는 것" \\
     --막힘신호 "막힐 때 어떤 신호로 오나 (로그인 창? 빈 응답? 200인데 내용 없음?)"

⛔ 「모른다」·「확인 못 함」을 적으면 통과 못 한다 — 그게 이 관문이 막는 바로 그것이다.
⛔ 내가 못 여는 곳이면 «창업자에게 물어볼 문장»을 만들어 준다(규칙 15).
MSG
exit 2
