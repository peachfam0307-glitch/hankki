#!/usr/bin/env bash
# 🧭 design-guard — 설계를 «시작하기 전»에 막는 문. **검사 둘이 한 파일에 산다.**
#
# 📮 창업자 2026-09-04 = *"설계할때 읽고 시작 코드로 만들어서 박아둬"*
#    ⭐ 규칙으로 적으면 안 지킨다(창업자 2026-07-31 = *"규칙만 만들면 뭐해 안지키는데"*). 그래서 «막는다».
#
# ⛔⛔ **왜 한 파일인가 — 같은 날 두 세션이 «같은 이름»으로 각각 만들었다.**
#    창업자가 위 말을 두 세션에 다 했고, 둘 다 `design-guard.sh` 를 지었다(2026-09-04 · 실제 충돌).
#    ⭐ 절대원칙 35 가 바로 이걸 말한다 — *"문제 날 때마다 하나씩 막는 설계 절대금지"*.
#       따로 두면 `design-guard` · `design2-guard` … 로 늘고, 셋째가 오면 또 는다.
#    ✅ 그래서 **문은 하나, 검사는 여럿.** 새 검사가 생기면 여기 «아래»에 덧붙인다.
#    ⛔ 새 훅 파일을 만들지 말 것.
#
# ⛔⛔ **변수명은 ASCII 로.** 한글 변수명은 대입이 «명령»으로 해석돼
#    판정이 한 줄도 안 돌고 **조용히 통과**한다(2026-09-04 에 실제로 그랬다).
#    📌 CLAUDE.md 규칙 24 에 박혀 있는 함정인데 또 밟았다 — 그래서 여기 다시 적는다.
#
# ⛔⛔ **합칠 때 충돌 표시(<<<<<<<)를 남기면 이 문이 통째로 죽는다** — 2026-09-04 에 실제로 그랬다.
#    문법이 깨진 훅이 `Write` 를 막아서 **그 훅을 고칠 수조차 없었다**(＝막다른 길 · 규칙 19).
#    ✅ 고치고 나면 반드시 `bash -n .claude/hooks/design-guard.sh` 로 문법을 본다.
#
# ⚠️ 시끄러우면 죽은 게이트다 — 둘 다 **새로 «만드는» 것만** 본다(이미 있는 파일 고치기는 안 막는다).

set -u
MODE="${1:-tool}"
MARK=/tmp/hankki-설계중
PASS=/tmp/hankki-설계통과

# ══════════════════════════════════════════════════════════════════
# ⑴ 창업자 말이 들어올 때 — 설계 신호를 보면 «표식»만 남긴다 (검사 ②가 쓴다)
# ══════════════════════════════════════════════════════════════════
if [ "$MODE" = "prompt" ]; then
  MSG=$(cat 2>/dev/null | tr -d '\000' | head -c 4000)
  # 표식이 이미 있으면 = 설계 얘기가 한 바퀴 돌았다 → 풀고 통과
  if [ -f "$MARK" ]; then rm -f "$MARK" "$PASS"; exit 0; fi
  if printf '%s' "$MSG" | grep -qE '설계|시스템|구조|근본|뿌리|재설계|만들어|만들자|장치|땜빵|넓히|한도|기조|아키'; then
    printf '%s' "$MSG" > "$MARK"
    cat <<'EOM'
🧭🧭 **설계다 — 내놓기 «전»에 3번 다각도로 검토한다.** (절대원칙 33·34 · 창업자 2026-09-04)

   ⛔ 2026-09-04 실측 = 설계 절대원칙 32·33·34 가 **장치 없이 맨몸**이라 그날 아침 셋 다 어겼다.

   👉 **한 줄로 통과시킨다 (통과하면 조용하다):**
      node hankki/scripts/design-gate.mjs --무엇 "..." \
        --사람 "1차: 실제 사람을 세워 따라가며 나온 «고칠 것»" \
        --사고 "2차: 일부러 잘못 굴려서 나온 «고칠 것»" \
        --규모 "3차: 유저 수 x 시간을 곱해 나온 «고칠 것» (숫자 포함)" \
        --잰것 "그 값을 «잰» 근거 (명령 출력 · 파일:줄 · 숫자+단위)" \
        --잃던것 "지금은 실패하면 뭘 잃나" --잃을것 "고친 뒤엔 뭘 잃나"

   ⭐ 세 각도에서 **«고칠 것»이 하나도 안 나오면 그건 검토를 안 한 것이다** — 각도를 바꿔 다시 본다.
   ⛔ 막는 자리는 좁다 = 표식이 있을 때 hankki/src · hankki/scripts 에 **«새 파일»을 만들 때만**.
      문서·재현판·캡처판·고치기는 안 막는다.
EOM
  fi
  exit 0
fi

# ══════════════════════════════════════════════════════════════════
# ⑵ 파일을 만들려는 순간 — 검사 둘을 순서대로 본다
# ══════════════════════════════════════════════════════════════════
INPUT="$(cat 2>/dev/null | tr -d '\000')"

TOOL="$(printf '%s' "$INPUT" | sed -n 's/.*"tool_name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
[ "$TOOL" = "Write" ] || exit 0

FPATH="$(printf '%s' "$INPUT" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
[ -n "$FPATH" ] || exit 0
# 이미 있는 파일이면 «고치는» 것이다 — 안 막는다(그건 이미 알아보고 만든 것이다)
[ -e "$FPATH" ] && exit 0

BODY="$(printf '%s' "$INPUT" | sed -n 's/.*"content"[[:space:]]*:[[:space:]]*"\(.*\)"[[:space:]]*}.*/\1/p' | head -1)"
[ -n "$BODY" ] || BODY="$INPUT"

# ──────────────────────────────────────────────────────────────────
# 검사 ① [절대원칙 37] 남의 서비스에 붙는 코드인가 — 알아보고 시작했나
#   ⛔ 2026-09-04 사고 = 인스타 표지 뽑기에서 «같은 자리»를 세 번 틀렸다.
#      ⑴ "인스타는 표지를 안 준다"(틀림) ⑵ 태그 모양에 맞춤(못 집음) ⑶ 넓게 잡음(로고를 집어 왔다)
#      ⭐ 셋 다 뿌리가 같다 — 그 서비스가 «실제로 어떻게 생겼는지»를 안 알아보고 만들었다.
# ──────────────────────────────────────────────────────────────────
if printf '%s' "$BODY" | grep -q 'fetch(' && printf '%s' "$BODY" | grep -q 'https://'; then
  # 우리 것끼리 부르는 건 «남의 서비스»가 아니다
  OUT="$(printf '%s' "$BODY" \
    | grep -o 'https://[a-zA-Z0-9._-]*' \
    | sed 's|https://||' \
    | grep -v 'peachfam0307-glitch\.github\.io' \
    | grep -v 'workers\.dev' \
    | grep -v 'localhost' \
    | grep -v '127\.0\.0\.1' \
    | sort -u | head -3)"
  if [ -n "$OUT" ]; then
    SEEN=0
    for D in $OUT; do
      ROOT="$(printf '%s' "$D" | awk -F. '{ if (NF>=2) printf "%s.%s", $(NF-1), $NF; else print $0 }')"
      [ -f "/tmp/hankki-설계-$D" ] && SEEN=1
      [ -f "/tmp/hankki-설계-$ROOT" ] && SEEN=1
    done
    if [ "$SEEN" -eq 0 ]; then
      FIRST="$(printf '%s' "$OUT" | head -1)"
      cat >&2 <<MSG
🔬🔬 **남의 서비스에 붙는 코드다 — 알아보고 시작한다** (절대원칙 37 · 창업자가 「제일 중요한」이라 못 박았다)

   만들려는 것 = $FPATH
   붙는 곳     = $OUT

⛔ 2026-09-04 에 인스타 표지 뽑기에서 «같은 자리»를 세 번 틀렸다.
   ⑴ "인스타는 표지를 안 준다"(틀림) ⑵ 태그 모양에 맞춤(못 집음) ⑶ 넓게 잡음(**로고를 집어 왔다**)
   ⭐ 셋 다 뿌리가 같다 — 그 서비스가 «실제로 어떻게 생겼는지»를 안 알아보고 만들었다.
   ⛔ 제일 나쁜 건 ⑶ 이다. 안 뜨면 유저는 「안 뜨네」 하지만,
      **엉뚱한 그림이 뜨면 «그게 그거인 줄» 안다.**

👉 넷을 알아보고 적으면 열린다:
   node hankki/scripts/design-check.mjs --붙는곳 "$FIRST" \\
     --모양     "원하는 걸 실제로 어떤 «모양»으로 내주나 (주소 규칙·필드 이름·만료)" \\
     --닮은것   "비슷하지만 «다른 것» — 오탐 후보" \\
     --바뀌는것 "그쪽이 바꿀 만한 것 / 잘 안 바꾸는 것" \\
     --막힘신호 "막힐 때 어떤 신호로 오나 (로그인 창? 빈 응답? 200인데 내용 없음?)"

⛔ 「모른다」·「확인 못 함」을 적으면 통과 못 한다 — 그게 이 관문이 막는 바로 그것이다.
⛔ 내가 못 여는 곳이면 «창업자에게 물어볼 문장»을 만들어 준다(규칙 15).
MSG
      exit 2
    fi
  fi
fi

# ──────────────────────────────────────────────────────────────────
# 검사 ② [절대원칙 32·33·34] 설계를 시킨 뒤인가 — 3번 검토하고 시작했나
#   ⛔ 2026-09-04 실측(`rules.mjs --bare`) = 32·33·34 가 장치 0개였고 그날 아침 셋 다 어겼다.
#   ⛔ 안 막는 것 = 문서 · `_repro` · `_shot` · `_probe` — 기록·재현까지 막으면 3번 검토를 못 한다.
# ──────────────────────────────────────────────────────────────────
[ -f "$MARK" ] || exit 0
[ -f "$PASS" ] && exit 0          # 관문을 통과했다

case "$FPATH" in
  */hankki/src/*|*/hankki/scripts/*) ;;
  *) exit 0 ;;
esac
case "$FPATH" in
  */docs/*|*_repro-*|*_shot-*|*_probe-*|*/scratchpad/*) exit 0 ;;
esac

cat >&2 <<'EOM'
🛑🛑 **설계 관문을 아직 안 지났다 — 새 파일을 만들기 «전»에 3번 검토한다.**

   📮 창업자 2026-09-04 = *"3번 다각도로 검토해서 가져와. 절대 땜빵식은 안돼. 절대원칙이야."*

   🚪 푸는 길 (하나만 하면 된다):
      node hankki/scripts/design-gate.mjs --무엇 "..." --사람 "..." --사고 "..." --규모 "..." \
        --잰것 "..." --잃던것 "..." --잃을것 "..."

   ⭐ 그 문이 보는 것 = ①diff 가 «숫자만» 바뀌었나(기계가 본다) ②세 각도에서 고칠 것이 나왔나
      ③실패했을 때 «잃는 것»의 모양이 바뀌었나
   ⛔ 통과 못 하면 새 파일을 만들지 말고 모자란 각도를 먼저 돈다.
   ✅ 문서·재현판·캡처판·이미 있는 파일 고치기는 이 훅이 «안» 막는다.
EOM
exit 2
