#!/bin/sh
# ❓❓ 「뭐 고를까?」 — 근거 없이 골라주지 못하게 그 자리에서 가로막는다.
#    (절대원칙 · 창업자 2026-09-20 = *"모르는건 모른다고 해."* · *"니가 지어내거나 대충 말하지 못하도록 코드로 막아"*)
#
# ⛔⛔ 그날 무슨 일이 났나 (2026-09-20 밤)
#    창업자가 인스타 광고 「행동 유도 버튼」을 뭘 고르냐고 «물었다».
#    나는 아무것도 안 찾아보고 「더 알아보기」라고 답했다. 그대로 광고가 돌았다.
#    창업자가 *"확실해?"* 하고 되물었을 때도 「캡처에 그렇게 적혀 있다」며 **확실하다고 했다** —
#    그 캡처에 그 글자가 있던 이유가 «내가 시켜서»인 걸 안 짚었다.
#    📮 창업자 = *"아니 물어볼때 근거없이 지어내는거면 내가 너한테 왜 물어봐?"* · *"네말을 못믿겠네 진짜"*
#
# 🌲 뿌리 = **모르면 「모르겠다」고 했어야 하는데 그냥 골라줬다.**
#    모른다고 했으면 창업자가 다른 데 물어보든 직접 정하든 했을 텐데,
#    내가 아는 척하는 바람에 **알아볼 기회까지 막았다.**
#
# ⚠️ 정직하게 — **이 훅은 「막지」 못한다.** 훅은 도구 호출을 막지 내가 «하는 말»은 못 막는다(규칙 26 과 같은 한계).
#    ✅ 대신 **고르라는 물음이 온 그 턴에** 세 갈래를 눈앞에 들이민다. 그게 이 장치가 하는 전부다.
#    ⛔ 그러니 「막아놨으니 괜찮겠지」로 읽지 말 것.
#
# ⛔ bash 변수명은 ASCII 로 (CLAUDE.md 규칙 24)
set -u
INPUT=$(cat 2>/dev/null || true)

# 「고르라는 물음」일 때만 뜬다 (시끄러운 게이트는 죽은 게이트)
# ⛔ 만들자마자 옛 상황으로 재 보니 «둘이 안 걸렸다» — 제일 중요한 자리였다.
#    ⑴ 「행동유도버튼 뭐하라고 했지?」 = 오늘 사고의 그 물음인데 「뭐하라고」가 잣대에 없었다
#    ⑵ 「진한보라가 예뻐? 연한보라가 예뻐?」 = 취향을 고르라는 물음인데 「예뻐?」가 없었다
#    📌 규칙 12 = 검사를 만들면 «옛 값으로 진짜 걸리는지» 먼저 돌려본다. 안 걸리면 내 가정이 틀린 것이다.
echo "$INPUT" | grep -qE '뭐로|뭘로|뭐하라|뭐했|뭐라고|어느|어떤|뭐가|무엇을|골라|고를|골랐|정해|정할|추천|나아|나을까|낫나|낫지|할까|괜찮나|괜찮아|맞아|맞나|맞지|확실|예뻐|어울리|좋을까|좋은지|좋은가|효과|나은지|어때' || exit 0

# 되묻는 말이면 더 세게 (오늘 두 번째 틀린 자리가 여기다)
AGAIN=0
echo "$INPUT" | grep -qE '확실|진짜|맞아\?|맞나|정말' && AGAIN=1

cat <<'MSG'
❓❓ **고르라는 물음이다 — 셋 중 «하나»로만 답한다.**

   ① 🔍 **찾아봤다** → 출처를 «같이» 댄다 (공식 원문·실측·파일:줄)
   ② 📂 **우리 기록에 있다** → `decided.mjs "<핵심어>"` 로 찾아 **어디 있는지 대고** 말한다
   ③ 🙅 **모른다** → **「모르겠다」고 말한다.** 그리고 «알아볼 길»을 준다

   ⛔⛔ **③ 을 부끄러워하지 않는다.** 그게 창업자가 나한테 물어볼 이유를 지키는 것이다.
      📮 창업자 = *"아니 물어볼때 근거없이 지어내는거면 내가 너한테 왜 물어봐?"*

   ⛔ 하지 말 것 = 「무난해 보여서」·「보통 이렇게 한다」·「이게 나을 거야」 **근거 없이 고르기**
   ⛔ 「내 생각엔」을 붙여도 «근거 없으면» 똑같다 — 창업자는 그걸 답으로 받는다.

   🌐 **내가 웹을 못 여는 주제면** (광고·정책·콘솔·남의 서비스) —
      ⛔ 「막혔다」로 끝내지 말고 **창업자가 퍼플렉시티·챗지피티에 붙여넣을 «물음 문장»을 써 준다.**
      ✅ 저장소·코드·우리 문서·계산·대조는 **내 일이다.**

   📌 갈라 적는다 = 「그때 그걸로 정했다」(기록)와 「그게 맞는 선택이다」(판단)는 **다른 말**이다.
MSG

if [ "$AGAIN" = "1" ]; then
cat <<'MSG2'

   🚨🚨 **되묻고 있다 — 여기가 2026-09-20 에 «두 번째로» 틀린 자리다.**
      그때 나는 「캡처에 그렇게 적혀 있다」며 **확실하다고 답했다.**
      ⛔ 그 캡처에 그 글자가 있던 이유가 **내가 시켜서**인 걸 안 짚었다.
      ✅ 되물음에 답할 땐 **«누가 정했는지»부터** 밝힌다 — 내가 골랐나, 창업자가 골랐나, 문서에 있던 값인가.
      ✅ 「확실하다」는 **출처를 댈 수 있을 때만** 쓴다.
MSG2
fi
exit 0
