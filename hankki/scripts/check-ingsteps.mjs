// 🔒 배포 게이트 — 「재료는 갈아끼웠는데 만드는 법엔 옛 재료가 남았나」
//
// ⛔⛔ 2026-08-10 창업자 폰 제보: *"위에는 초피 밑에는 국간장ㅠ"* (소고기 미역국)
//   재료 = 「초피액젓 2큰술 (없으면 일반 국간장)」 · 만드는 법 4번 = 「국간장 2큰술을 넣고…」
//   📌 **뿌리** = 「내 재료로 바꾸기」(창업자의 진짜 양념으로 교체)를 «재료 줄»에만 하고
//      «만드는 법»을 안 고쳤다. **읽는 사람은 뭘 넣어야 할지 모른다.**
//      실제로 넷이 그랬다 — 소고기 미역국 · 떡국 · 두부 들깨 버섯전골 · 7분 우삼겹 갈비탕.
//
// ⭐ 재는 것 = **재료 줄 «괄호 안» 대체품 이름이 만드는 법에 나오고, 정작 «주재료» 이름은 안 나올 때.**
//   재료 `A 2큰술 (없으면 B)` 에서 만드는 법이 B 를 부르면 어긋난 것이다.
//
// ⛔⛔ **처음 만든 판은 22건을 잡았는데 진짜는 4건이었다** — 「시끄러운 게이트는 죽은 게이트」.
//   나머지 18건은 **총칭**이라 문제가 아니었다:
//   · 재료 「아우노슈가 (일반설탕)」 → 만드는 법 「설탕」  ✅ 설탕은 아우노슈가의 총칭
//   · 재료 「진간장」 → 만드는 법 「간장」                ✅ 간장은 진간장의 총칭
//   ⭐ **순서에 브랜드를 쓰면 오히려 광고로 읽힌다** — 총칭으로 부르는 게 맞다.
//   ⛔ 반면 **초피액젓 ↔ 국간장은 총칭 관계가 아니라 «다른 재료»다.** 그래서 어긋남이다.
//   → 아래 `총칭` 표에 있는 짝만 봐준다.
import { basicRecipes } from '../src/data/basics.js'

// 「이건 총칭이라 봐준다」 — 총칭: [그 총칭으로 부를 수 있는 것들]
// ⚠️ 여기에 «다른 재료»를 넣지 말 것. 넣는 순간 이 게이트가 그 사고를 못 잡는다.
const 총칭 = {
  설탕: ['아우노슈가', '알룰로스', '백설탕', '황설탕'],
  간장: ['진간장', '국간장', '맛간장', '양조간장', '백간장'],
  액젓: ['초피액젓', '멸치액젓', '까나리액젓'],
  고춧가루: ['복이네먹거리 고춧가루'],
}
const 총칭인가 = (부른말, 주재료) => (총칭[부른말] || []).some((x) => 주재료.includes(x))

// 재료 줄 → { 주재료(괄호 밖), 대체품들(괄호 안) }
// ⛔⛔ **괄호가 다 «대체품»인 게 아니다** — 「(시판 콩국물 어떤 것이든)」·「(입맛따라 가감)」·
//    「(송송 썰기)」·「(양념장)」 처럼 **설명**인 괄호가 훨씬 많다.
//    그걸 다 대체품으로 치니 게이트가 22건 → 8건으로 줄여도 **여전히 전부 거짓 경보**였다.
// ⭐ **「없으면」이 붙은 괄호만 «대체품»으로 친다** — 그 말이 곧 「이게 없으면 저걸 넣어라」다.
//    이번 사고(초피액젓 ↔ 국간장) 넷이 전부 이 꼴이고, 거짓 경보는 하나도 안 남는다.
const 가르기 = (line) => {
  const s = String(line)
  const 괄호 = [...s.matchAll(/[（(]([^)）]*)[)）]/g)]
    .map((m) => m[1])
    .filter((t) => t.includes('없으면'))
    .join(' ')
  const 밖 = s.replace(/[（(][^)）]*[)）]/g, ' ')
  return { 주재료: 밖, 대체품: 괄호 }
}
// 대체품 문구에서 «재료 이름»만 추린다 — 「없으면」·「일반」 같은 말은 이름이 아니다.
const 이름들 = (문구) =>
  문구.split(/[\s,·/]+/)
    .map((w) => w.replace(/^(없으면|또는)$/, '').replace(/^일반/, '').replace(/\d.*$/, ''))
    .filter((w) => w.length >= 2)

let fail = 0
const 걸린것 = []
for (const r of basicRecipes) {
  const 순서 = (r.steps || []).join(' ')
  for (const line of r.ingredients || []) {
    const { 주재료, 대체품 } = 가르기(line)
    if (!대체품) continue
    for (const 옛 of 이름들(대체품)) {
      if (!순서.includes(옛)) continue          // 만드는 법이 대체품을 안 부른다 → OK
      if (총칭인가(옛, 주재료)) continue         // 「설탕」·「간장」 같은 총칭 → OK
      // 주재료의 «어느 낱말이든» 만드는 법에 있으면 OK
      // ⛔ 처음엔 «제일 긴 낱말 하나»만 봤다가 「자연누리 훈제오리」에서 브랜드(자연누리)를 골라
      //    멀쩡한 레시피를 잡았다 — 브랜드는 만드는 법에 안 쓰는 게 맞다(광고로 읽힌다).
      const 주낱말 = 주재료.split(/[\s,·/]+/).filter((w) => w.length >= 2 && !/^\d/.test(w))
      if (주낱말.some((w) => 순서.includes(w))) continue
      걸린것.push({ 제목: r.title, 재료: line.trim(), 옛 })
      fail++
    }
  }
}

console.log('\n🥄 「재료는 갈아끼웠는데 만드는 법엔 옛 재료가 남았나」 검사')
if (!fail) {
  console.log(`✅ 기본 레시피 ${basicRecipes.length}편 — 어긋난 곳 0\n`)
  process.exit(0)
}
console.log(`⛔ ${fail}건 — 만드는 법이 «괄호 안 대체품»을 부른다\n`)
for (const c of 걸린것) console.log(`   · ${c.제목} — 만드는 법의 「${c.옛}」   재료: ${c.재료}`)
console.log('\n   👉 만드는 법을 «재료에 적힌 주재료 이름»으로 고친다. 대체품은 재료 줄 괄호에만 둔다.\n')
process.exit(1)
