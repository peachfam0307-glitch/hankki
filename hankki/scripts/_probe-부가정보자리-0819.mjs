// 📋📋 «부가 정보 칸이 재료보다 위에 있나» — 레시피 편집 화면
//
// 📮📮 창업자 2026-08-16 = *"자동으로 한식 양식 종류 저장해주면 좋겠어.
//    솔직히 **맨날 까먹어 맨 아래 있어서 거기까지 잘 안보게돼**.."*
//    → 2026-08-19 방향 확정 = *"유저가 직접입력하게끔 **칸만 잘보이게** 두면좋겠어
//      (**2인분 시간도 위로 올리고**)"* · *"이것도 충돌안하게 잘짜야해"*
//
// ⭐⭐ **자동 분류는 «안» 한다 — 창업자가 스스로 접었고 그게 옳다.**
//    ⑴「구체어 먼저」 위반이 저장소에 **65곳**(2026-08-15 실측) — 자동으로 채우면 그게 유저 레시피에 박힌다
//    ⑵ `category` 실측값이 **열 가지**(한식99·양식17·일식6·국탕6·간식5·아시안3·밥3·반찬3·중식1·전골1)인데
//       고를 수 있는 칩은 **다섯**뿐이다(`theme.js` `CATEGORIES`) → 자동 분류가 «고를 수 없는 값»을 쓸 수 있었다
//    📌 창업자가 말한 「충돌」이 이것이다. 손으로 고르게 두면 이 위험이 통째로 사라진다.
//
// ⛔ 무엇이 문제였나 — 칸 순서가 이랬다:
//    제목 → 캡처 버튼 → 안내 카드 → **재료(7줄)** → **만드는 법(7줄)** → 카테고리 → 시간 → 인분 …
//    `EditorScreen.jsx` 주석 = *"부가 정보 — 캡처는 보통 제목+재료+만드는 법이 붙어 있어,
//    그걸 먼저 적고 나서 채우게 아래로 뺐다"* — **일부러** 뺀 것이고 이유도 있었다.
//    ⚠️ 그런데 «쓰는 사람»이 「거기까지 안 가게 된다」고 했다. **의도가 좋아도 결과가 그러면 진 것이다.**
//
// 🔢 이 판이 재는 것 = **「카테고리·조리시간·인분이 재료 칸보다 «위»에 있나」**
//    ⛔ 왜 브라우저로 안 재나 — 2026-08-19 에 실제로 해 봤더니 `stack-layer` 오버레이가
//       클릭을 가로채 편집 화면까지 가지 못했다. ＋ 레시피 «이름»으로 찾으면 시드가 바뀔 때 판이 죽는다.
//    ⭐ 그리고 창업자가 원하는 건 「보이는 순서」이고 그건 **소스 순서가 곧 답**이다.
//       실물은 고친 뒤 스크린샷으로 «내가 눈으로» 본다(규칙 21).
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(path.join(root, 'src/screens/EditorScreen.jsx'), 'utf8').split('\n')

const 찾기 = (re) => {
  for (let i = 0; i < src.length; i++) if (re.test(src[i])) return i + 1
  return -1
}
const 자리 = {
  캡처버튼: 찾기(/onClick=\{\(\) => pickOcr\('all'\)\}/),
  읽는중: 찾기(/\{\/\* 사진 읽는 중 — 칸 채우기 진행 표시/),
  제목: 찾기(/<label>제목<\/label>/),
  카테고리: 찾기(/<label>카테고리<\/label>/),
  조리시간: 찾기(/<label>조리시간/),
  인분: 찾기(/<label>인분<\/label>/),
  재료: 찾기(/<label[^>]*>재료 \(한 줄에 하나씩\)/),
  만드는법: 찾기(/<label[^>]*>만드는 법 \(한 줄에 한 단계\)/),
}

let bad = 0
const ok = (m) => console.log('  ✅', m)
const no = (m) => { bad++; console.log('  ⛔', m) }

console.log('📋 편집 화면 칸 자리(줄 번호)')
for (const [k, v] of Object.entries(자리)) console.log(`   ${k.padEnd(6)} ${v > 0 ? v + '줄' : '⛔ 못 찾았다'}`)
console.log('')

// ⛔ 하나라도 못 찾으면 «통과시키지 않는다» — 파서가 깨졌는데 초록불이면 아무것도 안 재는 판이다(규칙 18 ⓘ)
const 없는것 = Object.entries(자리).filter(([, v]) => v < 0).map(([k]) => k)
if (없는것.length) {
  console.error(`⛔ 칸을 못 찾았다: ${없는것.join(' · ')} — EditorScreen 모양이 바뀌었다. 위 정규식을 맞춰라.`)
  process.exit(1)
}

console.log('🔎 판정')
for (const k of ['카테고리', '조리시간', '인분']) {
  if (자리[k] < 자리.재료) ok(`${k} 이 재료 칸보다 «위»에 있다 (${자리[k]}줄 < ${자리.재료}줄)`)
  else no(`${k} 이 재료 칸보다 «아래»다 (${자리[k]}줄 > ${자리.재료}줄) — 재료 7줄·순서 7줄에 밀려 안 보인다`)
}
// 제목 바로 아래여야 «첫 화면»에 들어온다
if (자리.카테고리 > 자리.제목) ok(`카테고리가 제목(${자리.제목}줄) 아래에 있다 — 순서가 자연스럽다`)
else no('카테고리가 제목보다 위다 — 제목을 먼저 쓰게 두는 게 맞다')

// ⏳⏳ 「읽는 중」 진행 표시가 «캡처 버튼 바로 아래»에 있나 (2026-08-19 창업자)
//    📮 *"로딩느려질때 기다리라는 안내넣기로 했잖아. **2장이면 한장씩 읽으니까.
//       아무안내없이 기다리다 끌수도 있어**"*
//    ⛔⛔ 실제로 떨어져 나갔었다 — 캡처 버튼을 제목 위로 올렸는데 진행 표시는 제자리(63줄 아래)라
//       **누르고도 화면 위쪽엔 아무 표시가 없었다.** 창업자 걱정이 정확했다.
//    ⭐ 이 표시는 `ocr.busy` 일 때만 그려져 브라우저로는 «가만히» 두면 못 잰다 → 소스 순서로 지킨다.
if (자리.읽는중 > 자리.캡처버튼) ok(`「읽는 중」 표시가 캡처 버튼(${자리.캡처버튼}줄) 아래에 있다`)
else no('「읽는 중」 표시가 캡처 버튼보다 위다')
if (자리.읽는중 < 자리.제목) ok(`「읽는 중」 표시가 제목(${자리.제목}줄) «앞»에 있다 — 누르면 바로 눈에 든다`)
else no(`「읽는 중」 표시가 캡처 버튼에서 ${자리.읽는중 - 자리.캡처버튼}줄 떨어져 있다 — 누르고도 안 보인다`)

console.log('')
if (bad) {
  console.error(`❌ ${bad}개 — 📮 창업자 "맨날 까먹어 맨 아래 있어서 거기까지 잘 안보게돼"`)
  console.error('   👉 EditorScreen.jsx 에서 카테고리·조리시간·인분 묶음을 재료 칸 «위»로 올린다.')
  process.exit(1)
}
console.log('✅ 카테고리·조리시간·인분이 전부 재료 칸 위에 있다')
