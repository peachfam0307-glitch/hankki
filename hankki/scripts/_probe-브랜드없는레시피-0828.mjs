// 🔎 홍보물(스토어 스샷·인스타)에 쓸 «브랜드 없는» 레시피 찾기 — 2026-08-28
//
// 📮 창업자 = *"1번 레시피한장이면.. 예시에 브랜드이름 떡하니들어가있는데 풀무원. 오월햇살 이거 괜찮아??"*
//
// ⛔⛔ **앱 «안»은 안 건드린다** — 「브랜드 ＋ (대체품)」은 창업자가 정한 규칙이고 유저에겐 값어치다.
//    바꾸는 건 **홍보물에 «찍히는» 레시피 하나**뿐이다.
//
// ⭐ 잣대 = **「이건 브랜드다」 목록으로 찾지 않는다** — 목록은 반드시 빠뜨린다(오늘 「아우노슈가」를 놓쳤다).
//    대신 **「우리 규칙이 남긴 «흔적»」**으로 찾는다:
//    브랜드 줄은 규칙상 **반드시 «(대체품)» 괄호**를 달고 있다(⛔대체품 없는 브랜드 줄 금지 · CLAUDE.md).
//    → 「~ 어떤 것이든 / 또는 ~ / 일반 ~ / 시판 ~ / 브랜드 무관」이 붙은 줄 = **브랜드 줄로 본다.**
//    ＋ 안전망으로 **한글 고유명사 낌새**(2글자 이상 낱말이 재료 상식어가 아닌 것)도 같이 센다.
//
// 실행: cd /home/user/hankki/hankki && node scripts/_probe-브랜드없는레시피-0828.mjs
// 🏷 이름표 = 살아있는 도구
import { 레시피들 } from './recipe.mjs'
// ⏰ 「오늘(KST)」은 «한 곳»에서만 만든다(절대원칙 27) — ⛔여기서 직접 짜지 말 것
import { todayKST } from '../src/today.js'

// ⭐ 「(대체품)」 흔적 — 우리 규칙이 브랜드 줄에만 남기는 자국
const 대체품흔적 = /어떤\s*것이든|또는|브랜드\s*무관|일반\s*설탕|시판|대신|등\s*·/

// 흔한 재료·조리어는 브랜드로 보지 않는다(고유명사 낌새를 셀 때만 쓴다)
const 상식어 = new Set(`
돼지고기 소고기 닭고기 앞다리살 삼겹살 대패삼겹살 목살 다짐육 가슴살 안심 등심
양파 대파 쪽파 마늘 다진 생강 고추 청양고추 홍고추 당근 감자 애호박 호박 양배추 배추 무
버섯 표고 느타리 팽이 새송이 브로콜리 시금치 콩나물 숙주 부추 깻잎 상추 오이 토마토 방울토마토
두부 순두부 달걀 계란 우유 치즈 버터 생크림 요거트
고추장 된장 쌈장 간장 진간장 국간장 고춧가루 소금 후추 설탕 올리고당 물엿 식초 참기름 들기름
식용유 카레 미림 맛술 청주 소주 다시마 멸치 육수 참깨 통깨 김 미역 새우 오징어 조개 바지락
쌀 밥 면 소면 국수 라면 당면 떡 떡국떡 밀가루 부침가루 튀김가루 빵가루 전분
물 얼음 참치 스팸 햄 소시지 어묵 맛살 김치 단무지 유부 견과 아몬드 땅콩 잣 호두
큰술 작은술 컵 개 장 대 줌 알 모 인분 약간 조금 적당량 선택 g kg ml L cm
`.trim().split(/\s+/))

const 낱말들 = (s) => String(s).replace(/[()[\]·,~/]/g, ' ').split(/\s+/).filter(Boolean)

const 오늘 = todayKST()
const 결과 = []
for (const r of 레시피들()) {
  const 줄 = (r.ingredients || []).map(String)
  if (줄.length < 5) continue                       // 너무 짧으면 스샷이 허전하다
  // ⛔⛔ **아직 «안 열린» 편은 못 쓴다** — 스샷은 앱을 실제로 띄워 찍는다.
  //    2026-08-28 에 「국물 닭볶음탕」을 고를 뻔했는데  이 2026-12-14 였다.
  if (r.from && r.from > 오늘) continue
  const 의심 = []
  for (const l of 줄) {
    if (l.startsWith('[')) continue                 // [양념] 같은 머리
    if (대체품흔적.test(l)) { 의심.push(`${l}   ← (대체품) 흔적`); continue }
    // 고유명사 낌새 — 숫자·단위가 아니고 상식어도 아닌 두 글자 이상 한글
    for (const w of 낱말들(l)) {
      if (!/^[가-힣]{2,}$/.test(w)) continue
      if (상식어.has(w)) continue
      // 「~볶음」「~찌개」처럼 요리 이름 꼬리는 넘어간다
      if (/(볶음|찌개|국|탕|전|무침|조림|구이|찜|밥|죽|면)$/.test(w)) continue
      의심.push(`${l}   ← 낌새: ${w}`)
      break
    }
  }
  결과.push({ 제목: r.title, 줄수: 줄.length, 의심 })
}

// ⛔⛔ 「낌새」만으로 거르면 **141편 중 1편**만 남는다 — 상식어 목록이 반드시 모자라기 때문이다.
//    ⭐ 믿을 수 있는 신호는 **「(대체품) 흔적」 하나**다(우리 규칙이 브랜드 줄에만 남긴다).
//    → 그걸로 1차로 거르고, **재료 줄을 통째로 찍어 눈으로 판정한다**(절대원칙 21).
const 흔적있나 = (x) => x.의심.some((l) => l.includes('(대체품) 흔적'))
const 깨끗 = 결과.filter((x) => !흔적있나(x)).sort((a, b) => b.줄수 - a.줄수)

console.log(`\n🔎 기본 레시피 ${결과.length}편 중 «(대체품) 흔적 0» = ${깨끗.length}편\n`)
console.log('⭐ 재료가 많은 순 · 재료를 통째로 찍는다 — 눈으로 고른다\n')
for (const x of 깨끗.filter((x) => x.줄수 >= 7 && x.줄수 <= 14).slice(0, 6)) {
  const r = 레시피들().find((y) => y.title === x.제목)
  console.log(`\n── ${x.제목} (${x.줄수}줄) ${'─'.repeat(Math.max(0, 40 - x.제목.length * 2))}`)
  for (const l of r.ingredients || []) console.log(`   ${l}`)
}

console.log('\n⚠️ 지금 스샷이 쓰는 「콩국수」는 —')
const 콩 = 결과.find((x) => x.제목.includes('콩국수'))
if (콩) 콩.의심.forEach((l) => console.log('  ⛔', l))
console.log('\n📌 이 잣대는 «낌새»다 — 고른 편은 반드시 눈으로 한 번 더 본다(절대원칙 21).\n')
