// 📅📅 **SNS(수요일) 자리에 우주떡집 신상 둘을 앞세우고, 기존을 «한 주씩» 민다** (2026-09-08)
//
// 📮 창업자 = *"이게 따끈따끈한 sns 신상레시피 이번주1개 다음주1개할까"* → **「가」로 확정**
//    ＋ *"떡볶이는 25분"* ＋ *"아니야 그냥 그대로 해 11월 4일이후는 내가 또 줄게"*
//
// ⛔ 손으로 20군데를 고치지 않는다 — **못 찾으면 죽는다.** 그게 이 판의 존재 이유다.
//    (2026-08-02 두부 사고 = 조용히 실패한 치환. 여기선 한 줄이라도 못 찾으면 통째로 멈춘다)
// ⭐ 짝이 하나도 안 깨진다 — 20편 = 10주 × 2편. 빈 주도, 혼자 남는 편도 없다.
//
// 실행: cd /home/user/hankki/hankki && node scripts/_날짜밀기-SNS-0908.mjs [--진짜]
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const APP = new URL('..', import.meta.url).pathname
const 파일 = join(APP, 'src/data/basics.js')
const 진짜 = process.argv.includes('--진짜')

// 제목 ＋ «지금 날짜» → 새 날짜. ⭐ 위에서부터 «수요일 두 편씩»이다.
// ⛔⛔ 옛 날짜까지 같이 집는 이유 = **같은 제목이 두 편 있다.**
//    「닭볶음탕」이 SNS(10/21)와 우리 레시피(11/23)에 각각 있다 — 제목만 보면 엉뚱한 편을 민다.
//    📌 이 판을 처음 돌렸을 때 그걸로 죽었고, 죽은 게 맞다(조용히 틀리는 것보다 낫다).
const 새자리 = [
  ['명란 바지락 파스타', '2027-12-31', '2026-09-09'], ['애호박 국밥', '2026-09-09', '2026-09-09'],
  ['오리지날 떡볶이', '2027-12-31', '2026-09-16'], ['어남선생 두부조림', '2026-09-09', '2026-09-16'],
  ['어묵 당면볶음', '2026-09-16', '2026-09-23'], ['매콤 닭다리살 볶음', '2026-09-16', '2026-09-23'],
  ['돼지고기 고추장찌개', '2026-09-23', '2026-09-30'], ['어남선생 오징어볶음', '2026-09-23', '2026-09-30'],
  ['마늘 간장 닭날개조림', '2026-09-30', '2026-10-07'], ['야끼우동', '2026-09-30', '2026-10-07'],
  ['어남선생 15분 깍두기', '2026-10-07', '2026-10-14'], ['간장진미채볶음', '2026-10-07', '2026-10-14'],
  ['초간단 찜닭', '2026-10-14', '2026-10-21'], ['우렁 순두부 된장찌개', '2026-10-14', '2026-10-21'],
  ['닭볶음탕', '2026-10-21', '2026-10-28'], ['한판 탕수육', '2026-10-21', '2026-10-28'],
  ['어남선생 갈비치킨', '2026-10-28', '2026-11-04'], ['집에서 하는 족발', '2026-10-28', '2026-11-04'],
  ['계란후라이조림', '2026-11-04', '2026-11-11'], ['감자타코', '2026-11-04', '2026-11-11'],
]

let 글 = readFileSync(파일, 'utf8')
const 바뀐것 = []

for (const [제목, 옛날짜, 날짜] of 새자리) {
  // `title: '<제목>', from: '<옛날짜>'` 를 «통째로» 집는다 — 옛 날짜까지 봐야 같은 이름과 안 헷갈린다
  const 옛 = `title: '${제목}', from: '${옛날짜}'`
  const 몇군데 = 글.split(옛).length - 1
  if (몇군데 === 0) throw new Error(`⛔ 「${제목}」(${옛날짜}) 줄을 못 찾았다 — 판이 낡았다`)
  if (몇군데 > 1) throw new Error(`⛔ 「${제목}」(${옛날짜}) 이 ${몇군데}군데다 — 어느 걸 고칠지 모른다`)
  글 = 글.split(옛).join(`title: '${제목}', from: '${날짜}'`)
  바뀐것.push([제목, 옛날짜, 날짜])
}

// 📮 창업자 = *"떡볶이는 25분"* — 40분은 내가 낸 값이었다
const 시간찾기 = /(id: 'basic-uju-tteokbokki',[\s\S]{0,900}?)time: 40,/
if (!시간찾기.test(글)) throw new Error('⛔ 떡볶이의 time: 40 을 못 찾았다')
글 = 글.replace(시간찾기, '$1time: 25,   // 창업자 확정 2026-09-08 = "떡볶이는 25분"')

// ✅ 검수를 받았으니 표시를 붙인다 — 이게 없으면 「검수 안 된 편이 열린다」로 배포가 막힌다(절대원칙 28)
for (const id of ['basic-uju-tteokbokki', 'basic-uju-myeongran-bajirak-pasta']) {
  const 찾기 = new RegExp(`(id: '${id}',[\\s\\S]{0,600}?from: '\\d{4}-\\d{2}-\\d{2}',)`)
  if (!찾기.test(글)) throw new Error(`⛔ ${id} 의 from 줄을 못 찾았다`)
  if (new RegExp(`id: '${id}',[\\s\\S]{0,900}?review:`).test(글)) continue
  글 = 글.replace(찾기, `$1 review: '창업자',   // ✅ 2026-09-08 창업자 검수 (분량·메모 판정 반영)`)
}

if (!진짜) {
  console.log('🔎 미리보기 — 실제로 쓰려면 `--진짜`\n')
  바뀐것.forEach(([t, a, b]) => console.log(`   ${a} → ${b}   ${t}`))
  process.exit(0)
}
writeFileSync(파일, 글)
console.log(`✅ ${바뀐것.length}편의 날짜를 옮겼다 ＋ 떡볶이 25분 ＋ 검수 표시 둘`)
바뀐것.forEach(([t, a, b]) => console.log(`   ${a} → ${b}   ${t}`))
