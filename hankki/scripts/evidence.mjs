// 🛑 근거 관문 — «말하기 전에» 통과해야 하는 문.
//
// 왜 있나 (2026-08-02 프로덕션 반려 · 오늘 제일 큰 사고):
//   창업자: *"또 중요한 결정할때 서치안하고 니맘대로 대충 얘기하는거. 오늘 나 정말 너무너무 화가났어."*
//   구글이 «직접 말한» 반려 사유 두 개가 **둘 다 내가 만든 것**이었다.
//     ① 테스터 부탁 문구를 *"쓰지 말고 지우지만 말아달라"* 로 만들었다 → 깔아만 두면 「참여」로 안 세어진다
//     ② 웹만 배포하고 AAB 를 한 번만 올렸다 → 구글이 보는 건 AAB 뿐이라 「고쳐가며 테스트한 흔적」이 없다
//
// ⭐⭐⭐ 뿌리는 하나다 — **「확인 못 했다」고 스스로 적어놓고 그 위에서 창업자를 움직였다.**
//   CLAUDE.md 에 내 손으로 *"이 문장은 공식 문서에서 그대로 확인하지 못했다"* 라고 써놓고,
//   그 문구로 창업자에게 2주 동안 부탁을 시켰다.
//   창업자: *"제대로 알아보고 하라했잖아"* — 맞는 말이다. **모르고 어긴 게 아니라 알면서 어겼다.**
//   ⚠️ 그리고 **같은 날 새벽 네이버 커넥트에서 똑같이 했다**(§8에 「미확인」 써놓고 추천 ②번).
//      하루에 두 번 = 우연이 아니라 **구조다.** 그래서 구조로 막는다.
//
// ⭐ 이 도구의 핵심 규칙 딱 하나:
//      **모르는 게 남아 있으면 사람을 움직이는 제안을 못 낸다.**
//      낼 수 있는 건 「먼저 이걸 확인하자」뿐이다.
//
// 쓰는 법:
//   node scripts/evidence.mjs --주제 "프로덕션 재신청" --종류 창업자행동 \
//     --주장 "테스터에게 하루 한 번 열어달라고 부탁한다" \
//     --출처 "실물:창업자 콘솔 캡처 2026-08-02|반려 화면 전문" \
//     --출처 "url:https://support.google.com/googleplay/android-developer/answer/9845334|2026-08|공식" \
//     --리스크 "틀리면 14일 시계가 또 리셋된다 — 2주를 통째로 잃는다" \
//     --모르는것 없음
//
//   통과하면 붙여넣을 «근거 카드»가 나오고 도장이 찍힌다.
//   ⛔ 통과 못 하면 **아무 출력도 없다** — 그게 이 도구의 전부다.
import { writeFileSync, mkdirSync, existsSync } from 'node:fs'

const STAMP_DIR = '/tmp/hankki-evidence'

// ── 저장소가 «절대» 모르는 것 ────────────────────────────────────────
// 여기 걸리면 파일·검색만으로는 답이 안 나온다. **창업자 실물(캡처·화면)** 이 있어야 한다.
// 📌 2026-08-02 사고가 정확히 이 칸이었다 — Play Console 은 이 환경에서 403 이라 못 연다.
const OUTSIDE = [
  ['플레이|play console|콘솔|프로덕션|비공개 테스트|테스터|심사|반려|버전 코드|aab|스토어 등록', 'Play Console'],
  ['구글 폼|설문|의견 폼|응답', '구글 폼(문항·응답은 구글에 있다)'],
  ['스토어 페이지|스크린샷|피처그래픽|앱 설명|프로모', '스토어 등록정보'],
  ['파트너스|큐레이터|커넥트|제휴|어필리에이트|수수료', '제휴 프로그램 가입 화면'],
  ['사업자|세무|홈택스|통신판매|건보|부가세', '국세청·정부 민원 화면'],
  ['pg|토스|포트원|정산|계좌|결제', 'PG 관리자 화면'],
  ['특허로|kipris|출원|상표|등록료', '특허청 화면'],
  ['유튜브|팔로워|구독자|인스타', '창업자 계정 화면'],
]

// 공식·원문으로 쳐주는 곳. ⚠️ 개인 블로그·요약글은 **근거가 아니다**(오늘 새벽 네이버가 그거였다).
const OFFICIAL = /(support\.google\.com|developer\.android\.com|play\.google\.com|android-developers|\.go\.kr|law\.go\.kr|kipris|ftc\.go\.kr|partners\.coupang\.com|kurly\.com|naver\.com|apple\.com|w3\.org|developer\.mozilla)/i

const KINDS = ['창업자행동', '내작업', '사실보고']

// ── 인자 읽기 ────────────────────────────────────────────────────────
const argv = process.argv.slice(2)
const get = (k) => { const i = argv.indexOf(`--${k}`); return i >= 0 ? argv[i + 1] : undefined }
const getAll = (k) => argv.reduce((a, v, i) => (v === `--${k}` ? [...a, argv[i + 1]] : a), [])

const 주제 = get('주제')
const 주장 = get('주장')
const 종류 = get('종류')
const 출처 = getAll('출처').filter(Boolean)
const 리스크 = get('리스크')
const 모르는것 = get('모르는것')

const die = (title, lines) => {
  console.error(`\n⛔ ${title}\n`)
  for (const l of lines) console.error(`   ${l}`)
  console.error(`\n📌 이 문은 「대충 말하기」를 막으려고 창업자가 만들라고 한 것이다 (2026-08-03).`)
  console.error(`   통과 못 하면 **제안하지 말고**, 모르는 걸 먼저 확인하거나 창업자에게 실물을 요청한다.\n`)
  process.exit(1)
}

if (!주제 || !주장 || !종류) {
  die('빈칸이 있다 — 주제·주장·종류는 반드시 있어야 한다', [
    'node scripts/evidence.mjs --주제 "…" --종류 창업자행동|내작업|사실보고 \\',
    '  --주장 "…" --출처 "…" --출처 "…" --리스크 "…" --모르는것 "…"',
  ])
}
if (!KINDS.includes(종류)) die(`--종류 는 ${KINDS.join(' · ')} 중 하나여야 한다`, [`받은 값: ${종류}`])

// ── ① 출처가 «여러 경로» 인가 ────────────────────────────────────────
if (출처.length < 2) {
  die(`출처가 ${출처.length}개다 — 최소 2개, 서로 «다른 경로»여야 한다`, [
    '창업자 지시: *"다양한경로로 최신정보를 정확하게 서치후"*',
    '한 곳만 보면 그 한 곳이 틀렸을 때 통째로 틀린다.',
    '',
    '쓰는 꼴:  "url:<주소>|<날짜>|<공식·요약>"  ·  "file:<저장소 경로>"  ·  "실물:<창업자 캡처 설명>"',
  ])
}

const parsed = 출처.map((s) => {
  const [kind, ...rest] = s.split(':')
  const body = rest.join(':')
  const [ref, date, note] = body.split('|')
  return { kind: kind.trim(), ref: (ref || '').trim(), date: (date || '').trim(), note: (note || '').trim(), raw: s }
})
const bad = parsed.filter((p) => !['url', 'file', '실물'].includes(p.kind))
if (bad.length) die('출처 앞에 종류를 붙여야 한다 — url: / file: / 실물:', bad.map((b) => b.raw))

// ── ② 「공식·원문」 이 하나라도 있나 ──────────────────────────────────
const hasOfficial = parsed.some((p) => p.kind === '실물' || (p.kind === 'url' && OFFICIAL.test(p.ref)) || p.kind === 'file')
if (!hasOfficial) {
  die('전부 «남의 요약글» 이다 — 공식 원문이나 실물이 하나도 없다', [
    '⛔ 개인 블로그 요약은 근거가 아니다.',
    '   2026-08-03 새벽: 네이버 커넥트를 블로그 요약만 보고 "누구나 즉시 가입"이라 했다가 통째로 틀렸다.',
    '   창업자가 실제 화면을 열어보고 "인플루언서여야 되던데" 라고 잡아줬다.',
    '',
    '👉 공식 도메인 url · 저장소 file · 창업자 실물 캡처 중 하나는 반드시 있어야 한다.',
  ])
}

// ── ③ 저장소 밖 주제인데 «실물» 이 없나 ──────────────────────────────
const hay = `${주제} ${주장}`.toLowerCase()
const outHit = OUTSIDE.filter(([re]) => new RegExp(re, 'i').test(hay)).map(([, name]) => name)
const has실물 = parsed.some((p) => p.kind === '실물')
if (outHit.length && !has실물) {
  die(`이건 «저장소 밖» 이다 — 실물을 안 보고는 못 답한다`, [
    `걸린 것: ${[...new Set(outHit)].join(' · ')}`,
    '',
    '⭐ 창업자 절대원칙 (2026-08-03): **실물을 보지 않고 대답하는 거 금지.**',
    '   이 환경은 play.google.com·support.google.com 을 **못 연다(403)**.',
    '   파일에도 없고 내가 열 수도 없으면 — **아는 게 아니라 짐작하는 것**이다.',
    '',
    '📌 2026-08-02 반려가 정확히 이 칸이었다.',
    '   테스터 부탁 문구를 공식 문서로 확인 못 한 채 만들어 창업자를 2주 움직였고,',
    '   구글이 «테스터가 참여하지 않았다»로 반려했다.',
    '',
    '👉 할 일: **창업자에게 그 화면 캡처를 요청한다.** 받으면',
    '   --출처 "실물:창업자 <화면이름> 캡처 <날짜>|<거기 적힌 사실>" 로 다시 돌린다.',
    '   ⛔ 캡처 오기 전엔 제안하지 말 것. 「이 화면을 보여줘」까지만 말한다.',
  ])
}

// ── ④ 리스크를 봤나 ──────────────────────────────────────────────────
if (!리스크 || 리스크.trim().length < 10) {
  die('리스크 칸이 비었다', [
    '창업자 지시: *"리스크까지 알아보고 답해"*',
    '「이 말이 틀리면 무슨 일이 나는가」를 한 줄로 쓴다.',
    '2026-08-02 의 답 = **14일 시계가 리셋되고 2주를 통째로 잃는다.** 그걸 안 적어서 가볍게 갔다.',
  ])
}

// ── ⑤⭐ 모르는 게 남았는데 사람을 움직이려 하나 ──────────────────────
if (모르는것 === undefined) {
  die('--모르는것 칸이 아예 없다', [
    '⭐ 이 칸은 «비워두는 것»과 «없음이라고 쓰는 것»이 다르다.',
    '   빈칸 = 생각을 안 한 것. 「없음」 = 훑어보고 없다고 판단한 것.',
    '   반드시 --모르는것 "없음" 이라고 명시적으로 쓸 것.',
  ])
}
const 모름있음 = 모르는것.trim() !== '' && !/^(없음|없다|해당없음|-)$/.test(모르는것.trim())
if (모름있음 && 종류 === '창업자행동') {
  die('⭐⭐ 모르는 게 남았는데 «창업자를 움직이는» 제안이다 — 이게 오늘 사고의 정체다', [
    `모르는 것: ${모르는것}`,
    '',
    '⛔ **「확인 못 했다」고 적어놓고 그 위에서 사람을 움직이지 않는다.**',
    '   2026-08-02: 부탁 문구를 「공식 확인 못 함」이라 써놓고 창업자에게 2주 시켰다 → 반려.',
    '   2026-08-03 새벽: 「앱 가능 여부 미확인」이라 써놓고 네이버를 추천 ②번에 올렸다 → 틀림.',
    '   **하루에 두 번 = 우연이 아니라 구조다.**',
    '',
    '👉 둘 중 하나만 한다:',
    '   ① 모르는 걸 «먼저 확인»한다 (공식 원문 · 창업자 실물 캡처)',
    '   ② 종류를 --종류 사실보고 로 바꾸고 **「먼저 이걸 확인하자」까지만** 말한다',
    '      ⛔ 「아마 이럴 거니까 일단 해봐」 금지. 그게 2주를 태웠다.',
  ])
}

// ── 통과 ─────────────────────────────────────────────────────────────
const 날짜없음 = parsed.filter((p) => p.kind === 'url' && !p.date)
if (!existsSync(STAMP_DIR)) mkdirSync(STAMP_DIR, { recursive: true })
const key = 주제.replace(/[^가-힣a-zA-Z0-9]/g, '_').slice(0, 40)
writeFileSync(`${STAMP_DIR}/${key}.json`, JSON.stringify({ 주제, 주장, 종류, 출처: parsed, 리스크, 모르는것 }, null, 2))

const line = (p) => `- ${p.kind === '실물' ? '📸 실물' : p.kind === 'file' ? '📁 저장소' : OFFICIAL.test(p.ref) ? '🏛 공식' : '📰 요약'} — ${p.ref}${p.date ? ` (${p.date})` : ''}${p.note ? ` · ${p.note}` : ''}`

console.log(`
✅ 근거 관문 통과 — 「${주제}」

**${주장}**

**확인한 것** (${parsed.length}갈래)
${parsed.map(line).join('\n')}

**리스크** — ${리스크}
**모르는 것** — ${모르는것.trim() || '없음'}
`)
if (날짜없음.length) console.log(`⚠️ 날짜를 안 적은 출처 ${날짜없음.length}개 — 「최신인가」를 확인 못 했다는 뜻이다.\n`)
