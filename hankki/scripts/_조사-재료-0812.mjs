function 재료이름(줄) {
  let s = String(줄).trim()
  if (!s || /^\[.*\]$/.test(s) || /^[·※▶]/.test(s)) return null
  s = s.replace(/\([^)]*\)/g, ' ')                                   // (없으면 …) 곁말
  s = s.replace(꾸밈, ' ')
  // ⛔ 「1**과** 1/2큰술」 — 첫 판에 「와」로 잘못 써서 「1과1/2큰술」이 «재료 이름»으로 남았다
  s = s.replace(new RegExp(`[0-9¼½¾/.~-]+\\s*[과와]\\s*[0-9¼½¾/]+\\s*${단위}?`, 'g'), ' ')
  s = s.replace(new RegExp(`[0-9¼½¾/.~-]+\\s*${단위}\\b`, 'g'), ' ') // 「3토막」·「1/4포기」·「2인분」
  s = s.replace(new RegExp(`\\s[0-9¼½¾/.~-]+\\s*${단위}?\\s*$`, 'g'), ' ')
  s = s.replace(/\s*(또는|혹은|이나)\s.*$/, '')                      // 「A 또는 B」 → A
  s = s.replace(/\s+/g, ' ').trim()
  for (const b of 브랜드) if (s.startsWith(b + ' ')) { s = s.slice(b.length + 1).trim(); break }
  s = s.replace(상태, '')
  s = s.replace(/\s*(용|짜리)$/, '')
  s = s.replace(/[·,.]$/, '').replace(/\s+/g, ' ').trim()
  if (!s || s.length > 16) return null
  // ⛔ 수량만 남은 찌꺼기를 버린다 — 「1과1/2큰술」·「큰술」·「컵」
  if (new RegExp(`^[0-9¼½¾/.~과와\\s-]*${단위}?$`).test(s)) return null
  // ⛔ 「좋아하는 과일」처럼 «무엇이든 되는» 자리는 그림을 그릴 수 없다
  if (/좋아하는|여러\s*종류|아무거나|취향/.test(s)) return null
  return s
}

