  '간장 제육볶음': '굴',
  갈치국: '국,백',
  갈치조림: '국,참,백',
  '대패삼겹 달래덮밥': '참,백',
  전찌개: '국,참,백',
  두부참치찌개: '액,참',
  전복솥밥: '참,백',
  고등어조림: '국,백',
  샤브샤브: '백,연',
  '들기름 두부전골': '소금,백',
  황태국: '국,백',
