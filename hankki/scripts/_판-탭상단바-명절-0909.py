# 🔄 상단바 «기존 캐릭터»를 명절 컷으로 바꿔 끼운 시안
# 📮 창업자 2026-09-09 = "그 자리에 넣어야지 기존캐릭터떼고"
# ⭐ 실측 자리(_잰다-탭제목자리-0909.mjs) 그대로 — 짐작으로 밀지 않는다.
from PIL import Image

# 실측 (화면 비율 · 540x960)
자리 = {
 'rec':    {'왼':.1298,'오른':.2152,'위':.0136,'아래':.0616,'글왼':.2148},
 'log':    {'왼':.1298,'오른':.1925,'위':.0138,'아래':.0601,'글왼':.2000},
 'shop':   {'왼':.1294,'오른':.1928,'위':.0133,'아래':.0599,'글왼':.2056},
 'fridge': {'왼':.1293,'오른':.1929,'위':.0135,'아래':.0600,'글왼':.2056},
 'brag':   {'왼':.1292,'오른':.1838,'위':.0148,'아래':.0598,'글왼':.1926},
}
탭 = [('rec','레시피'),('log','일기'),('shop','장보기'),('fridge','냉장고'),('brag','레꾸자랑')]
컷 = {'cs': {'rec':'cs_b02','log':'duo101','shop':'hb09','fridge':'hb12','brag':'duo301'},
      'hw': {'rec':'hw_02','log':'hw_09','shop':'hw_13','fridge':'hw_03','brag':'hw_06'}}

import sys
키움 = float(sys.argv[1]) if len(sys.argv) > 1 else 1.0
for 갈래, 낼 in (('cs','추석'), ('hw','핼러윈')):
    칸h = 150
    판 = Image.new('RGB', (540, 칸h*5+6*6), (28,24,22))
    for i,(g,이름) in enumerate(탭):
        bg = Image.open(f'/tmp/tab_{이름}_위.png').convert('RGB').resize((540,960))
        칸 = bg.crop((0,0,540,칸h)).copy()
        z = 자리[g]
        L, R = round(z['왼']*540), round(z['오른']*540)
        T, B = round(z['위']*960), round(z['아래']*960)
        c = Image.open(f"/tmp/ed3/{컷[갈래][g]}.png").convert('RGBA')
        # 📮 창업자 2026-09-09 = "듀오도 귀여워 자리를 조금 마련해줄 순 없나?"
        #   ⭐ 세로로 «키운다». 상단바는 안 높아진다 — 지금 컷도 margin:-5px 로 이미 줄 밖으로 나와 있어서
        #      44px(줄 기여 34px) → 58px(margin -12px, 줄 기여 34px) 이면 «바 높이가 그대로»다.
        # 📮 창업자 2026-09-09 = "위에 안잘리게 잘해줘 (솔로컷)도"
        #   ⛔ 위로만 키우면 화면 «맨 위»에 닿아 잘린다 — 상단바 위 여백이 6px 밖에 안 남는다.
        #      그래서 «위 6px 을 넘지 않게» 자른다(듀오·솔로 다 같은 잣대).
        위한계 = 6
        h = min(round((B - T) * 키움), B - 위한계)
        w = round(c.width*h/c.height)
        T = B - h  # 아래를 맞추고 위로 키운다
        # 📮 창업자 2026-09-09 = "아주 살짝씩 아래로 내려도 될 것 같아 아주살짝. 머리가 닿아 다들"
        내림 = 5          # 다섯 탭 모두 같은 값 — 머리 위 틈이 6px → 11px
        T += 내림; B += 내림
        밀기 = max(0, w - (R - L))          # 새 컷이 넓으면 제목이 그만큼 오른쪽으로 밀린다
        # ① 제목 줄을 오른쪽으로 민다 (앱에선 flex 가 알아서 민다)
        if 밀기:
            줄 = 칸.crop((R, T-6, 540-밀기, B+6))
            칸.paste(줄, (R+밀기, T-6))
        # ② 기존 캐릭터 자리를 배경색으로 지운다
        # ⛔ x=6 은 «폰 테두리»라 상단바보다 어둡다 — 거기서 색을 떠서 칠했더니 네모가 보였다(창업자 2026-09-09 "왜 네모가 보여??").
        #    상단바 바탕은 x≈50~500 이 (244,241,234) 로 고르다 → 깨끗한 «세로 줄»을 통째로 옮겨 붙인다.
        지울폭 = (R + 밀기 + 2) - (L - 2)
        깨끗 = 칸.crop((300, T-4, 300+1, B+4)).resize((지울폭, (B+4)-(T-4)))
        칸.paste(깨끗, (L-2, T-4))
        # ③ 새 컷을 «같은 왼쪽·같은 높이»로 끼운다
        칸.paste(c.resize((w, h)), (L, T), c.resize((w, h)))
        판.paste(칸, (0, 6+i*(칸h+6)))
    꼬리 = '' if 키움 == 1.0 else f'-{round((B-T)*키움/(B-T)*44)}'
    판.save(f'/tmp/바꿔끼움-{낼}{꼬리}.png')
    판.resize((432, 판.height*432//540)).save(f'/tmp/바꿔끼움-{낼}{꼬리}-작게.jpg','JPEG',quality=55)
