// 🔬 [일회 · 2026-08-28] 확인 사살 — 원인이 «둘»이 겹친 것인가
//   ⑴ 빈 줄이 «흡수»된다 (앞줄이 「…고」로 열려 있으면 빈 줄을 먹고 계속 열려 있다)
//   ⑵ 「■」가 불릿 벗기기 목록에 없어 SEC_ING 방어막이 안 걸린다
import { __dbgMerge, __dbgMark } from './_dbg-parse-0828.js'
const 보기 = (이름, 글) => {
  const m = __dbgMerge(__dbgMark(글.split('\n')))
  const 붙었나 = m.some((l) => /해먹자고\s*[■▪]?\s*재료/.test(l))
  console.log(`${붙었나 ? '⛔ 붙었다' : '✅ 안 붙었다'}  ${이름}`)
  m.filter((l) => /해먹자고|재료/.test(l)).forEach((l) => console.log(`        ${JSON.stringify(l)}`))
}
보기('① 실물 그대로 (빈 줄 ＋ ■)', `남편이 오늘도 또 해먹자고\n\n■ 재료 (2-3인분 기준)\n파스타면 340g`)
보기('② ■ 를 없애면', `남편이 오늘도 또 해먹자고\n\n재료 (2-3인분 기준)\n파스타면 340g`)
보기('③ 빈 줄을 없애면 (■ 유지)', `남편이 오늘도 또 해먹자고\n■ 재료 (2-3인분 기준)\n파스타면 340g`)
보기('④ 둘 다 없애면', `남편이 오늘도 또 해먹자고\n재료 (2-3인분 기준)\n파스타면 340g`)
