#!/usr/bin/env node
// 💀 「앱이 정리됐다 되살아난다」 재현판 — 2026-09-04 (창업자 영상 두 편 실측)
//
// 📮 창업자 = *"뒤로가기해서 홈으로 가려고 하면 «앱을 열지 못했어요» 하면서 앱이 꺼져"*
//            ＋ *"유저가 가져오기했는데 이러면 어떻게해? 내 핸드폰용량문제인거야?"*
//
// 🔢 **실측 — 창업자 영상 두 편이 갈랐다** (2026-09-04 20:34 · 20:40)
//   · 1차(다른 앱 켜둔 채) = 최근앱으로 돌아올 때 안드로이드가 **「앱을 열지 못했어요」**
//   · 2차(모두 닫고)       = 멀쩡. 레시피까지 제대로 들어갔다
//   ⭐ ＝ **폰 탓이 아니라 «어느 폰에서든» 난다.** 안드로이드는 메모리가 빠듯하면 앱을 정리한다.
//      앱을 많이 켜두는 유저면 똑같이 겪는다 — 그러니 **우리가 감당해야 하는 상황**이다.
//
// 🌲 **본질 = 「무엇을 잃느냐」다.** 앱이 정리되는 건 우리가 못 막는다.
//   · 레시피 자체 = 이미 폰에 저장돼 있어 **안 잃는다**(그래서 껐다 켜면 보인다)
//   · **AI 다듬기 = 통째로 날아간다** — 20~60초 동안 «화면이 살아 있어야만» 받는 약속이라서.
//     ⛔⛔ 그런데 **열쇠(OCR)는 이미 나갔다.** 창업자 확정(2026-08-29) =
//        *"열쇠는 무조건 둘다 잘되어야해 돈이니까"* → 지금은 돈은 내고 값의 절반만 받는다.
//
// ⭐⭐ **이미 「만회하는 길」이 있다** — `RecipeDetailScreen:179` 는
//    「아직 못 다듬음」 표시(`tidyFail === 1`)가 있으면 그 레시피를 열 때 «저절로» 다시 다듬는다.
//    ⛔ 그런데 그 표시는 **AI 가 «실패했을 때만»** 남는다(`App.jsx`). 앱이 정리되면 표시를 남길 틈이 없다.
//    ✅ 그래서 **표시를 「끝났을 때」가 아니라 「시작할 때」 남긴다** — 새 장치가 아니라 «있는 길에 태우는 것».
//    📌 실패의 «모양»이 바뀐다(절대원칙 34): 「날아감」 → 「다음에 열면 저절로 채워짐」.
//
// 🧪 재는 것 — ⛔소스를 읽어서 «약속»을 잰다. 실제 앱을 죽여 보는 건 여기서 못 한다(정직하게).
//   ① AI 를 «시작할 때» 표시를 남기나            ← 이게 없으면 정리될 때 통째로 잃는다
//   ② 성공하면 그 표시를 지우나                  ← 안 지우면 다음에 또 다듬는다(뉴런 낭비)
//   ③ 「아직 못 다듬음」이면 «저절로» 만회하는 길이 살아 있나
//   ④ ⛔만회는 열쇠를 «안» 쓴다                  ← 유저가 두 번 물지 않게
//   ⑤ ⛔앱 켤 때 «전부» 훑지 않는다              ← 1만 명에서 뉴런이 터진다(절대원칙 32)
//
// 실행: node scripts/_repro-앱이정리됨-0904.mjs   (exit 0 = 통과)
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

let 나쁨 = 0
const 잰다 = (좋나, 이름, 덧 = '') => {
  if (!좋나) 나쁨++
  console.log('  ' + (좋나 ? '✅' : '⛔') + ' ' + 이름 + (덧 ? ' — ' + 덧 : ''))
}

const 뿌리 = join(dirname(fileURLToPath(import.meta.url)), '..')
const 읽기 = (p) => readFileSync(join(뿌리, p), 'utf8')
const 코드만 = (s) => s.split('\n').filter((줄) => !/^\s*(\/\/|\*|\/\*)/.test(줄)).join('\n')

const 앱 = 코드만(읽기('src/App.jsx'))
const 편집 = 코드만(읽기('src/screens/EditorScreen.jsx'))
const 상세 = 코드만(읽기('src/screens/RecipeDetailScreen.jsx'))

console.log('\n💀 앱이 정리됐다 되살아난다 — AI 다듬기를 «저장된 할 일»로\n')

// ── ① AI 를 «시작할 때» 표시를 남기나 ──────────────────────────────────────
//   ⭐ 잣대 = `tidyRecipe(` 를 부르기 «전»에 그 레시피에 표시를 쓰는 줄이 있나.
const 시작표시 = (원본) => {
  const i = 원본.indexOf('tidyRecipe(')
  if (i < 0) return false
  const 앞 = 원본.slice(Math.max(0, i - 900), i)
  return /tidyFail:\s*1/.test(앞)
}
잰다(시작표시(앱), '① 📱 공유로 들어온 길 — AI «시작할 때» 「아직 못 다듬음」을 남긴다',
  시작표시(앱) ? '남긴다' : '⛔안 남긴다 — 앱이 정리되면 통째로 잃는다')
잰다(시작표시(편집), '① 📝 편집 화면 길 — 〃',
  시작표시(편집) ? '남긴다' : '⛔안 남긴다 — 앱이 정리되면 통째로 잃는다')

// ── ② 성공하면 표시를 지우나 ──────────────────────────────────────────────
const 성공지움 = (원본) => /tidyFail:\s*0/.test(원본)
잰다(성공지움(앱), '② 📱 성공하면 그 표시를 지운다 (공유 길)',
  성공지움(앱) ? '지운다' : '⛔안 지운다 — 다음에 또 다듬어 뉴런을 낭비한다')
잰다(성공지움(편집), '② 📝 〃 (편집 화면 길)',
  성공지움(편집) ? '지운다' : '⛔안 지운다')

// ── ③ 만회하는 길이 살아 있나 ─────────────────────────────────────────────
잰다(/tidyFail\s*!==\s*1/.test(상세) && /tidyRecipe\(/.test(상세),
  '③ ↩️ 「아직 못 다듬음」이면 그 레시피를 열 때 «저절로» 만회한다')

// ── ④ ⛔만회는 열쇠를 안 쓴다 ─────────────────────────────────────────────
//   ⭐ 잣대 = 만회하는 자리에서 OCR(열쇠 쓰는 길)을 부르지 않는다.
const 만회자리 = 상세.slice(상세.indexOf('tidyFail'), 상세.indexOf('tidyFail') + 1500)
잰다(!/readTextFromImages|ocrImages|열쇠쓰기/.test(만회자리),
  '④ 💰 만회는 «열쇠를 안 쓴다» (유저가 두 번 물지 않는다)')

// ── ⑤ ⛔앱 켤 때 «전부» 훑지 않는다 ───────────────────────────────────────
//   📌 절대원칙 32 — 1만 명에서 「유저 수 × 레시피 수」로 늘면 죽는다.
//      만회는 «그 레시피를 열 때»만 돌아야 한다.
잰다(!/recipes\.(filter|forEach|map)\([^)]*tidyFail/.test(앱),
  '⑤ 📈 앱 켤 때 「못 다듬은 것」을 «전부» 훑지 않는다 (1만 명에서 터진다)')

console.log(나쁨 ? '\n⛔ ' + 나쁨 + '칸 빨간불 — 앱이 정리되면 AI 다듬기를 통째로 잃는다\n'
  : '\n✅ 앱이 정리돼도 «나중에 만회»된다\n')
process.exit(나쁨 ? 1 : 0)
