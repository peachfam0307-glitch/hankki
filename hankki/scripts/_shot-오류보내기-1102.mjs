// 👁️ 오류 보내기를 붙인 뒤 «홈»과 «오류 울타리 화면»을 실제로 띄워 본다 (2026-11-02)
import { chromium } from 'playwright'
import { spawn } from 'node:child_process'
const PORT = 4479, OUT = process.env.OUT || '/tmp/claude-0'
const srv = spawn('python3', ['-m', 'http.server', String(PORT), '--bind', '127.0.0.1', '--directory', 'dist'], { stdio: 'ignore' })
await new Promise((r) => setTimeout(r, 800))
const { SEED_COACH_SEEN } = await import('../src/coach.js')
const b = await chromium.launch(process.env.SMOKE_CHROMIUM ? { executablePath: process.env.SMOKE_CHROMIUM } : {})
const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
await c.addInitScript(SEED_COACH_SEEN)
await c.addInitScript(() => { localStorage.setItem('hankki:onboarded', '1'); localStorage.setItem('hankki:news:off', '1') })
const 보냄 = []; c.on('request', (r) => { if (r.url().includes('/error')) 보냄.push(r.url()) })
const p = await c.newPage(); const 에러 = []; p.on('pageerror', (e) => 에러.push(e.message))
await p.goto(`http://127.0.0.1:${PORT}/`, { waitUntil: 'networkidle' }); await p.waitForTimeout(1500)
await p.screenshot({ path: `${OUT}/눈-홈.png` })
// 일부러 오류를 던져 본다 — ⏩ 2026-11-05 켜짐=true 뒤로는 «나가야» 한다(받는 워커는 이 주소(127.0.0.1)를 403 으로 막는다 — 창업자 폰은 안 울린다)
await p.evaluate(() => { setTimeout(() => { throw new Error('눈검사 일부러') }, 0); Promise.reject(new Error('눈검사 약속')) })
await p.waitForTimeout(2800)   // 📦 2026-11-06 부터 2초 모아 «한 번에» 보낸다
console.log(`pageerror ${에러.length}개(일부러 던진 것 포함) · /error 로 나간 요청 ${보냄.length}개 (켜짐이면 «딱 1개» — 둘이 한 묶음)`)
if (보냄.length !== 1) { console.log('⛔ 묶음이 안 됐다'); process.exit(1) }
// 🔕 통계를 끈 폰은 «하나도» 안 나가야 한다(방침 6-2 「같은 스위치로 멈춥니다」)
const c2 = await b.newContext({ viewport: { width: 390, height: 844 } })
await c2.addInitScript(SEED_COACH_SEEN)
await c2.addInitScript(() => { localStorage.setItem('hankki:onboarded', '1'); localStorage.setItem('hankki:news:off', '1'); localStorage.setItem('hankki:stats:off', '1') })
const 꺼진보냄 = []; c2.on('request', (r) => { if (r.url().includes('/error')) 꺼진보냄.push(r.url()) })
const p2 = await c2.newPage(); p2.on('pageerror', () => {})
await p2.goto(`http://127.0.0.1:${PORT}/`, { waitUntil: 'networkidle' }); await p2.waitForTimeout(1200)
await p2.evaluate(() => { setTimeout(() => { throw new Error('눈검사 통계끔') }, 0) })
await p2.waitForTimeout(800)
console.log(`통계 끈 폰 /error 요청 ${꺼진보냄.length}개 (0이어야)`)
await b.close(); srv.kill()
process.exit(보냄.length && !꺼진보냄.length ? 0 : 1)
