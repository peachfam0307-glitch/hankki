// 🧩 [반영됨 · 2026-08-21] 「점 없는 번호」 때문에 걸음이 끊기고 번호가 남던 것
//
// 📮 창업자 폰 캡처(순살찜닭 · «자기가 담은» 레시피) —
//    STEP 1 = 「닭다리살은 씻지 않고 끓는물에 10분 데친 뒤」  ← 문장이 «중간»에서 끝났다
//    STEP 4 = 「**3** 10분 뒤 불린 당면, 떡, 대파를 …」       ← 걸음 번호 「3」이 «글자로» 남았다
// 📮 창업자 = *"나는 내가 직접한거라 엉망인데 **유저꺼에서는 어떻게 보이는지 모르겠어.. 테스트가 안돼**"*
// 📮 ＋ *"**네가 고쳐도 나한테 반영이 안되니까..**"*  ← ⭐규칙 18 ⓙ (이미 저장된 폰)
// 📮 ＋ *"**좋아 이런 디테일이 중요해**"*
//
// ⭐⭐ **증상 둘이 «한 뿌리»였다** — `STEP` 정규식이 번호 뒤에 «점·괄호»를 요구했다(`1.` `1)`).
//    사람들은 점 없이 **「1 」「2 」「3 」** 으로도 쓴다 → 파서 눈엔 번호가 아니라 그냥 글자.
//    ⑴ 번호가 본문에 남고  ⑵ 새 걸음의 시작으로 안 읽혀 **앞 걸음이 다음 걸음을 삼킨다.**
//
// ⭐ 이 검사의 심장 = **「사람이 매긴 번호를 파서가 «번호로» 보나」**
//    ⛔ 흉내가 아니다 — 앱이 쓰는 그 모듈(`../src/parseRecipe.js`)을 그대로 부른다(절대원칙 30).
//
// ⛔⛔ **아직 «안» 풀린 것 = 이미 저장된 레시피**(아래 ③). 파서는 «앞으로 담는 것»만 고친다.
//
// 실행: cd /home/user/hankki/hankki && node scripts/_repro-내레시피걸음-0821.mjs
import { parseRecipeText } from '../src/parseRecipe.js'

let 실패 = 0
const chk = (이름, ok, 덧 = '') => { console.log(`  ${ok ? '✅' : '⛔'} ${이름}${덧 ? ` — ${덧}` : ''}`); if (!ok) 실패++ }
const 걸음보기 = (steps) => steps.forEach((s, i) => console.log(`       ${i + 1}. ${s}`))

// ─────────────────────────────────────────────────────────────
// ① 창업자 캡처와 «같은 모양» — 점 없는 번호 ＋ 줄바꿈으로 잘린 문장
//    ⚠️ 창업자 원문 자체는 우리가 못 본다. 캡처에 «남은 글자»로 되짚은 모양이다.
// ─────────────────────────────────────────────────────────────
console.log('\n① 점 없는 번호 (창업자 캡처 모양)')
const A = parseRecipeText(`순살찜닭

재료
닭다리살 600g
당면 100g
감자 2개

만드는 법
1 닭다리살은 씻지 않고 끓는물에 10분 데친 뒤
깨끗이 씻어 냄비에 넣고
2 감자, 당근, 양파는 큼직하게 잘라줘요
3 10분 뒤 불린 당면, 떡, 대파를 넣고 버무리면서 5분 졸여주면 완성이에요`)
걸음보기(A.steps)
chk('걸음이 3개다 (번호 매긴 대로)', A.steps.length === 3, `${A.steps.length}개`)
chk('걸음 앞에 «번호가 글자로» 안 남는다', !A.steps.some((s) => /^\d{1,2}\s/.test(s)))
chk('2번 걸음이 1번에 안 삼켜졌다', A.steps.some((s) => s.startsWith('감자')))

// ─────────────────────────────────────────────────────────────
// ② ⛔ 넓히면 «안 되는» 자리 — 숫자로 시작한다고 다 번호가 아니다
//    ⭐ 「이어지는 번호가 둘 이상」이 잣대라서 아래는 안 걸린다
// ─────────────────────────────────────────────────────────────
console.log('\n② ⛔ 숫자로 시작하지만 «번호가 아닌» 것')
const B = parseRecipeText(`간장 소스

재료
간장 3큰술

만드는 법
볼에 간장을 넣어요.
3 큰술 넣고 잘 저어요.`)
걸음보기(B.steps)
chk('「3 큰술」이 안 잘린다', B.steps.some((s) => s.includes('3 큰술') || s.includes('3큰술')), '단위 뒤는 후보에서 뺀다')

const C = parseRecipeText(`불고기

만드는 법
2 인분 기준이에요.
고기를 양념에 재워요.`)
걸음보기(C.steps)
chk('「2 인분 기준」이 안 잘린다', C.steps.some((s) => s.includes('2 인분') || s.includes('2인분')))

// ─────────────────────────────────────────────────────────────
// ③ ⛔ 아직 못 고치는 것 — 「이미 저장된 걸음」을 도로 이어붙여 다시 돌리기
//    ⭐ 번호는 «담을 때» 떼어내므로 저장된 글엔 안 남는다 → 되돌릴 실마리가 없다.
//    📌 그래서 「다시 정리하기」 단추만으로는 창업자 폰이 «안» 고쳐진다.
//       이건 «실패»가 아니라 **아직 안 푼 자리**라 세지 않는다. 다만 조용히 지나가지도 않는다.
// ─────────────────────────────────────────────────────────────
console.log('\n③ ⏳ 이미 저장된 걸음을 다시 돌리면 (아직 안 푼 자리)')
const D = parseRecipeText(['만드는 법', ...A.steps].join('\n'))
걸음보기(D.steps)
console.log(`  ${D.steps.length === A.steps.length ? '✅' : '⏳'} 걸음 수 유지 — ${A.steps.length} → ${D.steps.length}`)
console.log('     📌 줄면 = 번호가 없어져 짧은 걸음이 앞에 붙는 것. 되살리려면 «원문»을 남겨 둬야 한다.')

console.log(`\n${실패 ? '⛔' : '✅'} ${실패 ? `실패 ${실패}칸` : '전부 통과'}\n`)
process.exit(실패 ? 1 : 0)
