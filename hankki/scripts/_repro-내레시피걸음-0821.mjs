// 🧩 [재현 · 2026-08-21] 「내 레시피」 걸음이 «중간에서 끊기고 번호가 남는» 것
//
// 📮 창업자 폰 캡처(순살찜닭 · STEP 1·2·4) —
//    STEP 1 = 「닭다리살은 씻지 않고 끓는물에 10분 데친 뒤」   ← 문장이 «중간»에서 끝났다
//    STEP 4 = 「**3** 10분 뒤 불린 당면, 떡, 대파를 …」        ← 걸음 번호 「3」이 «글자로» 남았다
// 📮 창업자 = *"나는 내가 직접한거라 엉망인데 **유저꺼에서는 어떻게 보이는지 모르겠어.. 테스트가 안돼**"*
// 📮 ＋ *"**네가 고쳐도 나한테 반영이 안되니까..**"*  ← ⭐이게 제일 큰 말이다(규칙 18 ⓙ)
//
// ⭐⭐ **문제가 «셋»이고 고치는 자리가 다 다르다**
//    ① 파서가 잘못 쪼갠다        → 고치면 «앞으로 담는 것»만 좋아진다
//    ② 이미 저장된 게 망가져 있다 → ①로는 «안» 고쳐진다. 되살리는 길이 따로 있어야 한다
//    ③ 유저 것이 어떻게 보이는지 볼 방법이 없다 → 이 판이 그 자리다
//
// ⭐ 이 판이 재는 것 = **⑴지금 파서가 진짜로 그렇게 쪼개나(재현) ⑵망가진 걸 되살릴 수 있나**
//    ⛔ 흉내가 아니다 — **앱이 쓰는 그 모듈**(`../src/parseRecipe.js`)을 그대로 부른다(절대원칙 30).
//
// 실행: cd /home/user/hankki/hankki && node scripts/_repro-내레시피걸음-0821.mjs
import { parseRecipeText } from '../src/parseRecipe.js'

const 줄 = (s) => console.log(s)
const 보기 = (제목, steps) => {
  줄(`\n  ${제목} — ${steps.length}걸음`)
  steps.forEach((s, i) => 줄(`    ${String(i + 1).padStart(2)}. ${s}`))
}

// ─────────────────────────────────────────────────────────────
// ① 재현 — 창업자가 실제로 붙여넣었을 «모양»을 그대로 만든다
//    ⭐ 핵심 두 가지 = ⓐ번호가 «점 없이» 맨 앞에 온다(1 2 3) ⓑ한 문장이 줄바꿈으로 잘린다
//    ⚠️ 창업자 원문 자체는 우리가 못 본다 — 캡처에 «남은 글자»로 되짚은 것이다.
//       그래서 이 판은 「창업자 것을 복원」하는 게 아니라 **「파서가 이 모양에 어떻게 반응하나」**를 잰다.
// ─────────────────────────────────────────────────────────────
const 붙여넣은_글 = `순살찜닭

재료
닭다리살 600g
당면 100g
떡 100g
대파 1대
감자 2개
당근 1/2개
양파 1개

만드는 법
1 닭다리살은 씻지 않고 끓는물에 10분 데친 뒤
깨끗이 씻어 냄비에 넣고
2 감자, 당근, 양파는 큼직하게 잘라줘요
3 10분 뒤 불린 당면, 떡, 대파를 넣고 버무리면서 5분 졸여주면 완성이에요`

const r = parseRecipeText(붙여넣은_글)
보기('① 지금 파서가 쪼갠 결과', r.steps)

// 🔎 캡처에서 눈으로 본 두 증상을 «글자로» 찾는다
const 번호남음 = r.steps.filter((s) => /^\d{1,2}\s/.test(s))
const 끊긴꼬리 = r.steps.filter((s) => /(뒤|후|다음|고|며|서|면)\s*$/.test(s))

줄('')
줄(`  🔢 걸음 앞에 «번호가 글자로» 남은 것 = ${번호남음.length}개`)
번호남음.forEach((s) => 줄(`     ⛔ ${s}`))
줄(`  🔢 문장이 «중간에서» 끝난 것 = ${끊긴꼬리.length}개`)
끊긴꼬리.forEach((s) => 줄(`     ⛔ ${s}`))

// ─────────────────────────────────────────────────────────────
// ② 되살리기 — 「이미 저장된 걸음」을 도로 이어붙여 다시 돌리면 복구되나
//    ⭐ 이게 되면 창업자 폰의 «이미 망가진» 레시피도 단추 하나로 고칠 수 있다.
//    ⚠️ 원문은 안 남아 있다 — 그래서 «걸음들을 이어붙인 것»이 우리가 가진 전부다.
// ─────────────────────────────────────────────────────────────
const 저장된_걸음 = r.steps
const 도로이어붙임 = ['만드는 법', ...저장된_걸음].join('\n')
const r2 = parseRecipeText(도로이어붙임)
보기('② 걸음을 도로 이어붙여 다시 돌린 결과', r2.steps)

const 번호남음2 = r2.steps.filter((s) => /^\d{1,2}\s/.test(s))
const 끊긴꼬리2 = r2.steps.filter((s) => /(뒤|후|다음|고|며|서|면)\s*$/.test(s))
줄('')
줄(`  🔢 되살린 뒤 — 번호 남음 ${번호남음2.length}개 · 끊긴 꼬리 ${끊긴꼬리2.length}개`)

줄('\n⭐ 읽는 법')
줄('   · ①에 ⛔가 있으면 = 창업자가 본 그 증상을 «여기서도» 재현한 것이다')
줄('   · ②가 ①보다 나아지지 않으면 = 「다시 정리하기」 단추로는 못 고친다 → 다른 길을 찾아야 한다')
줄('   · ⛔ 둘 다 «지금 파서»로 잰 값이다. 파서를 고치면 다시 돌려야 한다')
