#!/usr/bin/env node
// 🪦 클라우드 «무덤» 재현판 — 2026-09-04
//
// 📮 창업자 = *"클라우드 무덤 만들어줘"*
//
// ⭐⭐ **이 판이 지키는 한 줄 = 「지운 것은 «다른 기기에서도» 지워진 채로 있다」.**
//    ⛔ 합치기(`syncMerge.js`)는 **절대 안 지운다** — 그게 「잃지 않는다」의 값이다.
//       그 대신 «지웠다»는 표시가 있어야 지울 수 있다. 표시가 없으면 **좀비가 영원히 남는다.**
//    ⛔⛔ 무덤을 **폰에만** 두면 못 막는다 — 패드가 자기 것을 올려 **되살리기** 때문이다.
//       그래서 무덤은 **클라우드에도** 있어야 한다. 그게 이 파일이다.
//
// 🧪 재는 것 아홉 (설계 관문에서 세 각도로 나온 것 그대로)
//   ① 지우면 무덤이 남는다 · ② ⭐**무덤을 «먼저» 쓰고 그다음 문서를 지운다**
//   ③ ⭐**무덤 쓰기가 실패하면 «지우지 않는다»** (지금과 같아질 뿐 나빠지지 않는다)
//   ④ 무덤이 다른 기기에서 읽힌다 · ⑤ 무덤이 있으면 합치기가 그 편을 지운다
//   ⑥ ⭐**지운 뒤 «다른 기기가 고쳤으면» 되살린다** (사람이 다시 손댄 게 더 최근 뜻이다)
//   ⑦ 90일 지난 무덤은 청소된다 · ⑧ 무덤은 «문서 하나»에 담는다(읽기 1건)
//   ⑨ ⛔무덤에 «제목»을 안 남긴다 (id 만)
//
// 📐 설계 = `docs/폰패드-자동동기화-설계-2026-09-04.md` §3

let 나쁨 = 0
const 잰다 = (좋나, 이름, 덧 = '') => {
  if (!좋나) 나쁨++
  console.log(`  ${좋나 ? '✅' : '⛔'} ${이름}${덧 ? ` — ${덧}` : ''}`)
}

// ── 가짜 클라우드 ────────────────────────────────────────────────────────
//   ⭐ 파이어베이스 없이 전부 돌린다 — 판은 어디서 돌아도 같아야 한다.
const 클라우드 = new Map()
const 발자국 = []   // ⭐ «순서»를 재려고 남긴다(②가 순서 문제다)
const 가짜 = {
  async 읽기 (열쇠) { const v = 클라우드.get(열쇠); return v === undefined ? null : JSON.parse(JSON.stringify(v)) },
  async 쓰기 (열쇠, 값) { 발자국.push('쓰기:' + 열쇠); 클라우드.set(열쇠, JSON.parse(JSON.stringify(값))); },
  async 지우기 (열쇠) { 발자국.push('지우기:' + 열쇠); 클라우드.delete(열쇠) },
}
const 못쓰는가짜 = { ...가짜, async 쓰기 (열쇠) { 발자국.push('쓰기실패:' + 열쇠); throw new Error('못 씀') } }

let 모듈
try { 모듈 = await import('../src/syncGrave.js') } catch {
  console.log('\n⛔⛔ `src/syncGrave.js` 가 아직 없다 — **이 판이 먼저다.**\n')
  process.exit(1)
}
const { 묻기, 무덤읽기, 무덤청소, 무덤적용, _창고물리기, 무덤칸 } = 모듈
_창고물리기(가짜)

console.log('\n🪦 클라우드 무덤 — 「지운 것은 다른 기기에서도 지워진 채로」\n')

// ① 지우면 무덤이 남는다  ／ ② ⭐순서 = 무덤 «먼저», 문서는 그다음
발자국.length = 0
// ⭐ 일부러 «제목까지» 넘긴다 — 무덤이 그걸 «안 받는지»를 재려면 넘겨봐야 한다.
//    🧪 [2026-09-04] 처음엔 제목 없이 넘겨서 «제목을 넣게 고쳐도 판이 안 죽었다» — 헛돌던 칸이다.
const r1 = await 묻기([{ 갈래: 'recipes', id: 'u-zombie', title: '항정살조림', 본문: '내 일기' }], { 지운때: 5000 })
잰다(r1?.됐나 === true, '① 지우면 무덤이 남는다', r1?.됐나 ? '남았다' : '⛔못 남겼다')
const 무덤먼저 = 발자국.findIndex((x) => x.startsWith('쓰기:' + 무덤칸))
const 지우기나중 = 발자국.findIndex((x) => x.startsWith('지우기:'))
잰다(무덤먼저 >= 0 && (지우기나중 === -1 || 무덤먼저 < 지우기나중),
  '② ⭐ 무덤을 «먼저» 쓰고 그다음 문서를 지운다', 발자국.join(' → ') || '(없음)')

// ④ 다른 기기에서 읽힌다  ／ ⑧ 문서 «하나»에 담긴다  ／ ⑨ 제목 안 남긴다
const 무덤들 = await 무덤읽기()
잰다(무덤들.length === 1 && 무덤들[0].id === 'u-zombie', '④ 무덤이 다른 기기에서 읽힌다')
잰다(클라우드.size === 1, '⑧ 무덤은 «문서 하나»에 담긴다 (읽기 1건)', `문서 ${클라우드.size}개`)
const 무덤글 = JSON.stringify([...클라우드.values()])
잰다(!무덤글.includes('항정살') && !무덤글.includes('title'),
  '⑨ ⛔무덤에 «제목»을 안 남긴다 (id 만)')

// ③ ⭐ 무덤 쓰기가 실패하면 «지우지 않는다»
발자국.length = 0
_창고물리기(못쓰는가짜)
const r2 = await 묻기([{ 갈래: 'recipes', id: 'u-x' }], { 지운때: 6000 })
잰다(r2?.됐나 === false && !발자국.some((x) => x.startsWith('지우기:')),
  '③ ⭐ 무덤을 못 쓰면 «문서도 안 지운다»', 발자국.join(' → ') || '(아무것도 안 함)')
_창고물리기(가짜)

// ⑤ 무덤이 있으면 합치기가 그 편을 지운다 (＝합치기와 «같은 잣대»를 쓴다)
const { 합치기 } = await import('../src/syncMerge.js')
const 무덤목록 = await 무덤읽기()
const 합쳐진것 = 합치기({
  내것: { recipes: [{ id: 'u-keep', title: '남는 편', 고친때: 1 }] },
  받은것: { recipes: [{ id: 'u-zombie', title: '좀비', 고친때: 1000 }] },
  무덤: 무덤목록,
})
잰다(!(합쳐진것.recipes || []).some((r) => r.id === 'u-zombie'),
  '⑤ 무덤이 있으면 합치기가 그 편을 지운다')
잰다((합쳐진것.recipes || []).some((r) => r.id === 'u-keep'), '  ⑤-b 무덤에 없는 편은 «그대로» 남는다')

// ⑥ ⭐⭐ 지운 뒤 «다른 기기가 고쳤으면» 되살린다
//    사람이 다시 손댄 것이 «더 최근 뜻»이다. 지운때(5000) < 고친때(9000)
const 되살아나야 = 무덤적용(
  [{ id: 'u-zombie', title: '좀비', 고친때: 9000 }],
  무덤목록, 'recipes',
)
잰다(되살아나야.length === 1, '⑥ ⭐ 지운 «뒤»에 고친 편은 되살린다 (사람이 다시 손댄 것이 이긴다)',
  되살아나야.length ? '되살아났다' : '⛔지워졌다')
const 지워져야 = 무덤적용(
  [{ id: 'u-zombie', title: '좀비', 고친때: 1000 }],
  무덤목록, 'recipes',
)
잰다(지워져야.length === 0, '  ⑥-b 지우기 «전»에 고친 편은 그대로 지워진다')

// ⑥-c ⭐⭐ **합치기와 무덤이 «같은 답»을 내나** — 잣대가 갈리면 하나는 반드시 틀린 값이다
//    🧪 [2026-09-04] 실제로 갈려 있었다 — 같은 상황에서 합치기는 «지우고» 무덤적용은 «되살렸다».
//       판이 둘을 따로 재고 있어서 못 잡았다. 그래서 «맞대어» 재는 칸을 넣는다.
for (const [고친때, 뭐라야] of [[9000, 1], [1000, 0]]) {
  const 합 = (합치기({ 내것: { recipes: [] }, 받은것: { recipes: [{ id: 'u-zombie', 고친때 }] }, 무덤: 무덤목록 }).recipes || []).length
  const 무 = 무덤적용([{ id: 'u-zombie', 고친때 }], 무덤목록, 'recipes').length
  잰다(합 === 무 && 합 === 뭐라야,
    `  ⑥-c 합치기와 무덤이 «같은 답»을 낸다 (고친때 ${고친때})`,
    `합치기 ${합 ? '되살림' : '지움'} · 무덤 ${무 ? '되살림' : '지움'}`)
}

// ⑦ 90일 지난 무덤은 청소된다
const 옛무덤 = [
  { 갈래: 'recipes', id: 'old', 지운때: Date.now() - 100 * 24 * 3600 * 1000 },
  { 갈래: 'recipes', id: 'new', 지운때: Date.now() - 1 * 24 * 3600 * 1000 },
]
const 청소된것 = 무덤청소(옛무덤)
잰다(청소된것.length === 1 && 청소된것[0].id === 'new',
  '⑦ 90일 지난 무덤은 청소된다', `${청소된것.length}개 남음`)

console.log(나쁨 ? `\n⛔ ${나쁨}칸 실패\n` : '\n✅ 지운 것은 다른 기기에서도 지워진 채로 있다 — 무덤이 먼저, 실패하면 안 지운다\n')
process.exit(나쁨 ? 1 : 0)
