// 만드는 법이 «해요체»로 나가는지 검사한다 — 한다체가 남으면 배포를 막는다.
//
// 왜 있나 (2026-08-02): 창업자가 *"우리 요리레시피 한다체 안쓰지 않아?"* 라고 물어서 세어 보니
//   앱에 나가는 순서 **22줄이 한다체 그대로**였다. 전부 옛 레시피였다 — 매운 소갈비찜·버섯 솥밥·
//   불닭냉면·비프페퍼라이스… 아무도 몰랐다.
//
// 뿌리 = `polish.js` 는 «사전에 있는 어미만» 바꾸고, 모르는 동사는 조용히 지나간다.
//   (그 설계 자체는 옳다 — 틀리게 바꾸는 것보다 안 바꾸는 게 낫다.)
//   문제는 **빠진 걸 알려주는 사람이 없었다**는 것. 그래서 여기서 잡는다.
//
// ⛔ 새 레시피를 쓸 때 낯선 동사로 끝내면 여기서 걸린다 → `src/polish.js` ENDINGS 에 한 줄 추가.
// ⛔⛔ 2026-08-04 — **이 검사가 초록불인데 창업자가 눈으로 찾았다.**
//   창업자 *"나시고랭 해요체안바뀜"*. 그 폰에 저장돼 있던 네 줄은 이랬다:
//     「…넣고 볶아주기」 「…넣고 볶기」 「…넣어 스크램블」 「…뿌리면 완성」
//   ⭐ **한 줄도 「~다」로 끝나지 않는다.** 옛 그물은 `/다[.!]?$/` 하나뿐이라 **명사형은 밖**이었다.
//   📌 뿌리 = 검사 이름은 「해요체로 나가는지」인데 **실제로 본 건 「한다체가 있는지」**였다.
//      둘은 다른 질문이다 — 한다체가 없어도 해요체가 아닐 수 있다.
//   ✅ 그래서 «있으면 안 되는 것»을 찾는 대신 **«있어야 하는 것(요로 끝남)»을 확인**하도록 뒤집었다.
//
// ⚠️ 뒤집을 때 한 번 더 틀렸다 — 처음엔 22줄이 걸렸는데 **21줄이 헛것**이었다.
//    「…볶아요. (김치를 볶아야 국물이 깊어져요)」 처럼 **괄호 설명으로 끝나는 줄**을 못 봤다.
//    → 끝의 괄호와 문장부호를 «떼고» 본다.
//
// ⛔⛔ 2026-08-13 — **이 게이트에 큰 구멍이 있었다. `basicRecipes` 를 봤다.**
//   그건 **「오늘 열린 것」만** 이다(`from` 이 오늘 이하). 주간 레시피는 `from` 이 «미래»라
//   **게이트가 한 줄도 안 봤다.** 🔢 실측 = 전체 **111편 중 46편**만 검사 → **65편이 검사 밖.**
//   ⭐ 그 65편은 «날짜가 되면 저절로 열린다» — 그날 한다체로 나가고 아무도 안 막는다.
//   📌 「자동 공개 전날 검수」(절대원칙)가 사람 눈이라면, 이건 그 앞에 서 있어야 할 기계다.
//   ✅ 그래서 **`allBasicRecipes`(미래 것까지 전부)** 를 본다.
//   ⚠️ 실제로 2026-08-13 에 11월 주간 레시피 **11편**이 한다체로 걸렸는데,
//      이 게이트가 아니라 «내가 따로 만든 일회용 스크립트»가 잡았다. 다음엔 그 사람이 없다.
//   📌 #81 과 같은 성격이다 — **검사가 초록불이어도 «무엇을 보는지»를 봐야 한다**(규칙 18 ⓘ).
import { allBasicRecipes } from '../src/data/basics.js'

// 문장 «진짜 끝»만 남긴다 — 끝의 괄호 설명 · 마침표 · 느낌표 · 물결표를 뗀다
//
// ⛔⛔ [2026-08-17] 첫 판은 «한 번씩만» 떼서 **괄호 «뒤»에 마침표가 오면 못 읽었다.**
//    창업자가 검수로 준 문장이 정확히 그 모양이었다 —
//    「…노릇하게 구워져요(너무 두껍지 않게 잘라요).」
//    → 괄호 규칙은 `$` 에 안 맞아 그냥 지나가고, 마침표만 떼서 「…잘라요)」로 끝나 **한다체로 잡혔다.**
//    ⭐ 창업자가 준 «맞는 문장»을 게이트가 막으면 그건 게이트가 틀린 것이다(시끄러운 게이트는 죽은 게이트).
//    ✅ 그래서 **더 이상 안 줄어들 때까지 번갈아 뗀다.**
const tail = (s) => {
  let t = String(s).trim()
  for (let i = 0; i < 5; i++) {
    const 전 = t
    t = t.replace(/[.!~]+$/, '')          // 「…볶아요.」          → 「…볶아요」
      .replace(/\s*\([^)]*\)\s*$/, '')    // 「…볶아요 (팁)」      → 「…볶아요」
      .trim()
    if (t === 전) break
  }
  return t
}

const bad = []
for (const r of allBasicRecipes) {
  for (const [i, s] of (r.steps || []).entries()) {
    const t = tail(s)
    if (!t) continue
    // ✅ 해요체 = 「요」로 끝난다. ⛔한다체(~다)도, 명사형(~기·~완성)도 여기서 다 걸린다.
    if (!/요$/.test(t)) bad.push({ title: r.title, no: i + 1, step: s })
  }
}

if (bad.length) {
  console.error(`\n⛔ 만드는 법에 «한다체»가 ${bad.length}줄 남았다 — 앱엔 해요체로 나가야 한다.\n`)
  for (const b of bad) console.error(`   ${b.title} (${b.no})  ${b.step}`)
  console.error(`\n👉 고치는 법: src/polish.js 의 ENDINGS 에 [한다체, 해요체] 한 줄 추가.`)
  console.error(`   예) ['달군다', '달궈요']  ← 긴 어미를 «위»에 둔다(구체적인 게 먼저 걸려야 한다).\n`)
  process.exit(1)
}

console.log(`✅ 만드는 법 문체 통일 — 레시피 ${allBasicRecipes.length}개(⭐날짜로 잠긴 주간 레시피 포함), 해요체가 아닌 줄 0`)

// ⑤⑤ **[2026-08-17 창업자 절대원칙] «원문»도 해요체여야 한다.**
//
// 📮 창업자 = *"다 문체이상 해요체로 바꾸기"* → *"여름꺼 3개 문체이상이야."*
//    ＋ *"**완벽하게해. 강제하는 방법을 꼭 만들어**"*
//
// ⛔⛔ **위 ①~④ 는 «화면»만 본다** — `allBasicRecipes` 가 이미 `politeSteps()` 를 거친 값이라
//    **원문이 한다체여도 전부 초록불**이었다(실측: 114편 중 원문 한다체 71 · 섞임 14).
//    그래서 **앱은 멀쩡한데 내가 만든 검수판이 원문을 그려** 창업자가 «앱에 없는 문제»를 짚었다.
//    📌 규칙 18 ⓘ 그대로 — 「통과했나」가 아니라 «무엇을 보고 통과했나».
//
// ⭐ 원문 = 화면 이면 **어느 쪽을 보여줘도 같다.** 그래서 원문을 본다.
//    🛠 되돌아갔으면 `node scripts/_문체통일-0817.mjs` 한 번이면 고쳐진다(화면 불변까지 스스로 검증).
{
  const { readFileSync } = await import('node:fs')
  const src = readFileSync(new URL('../src/data/basics.js', import.meta.url), 'utf8')
  const 줄들 = src.split('\n')
  let steps안 = false
  const 원문나쁨 = []
  for (const l of 줄들) {
    if (/^\s*steps:\s*\[\s*$/.test(l)) { steps안 = true; continue }
    if (steps안 && /^\s*\],\s*$/.test(l)) { steps안 = false; continue }
    if (!steps안 || /^\s*\/\//.test(l)) continue
    const m = l.match(/^\s*'((?:[^'\\]|\\.)*)',\s*$/)
    if (!m) continue
    const t = tail(m[1].replace(/\\n/g, '\n'))
    if (t && !/요$/.test(t)) 원문나쁨.push(m[1])
  }
  if (원문나쁨.length) {
    console.error(`\n⛔⛔ **원문**에 해요체가 아닌 줄이 ${원문나쁨.length}개 — 화면은 멀쩡해도 «보여주는 판»이 틀려진다.`)
    for (const s of 원문나쁨.slice(0, 10)) console.error(`   ${s.slice(0, 70)}`)
    if (원문나쁨.length > 10) console.error(`   … 외 ${원문나쁨.length - 10}줄`)
    console.error(`\n👉 고치는 법: node scripts/_문체통일-0817.mjs  (바꾼 뒤 «화면이 그대로인지»까지 스스로 검증한다)\n`)
    process.exit(1)
  }
  console.log(`✅ **원문**도 해요체 — 원문 = 화면이라 어느 쪽을 보여줘도 같다`)
}
