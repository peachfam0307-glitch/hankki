# ⏱ 녹화판(_영상-추석장식릴스-0909.mjs)이 만드는 흐름 — 여기 숫자의 근거다
#    0.0~1.6 홈 맨 위 · 1.6~7.6 굴림 · 7.6~9.0 맨 아래 · 9.0~16.5 탭 다섯 · 16.5~ 마무리
import json, math, os, subprocess
from PIL import Image, ImageDraw

# ✂️ 어디부터가 «진짜»인가 — 녹화판이 남긴 값을 읽는다. ⛔손으로 옮겨 적지 않는다(옮기면 낡는다).
잘 = json.load(open('/tmp/추석릴스/자를지점.json'))['잘라낼초']
F = '/tmp/추석릴스/f'
if not os.path.isdir(F) or os.environ.get('다시뽑기'):
    os.makedirs(F, exist_ok=True)
    subprocess.run(['node_modules/ffmpeg-static/ffmpeg', '-v', 'error', '-y', '-ss', str(잘), '-t', '18',
                    '-i', '/tmp/추석릴스/추석장식-앱실사.webm',
                    '-vf', 'fps=30,scale=1080:-2:flags=lanczos', f'{F}/%04d.png'], check=True)
낼 = '/tmp/추석릴스/합성'
os.makedirs(낼, exist_ok=True)
W, H, FPS = 1080, 1920, 30

자막 = {k: Image.open(f'/tmp/추석릴스/{k}.png').convert('RGBA') for k in ('c1', 'c2', 'c3', 'c4')}

# 🧩 짜임을 넷 다 다르게 — 글꼴·색·배경꼴·정렬·자리 전부 갈랐다(창업자 지시)
장면 = [
    # (자막, 시작초, 끝초, x고정, y, 정렬)
    ('c1', 0.15, 2.70, None, 0.150, '왼쪽'),    # 손글씨 · 테두리만 · 왼쪽 위
    ('c2', 2.95, 8.70, None, 0.815, '가운데'),  # 진한웜 알약 · 흰 글씨 · 아래
    ('c3', 9.20, 14.80, None, 0.105, '왼쪽'),   # 진홍 말풍선 · 꼬리가 상단바를 가리킨다
    ('c4', 15.20, 17.90, None, 0.400, '가운데'),  # 큰 손글씨 두 줄 · 한가운데
]
# ✨ 반짝 — «캐릭터 자리»에만 (창업자 *"캐릭터에"*). 자리는 seasonDecor.js 의 비율 그대로다.
반짝터 = [
    (0.15, 2.70, 0.7914 * W, 0.0883 * H, 120),   # 보름달
    (9.20, 17.90, 0.160 * W, 0.048 * H, 105),    # 탭 상단바 한복 애들
]

def 별(그림, cx, cy, r, 알파):
    """네 갈래 별 — ⛔유니코드 이모지 금지(창업자)라 «그려서» 만든다.
    ⛔ 1판은 «연노랑 하나»라 살구 화면 위에서 안 보였다(대비 1.6 — 색을 재고도 그대로 썼다).
    ✅ 세 겹으로 그린다: ① 진한 금색 테두리(밝은 데서 형태를 잡아준다)
       ② 금빛 몸통 ③ 흰 속심(반짝이는 «심지»). 이러면 밝은 데서도 어두운 데서도 보인다."""
    d = ImageDraw.Draw(그림, 'RGBA')
    겹 = ((1.18, 0.20, (176, 116, 26), 0.85),   # 테두리(진한 금)
          (1.00, 0.17, (245, 196, 81), 1.00),   # 몸통(보름달 노랑)
          (0.52, 0.13, (255, 253, 245), 1.00))  # 속심(흰빛)
    for 배, 굵비, 색, 세기 in 겹:
        R, 굵 = r * 배, r * 배 * 굵비
        d.polygon([(cx, cy - R), (cx + 굵, cy - 굵), (cx + R, cy), (cx + 굵, cy + 굵),
                   (cx, cy + R), (cx - 굵, cy + 굵), (cx - R, cy), (cx - 굵, cy - 굵)],
                  fill=(*색, int(min(255, 알파 * 세기))))

칸수 = len(os.listdir(F))
for i in range(1, 칸수 + 1):
    t = (i - 1) / FPS
    프 = Image.open(f'{F}/{i:04d}.png').convert('RGBA')
    if 프.size != (W, H):
        프 = 프.resize((W, H), Image.LANCZOS)

    for 키, 시, 끝, _x, y, 맞춤 in 장면:
        if not (시 <= t <= 끝):
            continue
        c = 자막[키]
        # 들고 남 — 0.28초씩 부드럽게(툭 튀면 싸구려로 보인다)
        a = min(1.0, (t - 시) / 0.28, (끝 - t) / 0.28)
        # 들어올 때 살짝 떠오른다
        떠오름 = int(26 * (1 - min(1.0, (t - 시) / 0.34)))
        x = 64 if 맞춤 == '왼쪽' else (W - c.width) // 2
        칸 = c.copy()
        칸.putalpha(칸.getchannel('A').point(lambda v: int(v * max(0, a))))
        프.alpha_composite(칸, (x, int(y * H) + 떠오름))

    for 시, 끝, cx, cy, r in 반짝터:
        if not (시 <= t <= 끝):
            continue
        문 = min(1.0, (t - 시) / 0.5, (끝 - t) / 0.5)
        for n in range(7):
            각 = 2 * math.pi * (n / 7) + t * 0.55
            거리 = r * (0.72 + 0.3 * math.sin(t * 1.7 + n))
            깜 = 0.5 + 0.5 * math.sin(t * 3.1 + n * 1.9)     # 반짝반짝
            # 🔢 1판은 12~23px 이라 1080폭에서 «점»으로 보였다 → 26~50px 로 키운다.
            크기 = r * (0.22 + 0.20 * 깜)
            별(프, cx + math.cos(각) * 거리, cy + math.sin(각) * 거리 * 0.82,
               크기, 245 * (0.45 + 0.55 * 깜) * 문)

    프.convert('RGB').save(f'{낼}/{i:04d}.png')
print('합성', 칸수, '칸')
