# 📮 창업자 2026-09-09 = *"짜임 다르게 색깔 글자배치 등등 다 다르게 하는거 알지??
#    배경색이랑 리서치해보고 해. 효과도 넣고.(반짝반짝 효과넣으면 좋을 듯) 캐릭터에"*
