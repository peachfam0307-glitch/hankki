# 🎨 색은 «잰 값»으로 골랐다 (웹 검색으로는 추석 팔레트 hex 가 안 나와서 우리 화면에서 직접 쟀다):
#    살구 화면 = #fdfdfd~#fcf5ee · WCAG 대비 → 진한웜 10.51 · 먹빛 15.48 · 다홍 4.42 · 남색 4.48
#    ⛔ 보름달 노랑 #f5c451 은 살구 위에서 **1.60** — 밝은 데선 못 쓴다. 어두운 알약 위(8.85)에서만.
