// 🏷🏷 「제목이 「사진 레시피」로 남는다」 — 제목 사다리 (2026-09-02) 〔smoke〕
//
// 📮 창업자 폰 실물 = 보쌈무김치를 새로 담았는데 제목이 **「사진 레시피」** 그대로.
//    → *"제목은 잘 못읽고 아까랑 똑같이 나왔고"* → *"보쌈무김치야 새로 담은거야"*
// 📮📮 그리고 창업자가 «뿌리»를 짚었다 —
//    *"파서를 완벽하게 잡긴 어려울 것 같다는 생각이 드네.. 이게 다 다들게 레시피를 적으니까."*
//
// ⭐⭐ **그래서 이 판이 재는 것은 「모양 하나를 막았나」가 아니라 「사다리에 빈 칸이 없나」다.**
//    사흘에 제목이 세 번 죽었는데 셋 다 «다른 글자» 때문이었다(태그 · 머리말 · 끝쉼표).
//    네 번째 모양은 반드시 또 온다 → 모양을 세는 판을 만들면 그 판도 같이 낡는다.
//    ⛔ 그러니 셋을 «각각» 걸되, 마지막 칸(원문 머리에서 집기)이 «살아 있나»를 따로 못 박는다.
//
// ⭐ 잣대 = 앱이 진짜 쓰는 모듈(절대원칙 30) — `parseRecipeText`·`머리에서제목`·`mergeTidy` 를 그대로 부른다.
//
// 실행: node scripts/_repro-제목사다리-0902.mjs   (exit 0 = 통과)
// 🏷 이름표 = 반영됨
import { parseRecipeText, 머리에서제목 } from '../src/parseRecipe.js'
import { mergeTidy } from '../src/tidy.js'

let 통과 = 0
let 실패 = 0
const 칸 = (이름, 조건, 실물) => {
  if (조건) { 통과++; console.log(`  ✅ ${이름}`) } else { 실패++; console.log(`  ❌ ${이름}${실물 !== undefined ? ` — 실물: ${JSON.stringify(실물)}` : ''}`) }
}

// ── ① 창업자 원문 그대로(보쌈무김치 · 2026-09-02 캡처) ──────────────
// ⛔ 한 글자도 안 고친다 — 고치면 재는 게 달라진다.
const 보쌈 = `KT 1:45
1,675 148 647
kim_seoul_638 보쌈 무김치인데,,
이렇게 한번 해보세요
족발집에서 파는 수준으로 맛있습니다
무는 1.5kg고
꼬독한 식감을 위해서 조금 두께감있게 썰어주세요
소금 2스푼, 180ml 종이컵으로 물엿 1컵을 넣고
2시간을 절여줍니다
2시간 뒤에, 절인 무를 물에 헹구지말고, 물기만 빼주세요
고춧가루 7스푼, 설탕 1스푼, 물엿 2스푼, 매실액 2스푼,
까나리액젓 4스푼, 마늘 2스푼넣고 버무려주면 끝입니다
보쌈무김치는 이걸로 정착해도 될 정도로 맛있으니까
믿고 해보셔도 좋을 것 같습니다 간단히 보기
6월 18일`

console.log('① 보쌈무김치 — 끝쉼표 「,,」 (창업자 원문)')
{
  const r = parseRecipeText(보쌈, { fromOcr: true })
  칸('제목이 「보쌈 무김치」다', r.title === '보쌈 무김치', r.title)
  칸('제목에 계정명이 안 붙는다', !/kim|seoul|638/i.test(r.title), r.title)
  칸('제목에 「인데」·쉼표가 안 남는다', !/인데|,/.test(r.title), r.title)
  // ⛔ 제목을 집었다고 걸음이 사라지면 안 된다 — 창업자 폰의 일곱 걸음 그대로여야 한다.
  칸('걸음 7개 그대로', r.steps.length === 7, r.steps.length)
  칸('걸음 1번은 그대로 남아 있다', /보쌈 무김치인데/.test(r.steps[0] || ''), r.steps[0])
}

console.log('② 짬뽕밥 — 머리말에 밀린 해시태그 (2026-09-02 창업자 원문)')
{
  const r = parseRecipeText(`계랑스푼 기준(1T:15ml, 1t:5ml)
#짬뽕밥
재료
우삼겹 300g
당면 50g(불려서 준비)
1. 당면을 물에 불린다
2. 우삼겹을 볶는다`, { fromOcr: true })
  칸('제목이 「짬뽕밥」이다', r.title === '짬뽕밥', r.title)
  칸('「계랑스푼 기준」이 제목이 아니다', !/계랑|계량/.test(r.title), r.title)
}

console.log('③ 첫 줄 해시태그 (2026-08-31 삼치 모양)')
{
  const r = parseRecipeText(`#삼치간장조림 레시피
[계량] 밥숟가락 기준
재료
삼치 2마리
무 1/3개
1. 무를 깔고 삼치를 올린다
2. 양념을 붓고 조린다`, { fromOcr: true })
  칸('제목이 「삼치간장조림」이다', r.title === '삼치간장조림', r.title)
}

// ── ④ 사다리의 «마지막 칸» 자체 ────────────────────────────────
// ⭐⭐ 여기가 이 판의 심장이다 — 위 ①②③은 «모양»이고 이건 «구조»다.
//    모양은 새로 생기지만 이 칸이 살아 있으면 새 모양도 자리표까지는 안 떨어진다.
console.log('④ 마지막 칸 — 원문 머리에서 이름 집기')
{
  칸('계정명 ＋ 끝쉼표를 떼고 집는다',
    머리에서제목('kim_seoul_638 보쌈 무김치인데,,\n이렇게 한번 해보세요') === '보쌈 무김치',
    머리에서제목('kim_seoul_638 보쌈 무김치인데,,\n이렇게 한번 해보세요'))
  칸('꼬리 조사 「이에요」를 뗀다', 머리에서제목('간단 계란찜이에요') === '간단 계란찜', 머리에서제목('간단 계란찜이에요'))
  칸('끝의 「..」·「!!」도 뗀다', 머리에서제목('제육볶음!!') === '제육볶음', 머리에서제목('제육볶음!!'))
  // ⛔⛔ 여기부터가 창업자 걱정이다 — *"이상하게 이거였나요 권할 수도 있지않아?"*
  //    문장·분량·절 이름을 집으면 「사진 레시피」보다 나쁜 제목이 박힌다. 안 집는 것이 «기능»이다.
  칸('⛔ 문장은 안 집는다(해보세요)', 머리에서제목('이렇게 한번 해보세요\n무는 1.5kg고') === '', 머리에서제목('이렇게 한번 해보세요\n무는 1.5kg고'))
  칸('⛔ 문장은 안 집는다(맛있습니다)', 머리에서제목('족발집에서 파는 수준으로 맛있습니다') === '', 머리에서제목('족발집에서 파는 수준으로 맛있습니다'))
  칸('⛔ 분량 줄은 안 집는다', 머리에서제목('무는 1.5kg고') === '', 머리에서제목('무는 1.5kg고'))
  칸('⛔ 절 이름은 안 집는다', 머리에서제목('재료') === '' && 머리에서제목('만드는 법') === '', [머리에서제목('재료'), 머리에서제목('만드는 법')])
  칸('⛔ 계량 기준 머리말은 안 집는다', 머리에서제목('계랑스푼 기준(1T:15ml, 1t:5ml)') === '', 머리에서제목('계랑스푼 기준(1T:15ml, 1t:5ml)'))
  칸('⛔ 화면 글자·숫자 줄은 건너뛴다', 머리에서제목('KT 1:45\n1,675 148 647\n보쌈 무김치') === '보쌈 무김치', 머리에서제목('KT 1:45\n1,675 148 647\n보쌈 무김치'))
  // ⛔⛔ 이 칸은 «만들다 실제로 틀려서» 생겼다 — 첫 판이 태그 더미를 제목으로 집었고
  //    `_repro-삼치파서-0831` ①-e 가 스모크에서 잡았다(2026-09-02). 게이트가 맞게 걸린 것이다.
  칸('⛔ 태그 더미(둘 이상)는 안 집는다',
    머리에서제목('#오늘의집밥 #저녁메뉴 #맛스타그램') === '',
    머리에서제목('#오늘의집밥 #저녁메뉴 #맛스타그램'))
  칸('⛔ 머리 세 줄을 넘어가면 안 집는다',
    머리에서제목('이렇게 한번 해보세요\n족발집에서 파는 수준으로 맛있습니다\n무는 1.5kg고\n보쌈 무김치') === '',
    머리에서제목('이렇게 한번 해보세요\n족발집에서 파는 수준으로 맛있습니다\n무는 1.5kg고\n보쌈 무김치'))
}

// ── ⑤ 사다리 «차례» — 위 칸이 이긴다 ───────────────────────────
// ⛔ 마지막 칸이 앞 칸을 덮으면 안 된다. 덮는 순간 AI·규칙 파서가 잘 읽은 제목이 날아간다.
console.log('⑤ 차례 — 위 칸이 이긴다')
{
  const 기본 = parseRecipeText(보쌈, { fromOcr: true })
  칸('AI 제목이 있으면 AI 가 이긴다',
    mergeTidy(기본, { title: '보쌈무김치', ingredients: ['무 1.5kg'], steps: ['썰어요'], memo: '' }).title === '보쌈무김치')
  칸('AI 가 제목을 안 주면 원문에서 집은 것이 남는다',
    mergeTidy(기본, { title: '', ingredients: ['무 1.5kg'], steps: ['썰어요'], memo: '' }).title === '보쌈 무김치',
    mergeTidy(기본, { title: '', ingredients: [], steps: ['썰어요'], memo: '' }).title)
  // ⭐ 규칙 파서가 «제대로» 잡은 제목을 마지막 칸이 덮지 않는지 — 짬뽕밥이 그 증인이다.
  const 짬 = parseRecipeText('계랑스푼 기준(1T:15ml, 1t:5ml)\n#짬뽕밥\n재료\n우삼겹 300g\n1. 볶는다\n2. 끓인다', { fromOcr: true })
  칸('규칙 파서가 잡은 제목을 안 덮는다', 짬.title === '짬뽕밥', 짬.title)
}

console.log(`\n${통과}/${통과 + 실패} 통과`)
process.exit(실패 ? 1 : 0)
