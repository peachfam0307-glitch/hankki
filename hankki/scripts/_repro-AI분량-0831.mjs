// 🥄🥄 재현 — 「재료에 용량이 안 떠」 (창업자 제보 2026-08-31 · 삼치간장조림) 〔반영됨〕
//
// 📮 창업자 = *"재료에 용량이 안떠"* ＋ 폰 캡처(무 · 비비고 순살 삼치 · 식용유 · 물 …)
//    → *"이건 네가 알아서 해 ai관련이니까"*
//
// ⭐⭐ **이 판의 심장 = 「AI 가 분량을 떼도 화면엔 분량이 남나」**
//    ⛔ 「파서가 분량을 뽑나」가 아니다 — 파서는 «처음부터 멀쩡했다»(그날 실측).
//       화면이 비었던 건 그 뒤에 AI 결과가 통째로 덮었기 때문이다.
//       📌 그래서 재는 자리는 **얹는 자리(mergeTidy)** 다.
//
// 🔢 그날 갈라낸 증거 둘 (짐작 아님)
//    · 규칙 파서 = 「무 1/3개 · 식용유 2스푼 · 물 200ml」 ✅ / 화면 = 「무 · 식용유 · 물」 ⛔
//    · 걸음 말투가 「구워요」 — AI 결과에만 나오는 말이다(파서는 「구워줘요」) → AI 경로 확정
//
// 🧪 규칙 12 = `분량되살리기` 를 빼고 AI 것을 그대로 얹으면 ①②가 죽는다.
//
// 실행: cd /home/user/hankki/hankki && node scripts/_repro-AI분량-0831.mjs
import { mergeTidy, 분량되살리기 } from '../src/tidy.js'
import { parseRecipeText } from '../src/parseRecipe.js'

let 통과 = 0, 전체 = 0
const chk = (이름, 좋나, 덧 = '') => { 전체++; if (좋나) 통과++; console.log(`  ${좋나 ? '✅' : '❌'} ${이름}${덧 ? '  ' + 덧 : ''}`) }

// 📄 창업자가 준 원문 그대로 (인스타 캡처 OCR · 화면 찌꺼기까지 포함)
const 원문 = `KT 11:27 F
#삼치간장조림 레시피
[계량]
밥숟가락 기준
[재료]
무 1/3개
비비고 순살 삼치 2팩
식용유 2스푼
물 200ml
[양념]
미림 15스푼
청주 12스푼
간장 3스푼
생강즙 조금
[만드는 법]
1 팬에 식용유 2스푼을 두르고
중약불에서 무를 앞뒤로 3분씩 구워주세요.
2 물을 자작하게 붓고
미림 15스푼, 청주 12스푼, 간장 3스푼,
생강즙 조금을 넣어 강불에서 한소끔 끓여주세요.`

// 🤖 AI 가 실제로 돌려준 모양 — 창업자 화면에 뜬 그대로(분량이 전부 떨어져 있다)
const AI = {
  title: '삼치간장조림',
  ingredients: ['무', '비비고 순살 삼치', '식용유', '물', '미림', '청주', '간장', '생강즙'],
  steps: ['팬에 식용유 2스푼을 두르고 중약불에서 무를 앞뒤로 3분씩 구워요'],
  memo: '',
}

console.log('\n🥄 「재료에 용량이 안 떠」 — 창업자 삼치 원문으로 잰다\n')

const 파서 = parseRecipeText(원문)
chk('⓪ 규칙 파서엔 분량이 «원래» 있다 (범인이 파서가 아니라는 증거)',
  파서.ingredients.filter((x) => /\d/.test(x)).length >= 6,
  `(분량 붙은 줄 ${파서.ingredients.filter((x) => /\d/.test(x)).length}/${파서.ingredients.length})`)

const 합친것 = mergeTidy(파서, AI)
const 분량줄 = 합친것.ingredients.filter((x) => /\d|조금/.test(x)).length

chk('① 화면에 나갈 재료에 «분량»이 살아 있다', 분량줄 === 8, `(${분량줄}/8) ${합친것.ingredients.join(' · ')}`)
chk('② 「무」가 「무 1/3개」로 돌아왔다', 합친것.ingredients[0] === '무 1/3개', 합친것.ingredients[0])
chk('②-b 「생강즙」이 「생강즙 조금」으로 돌아왔다 (숫자 없는 분량도 분량이다)',
  합친것.ingredients.includes('생강즙 조금'))
chk('③ AI 제목·걸음은 그대로 이긴다 (되살리기가 딴 데 손대지 않았다)',
  합친것.title === '삼치간장조림' && /구워요/.test(합친것.steps[0] || ''))

// ── ⛔ 안 건드려야 하는 자리들 ──────────────────────────────────────────
chk('④ 이미 분량이 있으면 «안» 건드린다',
  분량되살리기(['소금 1스푼'], ['소금 2스푼']).join() === '소금 1스푼')
chk('⑤ 파서에 짝이 없으면 «지어내지 않는다»',
  분량되살리기(['월계수잎'], ['무 1/3개']).join() === '월계수잎')
chk('⑥ 이름이 겹쳐 보여도 «다른 재료»를 물지 않는다 (무 ↔ 무말랭이)',
  분량되살리기(['무'], ['무말랭이 100g']).join() === '무')
chk('⑦ 같은 이름이 둘이면 «한 줄은 한 번만» 쓴다',
  분량되살리기(['소금', '소금'], ['소금 1스푼', '소금 2스푼']).join(' / ') === '소금 1스푼 / 소금 2스푼')
chk('⑧ AI 가 재료를 아예 안 주면 규칙 파서 것이 그대로 남는다',
  mergeTidy(파서, { ...AI, ingredients: [] }).ingredients.join() === 파서.ingredients.join())

console.log(`\n🔢 ${통과}/${전체}`)
if (통과 !== 전체) { console.log('\n⛔ AI 가 분량을 떼면 화면에서 분량이 사라진다.'); process.exit(1) }
console.log('✅ AI 가 분량을 떼도 규칙 파서 것으로 되살아난다.')
