STK = 뿌리 / 'docs/stickers'
비율, 표 = {}, {}
for 원, 키, 이름 in 새것:
    src = STK / 원
    if not src.exists():
        raise SystemExit(f'⛔ 원본이 없다: {src}')
    dst = PHOTO / f'{키}.png'
    if dst.exists():
        raise SystemExit(f'⛔ 이미 있는 키다: {키} — 번호를 다시 잡을 것')
    shutil.copy2(src, dst)
    w, h = Image.open(dst).size
    비율[키] = round(w / h, 4)
    표[키] = 이름
    print(f'  {키}  {w}x{h}  비 {비율[키]:.4f}  「{이름}」')

# 🏷 이름표를 «파일»로 남긴다 — `icon-checked.json` 엔 본날·해시만 있고 「무슨 그림인가」가 없어서
