// 🛒 장보기에 담기는 이름이 「살 때 부르는 이름」인가 (2026-08-16)
//
// 📮 창업자 = *"장보기에 **두부1/2모 양파1/2개를 사진 않지..**"* ·
//    *"**그냥 두부 양파를 사지. 해물가루육수 1봉을 사진 않잖아**"*
//
// ⛔ 손으로 고른 몇 줄만 보면 통과한다 — 그건 검사가 아니다(규칙 18 ⓘ).
//    ✅ **기본 레시피의 재료 «전수»**를 돌려서 ⑴분량이 남았나 ⑵이름이 사라졌나 둘 다 본다.
//
// 실행: node scripts/_repro-장보기이름-0816.mjs
import { ingredientName } from '../src/utils.js'
import { basicRecipes } from '../src/data/basics.js'

// 「분량이 아직 붙어 있다」의 잣대 — 숫자·분수·계량말이 남아 있으면 장보기 이름이 아니다
// ⭐ 단 **파는 단위(600g·1망·300g·1판)는 남는 게 «맞다»** — 창업자 *"양파 1망 돼지고기 600g은 맞지."* · *"300g , 1판. 등등"*
const 분량남음 = /(\d|½|⅓|⅔|¼|¾|약간|적당량|적당히|넉넉|한\s?줌|한\s?꼬집)/
const 파는단위남음 = /\d+(\.\d+)?\s*(g|kg|ml|L|리터|망|단|팩|봉지|박스|판|캔|병|근|줄|손)(?![가-힣a-z])/i

const 줄들 = []
for (const r of basicRecipes) for (const ing of r.ingredients || []) 줄들.push({ 편: r.title, 원문: String(ing) })

let 분량잔류 = 0, 이름사라짐 = 0, 살단위유지 = 0
const 보기 = { 잔류: [], 사라짐: [], 살단위유지: [] }
for (const { 편, 원문 } of 줄들) {
  const 이름 = ingredientName(원문)
  if (!이름.trim()) { 이름사라짐++; if (보기.사라짐.length < 8) 보기.사라짐.push(`${편} · ${원문}`); continue }
  if (!분량남음.test(이름)) continue
  // ⭐ 남은 게 «파는 단위»뿐이면 정상이다 — 그걸 떼면 창업자 말(600g·1망·300g·1판)을 어긴다
  if (!분량남음.test(이름.replace(파는단위남음, ''))) {
    살단위유지++; if (보기.살단위유지.length < 8) 보기.살단위유지.push(`${편} · ${원문}  →  ${이름}`)
  } else {
    분량잔류++; if (보기.잔류.length < 10) 보기.잔류.push(`${편} · ${원문}  →  ${이름}`)
  }
}

console.log(`\n🔢 기본 레시피 ${basicRecipes.length}편 · 재료 줄 ${줄들.length}개`)
console.log(`  ⛔ «쓰는 양»이 아직 붙어 있다 = ${분량잔류}`)
console.log(`  ⛔ 이름이 통째로 사라짐 = ${이름사라짐}`)
console.log(`  ✅ «파는 단위»라 일부러 남긴 것 = ${살단위유지}`)
for (const [k, v] of Object.entries(보기)) if (v.length) console.log(`\n[${k}]\n  ` + v.join('\n  '))

// 👀 창업자가 콕 집은 줄들 — 여기가 틀리면 고친 게 아니다
const 콕 = [
  // ⛔ 떼는 것 — 레시피에서 «쓰는 양»
  ['두부 1/2모', '두부'],
  ['양파 1/2개', '양파'],
  ['해물가루육수 1봉', '해물가루육수'],
  ['신김치 1/4포기 (약 300g)', '신김치'],
  ['대파 1대', '대파'],
  ['소금 약간', '소금'],
  ['아우노슈가 3/4작은술 (일반설탕 1/2작은술)', '아우노슈가'],
  ['김치 국물 1/2컵', '김치 국물'],
  ['물 500ml'.replace('500ml', '2큰술'), '물'],
  // ✅ 남기는 것 — 창업자 *"양파 1망 돼지고기 600g은 맞지."*
  ['양파 1망', '양파 1망'],
  ['돼지고기 600g', '돼지고기 600g'],
  ['돼지고기 앞다리살 또는 삼겹살 200g', '돼지고기 앞다리살 또는 삼겹살 200g'],
  ['물 500ml', '물 500ml'],
  ['대파 1단', '대파 1단'],
  ['두부 1팩', '두부 1팩'],
]
let 틀림 = 0
console.log('\n👀 창업자가 짚은 줄')
for (const [원문, 바람] of 콕) {
  const 난것 = ingredientName(원문)
  const ok = 난것 === 바람
  if (!ok) 틀림++
  console.log(`  ${ok ? '✅' : '⛔'} ${원문}  →  ${난것}${ok ? '' : `   (기대: ${바람})`}`)
}

const 죽나 = 틀림 > 0 || 이름사라짐 > 0 || 분량잔류 > 0
console.log(죽나 ? '\n⛔ 실패' : '\n✅ 통과')
process.exit(죽나 ? 1 : 0)
