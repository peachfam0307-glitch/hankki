// ⚠️⚠️ **정직하게 — 아래 입력은 «스크린샷을 보고 내가 다시 친 것»이지 진짜 OCR 출력이 아니다.**
//    진짜 `rawText` 는 창업자 폰 안에 있고 꺼내 볼 입구가 아직 없다.
//    그래서 이 판은 «결함의 종류»를 재현할 뿐, 글자가 한 자도 안 다르다고는 말 못 한다.
//    📌 그래도 값어치가 있다 — 고친 뒤 이 여덟 칸이 다시 깨지는 것을 막는다.
//
// 📸 사례 ① 차돌 참나물양배추 파스타 — 소제목(■)이 또렷한 캡션
// 📸 사례 ② 강레오 양송이버섯 볶음 — 소제목이 «없고» 앞뒤에 남의 게시물이 걸친 캡션
import { parseRecipeText } from '../src/parseRecipe.js'

let fail = 0
const chk = (ok, label, extra = '') => {
  if (!ok) fail++
  console.log(`${ok ? '  ok  ' : 'FAIL  '}${label}${extra ? `\n        ${extra}` : ''}`)
}
const has = (arr, s) => arr.some((x) => x.includes(s))

// ── 사례 ① — 소제목이 있는 캡션 ──────────────────────────────
const 캡션1 = `차돌 느끼함도 싹 잡아줘서 더 맛있어요

간단한데 진짜 맛있으니
저장하셨다가 꼭! 해드셔보세요
남편이 오늘도 또 해먹자고

■ 재료 (2-3인분 기준)
파스타면 340g (면사랑 2개)
차돌박이 300g
참나물 한줌
대파 1대
양배추 (생략가능)

소스
다진마늘 1T
면수 5T
간장 1T
참치액 2T
후추
*매운거 좋아하심 페퍼론치노 추가

■ 차돌 참나물양배추 파스타
1. 파스타면은 뜨거운 물에 담가주세요
2. 참나물 잎과 줄기를 나누고 줄기는 송송 썰어주세요
3. 팬에 대파 구워주고 차돌박이 볶아 기름 내주세요
4. 양배추, 다진마늘, 줄기 넣어 함께 볶아주세요
5. 파스타면 넣어 소스 넣어 볶아주세요
6. 마지막에 참나물 듬뿍 올려 숨 죽여주고
후추, 페퍼론치노 뿌려주면 완성

✔참나물은 맨 마지막에 넣어야 향긋해요
✔대파를 먼저 구우면 단맛과 풍미가 좋아요`

console.log('── ① 차돌 참나물양배추 파스타 (소제목 ■ 있음) ──')
{
  const r = parseRecipeText(캡션1, { fromOcr: true })
  // ⑴ 제목 — 진짜 이름은 캡션 «안»에 있었다. 지금은 인사말 첫 줄이 제목이 된다.
  chk(/차돌.*파스타/.test(r.title || ''), '⑴ 제목이 「차돌 …파스타」', `제목="${r.title}"`)
  // ⑵⑶ 분량 없는 재료 — 재료 절 «안»이면 담아야 한다
  // ⛔ has() 로 재면 «거짓 통과»한다 — 뭉친 줄 「…차돌 참나물양배추 파스타」에도 「양배추」가 들어 있다.
  //    📌 재료는 «그 줄로» 담겼는지를 본다(규칙 18 ⓘ — 검사가 무엇을 보는지).
  chk(r.ingredients.some((x) => /^양배추/.test(x)), '⑵ 재료 줄이 「양배추…」로 시작', r.ingredients.join(' / '))
  chk(r.ingredients.some((x) => /^후추/.test(x)), '⑶ 재료 줄이 「후추」')
  // ⑷ 소제목이 재료 줄로 새면 안 된다
  chk(!r.ingredients.some((x) => /페퍼론치노 추가.*파스타|파스타$/.test(x)),
      '⑷ 재료에 소제목·주석이 안 섞였다',
      r.ingredients.filter((x) => x.length > 20).join(' / ') || '(긴 줄 없음)')
  // ⑸ 인사말은 걸음이 아니다
  chk(/^파스타면/.test(r.steps[0] || ''), '⑸ 걸음 1 = 「파스타면은 …」', `걸음1="${r.steps[0]}"`)
  // ⑹ ✔팁은 걸음이 아니다
  chk(!r.steps.some((s) => /향긋해요|풍미가 좋아요/.test(s)), '⑹ ✔팁이 걸음에 안 섞였다',
      `걸음 ${r.steps.length}개`)
}

// ── 사례 ② — 소제목이 없고 남의 게시물이 걸친 캡션 ──────────
const 캡션2 = `837 15 91 431
kim_seoul_638 강레오의 초간단 양송이버섯 볶음 레시피

양송이 250g을 4등분으로 썰어주세요

팬에 올리브유를 넣고 양송이랑, 소금, 후추를 넣고 센불에 볶아주세요

불이 약하면 버섯에서 물이나오니까 꼭 센불에 해주시구요

색이 노르스름해지면

버터 1조각, 다진양파 1/4개, 마늘 조금 넣고 양파가 익을때까지만 볶아줍니다

불끄고

엑스트라버진 올리브오일이랑 파슬리 뿌려서 버무려주면 완성입니다 간단히 보기
8월 18일

2na2jun_mom.official
BGM.Bon Petit jeuner`

console.log('\n── ② 강레오 양송이버섯 볶음 (소제목 없음 · 남의 게시물 걸침) ──')
{
  const r = parseRecipeText(캡션2, { fromOcr: true })
  // ⑺ 인스타는 「계정명 + 캡션」이 늘 한 줄이다 — 계정명은 떼야 한다
  chk(!/seoul|638|kim_/i.test(r.steps[0] || ''), '⑺ 걸음 1 에 계정명이 없다', `걸음1="${r.steps[0]}"`)
  // ⑻ 다음 게시물 꼬리(음원·계정명·날짜)가 걸음으로 들어오면 안 된다
  chk(!r.steps.some((s) => /BGM|Petit|official|8월 18일|간단히 보기/i.test(s)),
      '⑻ 남의 게시물 꼬리가 걸음에 안 섞였다',
      r.steps.map((s, i) => `${i + 1}.${s.slice(0, 24)}`).join(' | '))
  // ⑽ ⛔ 이 칸이 «없어서» 제목에 계정명 조각 「seoul 638」이 남은 걸 못 잡았다(2026-08-28).
  //    📌 재현판이 «안 보는 것»은 언제든 조용히 틀려 있을 수 있다(규칙 18 ⓘ).
  chk(/^강레오/.test(r.title || ''), '⑽ 제목에 계정명 조각이 없다', `제목="${r.title}"`)
  // ⑼ 걸음은 다섯 (썰기 · 볶기 · 센불 · 버터양파 · 마무리)
  chk(r.steps.length === 5, '⑼ 걸음 5개', `${r.steps.length}개`)
  // ⭐ 안 깨져야 하는 것 — 줄바꿈 병합은 «지금 잘 되고 있다». 건드리면 안 된다.
  chk(r.steps.some((s) => /노르스름.*버터/.test(s)), '⭐ 「색이 노르스름해지면」＋버터 줄이 이어졌다(기존 동작)')
  chk(r.steps.some((s) => /불끄고.*올리브오일/.test(s)), '⭐ 「불끄고」＋마무리 줄이 이어졌다(기존 동작)')
}

console.log(fail ? `\n⛔ ${fail}칸 실패` : '\n✅ 전부 통과')
process.exit(fail ? 1 : 0)
