  const 냉장고 = [칸만들기('양파', null), 칸만들기('계란', null)]
  const a = 세우기(냉장고).map((m) => m.r.title).join('|')
  const b = rankPantryRecipes([...allBasicRecipes].reverse(), 냉장고, 남은날).map((m) => m.r.title).join('|')
