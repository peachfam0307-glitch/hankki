console.log('\n── ⑥ 🗓 [창업자 2026-09-11] 유통기한이 «이틀» 지나면 그 재료는 안 센다 ──')
{
  // 📮 창업자 = "디데이 끝나고 하루지나면 빼고"
  //    잣대 = 당일(0)·하루 지남(-1) 까지는 급하다 · 이틀 지남(-2) 부터는 «없는 재료»
  칸(급하다(0) && 급하다(-1) && 급하다(3), '당일·하루 지남·D-3 은 급하다')
  칸(!급하다(-2) && !급하다(-30), '이틀 지남부터는 급하지 않다')
  칸(!급하다(4) && !급하다(null), 'D-4 와 기한 없음은 급하지 않다')
  칸(상했나(-2) && !상했나(-1) && !상했나(null), '상함 = 이틀 지남부터')
  const a = 세우기([칸만들기('두부', -5), 칸만들기('계란', null)])
  const b = 세우기([칸만들기('두부', -1), 칸만들기('계란', null)])
  칸(a.every((m) => m.급함 === 0), '⛔ 5일 지난 두부는 «급함»을 못 만든다')
  칸(b.some((m) => m.급함 > 0), '✅ 1일 지난 두부는 여전히 급하다 (창업자 폰 그대로)')
  칸(a.length < b.length, '상한 재료는 «개수»에도 안 들어간다', `상하면 ${a.length}편 · 멀쩡하면 ${b.length}편`)
}

console.log('\n── ⑦ 🚨 [창업자 2026-09-11] 줄을 «둘»로 가르면 아랫줄이 담는 대로 바뀐다 ──')
{
  // 📸 창업자 폰 캡처 그대로 — 두부만 「1일 지남」, 나머지는 유통기한 안 적음
  const 바탕 = ['닭고기','돼지고기','소고기','관자','계란','새우','참깨','김'].map((n) => 칸만들기(n, null))
  const 전 = [칸만들기('두부', -1), ...바탕]
  const 후 = [...전, 칸만들기('해물모듬', null), 칸만들기('오징어', null)]
  const 가르기 = (냉장고) => {
    const all = 세우기(냉장고)
    const 윗 = all.filter((m) => m.급함 > 0).slice(0, 12)
    const 윗id = new Set(윗.map((m) => m.r.id))
    return { 윗, 아랫: all.filter((m) => !윗id.has(m.r.id)) }
  }
  const A = 가르기(전), B = 가르기(후)
  // ⛔ 옛 판(한 줄) = 맨 앞이 «한 장도» 안 바뀌던 바로 그 증상
  const 옛앞 = 세우기(전).slice(0,3).map((m)=>m.r.title).join('|')
  const 옛뒤 = 세우기(후).slice(0,3).map((m)=>m.r.title).join('|')
  console.log(`   📌 한 줄이면 보이는 3장 = 「${옛앞}」 → 「${옛뒤}」${옛앞===옛뒤?'  ⛔그대로(창업자가 본 것)':''}`)
  칸(B.아랫.length > A.아랫.length, '✅ 아랫줄은 재료를 담으면 늘어난다', `${A.아랫.length}편 → ${B.아랫.length}편`)
  칸(A.윗.length > 0 && A.윗.every((m) => m.급함 > 0), '윗줄은 «급한 것만»', `${A.윗.length}편`)
  칸(A.윗.length <= 12 && B.윗.length <= 12, '윗줄은 12장에서 잘린다')
  칸(A.윗.filter((m) => A.아랫.some((x) => x.r.id === m.r.id)).length === 0, '⛔ 두 줄이 «한 장도» 안 겹친다')
  칸(A.아랫.length >= 20, '아랫줄이 안 마른다', `${A.아랫.length}편`)
}

console.log('\n── ⑧ 🔢 임박 재료가 «여러 개»여도 터지지 않는다 (창업자: 장은 한꺼번에 본다) ──')
{
  const 바탕 = ['닭고기','돼지고기','소고기','계란','김'].map((n) => 칸만들기(n, null))
  const 재기 = (임박) => {
    const all = 세우기([...임박, ...바탕])
    const 윗 = all.filter((m) => m.급함 > 0).slice(0, 12)
    const 윗id = new Set(윗.map((m) => m.r.id))
    return { 윗: 윗.length, 아랫: all.filter((m) => !윗id.has(m.r.id)).length, 맨앞급함: 윗[0]?.급함 ?? 0 }
  }
  const 없음 = 재기([])
  칸(없음.윗 === 0, '임박 0개 → 윗줄이 «아예 안 뜬다»', `아랫 ${없음.아랫}편`)
  const 하나 = 재기([칸만들기('두부', 1)])
  const 셋 = 재기([칸만들기('두부', 1), 칸만들기('애호박', 2), 칸만들기('양파', 0)])
  const 여섯 = 재기([칸만들기('두부',1),칸만들기('애호박',2),칸만들기('양파',0),칸만들기('대파',3),칸만들기('우유',1),칸만들기('버섯',2)])
  for (const [이름, v] of [['1개',하나],['3개',셋],['6개',여섯]]) {
    칸(v.윗 <= 12, `임박 ${이름} → 윗줄 ${v.윗}장 (12 이하)`, `아랫 ${v.아랫}편 · 맨앞이 쓰는 급한 재료 ${v.맨앞급함}개`)
    칸(v.아랫 >= 10, `임박 ${이름} → 아랫줄이 안 마른다`, `${v.아랫}편`)
  }
  칸(여섯.맨앞급함 >= 셋.맨앞급함 && 셋.맨앞급함 >= 하나.맨앞급함,
     '⭐ 급한 재료가 늘면 맨 앞이 «한 번에 더 많이 쓰는 편»이 된다',
     `1개→${하나.맨앞급함} · 3개→${셋.맨앞급함} · 6개→${여섯.맨앞급함}`)
}

console.log('\n── ⑨ 🔁 돌리기 — 뒤에 있던 것이 앞으로 오고, 한 바퀴 돌면 처음 ──')
{
  // ⛔ 화면 코드(`PantryView.돌린다`)와 «같은 셈»이라야 뜻이 있다.
  const 돌린다 = (목록, 자리) => (자리 % (목록.length || 1) === 0 ? 목록 : [...목록.slice(자리 % 목록.length), ...목록.slice(0, 자리 % 목록.length)])
  const 줄 = 세우기([칸만들기('계란', null), 칸만들기('대파', null), 칸만들기('소고기', null)])
  칸(줄.length > 6, '돌릴 만큼 길다', `${줄.length}편`)
  칸(돌린다(줄, 0).map((m)=>m.r.id).join() === 줄.map((m)=>m.r.id).join(), '0번 누르면 그대로')
  칸(돌린다(줄, 3)[0].r.id === 줄[3].r.id, '한 번 누르면 4번째가 맨 앞으로')
  칸(돌린다(줄, 6)[0].r.id === 줄[6].r.id, '두 번 누르면 7번째가 맨 앞으로')
  칸(돌린다(줄, 줄.length).map((m)=>m.r.id).join() === 줄.map((m)=>m.r.id).join(), '딱 한 바퀴면 처음으로 돌아온다')
  칸(돌린다(줄, 99999).length === 줄.length, '아무리 눌러도 장수가 안 변한다')
  칸(돌린다([], 3).length === 0 && 돌린다(줄.slice(0,1), 3).length === 1, '빈 줄·한 장짜리도 안 죽는다')
}

console.log('\n── ⑩ 🥩 [창업자 2026-09-11] 정육 이름 — 좁게 쓰면 좁게, 넓게 쓰면 넓게 ──')
{
  // 📮 창업자 = "갈비살하면 소,돼지 레시피 다보여주면돼" ＋ "직접소갈비살 쓰면 소만보여주면되고"
  const 셈 = (이름) => allBasicRecipes.filter((r) => hasIngredient(ingredientTokens(r.ingredients), pantryKey(이름))).length
  const 소 = 셈('소고기'), 돼 = 셈('돼지고기')
  칸(소 > 0 && 돼 > 0, '바탕값 — 소고기·돼지고기가 걸린다', `소 ${소} · 돼 ${돼}`)
  // ⛔ 괄호가 붙어도 걸린다 (영수증이 실제로 만드는 모양)
  for (const [이름, 바람] of [['소고기(채끝)', 소], ['소고기(구이용)', 소], ['돼지고기(찌개용)', 돼]])
    칸(셈(이름) === 바람, `괄호 — 「${이름}」`, `${셈(이름)}편`)
  // ⭐ 부위만 쓰면 «둘 다»
  for (const 부위 of ['갈비살', '등심', '사태'])
    칸(셈(부위) >= 소 && 셈(부위) >= 돼, `부위만 — 「${부위}」는 소·돼지 둘 다`, `${셈(부위)}편`)
  // 🎯 고기를 직접 쓰면 «그 고기만»
  칸(셈('소갈비살') === 소, '직접 — 「소갈비살」은 소고기만', `${셈('소갈비살')}편 (소 ${소})`)
  칸(셈('돼지갈비살') === 돼, '직접 — 「돼지갈비살」은 돼지고기만', `${셈('돼지갈비살')}편 (돼 ${돼})`)
  칸(셈('소갈비살') !== 셈('돼지갈비살'), '⭐ 소·돼지가 «갈린다»')
  칸(셈('한우갈비살') === 소, '한우도 소고기로 좁힌다')
  칸(셈('흑돼지목살') === 돼 || 셈('흑돼지목살') > 0, '흑돼지도 돼지고기로 좁힌다', `${셈('흑돼지목살')}편`)
  // 🏷 부위 이름만 적어도 걸린다
  for (const 부위 of ['채끝', '부채살', '토시살', '항정살', '오리로스', '생닭'])
    칸(셈(부위) > 0, `부위 사전 — 「${부위}」`, `${셈(부위)}편`)
  // ⚠️ 「소」 한 글자가 엉뚱한 데 안 걸리나 — 접두 규칙이 «부위일 때만» 발동해야 한다
  //    ⛔ 소금·소면·소시지는 그 재료가 «실제로 들어간» 편만 나와야지, 소고기 편이 나오면 안 된다
  const 소고기편 = new Set(allBasicRecipes.filter((r) => hasIngredient(ingredientTokens(r.ingredients), '소고기')).map((r) => r.id))
  for (const 말 of ['소금', '소면', '소시지', '소스', '소주']) {
    const 걸린것 = allBasicRecipes.filter((r) => hasIngredient(ingredientTokens(r.ingredients), pantryKey(말)))
    const 진짜 = 걸린것.every((r) => ingredientTokens(r.ingredients).some((t) => t === 말 || t.endsWith(말) || 말.endsWith(t)))
    칸(진짜, `⚠️ 「${말}」이 소고기로 안 샌다`, `${걸린것.length}편`)
  }
}
