#!/usr/bin/env node
// ⏪ 동기화 «되돌리기» 재현판 — 2026-09-04
//
// 📮 창업자 = *"폰-패드는 동기화가 꼬이면 진짜 답없어서.."* → *"되돌리기 만들어줘"*
//
// ⭐⭐ **이 판이 지키는 한 줄 = 「꼬여도 돌아갈 자리가 «반드시» 있다」.**
//    🚨 2026-09-01 에 자동 받기가 방금 담은 레시피를 덮었을 때 **되돌릴 길이 없었다.**
//       열쇠는 이미 깎여 있었고, 레시피는 없었다. 그게 이 파일이 있는 이유다.
//
// ⛔⛔ **되돌리기는 「합치기」보다 «먼저» 만든다.**
//    돌아갈 자리가 있어야 그다음(합치기·자동 받기)을 만질 수 있다.
//
// 🧪 재는 것 아홉 (설계 관문에서 세 각도로 나온 것 그대로)
//   ① 얹기 «전» 벌을 뜬다 · ② 사진·표지는 «안» 넣는다(무거워서) · ③ 큰 창고에 둔다(작은 서랍 ⛔)
//   ④ 되돌리면 그 벌 상태로 «정확히» 돌아간다 · ⑤ 3벌까지만 두고 오래된 것부터 지운다
//   ⑥ 벌마다 «언제·몇 편·어느 기기»가 보인다 · ⑦ 벌이 없으면 목록이 비어 있다(단추를 안 그리게)
//   ⑧ ⭐**못 뜨면 «조용히» 실패하지 않는다** — 9/2 사고가 정확히 조용한 실패였다
//   ⑨ 반쪽 벌은 목록에 «안» 보인다(다 쓴 뒤에 넣는다)
//
// 📐 설계 = `docs/폰패드-자동동기화-설계-2026-09-04.md` §3-ⓑ

let 나쁨 = 0
const 잰다 = (좋나, 이름, 덧 = '') => {
  if (!좋나) 나쁨++
  console.log(`  ${좋나 ? '✅' : '⛔'} ${이름}${덧 ? ` — ${덧}` : ''}`)
}

// ── 큰 창고(IndexedDB) 흉내 ──────────────────────────────────────────────
//   ⭐ 진짜 IndexedDB 없이 돌린다 — 판은 어디서 돌아도 같아야 한다(2026-09-03 /tmp 사고 교훈).
const 창고 = new Map()
let 창고쓰기수 = 0
const 가짜창고 = {
  async 넣기 (열쇠, 값) { 창고쓰기수++; 창고.set(열쇠, JSON.parse(JSON.stringify(값))); return true },
  async 꺼내기 (열쇠) { const v = 창고.get(열쇠); return v === undefined ? null : JSON.parse(JSON.stringify(v)) },
  async 지우기 (열쇠) { 창고.delete(열쇠) },
  async 열쇠들 () { return [...창고.keys()] },
}
// 🚫 못 넣는 창고(가득 참) — ⑧ 을 재려고
const 꽉찬창고 = { ...가짜창고, async 넣기 () { return false } }

// ⛔ 작은 서랍에 쓰면 «잡아낸다» — 여기 쓰면 9/2 사고(5MB 꽉 참)를 재현한다
let 서랍쓴횟수 = 0
const 칸 = new Map()
globalThis.localStorage = {
  getItem: (k) => (칸.has(k) ? 칸.get(k) : null),
  setItem: (k, v) => { 서랍쓴횟수++; 칸.set(k, String(v)) },
  removeItem: (k) => 칸.delete(k),
}

let 되돌리기모듈
try {
  되돌리기모듈 = await import('../src/syncUndo.js')
} catch {
  console.log('\n⛔⛔ `src/syncUndo.js` 가 아직 없다 — **이 판이 먼저다.**')
  console.log('   📐 무엇을 만들지 = docs/폰패드-자동동기화-설계-2026-09-04.md §3-ⓑ\n')
  process.exit(1)
}
const { 벌뜨기, 벌목록, 되돌리기, _창고물리기 } = 되돌리기모듈
_창고물리기(가짜창고)

const 사진 = 'data:image/png;base64,' + 'A'.repeat(3000)
const 판만들기 = (n, 꾸밈 = false) => ({
  recipes: Array.from({ length: n }, (_, i) => ({
    id: 'u' + i, title: '레시피' + i, image: 사진,
    ...(꾸밈 ? { 표지: 사진, decor: [{ id: 'd', key: 'sk_1' }] } : {}),
  })),
  diary: [{ id: 'd1', 속지: [사진] }],
  shoppingList: [{ name: '두부' }],
})

console.log('\n⏪ 되돌리기 — 「꼬여도 돌아갈 자리가 있다」\n')

// ① 얹기 «전» 벌을 뜬다
const 첫판 = 판만들기(3)
const r1 = await 벌뜨기(첫판, { 기기: '폰' })
잰다(r1?.됐나 === true, '① 얹기 «전» 벌을 뜬다', r1?.됐나 ? '떴다' : '⛔못 떴다')

// ② 사진·표지는 안 넣는다 — 무거운 것을 빼야 창고가 안 찬다
const 담긴글 = JSON.stringify(await 가짜창고.꺼내기((await 가짜창고.열쇠들()).find((k) => k.includes('벌'))))
잰다(!담긴글.includes('data:image'), '② 사진·표지는 «안» 들어간다 (글자만)',
  담긴글.includes('data:image') ? '⛔사진이 들어갔다' : '글자만')

// ③ 큰 창고에 둔다 — ⛔작은 서랍에 쓰면 9/2 사고 재현
잰다(서랍쓴횟수 === 0, '③ 작은 서랍(localStorage)에 «안» 쓴다', `서랍 쓴 횟수 ${서랍쓴횟수}`)
잰다(창고쓰기수 > 0, '  ③-b 큰 창고에 쓴다', `창고 쓴 횟수 ${창고쓰기수}`)

// ⑥ 벌마다 언제·몇 편·어느 기기
const 목록1 = await 벌목록()
잰다(목록1.length === 1 && 목록1[0].레시피 === 3 && 목록1[0].기기 === '폰' && !!목록1[0].때,
  '⑥ 벌마다 «언제·몇 편·어느 기기»가 보인다',
  목록1[0] ? `${목록1[0].레시피}편 · ${목록1[0].기기}` : '비었다')

// ④ 되돌리면 그 벌 상태로 «정확히» 돌아간다
//    ⭐ 사진은 벌에 없다 — 「지금 폰에 있는 것」에서 되살린다(사진은 폰을 안 떠난다)
await 벌뜨기(판만들기(5), { 기기: '패드' })
const 되돌린것 = await 되돌리기(목록1[0].id, { 지금: 판만들기(5) })
잰다((되돌린것?.recipes || []).length === 3, '④ 되돌리면 «그때 상태»로 돌아간다',
  `${(되돌린것?.recipes || []).length}편 (3이라야 맞다)`)
잰다(되돌린것?.recipes?.[0]?.image === 사진, '  ④-b 사진은 폰 것에서 되살아난다',
  되돌린것?.recipes?.[0]?.image ? '있다' : '⛔빈 칸')

// ⑤ 3벌까지만
for (let i = 0; i < 4; i++) await 벌뜨기(판만들기(2), { 기기: '폰' })
const 목록2 = await 벌목록()
잰다(목록2.length === 3, '⑤ 3벌까지만 두고 오래된 것부터 지운다', `${목록2.length}벌`)
// ⑤-b ⭐**창고에 «실제로» 남은 벌도 3개여야 한다**
//    🧪 [2026-09-04] 처음엔 목록 길이만 재서 «지우기를 빼도 판이 안 죽었다» — 헛돌던 칸이다.
//       목록은 slice 로 잘리니까 늘 3개로 보이는데, 창고엔 옛 벌이 그대로 남아 «영원히 쌓인다».
//    ⛔ 그게 무덤이 성능을 먹는 것과 같은 성질이다(조사에서 나온 업계 함정).
const 남은벌 = (await 가짜창고.열쇠들()).filter((k) => String(k).startsWith('벌:')).length
잰다(남은벌 === 3, '  ⑤-b 창고에 «실제로» 남은 벌도 3개다 (쓰레기가 안 쌓인다)', `${남은벌}개`)

// ⑧ ⭐ 못 뜨면 «조용히» 실패하지 않는다
_창고물리기(꽉찬창고)
const r2 = await 벌뜨기(판만들기(3), { 기기: '폰' })
잰다(r2?.됐나 === false && !!r2?.왜, '⑧ ⭐ 못 뜨면 «왜»를 알려준다 (조용한 실패 금지)',
  r2?.왜 || '⛔조용히 넘어갔다')
_창고물리기(가짜창고)

// ⑦ 벌이 없으면 목록이 비어 있다
_창고물리기({ ...가짜창고, async 열쇠들 () { return [] } })
잰다((await 벌목록()).length === 0, '⑦ 벌이 없으면 목록이 «비어» 있다 (단추를 안 그리게)')

console.log(나쁨 ? `\n⛔ ${나쁨}칸 실패 — 되돌리기가 없으면 합치기를 켜지 않는다\n`
  : '\n✅ 꼬여도 돌아갈 자리가 있다 — 글자만 · 큰 창고 · 3벌 · 조용한 실패 없음\n')
process.exit(나쁨 ? 1 : 0)
