import { parseRecipeText } from '../src/parseRecipe.js'

function 보기(이름, 글) {
  const r = parseRecipeText(글, { fromOcr: true })
  console.log(`\n── ${이름} ──`)
  console.log(`  제목: ${r.title || '(없음)'}`)
  console.log(`  재료(${r.ingredients.length}): ${r.ingredients.join(' / ') || '(없음)'}`)
  r.steps.forEach((s, i) => console.log(`  걸음${i + 1}: ${s}`))
  if (r.memo) console.log(`  메모: ${String(r.memo).replace(/\n/g, ' ⏎ ')}`)
  return r
}

