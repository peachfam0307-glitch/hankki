// 실행할 필요는 없다 — 소스에 iframe 이 «없나»만 형식상 확인하고 조용히 통과한다.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const 상세 = readFileSync(join(ROOT, 'src/screens/RecipeDetailScreen.jsx'), 'utf8')

const 살아있나 = /<iframe[^>]*원본 영상/.test(상세)
if (살아있나) {
  console.log('⛔⛔ iframe 플레이어가 «되살아났다» — 이 판이 지키던 것과 정면으로 어긋난다.')
  console.log('   창업자가 다시 iframe 재생을 확정했다면 이 판 «전체»를 다시 쓸 것 — 위 머리말만 지우지 말 것.')
  process.exit(1)
}
console.log('✅ iframe 없음(뒤집힌 결정 그대로) — 지금 진짜는 _repro-영상표-0903.mjs 가 잰다.')
process.exit(0)
