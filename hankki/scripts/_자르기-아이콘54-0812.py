# ⛔⛔ **`--grid 2x3` 만으로는 안 된다 — 라벨 조각이 딸려와 컷에 «빈 여백»이 생긴다.**
#    실측(시트04) = t02 428×472 · t03 495×462 인데 **그림은 389행에서 끝난다.**
#    아래 82~85px 이 빈칸이고, 거기 **1318·684 픽셀짜리 라벨 잔재**가 남아 bbox 를 늘렸다.
#    ⚠️ 그대로 앱에 넣으면 **그림이 그 칸에서 작게(위로 쏠려) 보인다** — 아무도 「잘못됐다」고는 안 하는데 어색하다.
#    ⭐ `--grid` 는 문서에도 *"칸으로 묶기만 한다"* 고 적혀 있다 — 칸 안 «모든» 덩어리를 한 컷으로 본다.
#
# ✅ **그래서 자르기 «전»에 라벨 띠를 흰색으로 눕힌다.**
#    · 칸 = 시트를 3열 × 2행으로 나눈 것
#    · 라벨 = 칸의 아래쪽 — 실측으로 **그림은 칸 높이의 69.3% 에서 끝났다**(위 시트04 기준)
#    · 그래서 **아래 26% 를 지운다**(74% 지점부터) — 그림 끝(69.3%)과 4.7%p 여유
#    ⚠️ 여유를 더 주면 라벨이 남고, 덜 주면 그림이 잘린다. **자른 뒤 잘림 검사로 확인한다**(cut-check 자동).
#
# 🏷 **이름표는 짐작으로 붙이지 않는다** — 지우기 «전»에 라벨 띠를 잘라 두었다가
#    컷 옆에 나란히 붙인 확인판을 만든다(2026-08-11 `_이름표-아이콘48-0811.py` 와 같은 방법).
#    ⛔ 2026-08-04 에 컨택트시트에서 칸을 밀려 읽어 엉뚱한 컷을 고른 적이 있다(규칙 18).
import subprocess, sys
from pathlib import Path
from PIL import Image

뿌리 = Path(__file__).resolve().parent.parent
폴더 = 뿌리 / 'docs/stickers/음식아이콘-창업자-2026-08-12'
시트들 = sorted((폴더 / '원본시트').glob('시트*.png'))
낼곳 = 폴더 / '낱개'
라벨곳 = 폴더 / '_라벨띠'
지운시트 = 폴더 / '_라벨지운시트'
for d in (낼곳, 라벨곳, 지운시트):
    d.mkdir(parents=True, exist_ok=True)

행, 열 = 2, 3
라벨시작 = 0.74      # 칸 높이의 이 지점부터 아래는 라벨 → 흰색으로 눕힌다

for s in 시트들:
    n = s.stem[-2:]
    im = Image.open(s).convert('RGB')
    W, H = im.size
    새 = im.copy()
    for r in range(행):
        for c in range(열):
            x0, y0 = int(W * c / 열), int(H * r / 행)
            x1, y1 = int(W * (c + 1) / 열), int(H * (r + 1) / 행)
            컷H = y1 - y0
            라벨y = y0 + int(컷H * 라벨시작)
            # 🏷 ① 지우기 «전»에 라벨 띠를 따로 남긴다 (이름 확정용)
            im.crop((x0, 라벨y, x1, y1)).save(라벨곳 / f'L{n}{r * 열 + c + 1:02d}.png')
            # 🧹 ② 그 자리를 흰색으로 — 시트 배경과 같은 색이라 자르기가 «없는 것»으로 본다
            새.paste((255, 255, 255), (x0, 라벨y, x1, y1))
    p = 지운시트 / f'시트{n}.png'
    새.save(p)
    print(f'🧹 시트{n} 라벨 띠 지움 → {p.name}')

print()
for p in sorted(지운시트.glob('시트*.png')):
    n = p.stem[-2:]
    # ⚠️ 접두어 `n{시트번호}` — 2026-08-11 판과 같은 규칙(n0101…)이라 도구가 헷갈리지 않는다
    r = subprocess.run([sys.executable, str(뿌리 / 'tools/cut.py'), str(p), str(낼곳), f'n{n}',
                        '--diecut', 'auto', '--grid', f'{행}x{열}'],
                       capture_output=True, text=True, cwd=str(뿌리))
    첫 = [l for l in r.stdout.splitlines() if '컷' in l][:1]
    print(f'✂️ 시트{n} → {첫[0].strip() if 첫 else r.returncode}')

컷들 = sorted(낼곳.glob('*.png'))
print(f'\n✅ 낱개 {len(컷들)}컷')
if len(컷들) != len(시트들) * 행 * 열:
    print(f'⛔ {len(시트들) * 행 * 열}컷이 나와야 하는데 {len(컷들)}컷이다')
