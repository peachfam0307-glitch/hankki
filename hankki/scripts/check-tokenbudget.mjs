// ⛔⛔ 사고 = 2026-09-13 「AI 다듬기가 8초 아니면 빈손」 (docs/AI다듬기-편차의정체-2026-09-13.md)
//    워커 `VISION_MAX_TOKENS` 가 8000 이었고 앱 대기(`tidy.js` 선반간격 5000 × 선반횟수 24 = 120초)는 그걸 몰랐다.
//    8000 토큰을 다 쓰면 120초를 «구조적으로» 넘어 앱은 떠나고 워커는 계속 돌았다 — 유저는 조용히 빈손.
//    ⭐ 뿌리 = **두 곳에 있는 숫자가 서로를 모르면 반드시 갈린다.**
//
// 무엇을 보나 = 저장소 안 두 파일에서 두 숫자를 읽어 «관계»를 잰다.
//    기준선 = 2026-09-13 창업자 실물로 확인된 「2000 토큰 ↔ 120,000ms 면 빠르다」.
//    토큰/대기 비율이 기준선보다 «나쁘면»(토큰만 올렸거나 대기만 줄였으면) 막는다.
//    ⭐ 둘을 «같이» 올리면 통과한다 — 문서 규칙이 말하는 그대로다.
//
// ⛔ 이 검사는 «저장소»만 지킨다. 서버(워커)에서 저장소를 안 거치고 직접 바꾸는 건 못 막는다(규칙 36).
//    그래서 빨간불 메시지에 그걸 적는다 — 초록불이 서버까지 보장한다고 읽히면 안 된다.
// ⛔ 이름을 못 찾으면 죽는다 — 조용히 통과하는 검사는 없는 검사다.
import { readFileSync } from 'node:fs'

const 뿌리 = new URL('../', import.meta.url)
const 워커길 = 'ocr-proxy/worker-tidy.js'
const 앱길 = 'src/tidy.js'

// 🔢 기준선 — 2026-09-13 창업자 실물 (멸치볶음·스테이크솥밥·아이폰 셋 다 "되게 빨랐어")
const 기준토큰 = 2000
const 기준대기ms = 120000

const 죽는다 = (why) => { console.error(`\n⛔⛔ 토큰 예산 게이트가 «검사를 못 했다» — ${why}\n   검사가 죽은 것이니 고칠 것. 조용히 통과시키지 않는다.\n`); process.exit(1) }

let 워커, 앱
try { 워커 = readFileSync(new URL(워커길, 뿌리), 'utf8') } catch { 죽는다(`${워커길} 를 못 읽었다`) }
try { 앱 = readFileSync(new URL(앱길, 뿌리), 'utf8') } catch { 죽는다(`${앱길} 를 못 읽었다`) }

// 줄 번호까지 같이 찾는다 — 빨간불에 «어디를 고치나»를 찍어 주려고
const 찾기 = (본문, 이름, 파일) => {
  const 줄들 = 본문.split('\n')
  const re = new RegExp(`^\\s*const\\s+${이름}\\s*=\\s*(\\d+)\\s*$`)
  for (let i = 0; i < 줄들.length; i++) {
    const m = re.exec(줄들[i])
    if (m) return { 값: Number(m[1]), 줄: i + 1 }
  }
  죽는다(`${파일} 에서 «const ${이름} = 숫자» 줄을 못 찾았다 — 이름이 바뀌었나?`)
}

const 토큰 = 찾기(워커, 'VISION_MAX_TOKENS', 워커길)
const 간격 = 찾기(앱, '선반간격', 앱길)
const 횟수 = 찾기(앱, '선반횟수', 앱길)
for (const [n, v] of [['VISION_MAX_TOKENS', 토큰], ['선반간격', 간격], ['선반횟수', 횟수]]) {
  if (!Number.isFinite(v.값) || v.값 <= 0) 죽는다(`${n} 이 양의 숫자가 아니다 (${v.값})`)
}

const 대기ms = 간격.값 * 횟수.값
// 「대기 1ms 당 몇 토큰을 허락하나」 — 기준선보다 크면 토큰만 늘었거나 대기만 줄었다
const 지금비율 = 토큰.값 / 대기ms
const 기준비율 = 기준토큰 / 기준대기ms

const 한줄 = `VISION_MAX_TOKENS=${토큰.값} (${워커길}:${토큰.줄}) · 앱 대기=${간격.값}×${횟수.값}=${대기ms}ms (${앱길}:${간격.줄}-${횟수.줄})`

if (지금비율 <= 기준비율 + 1e-12) {
  console.log(`🔢 토큰 예산 게이트 — ${한줄} ✅ 기준선(${기준토큰}↔${기준대기ms}ms) 안`)
  process.exit(0)
}

const 허용토큰 = Math.floor(기준비율 * 대기ms)
const 필요대기ms = Math.ceil(토큰.값 / 기준비율)
console.error(`
⛔⛔ 토큰 예산 게이트 — 워커의 답 길이 상한이 앱 대기보다 «크다». 2026-09-13 사고 모양이다.

   ${한줄}
   지금 대기(${대기ms}ms)로는 토큰 ≤ ${허용토큰} 까지만 안전하다.
   토큰 ${토큰.값} 을 쓰려면 앱 대기가 ≥ ${필요대기ms}ms 여야 한다.

   👉 둘 중 하나로 고친다 — «한쪽만» 손대면 이 사고가 되풀이된다:
      ⓐ ${워커길}:${토큰.줄}  VISION_MAX_TOKENS 를 ${허용토큰} 이하로
      ⓑ ${앱길}:${간격.줄}-${횟수.줄}  선반간격×선반횟수 를 ${필요대기ms}ms 이상으로 (그리고 그 시간을 유저가 기다릴 만한지 창업자에게)

   📄 왜 = docs/AI다듬기-편차의정체-2026-09-13.md — 8000 토큰이 120초를 넘어 유저가 빈손이 됐다.
   ⛔ 이 검사는 «저장소»만 지킨다. 서버에서 직접 바꾼 건 못 잡는다(규칙 36) — 워커를 붙여넣을 땐 저장소 파일 그대로.
`)
process.exit(1)
