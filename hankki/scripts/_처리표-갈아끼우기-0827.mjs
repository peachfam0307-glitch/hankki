/**
 * 🧾 새 음식 컷 125개 → 앱에 갈아끼울 «처리표»를 만든다 (2026-08-27)
 *
 * 📮 창업자 = *"다 잘라서 앱에 １：１로 짝찾아서 갈아끼워줘。앱에 옛컷 아직도 있거든（카와이스타일） 다 빼줘。"*
 *    → *"전복장 크림파스타만 왼쪽 나머지 다 오른쪽!"* · *"오징어무국은 얼큰이랑 맑은 2가지가 다"*
 *    → *"둘다 넣어줘. 이제 앱에 반영하고 갈아끼워줘."*
 *
 * ⭐ 왜 표를 «먼저» 만드나 = 자료가 다섯 갈래로 흩어져 있다(짝짓기·바꿀16·겹친18·카와이뺄컷·이름표).
 *    코드를 고치면서 그때그때 판단하면 반드시 하나를 놓친다. **한 표로 모아 놓고 그 표대로만 고친다.**
 *
 * ⛔ 시트23(n2301~n2306) 은 «뺀다» — 왼쪽 아래가 원본부터 잘려 창업자가 다시 뽑는 중이다.
 * ⛔ 파일은 하나도 지우지 않는다 — 픽커·규칙에서만 내린다(그 키로 저장한 레시피가 깨진다).
 *
 * 쓰기:  node scripts/_처리표-갈아끼우기-0827.mjs        (표만 찍는다)
 *        node scripts/_처리표-갈아끼우기-0827.mjs --저장  (JSON 으로 남긴다)
 */
import fs from 'node:fs'
import path from 'node:path'

const P = 'docs/stickers/음식-창업자-2026-08-26-2차/'
const J = (f) => JSON.parse(fs.readFileSync(P + f, 'utf8'))

const 이름표 = J('이름표.json')['음식']
const 짝짓기 = J('짝짓기.json')
const 바꿀16 = J('짝짓기-바꿀16.json')
const 중복 = J('중복검사-2026-08-27.json')
const 카와이 = JSON.parse(fs.readFileSync('docs/stickers/카와이-뺄컷-2026-08-27.json', 'utf8'))

/** ⛔ 원본부터 접시 왼쪽 아래가 잘렸다 → 이번 판에서 뺀다
 *  ⭐ n2305·n2306 은 2026-08-27 에 창업자가 다시 뽑아 줘서 «시트25»(n2501·n2502)로 살아났다.
 *     남은 넷 중 n2304(굴매생이떡국)는 앱에 이미 gr_315 가 있어 다시 뽑을 필요가 없다.
 *     ⏳ 판정 대기 = n2301 팟타이 · n2302 고추장제육볶음 · n2303 닭갈비 */
const 시트23 = ['n2301', 'n2302', 'n2303', 'n2304', 'n2305', 'n2306']
/** 잘린 컷을 대신하는 새 컷 */
const 되살림 = { n2305: 'n2501', n2306: 'n2502' }
/** 창업자 판정 = 지금 앱 컷을 남긴다 → 새 컷을 «안» 넣는다 */
const 왼쪽유지 = { n1303: 'gr_238(전복장)', n1905: 'gr_297(크림파스타)' }

// ── 새 컷마다 「무엇을 대신하나」를 모은다 ─────────────────────────
const 대신 = {}                       // 새키 → [옛키…]
const 붙임 = (새, 옛, 출처) => {
  if (!새 || !옛) return
  ;(대신[새] ||= []).push({ 옛, 출처 })
}
/** ⭐ 잘린 컷이 갖고 있던 짝은 «되살린 컷»이 물려받는다 — 안 그러면 옛 컷이 안 내려간다 */
const 옮김 = (k) => 되살림[k] || k
for (const p of 짝짓기.짝) 붙임(옮김(p.새키), p.키, '짝짓기')
for (const p of 바꿀16.바꿀16짝) 붙임(옮김(p.새키), p.옛키, '바꿀16')
for (const [번호, v] of Object.entries(중복['✅창업자확정_2026-08-27'].오른쪽으로갈것_16)) {
  붙임(v.새, v.옛, `겹친18 ${번호}`)
}

// ── 🏷 이름이 같은 컷 = 픽커엔 «둘 다» · 자동매칭은 «하나만» ────────
//  📮 창업자 = *"소스는 3개 4개 다 넣어 골고루 원하는대로 쓰게"* · *"아까 104컷도 다 갈아끼우는거 맞지?"*
//     → **다 넣는다.** 그림이 다르니 고를 수 있는 게 값어치다.
//  ⛔ 다만 «제목을 치면 뜨는 그림»(ICON_RULES)은 하나만 가리켜야 한다 —
//     둘이 가리키면 위에 적힌 쪽이 늘 이기고 아래 것은 «영영 안 뜨는 유령»이 된다(v11.13 사고).
//  ⭐ 어느 쪽을 자동매칭에 쓰나 = **원본이 큰 쪽**(v11.14 에 창업자가 고른 넷과 같은 기준)
const 크기 = (k) => {
  const p = `${P}낱개/${k}.png`
  if (!fs.existsSync(p)) return 0
  return fs.statSync(p).size
}
const 이름별 = {}
for (const [k, v] of Object.entries(이름표)) (이름별[v] ||= []).push(k)
const 자동매칭안함 = new Map()          // 새컷 → 왜
for (const [이름, ks] of Object.entries(이름별)) {
  if (ks.length < 2) continue
  const 이긴것 = ks.slice().sort((a, b) => 크기(b) - 크기(a))[0]
  for (const k of ks) if (k !== 이긴것) 자동매칭안함.set(k, `「${이름}」 자동매칭은 ${이긴것}(원본이 크다)이 맡는다 · 픽커엔 둘 다 있다`)
}

// ── 컷 하나하나의 운명 ────────────────────────────────────────────
const 키들 = Object.keys(이름표).sort()
let 다음 = 331
const 표 = []
for (const k of 키들) {
  const 이름 = 이름표[k]
  let 상태 = '넣는다'
  let 왜 = ''
  if (시트23.includes(k)) {
    상태 = '⛔뺀다(잘림)'
    왜 = 되살림[k]
      ? `원본이 잘렸다 → ${되살림[k]}(시트25)로 되살렸다`
      : k === 'n2304'
        ? '원본이 잘렸다 · 앱에 gr_315(굴매생이떡국)가 이미 있어 안 넣어도 된다'
        : '원본부터 접시 왼쪽 아래가 잘렸다 — ⏳창업자 판정 대기'
  }
  else if (왼쪽유지[k]) { 상태 = '⛔안넣는다'; 왜 = `창업자 판정 = ${왼쪽유지[k]} 를 남긴다` }
  표.push({
    새컷: k,
    이름,
    상태,
    왜,
    새키: 상태 === '넣는다' ? `gr_${다음++}` : null,
    대신할옛컷: (대신[k] || []).map((x) => x.옛),
    출처: (대신[k] || []).map((x) => x.출처),
    자동매칭: !자동매칭안함.has(k),
    자동매칭왜: 자동매칭안함.get(k) || '',
  })
}

// ── 픽커에서 내릴 옛 컷 ───────────────────────────────────────────
const 내릴것 = new Set()
for (const r of 표) if (r.상태 === '넣는다') for (const o of r.대신할옛컷) 내릴것.add(o)
for (const k of 카와이.뺄것_카와이) 내릴것.add(k)
for (const k of Object.keys(카와이.그밖에_뺄것 || {})) 내릴것.add(k)
for (const p of 짝짓기.뺄옛컷) 내릴것.add(p.키)
// ⛔ 창업자가 「왼쪽을 남긴다」고 한 컷은 절대 안 내린다 — 판정을 뒤집는 것이다
for (const v of Object.values(왼쪽유지)) 내릴것.delete(v.split('(')[0])

const 넣을것 = 표.filter((r) => r.상태 === '넣는다')
const 결과 = {
  _만든날: '2026-08-27',
  _무엇: '새 음식 컷 125개를 앱에 갈아끼울 처리표. 코드는 이 표대로만 고친다',
  _창업자판정: [
    '다 잘라서 앱에 1:1로 짝찾아서 갈아끼워줘. 앱에 옛컷 아직도 있거든(카와이스타일) 다 빼줘',
    '전복장 크림파스타만 왼쪽 나머지 다 오른쪽!',
    '오징어무국은 얼큰이랑 맑은 2가지가 다 들어가야하거든? / 둘다 넣어줘',
  ],
  숫자: {
    새컷전체: 표.length,
    넣는다: 넣을것.length,
    뺀다잘림: 표.filter((r) => r.상태 === '⛔뺀다(잘림)').length,
    안넣는다: 표.filter((r) => r.상태 === '⛔안넣는다').length,
    픽커에는넣고_자동매칭만_뺀것: 넣을것.filter((r) => !r.자동매칭).length,
    픽커에서내릴옛컷: 내릴것.size,
    새키범위: 넣을것.length ? `${넣을것[0].새키} ~ ${넣을것.at(-1).새키}` : '-',
  },
  표,
  픽커에서내릴옛컷: [...내릴것].sort(),
}

console.log('📦 새 컷', 표.length, '컷')
for (const [k, v] of Object.entries(결과.숫자)) console.log(`   ${k.padEnd(16)} ${v}`)
console.log()
console.log('⛔ 뺀다(잘림) :', 표.filter((r) => r.상태 === '⛔뺀다(잘림)').map((r) => `${r.새컷} ${r.이름}`).join(' · '))
console.log('⛔ 안 넣는다   :', 표.filter((r) => r.상태 === '⛔안넣는다').map((r) => `${r.새컷} ${r.이름}`).join(' · '))
console.log()
const 짝없음 = 넣을것.filter((r) => !r.대신할옛컷.length)
console.log(`🆕 대신할 옛 컷이 없는 «순수 새 요리» ${짝없음.length}개`)
console.log('   ' + 짝없음.map((r) => r.이름).join(' · '))

if (process.argv.includes('--저장')) {
  const out = P + '처리표-갈아끼우기-2026-08-27.json'
  fs.writeFileSync(out, JSON.stringify(결과, null, 1))
  console.log('\n💾', out)
}
