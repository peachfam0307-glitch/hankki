// 📏🚨 **「T」가 «큰술»이 되기도 하고 «작은술»이 되기도 한다** (2026-09-03)
//
// ⭐⭐ **이건 흠이 아니라 «양이 3배 틀리는» 자리다.** 1큰술 = 3작은술.
//    창업자가 「배 12T」라고 적었는데 앱에 「배 12작은술」로 들어가면 **1/3 만 넣게 된다.**
//
// 🔢 **실측 (창업자 백업 259편 · 2026-09-03)** — 메모에 「숫자＋T」가 있고 재료칸에서 그 값을 찾은 편
//    · 뚝배기 파스타   고추장 1T   → **큰술**   ✅
//    · 목살돼지갈비구이 배 12T      → 작은술 ⛔
//    · 편육냉채       1/2T ×2     → 작은술 ⛔
//    · 돼지고기 된장덮밥 물 3T      → 작은술 ⛔
//    · LA갈비        참기름 2T    → 작은술 ⛔
//    ＝ **6곳 중 5곳이 작은술.** 같은 「T」가 편마다 다르게 들어갔다.
//
// ⭐⭐ **어긋난다는 것이 곧 증거다** — 규칙이면 여섯 곳이 «다 같게» 나온다.
//    갈렸다는 건 «그때그때 판단하는 것»이 했다는 뜻이고, 그건 **AI 정리**다.
//
// ✅ 우리 코드는 결백하다 — 재현해서 확인했다(규칙 7):
//    `parseRecipeText('… 배 12T …')` → 재료칸에 **「배 12T」 그대로** 나온다. 안 바꾼다.
//    ＋ `parseRecipe.js:329` 주석이 오히려 **「T(큰술)」**이라 적고 있다.
//    ＋ `ocr-proxy/` 어디에도 단위를 바꾸는 줄이 **0개**다.
//
// ⭐ 그리고 **앱이 화면에 직접 안내하고 있다** — `EditorScreen.jsx:699` = **「T=큰술·t=작은술」**
//    → 즉 «앱이 유저에게 약속한 뜻»과 «저장된 값»이 어긋난다.
//
// ⏳ **⛔지금 워커 지시문을 고치지 않는다** — 창업자가 아직 새 워커를 안 붙여넣었고,
//    「워커 프롬프트를 짐작으로 고치지 않는다」가 오늘 할 일에 못 박혀 있다(2026-09-02에 실제로 틀렸다).
//    ✅ 이 도구는 **그날이 왔을 때 「고쳐졌나」를 재는 잣대**다.
//
// 📌 절대원칙 34(땜빵 금지) — 이 6곳만 손으로 고치면 **다음에 담는 레시피에서 또 난다.**
//    고칠 자리는 «지시문»이고, 이 도구가 그게 됐는지 잰다.
//
// 쓰기:  node scripts/_probe-T단위-0903.mjs <백업.json>
import { readFileSync } from 'node:fs'

const 백업 = process.argv[2]
if (!백업) { console.error('⛔ 백업 파일 경로를 준다'); process.exit(1) }

const d = JSON.parse(readFileSync(백업, 'utf8'))
const 이스케이프 = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

const 찾은것 = []
for (const r of d.recipes) {
  const 밑감 = String(r.memo || '') + '\n' + String(r.rawText || '')
  const 재 = (r.ingredients || []).join(' | ')
  // 「이름 + 숫자 + T」 (뒤에 영문이 이어지면 낱말이라 뺀다 — 「1TB」·「2Ts」)
  for (const m of 밑감.matchAll(/([가-힣]{1,6})\s*([\d]+(?:[./][\d]+)?)\s*T(?![a-zA-Z])/g)) {
    const [, 이름, 양] = m
    const 몸 = 이스케이프(이름) + '\\s*' + 이스케이프(양) + '\\s*'
    const 작 = new RegExp(몸 + '작은술').test(재)
    const 큰 = new RegExp(몸 + '큰술').test(재)
    if (작 || 큰) 찾은것.push({ 편: (r.title || '').trim(), 이름, 양, 된것: 작 ? '작은술' : '큰술' })
  }
}

const 작 = 찾은것.filter((x) => x.된것 === '작은술')
const 큰 = 찾은것.filter((x) => x.된것 === '큰술')

console.log(`📂 ${백업.split('/').pop()}  ·  편 ${d.recipes.length}`)
console.log(`📏 메모의 「숫자＋T」가 재료칸에서 발견된 곳 — ${찾은것.length}곳\n`)
for (const x of 찾은것) {
  console.log(`  ${x.된것 === '큰술' ? '✅' : '⛔'} ${x.편.padEnd(20)} ${x.이름} ${x.양}T  →  ${x.된것}`)
}
console.log(`\n   큰술 ${큰.length}곳 · 작은술 ${작.length}곳`)

if (큰.length && 작.length) {
  console.log('\n🚨 **같은 「T」가 두 가지로 갈렸다** — 규칙이 아니라 «그때그때 판단»이 한 것이다(＝AI 정리).')
  console.log('   ⭐ 앱 화면 안내는 「T=큰술·t=작은술」(EditorScreen.jsx:699) 하나뿐이다.')
  process.exitCode = 1
} else if (작.length) {
  console.log('\n⛔ 전부 「작은술」이다 — 앱 안내(T=큰술)와 어긋난다.')
  process.exitCode = 1
} else {
  console.log('\n✅ 전부 「큰술」이다 — 앱 안내와 맞는다.')
}
