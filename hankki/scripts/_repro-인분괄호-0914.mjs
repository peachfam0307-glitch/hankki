// 🍚 인분을 바꿀 때 «괄호 안 대체 재료»가 안 바뀌던 것 — 재현판 (2026-09-14)
//
// 📮 창업자 = *"인분고칠때 괄호안에들어간 설탕이나 대체재료는 안고쳐짐"*
//
// 🌲 뿌리 = 수량 계산이 줄에서 **첫 숫자 하나만** 바꿨다(`src/scale.js` 의 `s.match(...)`).
//    🔢 실측 = 재료 1029줄 중 **괄호 안에 숫자가 있는 줄 78개(7.6%)**.
//       「아우노슈가 3큰술 (설탕 2큰술)」 × 2 → 앞만 6큰술이 되고 설탕은 2큰술 그대로.
//       설탕으로 만드는 사람은 **절반만 넣는다.** 그런데 화면은 «다 바뀐 것처럼» 보인다.
//
// ⛔ **＋ 같이 찾은 것** — 「1과1/2큰술」 × 2 = 「2와1/2큰술」. 「1」만 곱해서 **틀린 값**이 된다.
//
// ⭐ 무엇을 «안» 곱하나 = `docs/레시피-작성-규격.md` §1 계량 단위 표가 근거다 —
//    온도는 「도」 · 시간은 「분」 · 비율은 「1:1」 로 쓰라고 못 박혀 있다. 그 셋은 곱하면 안 된다.
//    반대로 「1컵(200ml)」 처럼 «병기»한 값은 곱해야 맞다(같은 표가 그렇게 쓰라고 한다).
//
// 실행: cd /home/user/hankki/hankki && node scripts/_repro-인분괄호-0914.mjs
import { scaleIngredient } from '../src/scale.js'

let 통과 = 0, 실패 = 0
const 실패목록 = []
const chk = (이름, 값, 기대) => {
  const ok = String(값) === String(기대)
  console.log(`  ${ok ? '✅' : '⛔'} ${이름}${ok ? '' : `\n       나온 값 = 「${값}」  ·  기대 = 「${기대}」`}`)
  ok ? 통과++ : (실패++, 실패목록.push(이름))
}

console.log('\n🍚 인분 바꾸기 — 괄호 안 재료도 같이 바뀌나\n')

// ───────── ① 창업자가 짚은 자리 — 괄호 안 대체 재료 ─────────
console.log('① 괄호 안 대체 재료도 같이 바뀐다 (창업자 제보)')
chk('「아우노슈가 3큰술 (설탕 2큰술)」 × 2', scaleIngredient('아우노슈가 3큰술 (설탕 2큰술)', 2), '아우노슈가 6큰술 (설탕 4큰술)')
chk('「아우노슈가 3/4작은술 (설탕 1/2작은술)」 × 4', scaleIngredient('아우노슈가 3/4작은술 (설탕 1/2작은술)', 4), '아우노슈가 3작은술 (설탕 2작은술)')
chk('「신김치 1/4포기 (약 300g)」 × 2 — 장 볼 때 무게를 본다', scaleIngredient('신김치 1/4포기 (약 300g)', 2), '신김치 ½포기 (약 600g)')
chk('「토마토소스 1컵 (200ml)」 × 2 — 규격이 ml 병기를 시킨다', scaleIngredient('토마토소스 1컵 (200ml)', 2), '토마토소스 2컵 (400ml)')
chk('「플레인 그릭요거트 400g (2컵)」 × 2', scaleIngredient('플레인 그릭요거트 400g (2컵)', 2), '플레인 그릭요거트 800g (4컵)')

// ───────── ② 혼합수 — 「N과 M/K」 ─────────
console.log('\n② 「1과1/2」 를 한 수로 읽는다 (⛔지금은 「1」만 곱해 틀린 값이 된다)')
chk('「아우노슈가 1과1/2큰술 (설탕 1큰술)」 × 2', scaleIngredient('아우노슈가 1과1/2큰술 (설탕 1큰술)', 2), '아우노슈가 3큰술 (설탕 2큰술)')
chk('「아우노슈가 2와1/4큰술 (설탕 1과1/2큰술)」 × 2', scaleIngredient('아우노슈가 2와1/4큰술 (설탕 1과1/2큰술)', 2), '아우노슈가 4½큰술 (설탕 3큰술)')

// ───────── ③ ⛔곱하면 «안 되는» 것 — 여기가 깨지면 레시피가 망가진다 ─────────
console.log('\n③ ⛔곱하면 안 되는 값은 그대로 둔다 (규격 §1 = 온도는 도 · 시간은 분 · 비율은 1:1)')
chk('「청양고추 2개 (5cm 크기)」 × 2 — 고추가 10cm 가 되면 안 된다', scaleIngredient('청양고추 2개 (5cm 크기)', 2), '청양고추 4개 (5cm 크기)')
chk('「맥된장 2/3큰술 + 백합된장 1과1/3큰술 (된장 총 2큰술 · 맥:백합=1:2)」 × 2 — 비율은 그대로', scaleIngredient('맥된장 2/3큰술 + 백합된장 1과1/3큰술 (된장 총 2큰술 · 맥:백합=1:2)', 2), '맥된장 1⅓큰술 + 백합된장 2⅔큰술 (된장 총 4큰술 · 맥:백합=1:2)')
chk('「빵가루 1컵 (180도에서 10분)」 × 2 — 온도·시간은 그대로', scaleIngredient('빵가루 1컵 (180도에서 10분)', 2), '빵가루 2컵 (180도에서 10분)')

// ───────── ④ 이미 되던 것이 «안 멈춘다» ─────────
console.log('\n④ 원래 되던 것은 그대로 된다 (⛔여기가 깨지면 고친 게 아니라 부순 것이다)')
chk('「스파게티 면 160g」 × 2', scaleIngredient('스파게티 면 160g', 2), '스파게티 면 320g')
chk('「마늘 1/2쪽」 × 4', scaleIngredient('마늘 1/2쪽', 4), '마늘 2쪽')
chk('「대파 2~3대」 × 2 — 범위', scaleIngredient('대파 2~3대', 2), '대파 4~6대')
chk('「소금 약간」 × 2 — 숫자가 없으면 그대로', scaleIngredient('소금 약간', 2), '소금 약간')
chk('배율이 1 이면 원문 그대로', scaleIngredient('아우노슈가 3큰술 (설탕 2큰술)', 1), '아우노슈가 3큰술 (설탕 2큰술)')
chk('「설탕 ½큰술」 × 2 — 유니코드 분수', scaleIngredient('설탕 ½큰술', 2), '설탕 1큰술')

console.log(`\n${실패 ? '⛔' : '✅'} ${통과}/${통과 + 실패}`)
if (실패) console.log('   ' + 실패목록.join('\n   '))
console.log()
process.exit(실패 ? 1 : 0)
