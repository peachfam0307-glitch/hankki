#!/usr/bin/env node
// 🔁 폰↔패드 «왕복» 재현판 — 2026-09-04 (창업자 실물 그대로)
//
// 📮 창업자 = *"하루종일 이게 뭐야"* · *"땜빵질하지말라니까"*
//    ⭐⭐ 맞는 말이다. 오늘 v12.43~46 네 판을 냈는데 **증상을 하나씩 쫓았다.**
//       그래서 이 판은 **증상이 아니라 «창업자 두 기기의 실제 상태»를 그대로 세워놓고** 잰다.
//
// 🔢 실물 (2026-09-04 17:55 창업자 캡처 · 둘 다 v12.46)
//    · 폰   = 레시피 262 · 「가져온 적 있음」 · 「마지막 올린 기기 = 없음」 · 기록 «비어 있음»
//    · 패드 = 레시피 260 · 〃                                              · 기록 «비어 있음»
//    · 클라우드 = 260 · at 09:02 · 도장 «없음»
//    ⭐ 즉 **아침 09:02 이후로 아무 기기도 못 올리고 못 받았다.**
//
// 🌲 뿌리 하나 — 「기억」이 셋인데 서로 어긋난다 (증상은 여섯이었다)
//    ⒜ `지문` = «내가 클라우드에 올려둔 것»이어야 하는데,
//       받은 «뒤»에 «내가 가진 것»으로 덮어써서 **안 올린 것도 「올렸다」가 된다.**
//       → 폰 262 / 클라우드 260 이 «영원히» 안 맞는다.
//    ⒝ 「받기」가 **「올리기가 막혔을 때의 곁가지」**로 매달려 있다(App.jsx 는 `왜 === '다른기기'` 일 때만 받는다).
//       → **올릴 게 없는 기기는 받지도 못한다.** 패드가 그 자리다.
//    ⒞ 판을 «뜬 시점»과 «얹는 시점» 사이가 벌어져 그 사이에 담은 것이 화면에서 사라진다.
//
// 🧪 이 판이 재는 것 — ⛔전부 «두 기기를 번갈아 켜서» 잰다. 한 기기만 보면 이 버그들은 안 잡힌다.
//   ① 폰이 «자기만 가진 편»을 올린다 (＝262 가 클라우드로 간다)   ← ⒜
//   ② 패드가 «올릴 게 없어도» 받는다 (＝260 → 262)               ← ⒝
//   ③ 한 바퀴 돌면 «양쪽 수가 같아진다» (262 = 262 = 262)
//   ④ 패드에서 꾸민 것이 폰으로 간다 (반대 방향)
//   ⑤ ⭐받는 «도중»에 담은 것이 «안 사라진다»                      ← ⒞
//   ⑥ 도장이 늘 찍힌다 (어느 길로 올려도)
//
// 📐 설계 = `docs/폰패드-자동동기화-설계-2026-09-04.md`

let 나쁨 = 0
const 잰다 = (좋나, 이름, 덧 = '') => {
  if (!좋나) 나쁨++
  console.log(`  ${좋나 ? '✅' : '⛔'} ${이름}${덧 ? ` — ${덧}` : ''}`)
}

// ── 두 기기를 «따로» 흉내 낸다 ────────────────────────────────────────────
//   ⭐⭐ 여기가 이 판의 핵심이다 — 기기마다 «자기 서랍»(localStorage)이 따로 있어야
//      지문·도장·받았나가 어긋나는 것을 잴 수 있다. 하나로 두면 오늘 버그가 안 재현된다.
const 서랍들 = { 폰: new Map(), 패드: new Map() }
let 지금기기 = '폰'
globalThis.localStorage = {
  getItem: (k) => { const m = 서랍들[지금기기]; return m.has(k) ? m.get(k) : null },
  setItem: (k, v) => { 서랍들[지금기기].set(k, String(v)) },
  removeItem: (k) => { 서랍들[지금기기].delete(k) },
}

// ── 가짜 파이어베이스 (기존 판들과 «같은 얼개») ────────────────────────────
const 창고 = new Map()
const 길 = (조각들) => 조각들.join('/')
const F = {
  doc: (_db, ...조각) => ({ _길: 길(조각), id: 조각[조각.length - 1] }),
  collection: (_db, ...조각) => ({ _길: 길(조각) }),
  async getDoc (자리) { const v = 창고.get(자리._길); return { exists: () => v !== undefined, data: () => v, ref: 자리 } },
  async getDocs (모음) {
    const 안 = []
    for (const [k, v] of 창고) {
      if (!k.startsWith(모음._길 + '/')) continue
      안.push({ id: k.slice(모음._길.length + 1), data: () => v, ref: { _길: k } })
    }
    return { forEach: (f) => 안.forEach(f), docs: 안, size: 안.length }
  },
  writeBatch: () => {
    const 할일 = []
    return {
      set: (자리, 값) => 할일.push(['set', 자리._길, 값]),
      delete: (자리) => 할일.push(['del', 자리._길]),
      commit: async () => { for (const [무엇, k, v] of 할일) 무엇 === 'set' ? 창고.set(k, v) : 창고.delete(k) },
    }
  },
  serverTimestamp: () => new Date().toISOString(),
}
const 사람 = { uid: 'fb-uid', providerData: [{ providerId: 'google.com', uid: '구글번호1' }] }

const C = await import('../src/cloud.js')
C._가짜창고물리기({ F, db: {}, auth: { currentUser: 사람 }, A: {} })

// ── 큰 창고도 기기마다 따로 ───────────────────────────────────────────────
const 큰창고들 = { 폰: new Map(), 패드: new Map() }
const 큰창고 = {
  async 넣기 (k, v) { 큰창고들[지금기기].set(k, JSON.parse(JSON.stringify(v))); return true },
  async 꺼내기 (k) { const v = 큰창고들[지금기기].get(k); return v === undefined ? null : JSON.parse(JSON.stringify(v)) },
  async 지우기 (k) { 큰창고들[지금기기].delete(k) },
  async 열쇠들 () { return [...큰창고들[지금기기].keys()] },
}
const U = await import('../src/syncUndo.js'); U._창고물리기(큰창고)
const L = await import('../src/syncLog.js'); L._창고물리기(큰창고)
const M = await import('../src/syncMeter.js'); M._창고물리기(큰창고)
const { 합치기 } = await import('../src/syncMerge.js')

// ── 두 기기의 «손안에 든 것» ──────────────────────────────────────────────
const 빈판 = () => ({
  _app: 'hankki', _v: 2, recipes: [], diary: [], folders: [], profile: { name: '한끼연구소' },
  shops: [], wishlist: [], shoppingList: [], pantry: [], seedV: 1, memoCleanV: 1, removedSeedIds: [],
})
const 편 = (id, 때) => ({ id, title: id, 고친때: 때 })
const 손 = {
  폰: { ...빈판(), recipes: [] },
  패드: { ...빈판(), recipes: [] },
}
// 둘 다 260편을 갖고 있다(아침에 맞춰진 것) ＋ 폰만 2편 더 담았다 = 262
for (let i = 1; i <= 260; i++) {
  손.폰.recipes.push(편('r' + i, 1000))
  손.패드.recipes.push(편('r' + i, 1000))
}
손.폰.recipes.push(편('새1', 5000), 편('새2', 5001))

const 백업만들기 = () => JSON.parse(JSON.stringify(손[지금기기]))

// ⭐ App.jsx 가 하는 그대로 «얹는다» — 판이 앱을 흉내 내야 실제와 안 갈린다
const 얹기 = (판) => { 손[지금기기] = JSON.parse(JSON.stringify(판)) }

// ⭐⭐ **앱을 «켜는 것»을 그대로 흉내 낸다** — App.jsx 의 순서를 여기에 옮겨 적는다.
//   ⛔ 이 순서가 바로 ⒝ 의 자리다. 앱이 바뀌면 이 함수도 같이 바뀌어야 한다.
const 앱켜기 = async (기기) => {
  지금기기 = 기기
  const 받 = await C.저절로받기(백업만들기)
  let 얹은판 = null
  if (받?.했나 && 받.판) {
    // ⭐ App.jsx 와 «같은 순서» — 얹기 직전에 «지금 화면»과 한 번 더 합친다
    얹은판 = 합치기({ 내것: 백업만들기(), 받은것: 받.판 })
    얹기(얹은판)
  }
  const 확인함 = !!(받?.했나 || 받?.왜 === '내가마지막' || 받?.왜 === '클라우드비었음')
  let 올 = null
  if (확인함) {
    const 올릴것 = 얹은판 ? async () => 얹은판 : 백업만들기
    올 = await C.저절로올리기(올릴것, { 확인함: true })
  }
  return { 올림: 올, 받음: 받 }
}

const 수 = (기기) => 손[기기].recipes.length
const 클라우드수 = () => [...창고.keys()].filter((k) => k.startsWith('users/구글번호1/recipes/')).length

// ── 아침 09:02 상태를 만든다 — ⭐도장 «없이» 올라간 판(수동 올리기 길) ──────
지금기기 = '폰'
서랍들.폰.set('hankki:cloud:on', '1')
서랍들.패드.set('hankki:cloud:on', '1')
서랍들.폰.set('hankki:did', '폰기기')
서랍들.패드.set('hankki:did', '패드기기')
C.받았다표시()
{
  // 260편만 든 판을 «도장 없이» 올린다 = 창업자 클라우드의 실제 모양
  const 아침 = JSON.parse(JSON.stringify(손.폰))
  아침.recipes = 아침.recipes.filter((x) => !String(x.id).startsWith('새'))
  await C.올리기(아침)
  const 메타 = 창고.get('users/구글번호1')
  창고.set('users/구글번호1', { ...메타, 기기: undefined, at: '2026-09-04T00:02:00.000Z' })
}
// 패드도 그때 받아 뒀다 = 「가져온 적 있음」
지금기기 = '패드'
C.받았다표시()

console.log('\n🔁 폰↔패드 왕복 — 창업자 두 기기를 그대로 세워놓고 잰다\n')
console.log(`   시작 = 폰 ${수('폰')} · 패드 ${수('패드')} · 클라우드 ${클라우드수()}\n`)

// ── ① 폰을 켠다 — 자기만 가진 2편을 올려야 한다 ────────────────────────────
const dbg1 = await 앱켜기('폰')
if (process.env.DBG) console.log('   [디버그] 받음 =', JSON.stringify(dbg1.받음 && { 했나: dbg1.받음.했나, 왜: dbg1.받음.왜 }), '· 올림 =', JSON.stringify(dbg1.올림 && { 했나: dbg1.올림.했나, 왜: dbg1.올림.왜, 올린것: dbg1.올림.올린것 }))
잰다(클라우드수() === 262, '① 📱 폰이 «자기만 가진 편»을 올린다 (262 가 클라우드로)',
  `클라우드 ${클라우드수()}편 (262 라야 맞다)`)

// ── ② 패드를 켠다 — ⭐«올릴 게 없어도» 받아야 한다 ─────────────────────────
await 앱켜기('패드')
잰다(수('패드') === 262, '② 📟 패드가 «올릴 게 없어도» 받는다 (260 → 262)',
  `패드 ${수('패드')}편 (262 라야 맞다)`)

// ── ③ 한 바퀴 돌면 셋이 같아진다 ──────────────────────────────────────────
await 앱켜기('폰')
잰다(수('폰') === 262 && 수('패드') === 262 && 클라우드수() === 262,
  '③ 🔁 한 바퀴 돌면 «셋이 같아진다»',
  `폰 ${수('폰')} · 패드 ${수('패드')} · 클라우드 ${클라우드수()}`)

// ── ④ 반대 방향 — 패드에서 담은 것이 폰으로 간다 ──────────────────────────
손.패드.recipes.push(편('패드가담음', 9000))
await 앱켜기('패드')
await 앱켜기('폰')
잰다(손.폰.recipes.some((x) => x.id === '패드가담음'),
  '④ ⬅️ 패드에서 담은 것이 «폰으로» 간다', `폰 ${수('폰')}편`)

// ── ⑤ ⭐받는 «도중»에 담은 것이 안 사라진다 ───────────────────────────────
//   ⛔ 이게 창업자가 본 「보관함에서 금방 사라지고 껐다 켜면 보인다」이다.
//      판을 «뜬 시점»과 «얹는 시점» 사이에 담기면, 얹기가 그 편을 지운다.
{
  지금기기 = '패드'
  손.패드.recipes.push(편('패드만9', 9100))
  await 앱켜기('패드')            // 패드가 올려서 클라우드가 앞선 상태로 만든다
  지금기기 = '폰'
  const 뜬판 = 백업만들기()        // ← 앱이 «판을 뜨는» 순간
  손.폰.recipes.push(편('받는중에담음', 9999))   // ← 그 뒤에 유저가 담는다
  const 받 = await C.저절로받기(async () => 뜬판)
  if (받?.했나 && 받.판) 얹기(합치기({ 내것: 백업만들기(), 받은것: 받.판 }))
  잰다(손.폰.recipes.some((x) => x.id === '받는중에담음'),
    '⑤ ⭐ 받는 «도중»에 담은 것이 안 사라진다 (창업자 = 「금방 사라져버려」)',
    손.폰.recipes.some((x) => x.id === '받는중에담음') ? '살아남았다' : '⛔사라졌다')
}

// ── ⑥ 도장은 어느 길로 올려도 찍힌다 ──────────────────────────────────────
잰다(!!창고.get('users/구글번호1')?.기기, '⑥ 🏷 도장이 찍혀 있다',
  창고.get('users/구글번호1')?.기기 ? '찍혔다' : '⛔비었다')

console.log(`\n   끝 = 폰 ${수('폰')} · 패드 ${수('패드')} · 클라우드 ${클라우드수()}`)
console.log(나쁨 ? `\n⛔ ${나쁨}칸 빨간불 — 폰·패드가 «실제로» 안 맞는다\n`
  : '\n✅ 폰↔패드가 양쪽으로 돈다\n')
process.exit(나쁨 ? 1 : 0)
