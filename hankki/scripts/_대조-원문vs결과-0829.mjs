// 🔍🔍 [2026-08-29] AI 다듬기 «원문 ↔ 결과» 자동 대조 — 창업자가 일일이 안 보게 (규칙 8)
//
// 📮 창업자 = "일일이 대조하기 힘들어 나는.."
// ⭐ 할 수 있다 — 앱이 8/22부터 원문(rawText)을 «같은 레코드 안»에 저장한다(v11.19 · 규칙 18 ⓙ).
//    그래서 백업 파일 하나면 담긴 편을 «전부» 기계가 잰다.
//
// 🔢 재는 것 넷
//   ① 제목  — 원문에 있는 말인가 · 수식어(사람이름·「초간단」·인분·「레시피」)가 남았나
//   ② 재료  — 이름이 원문에 있나 · 분량 숫자가 원문에 있나  ⛔없으면 «지어냄» 후보
//   ③ 걸음  — 걸음에 쓴 숫자·분량이 원문에 있나
//   ④ 빠짐  — 원문 재료 줄 중 결과에 «안 담긴» 것
//
// ⛔ 이 도구는 «판정»이 아니라 «짚어주기»다 — 마지막 판정은 창업자(규칙 11).
//    한글은 조사·활용이 붙어서 「없다」가 곧 「지어냈다」는 아니다. 그래서 ⚠️로만 띄운다.
// ⛔ 백업 파일은 창업자 개인 데이터다 — 저장소에 넣지 않는다. scratchpad 에서만 읽는다.
//
// 쓰기 = node hankki/scripts/_대조-원문vs결과-0829.mjs <백업.json> [제목조각]

import fs from 'node:fs'

const 파일 = process.argv[2]
const 고르기 = process.argv[3] || ''
if (!파일) { console.log('쓰기: node _대조-원문vs결과-0829.mjs <백업.json> [제목조각]'); process.exit(1) }

const 백업 = JSON.parse(fs.readFileSync(파일, 'utf8'))
const 편들 = (백업.recipes || []).filter(r => r.rawText && String(r.rawText).trim())
  .filter(r => !고르기 || String(r.title || '').includes(고르기))

// 견줄 때만 쓰는 «납작한» 글자 — 공백·문장부호를 떼고 소문자로
const 납작 = s => String(s || '').toLowerCase().replace(/[\s·,.()\[\]{}'"`~!?:;\-–—/\\|]/g, '')

// 숫자＋단위 (300g · 3큰술 · 1/2개 · 2컵)
const 분량뽑기 = s => [...String(s || '').matchAll(/(\d+(?:[./]\d+)?)\s*(g|kg|ml|l|L|개|장|알|큰술|작은술|컵|스푼|줌|톨|봉|캔|모|쪽|마리|인분|분|초|시간|T|t)?/g)]
  .map(m => ({ 수: m[1], 단위: m[2] || '', 통째: m[0].replace(/\s+/g, '') }))
  .filter(x => x.수)

// 재료 줄 → 이름 / 분량
function 재료쪼개기 (줄) {
  const t = String(줄 || '').trim()
  const m = t.match(/^(.*?)\s*([\d].*)$/)          // 숫자가 시작되는 자리에서 가른다
  if (m && m[1].trim()) return { 이름: m[1].trim(), 분량: m[2].trim() }
  return { 이름: t, 분량: '' }
}

const 수식어 = [
  { 이름: '「초간단」류 수식어', 재기: t => /초간단|간단한|황금|레전드|백종원|강레오|만능|최고의|미친|존맛|꿀맛/.test(t) },
  { 이름: '「레시피」가 제목에 남음', 재기: t => /레시피|만드는\s*법|만들기$/.test(t) },
  { 이름: '인분·개수가 제목에 남음', 재기: t => /\(?\s*\d+\s*인분\s*\)?/.test(t) },
  { 이름: '제목이 너무 김(14자↑)', 재기: t => t.replace(/\s/g, '').length >= 14 },
]

let 전체흠 = 0
console.log(`\n🔍 «원문 ↔ 결과» 대조 — 원문이 담긴 편 ${편들.length}개\n`)

for (const r of 편들) {
  const 원문 = String(r.rawText)
  const 원문납작 = 납작(원문)
  const 제목 = String(r.title || '')
  const 흠 = []

  // ① 제목
  for (const s of 수식어) if (s.재기(제목)) 흠.push(`제목 ⚠️ ${s.이름} — 「${제목}」`)
  if (제목 && !원문납작.includes(납작(제목))) {
    // 제목 낱말이 조각조각이라도 원문에 다 있으면 지어낸 게 아니다
    const 조각 = 제목.split(/\s+/).filter(Boolean)
    const 없는조각 = 조각.filter(w => !원문납작.includes(납작(w)))
    if (없는조각.length) 흠.push(`제목 ⛔ 원문에 없는 말: ${없는조각.join(' / ')}`)
  }

  // ② 재료
  const 재료 = (r.ingredients || []).map(String)

  // ⛔⛔ [2026-08-29 · 이 검사의 구멍이었다] 재료가 «아예 없으면» 아래 검사가 한 줄도 안 돌아
  //    제일 나쁜 사고(재료칸이 텅 빔)가 ✅ 로 통과했다. 실제로 「콩나물무침」이 그랬다.
  //    📌 규칙 18 ⓘ — 「통과했나」가 아니라 «무엇을 보고 통과했나». 빈 배열은 아무것도 안 본 것이다.
  if (!재료.length && /\d\s*(g|kg|ml|개|장|알|큰술|작은술|컵|스푼|줌|톨|봉|캔|모|쪽|마리)/.test(원문)) {
    흠.push('재료 ⛔⛔ 재료칸이 «통째로 비었다» — 원문엔 분량이 붙은 재료가 있다')
  }
  for (const 줄 of 재료) {
    const { 이름, 분량 } = 재료쪼개기(줄)
    if (이름 && !원문납작.includes(납작(이름))) 흠.push(`재료 ⛔ 원문에 없는 이름: 「${줄}」`)
    else for (const q of 분량뽑기(분량)) {
      if (!원문납작.includes(납작(q.통째)) && !원문납작.includes(q.수)) {
        흠.push(`재료 ⚠️ 원문에 없는 분량: 「${줄}」 → ${q.통째}`)
      }
    }
  }

  // ③ 걸음의 숫자
  for (const [i, 걸음] of (r.steps || []).entries()) {
    for (const q of 분량뽑기(걸음)) {
      if (!원문납작.includes(납작(q.통째)) && !원문납작.includes(q.수)) {
        흠.push(`걸음${i + 1} ⚠️ 원문에 없는 숫자: ${q.통째} — 「${String(걸음).slice(0, 40)}…」`)
      }
    }
  }

  // ⑤ [2026-08-29 신설] 새 지시문 ⑹ 이 도나 — «순서에 분량이 남았나»
  //   📮 흠 = 「물은 딱 1/3컵만 넣어주세요」가 걸음에서 「물을 넣어요」로 깎였다.
  //      그 편에선 1/3컵이 «핵심»인데 재료칸으로 밀려나 요리 중에 왔다갔다 해야 한다.
  //   ⭐ 재는 법 = 원문 «순서 줄»에 붙은 분량이 결과 걸음에도 살아 있나.
  //      ⛔ 재료 줄의 분량은 안 센다 — 그건 ingredients 몫이라 걸음에 없어도 정상이다.
  const 순서줄 = 원문.split(/\r?\n/).map(s => s.trim())
    .filter(s => /^\s*\d+\s*[.)]/.test(s) || /해\s*주세요|주시고|넣어주세요|볶아|삶아|섞어/.test(s))
  const 걸음납작 = 납작((r.steps || []).join(' '))
  const 본분량 = new Set()
  for (const 줄 of 순서줄) for (const q of 분량뽑기(줄)) {
    if (!q.단위) continue                                  // 「1.」 같은 번호는 분량이 아니다
    if (본분량.has(q.통째)) continue
    본분량.add(q.통째)
    if (!걸음납작.includes(납작(q.통째))) {
      흠.push(`분량 ⚠️ 원문 순서엔 있는데 걸음에서 빠졌다: ${q.통째} — 「${줄.slice(0, 34)}…」`)
    }
  }

  // ④ 원문에 있는데 결과에 안 담긴 재료 줄
  const 결과납작 = 납작(재료.join(' ') + ' ' + (r.steps || []).join(' '))
  const 원문재료줄 = 원문.split(/\r?\n/).map(s => s.trim())
    .filter(s => s && /\d/.test(s) && /(g|kg|ml|개|장|알|큰술|작은술|컵|스푼|줌|톨|봉|캔|모|쪽|마리)\b|[가-힣]\s*\d/.test(s))
    .filter(s => s.replace(/\s/g, '').length <= 20)
  for (const 줄 of 원문재료줄) {
    // ⛔ 번호가 붙은 줄(「1.진미채 300g을…」)은 «순서»지 재료 목록이 아니다 —
    //    안 걸러내면 이름이 「1.진미채」로 잘려 «멀쩡한 편»에 흠이 뜬다(2026-08-29 실측 2건).
    //    📌 시끄러운 게이트는 죽은 게이트다.
    if (/^\s*\d+\s*[.)]/.test(줄)) continue
    const { 이름 } = 재료쪼개기(줄)
    // ⛔ SNS 부스러기(「3월 26일」·「댓글 45」·「릴스 친구 1」)는 재료가 아니다 — 안 담기는 게 «옳다»
    if (/댓글|좋아요|답글|릴스|팔로|조회|공유|저장|\d+월\s*\d+일|\d+시간|\d+분\s*전|광고/.test(줄)) continue
    if (이름.replace(/\s/g, '').length >= 2 && !결과납작.includes(납작(이름))) {
      흠.push(`빠짐 ⚠️ 원문에 있는데 결과에 없다: 「${줄}」`)
    }
  }

  전체흠 += 흠.length
  console.log(`${흠.length ? '⚠️' : '✅'} ${제목}  (재료 ${재료.length} · 걸음 ${(r.steps || []).length} · 원문 ${원문.length}자)`)
  for (const h of 흠) console.log(`     ${h}`)
  console.log('')
}

console.log(`── 흠 후보 ${전체흠}개 · ⛔ = 지어냄 의심 · ⚠️ = 눈으로 확인\n`)
