    def 가로중심(path, y0, y1, 색으로=True, 최소=45):
        a = np.asarray(Image.open(path).crop((0, y0, 1080, y1)).convert('RGB'), dtype=float)
        신호 = (a.max(axis=2) - a.min(axis=2)) if 색으로 else (255 - a.mean(axis=2))
        col = 신호.mean(axis=0)
        문턱 = max(col.max() * (0.25 if 색으로 else 0.30), 8)
        묶, cur = [], None
        for x, v in enumerate(col):
            if v > 문턱:
                cur = [x, x] if cur is None else [cur[0], x]
            elif cur:
                묶.append(cur); cur = None
        if cur:
            묶.append(cur)
        return [((m[0] + m[1]) // 2, m[1] - m[0]) for m in 묶 if m[1] - m[0] > 최소]

