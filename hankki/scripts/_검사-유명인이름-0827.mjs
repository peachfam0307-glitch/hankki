import { 레시피들 } from './recipe.mjs'

const 이름 = [
  '백종원','류수영','어남선생','성시경','안성재','강레오','이연복','최현석','정지선',
  '에드워드리','에드워드 리','김풍','오세득','샘킴','샘 킴','최강록','정호영','여경래',
  '이원일','임짱','승우아빠','쯔양','히밥','밥아저씨','박은영','김수미','이혜정',
  '심영순','최현석','고든램지','고든 램지','제이미','제이미올리버',
]
const 프로 = [
  '흑백요리사','편스토랑','골목식당','냉장고를부탁해','냉장고를 부탁해','수요미식회',
  '삼시세끼','윤식당','한식대첩','마이리틀텔레비전','신상출시편스토랑','최자로드',
]

const r = 레시피들()
let 걸림 = 0
const 표 = []
for (const x of r) {
  const 통 = JSON.stringify(x)
  for (const n of [...이름, ...프로]) {
    if (통.includes(n)) { 표.push(`⛔ ${x.title} ← 「${n}」`); 걸림++ }
  }
}
표.forEach(s => console.log(s))
console.log(`\n레시피 ${r.length}편 × 이름 ${이름.length}개 ＋ 프로 ${프로.length}개 → 걸린 것 ${걸림}건`)
process.exit(0)
