// 🛑 설계 관문 — «설계를 내놓기 전»에 통과해야 하는 문. (창업자 2026-09-04)
//
// 📮 창업자 원문 = *"3번 다각도로 검토해서 가져와. **절대 땜빵식은 안돼. 절대원칙이야.**
//    설계는 촘촘하고 세밀하게, 리스크 고려해서 다각도 서치 검토 후 설계한다.
//    **설계할때 읽고 시작 — 코드로 만들어서 박아둬**"*
//
// ⛔⛔ **왜 만들었나 — 도구가 뿌리를 짚어줬다.**
//    `node scripts/rules.mjs --bare` 실측(2026-09-04) = **설계 절대원칙 셋이 «전부 맨몸»**이었다.
//      32 「수만 명이 되어도」 · 33 「3번 다각도 검토 후 보고」 · 34 「땜빵 금지」 → 장치 0개
//    그래서 그날 아침 내가 **셋 다 어겼다** — 규칙을 몰라서가 아니라 **아무것도 안 막고 있어서**다.
//    📌 `rules.mjs` 가 그 아래 이렇게 적어뒀다:
//       *"규칙 글을 더 크게 쓰는 것은 고치는 게 아니다 — 그날 그 규칙들은 이미 «절대원칙»이었다."*
//
// ⭐⭐ **이 문의 핵심 = 「세 각도 채웠냐」고 «묻지» 않는다. 땜빵을 «기계가» 알아본다.**
//    절대원칙 34 가 이미 잣대 셋을 줬는데 그중 둘은 **말을 안 믿고 판정할 수 있다**:
//      ① 숫자만 바꾸는가   → **워킹트리 diff 를 읽는다.** 내가 뭐라 우겨도 못 속인다.
//      ③ 잃는 것이 그대로인가 → 전/후를 둘 다 받아 **같으면 거부**한다.
//    ② 「왜 그 값인지 잰 근거」만 글로 받되, **「확인함」·「적당히」류는 값으로 안 쳐준다**
//       (`evidence.mjs` 가 2026-08-03 부터 쓰는 방식 그대로).
//
// ⚠️⚠️ **정직하게 — 못 막는 것.** 세 각도 «글»을 성의 없이 채우면 그건 못 잡는다.
//    `evidence.mjs` 도 같은 한계다. 기계가 잡는 건 ①과 ③이고 ②는 「잰 것을 붙였나」까지다.
//
// 🧾 쓰는 법
//   node scripts/design-gate.mjs --무엇 "무엇을 설계하나" \
//     --사람 "1차: 실제 사람을 세워 흐름을 따라가며 «고칠 것»이 뭐가 나왔나" \
//     --사고 "2차: 일부러 잘못 굴려서 «고칠 것»이 뭐가 나왔나" \
//     --규모 "3차: 유저 수 × 시간을 곱해 «고칠 것»이 뭐가 나왔나 (숫자 포함)" \
//     --잰것 "그 값을 «잰» 근거 (명령 출력 · 파일:줄 · 숫자＋단위)" \
//     --잃던것 "지금은 실패하면 무엇을 잃나" \
//     --잃을것 "고친 뒤엔 실패하면 무엇을 잃나"
//   ＋ diff 가 숫자만 바뀌었을 때만: --왜숫자 "왜 이게 땜빵이 아닌지"
//
// 🚪 이 문은 **막다른 길이 아니다** — 통과 못 하면 «무엇이 모자란지»를 그 자리에서 찍는다.
//    (규칙 19 = 2026-08-13 에 게이트가 «푸는 길»까지 막아 두 번 사고가 났다)

import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(new URL('../..', import.meta.url).pathname)
const argv = process.argv.slice(2)
const get = (k) => { const i = argv.indexOf(`--${k}`); return i >= 0 ? argv[i + 1] : undefined }

const 무엇 = get('무엇')
const 각도 = { 사람: get('사람'), 사고: get('사고'), 규모: get('규모') }
const 잰것 = get('잰것')
const 잃던것 = get('잃던것')
const 잃을것 = get('잃을것')
const 왜숫자 = get('왜숫자')

let 실패 = []
const 잡음 = (제목, ...줄) => 실패.push({ 제목, 줄 })

// ── 절대원칙 제목은 «박지 않고 읽어 온다» ───────────────────────────
//    ⛔ 2026-09-04 에 `latest-map` 이 「전문 17KB」를 박아뒀다가 낡았다. 같은 실수를 여기서 안 한다.
const 원칙제목 = (번호) => {
  try {
    const md = readFileSync(join(ROOT, 'hankki/CLAUDE.md'), 'utf8')
    const m = md.match(new RegExp(`^${번호}\\. \\*\\*(.+)$`, 'm'))
    return m ? m[1].replace(/\*\*/g, '').trim().slice(0, 96) : `절대원칙 ${번호}`
  } catch { return `절대원칙 ${번호}` }
}

// ── ⓪ 무엇을 설계하나 ───────────────────────────────────────────────
if (!무엇 || 무엇.trim().length < 6) {
  잡음('--무엇 이 비었다', '무엇을 설계하는지 한 줄로 적는다. 그게 없으면 각도도 못 잡는다.')
}

// ── ① [기계] 숫자만 바꾸는가 — diff 를 «읽어» 판정한다 ──────────────
//    ⭐ 절대원칙 34 의 첫 잣대. 여기만은 내 말을 안 믿는다.
let 숫자만 = false
let diff요약 = ''
try {
  const d = execFileSync('git', ['diff', 'HEAD', '-U0'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 24 })
  const 뺀줄 = [], 넣은줄 = []
  for (const l of d.split('\n')) {
    if (l.startsWith('+++') || l.startsWith('---')) continue
    if (l.startsWith('+')) 넣은줄.push(l.slice(1))
    else if (l.startsWith('-')) 뺀줄.push(l.slice(1))
  }
  const 숫자뺀꼴 = (a) => a.map((s) => s.replace(/[\d.]+/g, '#')).sort().join('\n')
  const 바뀐게있나 = 뺀줄.length > 0 && 넣은줄.length > 0
  숫자만 = 바뀐게있나 && 숫자뺀꼴(뺀줄) === 숫자뺀꼴(넣은줄)
  diff요약 = `뺀 줄 ${뺀줄.length} · 넣은 줄 ${넣은줄.length}`
} catch { /* git 이 없으면 이 검사는 건너뛴다 — 막는 게 목적이지 멈추는 게 목적이 아니다 */ }

if (숫자만 && !왜숫자) {
  잡음(
    '🩹 지금 고침은 «숫자만» 바뀌었다 — 절대원칙 34 의 첫 잣대에 걸린다',
    `실측 = ${diff요약} · 숫자를 빼고 보면 앞뒤가 «같은 줄»이다`,
    원칙제목(34),
    '',
    '⛔ 한도·대기·크기를 넓히는 것은 그 숫자에 또 닿으면 똑같이 터진다.',
    '✅ 대신 «실패의 모양»을 바꾼다 — 예: 「초과 = 한 일을 전부 잃음」 → 「초과 = 있는 것만 받음」',
    '',
    '👉 정말 숫자가 맞는 답이면(버전 올리기·오타 등) --왜숫자 "…" 로 한 줄만 대면 통과한다.',
  )
}

// ── ② [33] 세 각도 — «다른 각도로» 세 번. 같은 것을 세 번이 아니다 ──
const 각도설명 = {
  사람: '실제 유저를 세워놓고 흐름을 따라간다 — 갓 깐 사람 · 오래 쓴 사람 · 폰 바꾼 사람 · 무료/유료 · 창업자 본인',
  사고: '«잘못될 수 있는 것»을 일부러 일으킨다 — 중간에 꺼짐 · 저장 실패 · 두 탭 · 네트워크 끊김 · 되돌리기',
  규모: '유저 수와 «시간»을 곱한다 — 1만 명 · 1년 뒤 · 갑자기 몰릴 때 (절대원칙 32)',
}
for (const [이름, 값] of Object.entries(각도)) {
  if (!값 || 값.trim().length < 20) {
    잡음(`${이름} 각도가 비었다 (--${이름})`, 각도설명[이름], '', 원칙제목(33))
  }
}
// ⭐ 33 원문 = *"세 번 다 «아무것도 안 나오면» 그건 검토를 안 한 것이다"*
const 빈말 = /^(없음|없다|해당\s*없음|괜찮|문제\s*없|ok|n\/a)/i
for (const [이름, 값] of Object.entries(각도)) {
  if (값 && 빈말.test(값.trim())) {
    잡음(`${이름} 각도에서 «고칠 것이 하나도 안 나왔다»`,
      '그건 검토를 안 한 것이다 — 각도를 바꿔 다시 본다.',
      원칙제목(33))
  }
}
// ⭐ 32 = 규모 각도엔 «숫자»가 있어야 한다. 「나중에 문제될 수도」로 뭉개지 말 것.
if (각도.규모 && !/\d/.test(각도.규모)) {
  잡음('규모 각도에 «숫자»가 없다',
    '「그 벽에 «몇 명»에서 닿나」를 숫자로 낸다. ⛔「나중에 문제될 수도」로 뭉개지 말 것.',
    원칙제목(32))
}

// ── ③ [34-②] 그 값을 «잰» 근거가 있나 ──────────────────────────────
const 값이아닌말 = /^(확인함|받았음|봤음|적당히|되겠지|충분히|알아서|대충)/
const 잰티 = /(\d)|(\.mjs|\.js|\.jsx|\.md|\.json)|(:\d+)|(node |npm |git |curl )/
if (!잰것 || 잰것.trim().length < 4) {
  잡음('--잰것 이 비었다 — «왜 그 값인지» 잰 근거가 없다',
    '잰 게 아니라 「되겠지」로 고른 것이다. 명령 출력 · 파일:줄 · 숫자＋단위 중 하나를 댄다.',
    원칙제목(34))
} else if (값이아닌말.test(잰것.trim()) || !잰티.test(잰것)) {
  잡음('--잰것 이 «값»이 아니다',
    `받은 값: ${잰것}`,
    '⛔ 「확인함」·「적당히」는 값이 아니다 (evidence.mjs 가 2026-08-03 부터 쓰는 잣대와 같다).',
    '✅ 예: "rules.mjs --bare 실측 = 맨몸 20개" · "ProfileScreen.jsx:402" · "17,625 B"')
}

// ── ④ [기계] [34-③] 실패의 «모양»이 바뀌었나 ───────────────────────
const 눌러 = (s) => (s || '').replace(/\s+/g, '').toLowerCase()
if (!잃던것 || !잃을것) {
  잡음('--잃던것 · --잃을것 둘 다 있어야 한다',
    '「실패했을 때 무엇을 잃나」를 «전»과 «후»로 각각 적는다.',
    '그 둘이 같으면 고친 게 아니라 미룬 것이다.',
    원칙제목(34))
} else if (눌러(잃던것) === 눌러(잃을것)) {
  잡음('🩹 실패했을 때 «잃는 것»이 그대로다 — 모양이 안 바뀌었다',
    `전: ${잃던것}`,
    `후: ${잃을것}`,
    '📌 숫자는 언젠가 또 닿는다. 모양이 바뀌면 닿아도 안 터진다.',
    원칙제목(34))
}

// ── 판정 ────────────────────────────────────────────────────────────
if (실패.length) {
  console.error(`\n⛔⛔ 설계 관문 — ${실패.length}칸이 막혔다. 이대로 내놓지 말 것.\n`)
  for (const f of 실패) {
    console.error(`  ⛔ ${f.제목}`)
    for (const l of f.줄) console.error(`     ${l}`)
    console.error('')
  }
  console.error('📌 이 문은 창업자가 2026-09-04 에 만들라고 한 것이다 —')
  console.error('   *"3번 다각도로 검토해서 가져와. 절대 땜빵식은 안돼. 절대원칙이야."*')
  console.error('   통과 못 하면 **설계를 내놓지 말고** 모자란 각도를 먼저 돈다.\n')
  process.exit(1)
}

// 🚪 통과했다는 «표»를 남긴다 — `design-guard.sh` 가 이걸 보고 길을 연다.
//    ⭐ 이 표는 설계 «내용»을 담는다 — 빈 표로는 못 연다(스스로 열려면 없는 말을 지어내야 한다).
try {
  const fs = await import('node:fs')
  fs.writeFileSync('/tmp/hankki-설계통과', `${무엇}\n잰것: ${잰것}\n${잃던것} → ${잃을것}\n`)
} catch { /* 표를 못 남겨도 판정은 끝났다 */ }

console.log(`\n✅ 설계 관문 통과 — ${무엇}`)
console.log(`   1차·사람 · 2차·사고 · 3차·규모 셋 다 «고칠 것»이 나왔다 (절대원칙 33)`)
console.log(`   잰 근거 = ${잰것}`)
console.log(`   실패의 모양 = 「${잃던것}」 → 「${잃을것}」 (절대원칙 34)`)
if (숫자만) console.log(`   ⚠️ diff 는 숫자만 바뀌었다 — 댄 이유: ${왜숫자}`)
console.log('')
