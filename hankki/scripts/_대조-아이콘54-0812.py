# ■ ③ «이름»으로 겹침 — 픽셀로는 못 잡는 진짜 겹침
#    앱이 제목을 보고 그림을 고르는 규칙(`ICON_RULES`)에 이 이름이 «이미» 걸리는가.
#    걸린다면 = 그 요리 그림이 앱에 이미 있다 → 갈아끼울지 창업자가 정한다(규칙 11).
print('\n■ ③ 이름으로 겹침 — 이 이름을 지금 앱에 치면 무슨 그림이 붙나')
소스 = (뿌리 / 'src/components/FoodIcon.jsx').read_text(encoding='utf-8')
규칙 = []
# ⚠️ 값이 «따옴표 친 파일 키»(`'fe_156'`)일 때도, «SVG 컴포넌트 이름»(`stirfry`)일 때도 있다.
#    둘 다 받는다 — 한쪽만 받으면 조용히 0줄이 된다.
for m in re.finditer(r"\[\s*\[([^\]]*)\]\s*,\s*('[^']+'|[A-Za-z_$][\w$]*)\s*\]", 소스):
    낱말 = re.findall(r"'([^']+)'", m.group(1))
    if 낱말:
        규칙.append((낱말, m.group(2).strip("'")))
# 🛑 **0줄이면 죽는다** — 안 그러면 「전부 겹침 없음」이라는 «거짓 통과»가 된다.
