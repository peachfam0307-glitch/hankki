N = 128


def 지문(p):
    im = Image.open(p).convert('RGBA')
    상자 = im.split()[3].getbbox()          # ⭐ 그림이 실제로 있는 자리만
    if 상자:
        im = im.crop(상자)
    바탕 = Image.new('RGB', im.size, (255, 255, 255))   # ⚠️ 흰 판에 얹는다(투명이 검정으로 안 잡히게)
    바탕.paste(im, (0, 0), im)
    return list(바탕.resize((N, N), Image.LANCZOS).getdata())


def 차이(a, b):
    s = 0
    for (r1, g1, b1), (r2, g2, b2) in zip(a, b):
        s += abs(r1 - r2) + abs(g1 - g2) + abs(b1 - b2)
    return s / (len(a) * 3)


