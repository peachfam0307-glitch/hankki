// 🐟🔢 재현 — 「제목이 «계량» · 걸음에 번호 13·4 가 남는다」 (창업자 원문 2026-08-31) 〔반영됨〕
//
// 📮 창업자가 삼치간장조림 인스타 캡처 원문을 그대로 붙여 줬다. 그걸로 잰다.
//    (원문은 화면 찌꺼기까지 그대로다 — 「KT 11:27 F」·OCR 오독 「13」)
//
// ⭐⭐ 이 판이 지키는 것 셋
//   ① **제목** — 첫 줄이 `#삼치간장조림 레시피` 인데 제목이 「계량」이 됐다
//      🔎 구멍이 «둘»이었다(실측으로 하나씩 갈랐다):
//         ⑴ `#` 로 시작하는 줄을 **통째로 버렸다**(태그 더미 규칙) → 제목 가지까지 가지도 못했다
//         ⑵ 그리고 화면 찌꺼기 「KT 11:27 F」가 «첫 줄»을 차지해 제목 가지(idx 0)가 안 돌았다
//         → 둘 다 고쳐야 제목이 잡힌다. 하나만 고치면 여전히 빈다.
//   ② **번호** — OCR 이 ③을 「13」으로 읽어 차례가 깨지자 **13 과 4 가 본문 글자로 남았다**
//      ⭐ 사람은 1,2 다음에 「13」을 보면 3 으로 읽는다 → 그 규칙을 코드에 넣었다
//   ③ **재료 분량** — 8줄이 분량과 함께 살아 있다(규칙 파서 쪽은 원래 멀쩡했다 · AI 쪽은 별도 판)
//
// 🧪 규칙 12 = ①을 되돌리면 제목이 「계량」으로, ②를 되돌리면 「13」·「4」가 본문에 되살아난다.
//
// 실행: cd /home/user/hankki/hankki && node scripts/_repro-삼치파서-0831.mjs
import { parseRecipeText } from '../src/parseRecipe.js'

let 통과 = 0, 전체 = 0
const chk = (이름, 좋나, 덧 = '') => { 전체++; if (좋나) 통과++; console.log(`  ${좋나 ? '✅' : '❌'} ${이름}${덧 ? '  ' + 덧 : ''}`) }

const 원문 = `KT 11:27 F
#삼치간장조림 레시피

[계량]
밥숟가락 기준

[재료]
무 1/3개
비비고 순살 삼치 2팩
식용유 2스푼
물 200ml

[양념]
미림 15스푼
청주 12스푼
간장 3스푼
생강즙 조금

[만드는 법]

1 팬에 식용유 2스푼을 두르고
중약불에서 무를 앞뒤로 3분씩 구워주세요.
※무의 각진 모서리는 돌려깎기 했어요.

2 물을 자작하게 붓고
미림 15스푼, 청주 12스푼, 간장 3스푼,
생강즙 조금을 넣어 강불에서 한소끔 끓여주세요.

13 중약불로 줄이고
양념을 끼얹어가며 양념이 찐득해질 때까지 졸여주세요.

4 무가 거의 다 익으면
비비고 순살 삼치구이를 올리고
양념을 촉촉하게 끼얹어주면 완성이에요.`

console.log('\n🐟 창업자 삼치 원문 — 파서에 그대로 넣는다\n')
const r = parseRecipeText(원문)

// ── ① 제목 ────────────────────────────────────────────────────────────
chk('① 제목이 「삼치간장조림」이다', r.title === '삼치간장조림', JSON.stringify(r.title))
chk('①-b 절 이름이 제목을 채가지 않는다 (계량·재료)', !/^(계량|재료|양념|만드는\s*법)$/.test(r.title || ''))

// ⭐ 구멍이 둘이었다는 것 자체를 못 박는다 — 하나만 고치면 다시 빈다
chk('①-c 화면 찌꺼기가 첫 줄이어도 제목을 잡는다',
  parseRecipeText('KT 11:27 F\n#김치볶음밥 레시피\n[재료]\n김치 1컵').title === '김치볶음밥')
chk('①-d 화면 찌꺼기가 없어도 잡는다 (해시태그만 있는 경우)',
  parseRecipeText('#김치볶음밥 레시피\n[재료]\n김치 1컵').title === '김치볶음밥')
chk('①-e ⛔ «태그 더미»는 제목이 아니다 (예전처럼 버린다)',
  parseRecipeText('#오늘의집밥 #저녁메뉴 #맛스타그램\n[재료]\n김치 1컵').title !== '오늘의집밥 #저녁메뉴 #맛스타그램')

// ── ② 번호 ────────────────────────────────────────────────────────────
const 번호남음 = (r.steps || []).filter((s) => /^\s*\d/.test(s))
chk('② 걸음 앞에 번호 글자가 «하나도» 안 남았다', 번호남음.length === 0,
  번호남음.length ? 번호남음.join(' / ') : '')
chk('②-b OCR 이 잘못 읽은 「13」도 걸음으로 갈렸다',
  (r.steps || []).some((s) => /중약불로 줄이고/.test(s) && !/13/.test(s)))
chk('②-c 마지막 걸음도 살아 있다', (r.steps || []).some((s) => /완성이에요/.test(s)))

// ⛔ 안 건드려야 하는 자리 — 분량·인분은 여전히 «번호가 아니다»
chk('②-d ⛔ 「3 큰술」·「2 인분」을 번호로 오해하지 않는다',
  (() => {
    const t = parseRecipeText('감자조림\n[재료]\n감자 2개\n[만드는 법]\n1 감자를 썰어요.\n2 물을 부어요.\n3 큰술 간장을 넣어요.')
    return (t.steps || []).some((s) => /3\s*큰술/.test(s))
  })())

// ── ③ 재료 ────────────────────────────────────────────────────────────
const 분량줄 = (r.ingredients || []).filter((x) => /\d|조금/.test(x))
chk('③ 재료 8줄에 분량이 붙어 있다', (r.ingredients || []).length === 8 && 분량줄.length === 8,
  `${분량줄.length}/${(r.ingredients || []).length} · ${(r.ingredients || []).join(' · ')}`)

console.log(`\n🔢 ${통과}/${전체}`)
if (통과 !== 전체) { console.log('\n⛔ 창업자 삼치 원문이 다시 어긋난다.'); process.exit(1) }
console.log('✅ 제목 · 번호 · 분량 셋 다 맞다.')
