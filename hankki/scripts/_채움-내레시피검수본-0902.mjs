const 다듬 = (s) => String(s || '').replace(/\s+/g, '').trim()

function 문서에서읽기() {
  const 통 = new Map()
  for (const 상대 of 문서들) {
    const 글 = readFileSync(path.join(뿌리, 상대), 'utf8')
    // ⛔⛔ **문서 «자리»로 원문 절을 찾지 않는다** — 처음엔 「창업자 원문」 뒤만 잘랐는데
    //    1차 문서는 그 말이 원문 «뒤»(151줄)에 나와서 **원문 절을 통째로 잘라 버렸다**(4편 실패).
    //    ⭐ 두 문서의 «생김새»가 다르다 — 자리를 잣대로 삼으면 문서를 고칠 때마다 또 깨진다.
    //    ✅ 그래서 「■ …」 을 다 훑되 **`[만드는 법]`·`[재료]` 표가 «있는» 덩이만** 쓴다.
    //       뒤쪽 「앱에 넣을 때 할 일」의 ■ 들은 그 표가 없어 저절로 걸러진다.
    const 덩이 = 글.split(/^■[ \t]*/m).slice(1)
    for (const d of 덩이) {
      const 줄 = d.split('\n')
      const 이름 = 줄[0].replace(/\s*—.*$/, '').trim()   // 「■ 약밥 — 나중에」 의 꼬리를 뗀다
      if (!이름 || /나중에/.test(줄[0])) continue
      const 몸 = 줄.slice(1)
      const 걸음 = [], 재료 = []
      let 칸 = null, 시간 = 0, 인분 = 0
      for (const l0 of 몸) {
        const l = l0.trim()
        if (!l) continue
        if (/^\[만드는\s*법\]/.test(l)) { 칸 = 'step'; continue }
        if (/^\[재료\]/.test(l))       { 칸 = 'ing';  continue }
        const t = l.match(/^\[(\d+)\s*분\s*·\s*(\d+)\s*인분\]/)
        if (t) { 시간 = Number(t[1]); 인분 = Number(t[2]); 칸 = null; continue }
        if (/^(═|─|📮|⭐|⛔|✅|##|\||>)/.test(l)) { 칸 = null; continue }
        if (칸 === 'step') 걸음.push(l)
        else if (칸 === 'ing') 재료.push(l)
      }
      if (걸음.length || 재료.length) 통.set(다듬(이름), { 걸음, 재료, 시간, 인분 })
    }
  }
  return 통
}

