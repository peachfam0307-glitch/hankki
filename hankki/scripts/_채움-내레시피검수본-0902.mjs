for (const 줄 of 표) {
  const 대상 = (백업.recipes || []).filter((r) => 다듬(r.title) === 다듬(줄.백업))
  if (!대상.length) { 못찾음.push(`${줄.백업} — 백업에 그 이름이 없다`); continue }

  // 어디서 가져오나
  let 재료, 걸음, 시간, 인분, 출처
  if (줄.곳 === 'repo') {
    const s = 저장소.get(다듬(줄.앱))
    if (!s) { 못찾음.push(`${줄.백업} → ${줄.앱} — basics.js 에 없다`); continue }
    재료 = (s.ingredients || []).slice(); 걸음 = (s.steps || []).slice()
    시간 = s.time || 0; 인분 = s.serves || 0; 출처 = `저장소 「${s.title}」`
  } else {
    // ⛔ 문서 절 이름은 «백업 이름»이다(앱 이름이 아니다)
    const d = 문서.get(다듬(줄.백업))
    if (!d) { 못찾음.push(`${줄.백업} — 검수 문서에서 절을 못 찾았다`); continue }
    걸음 = d.걸음.slice(); 시간 = d.시간; 인분 = d.인분; 재료 = null; 출처 = '검수 문서'
  }

  for (const r of 대상) {
    if (!덜됨(r)) { 이미멀쩡.push(`${r.title} [재료 ${셈(r.ingredients)} · 걸음 ${셈(r.steps)}]`); continue }
    const 전 = `재료 ${셈(r.ingredients)} · 걸음 ${셈(r.steps)}`

    if (걸음.length) r.steps = 걸음.slice()
    // ⭐ 재료 = 저장소본은 통째로 갈아끼운다(검수가 끝난 값이다).
    //    ⛔ 문서본은 «덧붙임»이라 백업이 이미 갖고 있으면 안 건드린다 — 덮으면 오히려 줄어든다.
    if (재료 && 재료.length) r.ingredients = 재료.slice()
    if (시간 && !r.time) r.time = 시간
    if (인분 && !r.serves) r.serves = 인분

    채움 += 1
    보고.push(`  ✅ ${r.title.padEnd(18)} ${전}  →  재료 ${셈(r.ingredients)} · 걸음 ${셈(r.steps)}   (${출처}${줄.앱 !== 줄.백업 ? ` · 앱 이름 「${줄.앱}」` : ''})`)
  }
}

