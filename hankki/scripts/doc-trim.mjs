// 🧹🧹 HANDOVER.md 자동 정리 — 「기록」을 덜어내 「기억」만 남긴다
//
// 📮 창업자 2026-09-03: *"지울 것과 남길 것을 분류해야할 것 같아. **다 집어넣으니까 이지경이 된 듯.**"*
//    ＋ *"본질적으로 파서 이런일이 다시는 안생기게."*
//
// ⛔⛔ 무슨 일이 있었나 — 실측
//    HANDOVER.md 는 2026-08-23 에 **9,492 B(128줄)** 로 태어나 **11일 만에 301,307 B(3,443줄)** 가 됐다.
//    32배. 하루 +26KB. 손댄 커밋 79개 중 **늘어난 게 76회, 줄어든 게 3회.**
//    CLAUDE.md 와 합쳐 748KB — 한글은 대략 2~3바이트가 토큰 하나라 **대화를 열자마자 창이 찼다.**
//
// ⭐⭐ **왜 아무도 안 덜어냈나 (뿌리 넷)**
//    ⓐ 유일한 감시 장치(`check-mistakes` ⑫)가 **죽은 글자**를 세고 있었다 —
//       `- 옛 기록 ↓` 를 세는데 실제로 쌓인 건 `- **옛 버전**:`. 매 배포마다 「✅ 0줄」을 찍었다.
//    ⓑ **규칙이 「덧붙이기」를 «명령»한다** — 핀 「세션 영역 분담」②(*"남의 절을 지우지 않는다ㆍ
//       맨 아래로 얹는다"*) ＋ `check-current.mjs`(*"현행은 맨 아래"* · 어기면 배포 차단).
//       ⛔ **규칙을 잘 지킬수록 파일이 커지는 구조**였다. 안 지킨 게 아니다.
//    ⓒ **덜어내는 사람이 아무 명령어에도 없었다** — `/잘자` 는 세션 «끝»에 자기가 한 걸 «적고» 나간다.
//    ⓓ **정리하려면 150KB 를 읽어야 했다** — 그래서 아무도 시작을 못 했다. ⭐이 파일이 그걸 없앤다.
//
// ⭐ **분류 기준 = 제목에 «날짜»가 있나** (사람 판단이 필요 없게 · 창업자 *"분류해야할 것 같아"*)
//      `## 🎨 [2026-09-03 00:05 · 앱 갈래] v12.29 …`  → 날짜 있음 = 「그날 무슨 일이 있었다」 = 🗄기록
//      `## 하면 안 되는 작업`                          → 날짜 없음 = 「지금 상태가 이렇다」 = 🟢기억
//    📌 **날짜가 붙었다는 건 이미 「지나간 일」이라는 뜻**이다. 그래서 기계가 100% 자동으로 가른다.
//
// ⛔ **한 글자도 안 지운다 — 옮길 뿐이다.** (창업자 *"「지운다」가 아니라 「보관소로 옮긴다」여야 해"*)
//    나간 줄 수와 새 파일에 들어간 줄 수가 «같은지» 스스로 세서 확인한다. 안 맞으면 아무것도 안 한다.
//
// ── 쓰는 법 ──────────────────────────────────────────────
//    node scripts/doc-trim.mjs              # 👀 뭘 옮길지 «보여만» 준다 (기본값 — 안전)
//    node scripts/doc-trim.mjs --옮김        # ✂️ 실제로 옮긴다
//    node scripts/doc-trim.mjs --남길날 2    # 최근 2일치는 HANDOVER 에 남긴다 (기본 1)
//
// 📁 어디로 가나
//    최근(--남길날 안쪽) → `docs/세션기록/<날짜>-<갈래>.md`   ← 보관소 아님. 그냥 읽어도 된다.
//    그보다 오래된 것    → `docs/_archive/세션기록/<날짜>-<갈래>.md` ← 🗄보관소. 훅이 읽기를 막는다.
