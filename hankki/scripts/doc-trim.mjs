import { todayKST } from '../src/today.js'

const APP0 = existsSync('hankki/docs') ? 'hankki' : '.'      // 뿌리가 둘이다(cwd-guard 와 같은 판정)
const ROOT = APP0 === 'hankki' ? '.' : '..'

const 인자 = process.argv.slice(2)
const 값 = (이름) => { const i = 인자.indexOf(이름); return i >= 0 ? 인자[i + 1] : '' }
const 실행 = 인자.includes('--옮김')
const 남길날 = Number(값('--남길날')) || 1

// ⭐ [2026-09-03] `--파일`·`--내보낼곳` = **재현판이 이 도구를 «진짜로» 돌려보게** 하려고 뚫었다.
//    ⛔ 없으면 시험이 «진짜 HANDOVER.md» 를 건드려야 한다 — 그건 시험이 아니라 사고다.
//    📌 규칙 19 = 회귀·함정은 «규칙»이 아니라 «장치»가 잡는다. 장치를 재려면 장치가 시험 가능해야 한다.
const HANDOVER = 값('--파일') || join(ROOT, 'HANDOVER.md')
const APP = 값('--내보낼곳') || APP0

// ── 갈래 이름 뽑기 — 파일 이름이 갈리면 두 세션이 같은 파일을 안 건드린다(충돌 0) ──
//   ⚠️ 못 알아보면 「기타」. ⛔알아보는 척하고 엉뚱한 파일에 합치면 그게 충돌이다.
const 갈래뽑기 = (제목) =>
  /앱 ?갈래/.test(제목) ? '앱' : /바깥 ?갈래/.test(제목) ? '바깥' : '기타'

// ── 파일 이름 = `<갈래>세션-YYYY-MM-DD.md` ──────────────────────
//   ⛔⛔ **날짜를 «앞»에 두면 안 된다** (첫 판이 `2026-09-03-앱.md` 였다가 잡았다).
//      `latest-map.mjs` 는 **파일명 첫 토막**을 「주제」로 삼는다(그 파일 54행).
//      그래서 주제가 통째로 「2026」이 됐고, 같은 날 앱·바깥 기록이 «한 주제»로 묶여
//      **하나가 「옛것」으로 찍혔다** — 나란한 기록인데 한쪽을 낡은 걸로 오해하게 된다.
//   ✅ 갈래를 앞에 두면 주제가 「앱세션」·「바깥세션」으로 갈려서 각자 최신을 갖는다.
const 기록파일 = (갈래, 날짜) => `${갈래}세션-${날짜}.md`

// ── 세션 블록 = 「날짜 붙은 절」 하나 ＋ 그 뒤에 딸린 「날짜 없는 절」들 ──
//   ⭐ 딸린 절까지 같이 옮기는 이유 = `## ✅ 이 절에서 한 것` 같은 것은 «그 세션의» 몸통이다.
//      떼어 놓으면 HANDOVER 에 머리 없는 몸통만 남는다(지금 실제로 8쌍이 그렇게 중복돼 있다).
function 블록뽑기(줄들) {
  const 제목자리 = []
  줄들.forEach((l, i) => { if (l.startsWith('## ')) 제목자리.push(i) })
  const 블록 = []
  for (let k = 0; k < 제목자리.length; k++) {
    const i = 제목자리[k]
    const m = 줄들[i].match(/\[(\d{4}-\d{2}-\d{2})/)
    if (!m) continue                                    // 날짜 없는 절 = 🟢기억. 건드리지 않는다
    // 다음 «날짜 붙은» 절 직전까지가 이 블록이다
    let 끝 = 줄들.length
    for (let j = k + 1; j < 제목자리.length; j++) {
      if (/\[\d{4}-\d{2}-\d{2}/.test(줄들[제목자리[j]])) { 끝 = 제목자리[j]; break }
    }
    블록.push({ 날짜: m[1], 제목: 줄들[i].slice(3).trim(), 시작: i, 끝, 갈래: 갈래뽑기(줄들[i]) })
    k = 제목자리.findIndex((x) => x === 끝) - 1
    if (k < 0) break
  }
  return 블록
}

// ── 2단계: 날짜 없는 절 «안»의 `###` 소제목 중 「이미 끝났다고 스스로 적어 둔 것」 ──
//   ⭐⭐ 이게 창업자 *"다 집어넣으니까 이지경이 된 듯"* 의 정확한 모습이다 —
//      우리는 **이미 「✅나갔다」·「✅ 이 자리에 있다가 «닫힌» 것」이라고 라벨까지 붙여 놓고**
//      그걸 «빼지만» 않았다. 실측 = 날짜 없는 절 안 ### 59개 중 **34개(80,035 B)가 끝난 것**이었다.
//      「바로 다음 행동」이 29,775 B 였던 이유가 이것이다 — 「바로 다음」이 29KB 일 리가 없다.
//   ⛔ 라벨이 없으면 «건드리지 않는다». 애매한 것을 옮기느니 남기는 게 낫다(잃는 것보다 큰 게 낫다).
//   ⛔⛔ **「날짜가 오래됐다」만으로는 «옮기지 않는다».** (2026-09-03 · 하마터면 잃을 뻔했다)
//      첫 판이 그렇게 했더니 옮길 목록에 이런 것들이 섞였다 —
//        `[2026-08-29 · 여기서 멈췄다] AI 제목이 …`   ← 멈춘 것 = 아직 «살아 있다»
//        `⏳ [2026-08-27 남은 판정] 시트23 잘린 셋`      ← ⏳ = 판정 대기
//        `🗓 2026-08-28 = 명의 이전 날 (제일 급하다)`    ← 급한 일이 보관소로 갈 뻔했다
//      ⭐ **날짜가 오래된 것과 끝난 것은 다르다.** 오래 안 끝난 일일수록 오히려 «살아 있는» 일이다.
//      👉 그래서 자동은 «저장소가 스스로 끝났다고 적어 둔 것»만 옮기고,
//         날짜만 오래된 것은 **창업자에게 목록으로 보여 준다**(판정은 사람 몫).
// ⛔⛔ **[2026-09-03 · 창업자 판정 중에 드러난 구멍] 「완료」를 «형식»으로 봤다가 놓쳤다.**
//    첫 판 = `배포 완료|완료\*\*` — 「완료」 뒤에 `**` 가 와야만 봤다.
//    그런데 실제 제목은 「데이터 보안 재신고 **«게시 완료»** ＋ v11.58」 — 뒤가 `»` 라 **안 잡혔다.**
//    ⭐ 오늘 잡은 ⑫번 사고(죽은 글자를 셈)와 «같은 종류»다 — 뜻이 아니라 «글자 모양»을 봤다.
//    ✅ 이제 뒤에 한글이 안 붙은 「완료」면 잡는다. ⛔단 「미완료」·「불완료」는 앞글자로 걸러낸다.
const 끝났다고적힌 = (제목) => /✅|«닫힌»|나갔다|(?<![미불])완료(?![가-힣])/.test(제목)
const 살아있음표 = /⏳|멈췄다|남은|급하다|지시|D-\d|판정|확인 필요/
const 오래된날짜 = (제목, 기준) => {
  const m = 제목.match(/(\d{4}-\d{2}-\d{2})/)
  return m ? m[1] < 기준 : false
}

function 끝난소제목뽑기(줄들, 기준, 물어볼것) {
  const h2 = [], h3 = []
  줄들.forEach((l, i) => { if (l.startsWith('## ')) h2.push(i); else if (l.startsWith('### ')) h3.push(i) })
  const 것들 = []
  for (let k = 0; k < h3.length; k++) {
    const s = h3[k]
    const 제목 = 줄들[s].slice(4)
    if (!끝났다고적힌(제목)) {
      // 라벨은 없는데 날짜가 오래된 것 = «내가 정할 게 아니다». 목록에만 올린다.
      if (오래된날짜(제목, 기준) && !살아있음표.test(제목)) 물어볼것.push(제목)
      continue
    }
    // 이 소제목의 끝 = 다음 ### 또는 다음 ## 중 먼저 오는 것
    const 다음3 = h3[k + 1] ?? 줄들.length
    const 다음2 = h2.find((x) => x > s) ?? 줄들.length
    const e = Math.min(다음3, 다음2)
    const 부모 = [...h2].reverse().find((x) => x < s)
    것들.push({ 시작: s, 끝: e, 제목, 부모: 부모 == null ? '(머리말)' : 줄들[부모].slice(3).trim() })
  }
  return 것들
}

const 원본 = readFileSync(HANDOVER, 'utf8')
const 줄들 = 원본.split('\n')
const 블록 = 블록뽑기(줄들)

// ── 어디로 보낼지 = 나이로 가른다 ──
// ⛔ 날짜를 «여기서» 만들지 않는다 — `todayKST()` 한 곳에서만 만든다(절대원칙 · `check-kst.mjs` 가 막는다).
//    ⚠️ 첫 판이 `new Date(Date.now()+9*3600e3)` 을 직접 썼다가 게이트에 걸렸다. 게이트가 제 일을 했다.
const 오늘 = todayKST()
const 며칠전 = (d) => Math.round((Date.parse(오늘) - Date.parse(d)) / 86400e3)
const 기준날 = todayKST(new Date(Date.now() - 남길날 * 86400e3))

const 짐 = new Map()          // 목적지 파일 → { 늙음, 줄[] }
const 담기 = (파일, 늙음, 줄) => {
  if (!짐.has(파일)) 짐.set(파일, { 늙음, 줄: [] })
  짐.get(파일).줄.push(...줄)
}

// ── 1단계: 날짜 붙은 `##` 세션 블록을 통째로 ──
let 뺀줄 = 0
for (const b of 블록) {
  const 늙음 = 며칠전(b.날짜) >= 남길날
  const 폴더 = 늙음 ? join(APP, 'docs/_archive/세션기록') : join(APP, 'docs/세션기록')
  담기(join(폴더, 기록파일(b.갈래, b.날짜)), 늙음, 줄들.slice(b.시작, b.끝))
  뺀줄 += b.끝 - b.시작
}
const 남는1 = 줄들.filter((_, i) => !블록.some((b) => i >= b.시작 && i < b.끝))

// ── 2단계: 남은 것 «안»에서 「끝났다고 스스로 적어 둔」 ### 소제목 ──
const 물어볼것 = []
const 끝난것 = 끝난소제목뽑기(남는1, 기준날, 물어볼것)
const 끝난파일 = join(APP, `docs/_archive/핸드오버-끝난것-${오늘}.md`)
const 끝난줄 = []
for (const x of 끝난것) {
  끝난줄.push(`<!-- 원래 자리: ## ${x.부모} -->`)        // ⭐어디서 왔는지 남긴다 — 근거를 찾을 수 있게
  끝난줄.push(...남는1.slice(x.시작, x.끝))
}
if (끝난줄.length) 담기(끝난파일, true, 끝난줄)
const 남는몸 = 남는1.filter((_, i) => !끝난것.some((x) => i >= x.시작 && i < x.끝))
const 뺀줄2 = 남는1.length - 남는몸.length

// ── 보여주기 ──
const B = (a) => Buffer.byteLength(a.join('\n')).toLocaleString()
console.log(`🧹 HANDOVER.md — 지금 ${Buffer.byteLength(원본).toLocaleString()} B · ${줄들.length}줄\n`)
console.log(`① 날짜 붙은 세션 절 ${블록.length}덩이 · ${뺀줄}줄   (최근 ${남길날}일치는 «세션기록»에, 그 앞은 🗄보관소로)`)
console.log(`② 「✅나갔다」·「«닫힌»」 라벨이 붙은 ### 소제목 ${끝난것.length}개 · ${뺀줄2}줄   ⭐이미 끝났다고 적어 놓고 안 뺀 것\n`)
for (const [파일, v] of 짐) {
  console.log(`   ${v.늙음 ? '🗄' : '📁'} ${파일.padEnd(48)} ${String(v.줄.length).padStart(5)}줄  ${B(v.줄).padStart(8)} B`)
}
console.log(`\n   → HANDOVER.md ${Buffer.byteLength(원본).toLocaleString()} → ${Buffer.byteLength(남는몸.join('\n')).toLocaleString()} B · ${남는몸.length}줄`)

// ── ❓ 창업자 판정이 필요한 것 — ⛔내가 정하지 않는다 ──
if (물어볼것.length) {
  console.log(`\n❓ **끝났는지 «내가» 정할 수 없는 것 ${물어볼것.length}개** — 날짜는 오래됐는데 「✅」 라벨이 없다.`)
  console.log('   👉 끝난 것이면 제목에 「✅」를 붙이고 이 도구를 다시 돌린다. 아니면 그대로 둔다.')
  for (const t of 물어볼것) console.log('     · ' + t.slice(0, 76))
}

if (!실행) {
  console.log('\n👀 «보여만» 줬다. 실제로 옮기려면 → node scripts/doc-trim.mjs --옮김')
  process.exit(0)
}

// ── ⛔ 안전장치: 「뺀 줄 == 넣을 줄」이 아니면 아무것도 안 한다 ──
//    창업자 절대원칙 = 지우지 않고 «옮긴다». 숫자가 안 맞으면 어딘가 흘린 것이다.
//    ⚠️ 2단계가 넣는 「원래 자리」 주석은 «더한» 줄이라 계산에서 뺀다.
const 넣을줄 = [...짐.values()].reduce((a, v) => a + v.줄.length, 0) - 끝난것.length
if (넣을줄 !== 뺀줄 + 뺀줄2 || 남는몸.length + 뺀줄 + 뺀줄2 !== 줄들.length) {
  console.error(`\n⛔ 줄 수가 안 맞는다 — 뺄 ${뺀줄 + 뺀줄2} · 넣을 ${넣을줄} · 남을 ${남는몸.length} / 원래 ${줄들.length}`)
  console.error('   아무것도 안 했다. 이대로 두는 게 잃는 것보다 낫다.')
  process.exit(1)
}

// ── 옮긴다 ──
const 머리말 = (늙음, 파일) =>
  (늙음
    ? `> 🗄 **보관소** — 끝난 세션 기록이다. ⛔창업자가 지시할 때만 연다(절대원칙 24).\n`
    : `> 📁 **세션 기록** — 그 세션이 «한 일». HANDOVER.md 는 「지금 이어서 할 것」만 담는다.\n`) +
  `> 🧹 \`scripts/doc-trim.mjs\` 가 HANDOVER.md 에서 옮겼다 (${오늘}).\n\n`

for (const [파일, v] of 짐) {
  mkdirSync(dirname(파일), { recursive: true })
  if (existsSync(파일)) appendFileSync(파일, '\n' + v.줄.join('\n') + '\n')   // ⛔덮지 않는다 — 이어붙인다
  else writeFileSync(파일, 머리말(v.늙음, 파일) + v.줄.join('\n') + '\n')
}

// HANDOVER 에는 «어디로 갔는지» 한 줄만 남긴다 — 나중에 근거를 찾을 수 있게
// ⛔⛔ **[2026-09-03] 두 번 돌리니 같은 제목의 절이 «둘» 생겼다 — 내 도구가 낸 버그다.**
//    오늘 진단한 「중복 절 8쌍」(두 세션이 같은 걸 각자 쓴 것)을 이 도구가 그대로 저질렀다.
//    ✅ 이미 있으면 «그 절에 이어 붙인다». 같은 파일이 또 나오면 한 번만 적는다.
const 자국제목 = '## 🗂 지난 세션 기록 (여기서 덜어냈다)'
const 줄목록 = [...짐].map(([파일, v]) => `- ${v.늙음 ? '🗄' : '📁'} \`${파일}\``)
const 있던자리 = 남는몸.findIndex((l) => l.startsWith(자국제목))
let 결과
if (있던자리 >= 0) {
  // 그 절이 끝나는 자리(다음 `## ` 또는 파일 끝)를 찾아 그 «안»에 넣는다
  let 끝 = 남는몸.length
  for (let i = 있던자리 + 1; i < 남는몸.length; i++) if (남는몸[i].startsWith('## ')) { 끝 = i; break }
  const 이미 = new Set(남는몸.slice(있던자리, 끝).filter((l) => l.startsWith('- ')))
  const 새것 = 줄목록.filter((l) => !이미.has(l))
  결과 = [...남는몸.slice(0, 끝), ...(새것.length ? [...새것, ''] : []), ...남는몸.slice(끝)]
} else {
  결과 = [...남는몸, '', 자국제목, '', ...줄목록, '']
}
writeFileSync(HANDOVER, 결과.join('\n'))

const 뒤 = readFileSync(HANDOVER, 'utf8')
console.log(`\n✅ 옮겼다 — HANDOVER.md ${Buffer.byteLength(원본).toLocaleString()} → ${Buffer.byteLength(뒤).toLocaleString()} B`)
console.log('   ⛔ 한 글자도 안 지웠다. 위 파일들에 그대로 있다.')
