// 🔁 [2026-09-14] 「같은 폰·같은 계정 재로그인 = 덮지 않고 합치기」 판정이 맞나 — 재현판
// 🔢 왜 = 딸 폰 23판 실측 — 로그아웃→재로그인→가져오기 → 97편이 옛 클라우드본 87편으로 되돌아갔다(창업자 "유저들 당황할듯").
import { 받을때합칠까, 합치기 } from '../src/syncMerge.js'
let 나쁨 = 0
const 잰다 = (참, 말) => { if (참) console.log(`  ✅ ${말}`); else { 나쁨 += 1; console.log(`  ⛔ ${말}`) } }
잰다(받을때합칠까({ 이전주인: '', 주인전: '111', 번호: '111' }) === true, '같은 폰 같은 계정(주인전 == 번호) → 합친다')
잰다(받을때합칠까({ 이전주인: '', 주인전: '', 번호: '111' }) === false, '새 폰(주인전 없음) → 통째 가져오기 그대로')
잰다(받을때합칠까({ 이전주인: '222', 주인전: '222', 번호: '111' }) === false, '다른 계정(이전주인 있음) → 여기선 안 건드림(기존 물음 흐름)')
잰다(받을때합칠까({ 이전주인: '', 주인전: '111', 번호: '' }) === false, '번호 없음 → 안 합침(지어내지 않는다)')
잰다(받을때합칠까() === false, '아무 값 없음 → false')
// 합치기가 정말 «덮지 않는지» — 폰 97 · 클라우드 87(옛것) → 97 그대로
const 내것 = { recipes: Array.from({ length: 97 }, (_, i) => ({ id: `r${i}`, title: `편${i}` })) }
const 받은것 = { recipes: 내것.recipes.slice(0, 87).map((r) => ({ ...r })) }
const 합 = 합치기({ 내것, 받은것 })
잰다(합.recipes.length === 97, `합치기 뒤 97편 그대로 (지금 = ${합.recipes.length})`)
console.log(나쁨 ? `\n⛔ ${나쁨}칸 틀렸다` : '\n✅ 전부 통과')
process.exit(나쁨 ? 1 : 0)
