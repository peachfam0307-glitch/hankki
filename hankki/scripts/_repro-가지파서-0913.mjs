// 🍆 [2026-09-13 · 창업자 아이폰 빌드 15 실물] 「✅재료 1~15 / ✅ 조리방법 1~6」 캡션이 «제목 √ 재료 · 재료 0 · 걸음 24»가 됐다.
//   창업자 = *"너무심한데..."* — 재료 목록이 따로 있는 제일 깔끔한 글에서 났다.
//   뿌리 셋 = ① 머리에서제목 이 체크표시(√)를 안 벗겨 절 이름을 제목으로 집음
//            ② 재료 절 안의 번호 줄(1. 가지 1개 반)을 「번호 = 걸음」으로 읽음
//            ③ 인스타가 폭에 맞춰 낱말 «중간»에서 끊은 줄(노릇해질／때까지 · 알／룰로스)을 안 이어붙임
import { parseRecipeText } from '../src/parseRecipe.js'
let 나쁨 = 0
const 잰다 = (ok, 말, 값) => { console.log(`  ${ok ? '✅' : '⛔'} ${말}${값 === undefined ? '' : ' — ' + String(값).slice(0, 90)}`); if (!ok) 나쁨++ }
const 글 = `√재료
1. 가지 1개 반
2. 소고기 다짐육 300g
3. 대파 1/2대
4. 계란 1개
5. 다진 마늘 1/2스푼
6. 간장 2스푼
7. 참치액 1/2스푼
8. 맛술 2스푼
9. 알룰로스 1/2스푼
10. 고춧가루 1스푼
11. 물 3스푼
12. 후추 약간
13. 참기름 1스푼
14. 식용유 1스푼
15. 밥 1~2공기

√ 조리방법
1. 가지 1개 반은 1~1.5cm 정도로 깍둑썰기하고 대파 1/2대는 송
송 썰어주세요.
2. 팬에 식용유 1스푼을 두르고 다진 마늘 1/2스푼을 넣어 마늘 향
이 올라올 정도로 볶아주세요.
3. 소고기 다짐육 300g을 넣어 수분이 충분히 날아가고 노릇해질
때까지 볶아주세요. 소고기의 수분을 충분히 날려야 고소한 풍미가
살아납니다.
4. 소고기가 노릇하게 볶아지면 가지를 넣어주세요.
5. 고춧가루 1스푼, 간장 2스푼, 참치액 1/2스푼, 맛술 2스푼, 알
룰로스 1/2스푼, 물 3스푼, 후추 약간을 넣고 가지가 부드러워지면
서 양념이 소고기와 가지에 착 붙을 정도로 볶아주세요.
6. 마지막에 참기름 1스푼과 송송 썬 대파를 넣어 한 번 빠르게 섞
어주세요. 밥 위에 듬뿍 올린 뒤 반숙 계란후라이를 얹어 완성해주
세요.`
for (const [이름, v] of [['OCR 「√」', 글], ['원문 「✅」', 글.replace(/√/g, '✅')]]) {
  const r = parseRecipeText(v, { fromOcr: true })
  console.log(`── ${이름}`)
  잰다(!/재료/.test(r.title || ''), '① 제목이 절 이름(재료)이 아니다', JSON.stringify(r.title))
  잰다(r.ingredients.length === 15, '② 재료 15개', r.ingredients.length)
  잰다(r.ingredients[0] === '가지 1개 반' && r.ingredients[14] === '밥 1~2공기', '② 처음·끝 재료가 맞다', r.ingredients[0] + ' … ' + r.ingredients[14])
  잰다(r.steps.length === 6, '③ 걸음 6개', r.steps.length)
  잰다(/송송 썰어/.test(r.steps[0] || ''), '③ 「송／송」이 「송송」으로 붙었다', r.steps[0])
  잰다(/노릇해질 때까지/.test(r.steps[2] || ''), '③ 「노릇해질／때까지」는 «띄어서» 이어졌다', r.steps[2])
  잰다(/알룰로스/.test(r.steps[4] || '') && /부드러워지면서/.test(r.steps[4] || ''), '③ 「알／룰로스」「지면／서」가 붙었다', r.steps[4])
  잰다(/섞어줘요/.test(r.steps[5] || '') && /완성해줘요/.test(r.steps[5] || ''), '③ 「섞／어주세요」「완성해주／세요」가 붙었다', r.steps[5])
  잰다(!r.steps.some((s) => /^(가지 1개 반|소고기 다짐육 300g)$/.test(s)), '② 재료가 걸음에 안 섞였다')
}
// 🛡 절 밖의 번호 줄은 그대로 걸음이다 — 「1. 가지를 썰어주세요」
{
  const r = parseRecipeText('가지볶음\n1. 가지를 썰어주세요.\n2. 팬에 볶아주세요.', { fromOcr: true })
  잰다(r.steps.length === 2 && r.ingredients.length === 0, '④ 재료 절 밖의 번호 줄은 걸음 그대로', r.steps.length + '/' + r.ingredients.length)
}
// 🛡 빈 줄로 나뉜 문단은 28자가 넘어도 안 붙인다(강레오 캡션 모양)
{
  const r = parseRecipeText('양송이볶음\n\n불이 약하면 버섯에서 물이나오니까 꼭 센불에 해주시구요\n\n색이 노르스름해지면\n\n버터 1조각 넣고 양파가 익을때까지만 볶아줍니다', { fromOcr: true })
  잰다(r.steps.length >= 2 && !/해주시구요 색이/.test(r.steps.join(' | ')), '⑤ 빈 줄 사이 문단은 안 붙는다', r.steps.join(' | '))
}
console.log(나쁨 ? `⛔ ${나쁨}칸 실패` : '✅ 전부 통과')
process.exit(나쁨 ? 1 : 0)
