// 🔒 배포 게이트 — 「냉장고 재료 ↔ 레시피 재료」 맞추기가 헐거워지면 배포를 막는다.
//
// ⛔⛔ 2026-08-10 에 실제로 이랬다 — 두 곳이 `ings.includes(키)` 로 «글자 포함»만 봤다:
//   · 「무」가 **풀무원 · 단무지 · 마무리용**에 걸렸다(실측 5편)
//   · 「파」가 **스파게티 · 파마산 · 양파 · 슈가파우더**에 걸렸다(실측 28편)
//   · 「냉장고 파먹기」는 «풀네임»으로 맞춰서 **「돼지고기 앞다리살」이 「돼지고기 300g」에 안 걸렸다**
//   📌 규칙으로 적어두면 다음에 또 헐거워진다 → **기계가 지킨다.**
//
// ⭐ 규칙 12 — 옛 방식(`includes`)으로 돌려 **진짜 걸리는지** 이 파일 안에서 같이 확인한다(아래 ⑧).
import { hasIngredient, ingredientTokens, pantryKey, countPantryHits, pantryScore } from '../src/pantryMatch.js'

let fail = 0
const 칸 = (ok, 이름, 값) => { console.log(`${ok ? '  ✅' : '  ⛔'} ${이름}${값 ? ` — ${값}` : ''}`); if (!ok) fail++ }
const 맞나 = (재료, 이름) => hasIngredient(ingredientTokens(재료), pantryKey(이름))

console.log('\n🧊 냉장고 매칭 검사')

// ① 걸려야 하는 것
칸(맞나(['무 1/4개', '고춧가루 1큰술'], '무'), '① 「무」 → 「무 1/4개」')
칸(맞나(['다진마늘 1큰술'], '마늘'), '① 「마늘」 → 「다진마늘」 (한국어는 핵심 명사가 뒤에 온다)')
칸(맞나(['진간장 2큰술'], '간장'), '① 「간장」 → 「진간장」')
칸(맞나(['양파(중) 1개'], '양파'), '① 괄호가 붙어도 걸린다 — 「양파(중) 1개」')

// ② ⛔ 걸리면 «안» 되는 것 — 옛 코드가 전부 걸었던 것들
칸(!맞나(['풀무원 순두부 1팩'], '무'), '② 「무」가 «풀무원»에 안 걸린다')
칸(!맞나(['단무지 4줄'], '무'), '② 「무」가 «단무지»에 안 걸린다')
칸(!맞나(['마무리용 참기름'], '무'), '② 「무」가 «마무리용»에 안 걸린다')
칸(!맞나(['스파게티 200g'], '파'), '② 「파」가 «스파게티»에 안 걸린다')
칸(!맞나(['파마산 치즈'], '파'), '② 「파」가 «파마산»에 안 걸린다')
칸(!맞나(['양파 1개'], '파'), '② 「파」가 «양파»에 안 걸린다 (다른 채소다)')
칸(!맞나(['알배추 1/4통'], '알'), '② 「알」이 «알배추»에 안 걸린다')
칸(!맞나(['국물 500ml'], '물'), '② 「물」이 «국물»에 안 걸린다')

// ③ 냉장고 이름 뒤에 부위·용량이 붙어도 걸린다 (냉장고 파먹기가 여기서 통째로 죽어 있었다)
칸(맞나(['돼지고기 300g'], '돼지고기 앞다리살'), '③ 「돼지고기 앞다리살」 → 「돼지고기 300g」')
칸(맞나(['소고기 200g'], '소고기 국거리용'), '③ 「소고기 국거리용」 → 「소고기 200g」')

// ④ 같은 재료를 두 번 세지 않는다
칸(countPantryHits({ ingredients: ['대파 1대', '대파흰부분'] }, [{ name: '대파' }, { name: '대파' }]) === 1,
  '④ 냉장고에 같은 이름이 둘이어도 1로 센다')

// ⑤ 점수 — 개수가 먼저, 같으면 «가진 비율»이 높은 쪽(＝살 게 적은 쪽)이 이긴다
const 냉장고 = [{ name: '양파' }, { name: '대파' }, { name: '달걀' }]
const 적은재료 = { ingredients: ['양파 1개', '대파 1대', '달걀 2개', '소금'] }         // 3/4
const 많은재료 = { ingredients: ['양파 1개', '대파 1대', '달걀 2개', ...Array.from({ length: 11 }, (_, i) => `재료${i}`)] } // 3/14
칸(pantryScore(적은재료, 냉장고) > pantryScore(많은재료, 냉장고),
  '⑤ 같은 3개가 걸리면 «재료 적은 쪽»이 이긴다',
  `${pantryScore(적은재료, 냉장고).toFixed(2)} vs ${pantryScore(많은재료, 냉장고).toFixed(2)}`)

// ⑥ ⛔ 비율«만» 보면 안 된다 — 1개 걸린 작은 레시피가 3개 걸린 것을 이기면 안 된다
const 하나걸림 = { ingredients: ['양파 1개', '소금', '후추'] } // 1/3 = 33%
칸(pantryScore(많은재료, 냉장고) > pantryScore(하나걸림, 냉장고),
  '⑥ 3개 걸린 쪽이 «1개 걸린 33%» 보다 위다',
  `${pantryScore(많은재료, 냉장고).toFixed(2)} vs ${pantryScore(하나걸림, 냉장고).toFixed(2)}`)

// ⑦ 냉장고가 비면 0
칸(pantryScore(적은재료, []) === 0, '⑦ 냉장고가 비면 0점')

// ⑧ ⭐ 규칙 12 — **옛 방식이 진짜로 걸렸는지** 여기서 같이 확인한다.
//    이게 없으면 「고쳤다」가 내 말뿐이고, 검사가 늘 초록불인 「실패할 줄 모르는 검사」가 된다.
const 옛방식 = (재료, 이름) => 재료.join(' ').includes(String(이름).trim().split(/\s+/)[0])
const 옛것이걸린것 = [
  [['풀무원 순두부 1팩'], '무'], [['단무지 4줄'], '무'], [['스파게티 200g'], '파'],
  [['양파 1개'], '파'], [['알배추 1/4통'], '알'], [['국물 500ml'], '물'],
].filter(([재료, 이름]) => 옛방식(재료, 이름))
칸(옛것이걸린것.length === 6, '⑧ 옛 방식(글자 포함)은 위 6건을 «전부» 잘못 걸었다', `${옛것이걸린것.length}/6`)
칸(!옛방식(['돼지고기 300g'], '돼지고기 앞다리살') === false, '⑧ …그리고 「앞다리살」은 첫 낱말로는 걸렸다(파먹기는 풀네임이라 놓쳤다)')

console.log(fail ? `\n⛔ 냉장고 매칭 검사 ${fail}칸 어긋남\n` : '\n✅ 냉장고 매칭 검사 통과\n')
process.exit(fail ? 1 : 0)
