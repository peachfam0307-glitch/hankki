#!/usr/bin/env node
// 👁️👁️ [절대원칙 · 창업자 2026-09-20] 눈검사 — 「내보내기 전에 눈으로 시뮬레이션 ＋ 전수검사」 — 배포 게이트
//
// 📮 창업자 원문 = *"앞으로 너 내보내기전에 눈으로 시뮬레이션 돌리고 전수검사해.
//    네가 확인 안되는건 나한테 확인하라고 하고 빌드구울거야. 절대원칙.
//    **코드로 네가 대충 내보내지 못하게 막아.** 내가 다 확인하면 내보낼 수있어."*
//
// ⛔⛔ 왜 생겼나 (2026-09-20 낮) — 식비 「달 시작일」 시트가 아이폰에서 «키보드 뒤에» 깔렸다.
//    🔢 그때 상태 = 관문 220칸 fail 0 · 빌드 exit 0 · 30판 구워 1.0.4 심사까지 통과. **전부 초록불이었다.**
//    📌 그런데 그 화면을 **한 번도 안 봤다.** 관문은 «코드»를 보지 «화면»을 안 본다(규칙 18 ⓘ 와 같은 구멍).
//    ⭐ 그 시트는 갤럭시 세션이 만든 것이었다 — 그래도 **내보낸 사람이 나였다.**
//       「남이 만든 것」은 안 봐도 된다는 뜻이 아니다. ⭐**내보내는 사람이 본다.**
//
// 🔎 무엇을 보나 = **이번(HEAD) 커밋이 «화면 파일»을 고쳤나.**
//    · 화면 파일 = `hankki/src/**/*.jsx` · `hankki/src/*.css`  (유저가 «보는» 것)
//    · 고쳤으면 그 커밋 메시지에 **세 줄이 다 있어야** 한다:
//        👁️ (또는 「눈으로」)  — 무엇을 «렌더해서 열어 봤나»
//        📋 (또는 「전수」)    — 그 변경이 닿는 자리를 몇 곳 셌나
//        ❓ (또는 「못 본」)   — 내가 «못 본» 것 (⛔없으면 「없음」이라고 «적어야» 한다 — 빈칸은 통과 못 한다)
//
// ⚠️ **정직하게 — 이 관문이 못 막는 것**: 「찍어만 놓고 안 보는 것」은 못 막는다(`evidence.mjs` 와 같은 한계).
//    ⭐ 그래도 «대충»의 값을 크게 올린다 — 세 줄을 다 적으려면 무엇을 봤는지·몇 곳인지·무엇을 못 봤는지를
//       그 자리에서 생각해야 한다. 그리고 **못 본 것을 적게 하는 것**이 창업자에게 확인을 청하는 자리다.
//
// 🚪 푸는 길 = 관문을 «끄는» 길은 없다. 세 줄을 적으면 열린다(＝시키는 대로 하면 열린다 · 규칙 19).
//    ⛔ 막다른 길을 만들지 않는다 — 화면을 «안» 고친 판은 조용하다.
//
// 🧪 규칙 12 = 아래 `--시험` 으로 ⓐ화면 안 고침=통과 ⓑ고쳤는데 세 줄 없음=죽음 ⓒ세 줄 있음=통과
//    ⓓ❓가 빈칸=죽음 — 넷을 실제로 돌려 확인한다.
import { execSync } from 'node:child_process'

const 뿌리 = new URL('../..', import.meta.url).pathname.replace(/\/$/, '')
const 화면인가 = (p) => /^hankki\/src\/.+\.jsx$/.test(p) || /^hankki\/src\/[^/]+\.css$/.test(p)

function 그것(cmd) {
  try { return execSync(cmd, { cwd: 뿌리, encoding: 'utf8' }).trim() } catch { return '' }
}

// 커밋 메시지에서 세 줄을 찾는다 — 이모지든 우리말이든 받는다(이모지가 깨지는 자리가 있어서)
function 도장(글) {
  const 눈 = /👁|눈으로|눈검사/.test(글)
  const 전수 = /📋|전수/.test(글)
  const m = /(?:❓|못 본|못본)[^\n]*/.exec(글)
  const 못본줄 = m ? m[0] : ''
  // ❓ 뒤에 «내용»이 있어야 한다 — 표식만 찍고 비우면 안 된다
  const 못본채움 = /(?:❓|못 본 것|못본것|못 본|못본)\s*[:=＝]?\s*\S{2,}/.test(못본줄)
  return { 눈, 전수, 못본: 못본채움, 못본줄 }
}

function 판정(해시 = 'HEAD') {
  const 파일들 = 그것(`git show --name-only --format= ${해시}`).split('\n').map((s) => s.trim()).filter(Boolean)
  const 화면 = [...new Set(파일들.filter(화면인가))]
  const 글 = 그것(`git log -1 --format=%B ${해시}`)
  return { 화면, 글, ...도장(글) }
}

// ── 시험(규칙 12) ────────────────────────────────────────────
if (process.argv.includes('--시험')) {
  const 판 = [
    ['ⓐ 화면 안 고침', { 화면: [], 눈: false, 전수: false, 못본: false }, true],
    ['ⓑ 고쳤는데 세 줄 없음', { 화면: ['hankki/src/App.jsx'], 눈: false, 전수: false, 못본: false }, false],
    ['ⓒ 세 줄 다 있음', { 화면: ['hankki/src/App.jsx'], 눈: true, 전수: true, 못본: true }, true],
    ['ⓓ ❓ 가 빈칸', { 화면: ['hankki/src/App.jsx'], 눈: true, 전수: true, 못본: false }, false],
  ]
  let 실패 = 0
  for (const [이름, s, 바람] of 판) {
    const ok = s.화면.length === 0 || (s.눈 && s.전수 && s.못본)
    const 맞나 = ok === 바람
    if (!맞나) 실패++
    console.log(`${맞나 ? '✅' : '❌'} ${이름} → ${ok ? '통과' : '죽음'} (바란 것 = ${바람 ? '통과' : '죽음'})`)
  }
  // ❓ 채움 판정도 글자로 한 번 더
  const 글시험 = [
    ['❓ 없음 이라고 적음', '👁️ 봤다\n📋 전수 3곳\n❓ 못 본 것 = 없음', true],
    ['❓ 표식만', '👁️ 봤다\n📋 전수 3곳\n❓', false],
  ]
  for (const [이름, 글, 바람] of 글시험) {
    const d = 도장(글)
    const ok = d.눈 && d.전수 && d.못본
    const 맞나 = ok === 바람
    if (!맞나) 실패++
    console.log(`${맞나 ? '✅' : '❌'} ${이름} → ${ok ? '통과' : '죽음'}`)
  }
  console.log(실패 ? `\n⛔ 시험 ${실패}칸 실패` : '\n✅ 시험 6칸 전부 통과')
  process.exit(실패 ? 1 : 0)
}

// ── 본 일 ────────────────────────────────────────────────────
const 해시 = process.argv.find((a) => /^[0-9a-f]{7,40}$/.test(a)) || 'HEAD'
const r = 판정(해시)

if (r.화면.length === 0) process.exit(0)   // 화면을 안 고친 판 — 조용하다

if (r.눈 && r.전수 && r.못본) {
  console.log(`👁️ 눈검사 도장 확인 — 화면 파일 ${r.화면.length}개`)
  process.exit(0)
}

console.log('')
console.log('👁️⛔ **눈검사 도장이 없다 — 화면을 고쳤는데 「봤다」는 기록이 없다.**')
console.log('')
console.log(`   이번 판이 고친 «화면 파일» ${r.화면.length}개:`)
for (const f of r.화면.slice(0, 12)) console.log(`     · ${f}`)
if (r.화면.length > 12) console.log(`     … 그 밖 ${r.화면.length - 12}개`)
console.log('')
console.log('   📮 창업자 2026-09-20 = *"내보내기전에 눈으로 시뮬레이션 돌리고 전수검사해.')
console.log('      네가 확인 안되는건 나한테 확인하라고 하고 빌드구울거야. 절대원칙."*')
console.log('')
console.log('   ⛔ 2026-09-20 에 이게 없어서 터졌다 — 식비 시트가 아이폰에서 키보드 뒤에 깔렸는데')
console.log('      관문 220칸·빌드·심사까지 «전부 초록불»이었다. 아무도 화면을 안 봤다.')
console.log('')
console.log('   👉 이렇게 연다 — 먼저 «진짜로» 하고, 그 결과를 커밋 메시지에 세 줄로 적는다:')
console.log('      ① 👁️ 바뀐 화면을 실제 크기로 렌더·캡처해 **열어서 본다**')
console.log('         (못 만드는 조건은 «흉내»낸다 — 예: 키보드 높이를 --kb-inset 에 넣고 찍기)')
console.log('      ② 📋 그 변경이 «닿는 자리»를 전수로 센다(시트 바탕을 고치면 시트 쓰는 곳 전부)')
console.log('      ③ ❓ 내가 «못 본» 것을 적는다 — 없으면 「없음」이라고 «적는다»(빈칸은 통과 못 한다)')
console.log('')
console.log('      커밋 메시지 보기:')
console.log('        👁️ 눈으로 = 390x844 에 키보드 336px 넣고 고침 전/후 두 장 찍어 열어 봄(가려짐 336px → 0px)')
console.log('        📋 전수 = 바닥 시트 43곳 전부 · 키보드 없을 때 변화 0 실측')
console.log('        ❓ 못 본 것 = 실물 아이폰 키보드(이 환경엔 키보드가 없다) → 창업자 확인 대기')
console.log('')
console.log('   📄 전문 = hankki/docs/규칙-눈으로시뮬레이션-2026-09-20.md')
console.log('')
process.exit(1)
