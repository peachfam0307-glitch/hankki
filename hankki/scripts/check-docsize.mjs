// 📏📏 **HANDOVER.md · CLAUDE.md 가 「대화 창을 먹는」 크기인지 — 배포 게이트** (창업자 2026-09-03)
//
// 📮 창업자 원문 = *"도대체 프롬프트창은 왜저렇게 빨리차는거야."*
//    ＋ *"본질적으로 파서 이런일이 다시는 안생기게."*  ＋ *"한 세션이 계속 정리안하면
//      다른세션이 정리한다거나 **브레이크를 건다거나**"*  ← 이 파일이 그 «브레이크»다.
//
// ⛔⛔ **무슨 일이 있었나 (2026-09-03 실측)**
//    `CLAUDE.md` 461,814 B ＋ `HANDOVER.md` 301,307 B = **763KB.**
//    한글은 대략 2~3바이트가 토큰 하나 → 어림 **25만~38만 토큰.** 창은 **20만.**
//    ⭐ **대화가 길어서 찬 게 아니라, 일을 시작하기 «전»에 이미 차 있었다.**
//    HANDOVER 는 8/23 에 9,492 B 로 태어나 11일 만에 **32배**가 됐다(하루 +26KB).
//
// ⭐⭐⭐ **왜 「크기」로 재나 — 글자로 재던 게이트가 «눈이 멀어» 있었다**
//    `check-mistakes.mjs` ⑫ 는 바로 이걸 막으려고 8/13 에 만든 게이트다. 그런데 —
//      세는 글자 = `- 옛 기록 ↓`      → CLAUDE.md 에 **0개**
//      실제 쌓인 것 = `- **옛 버전**:` → **9개 · 21,601 B**
//    **형식이 바뀌었는데 게이트를 안 고쳤다.** 그래서 매 배포마다 «✅ 옛 기록 0줄»을 찍으면서
//    막으라고 만든 그것이 그대로 자랐다. 📌 규칙 18 ⓘ — 「통과했나」가 아니라 «무엇을 보고 통과했나».
//    ✅ **크기는 형식이 바뀌어도 안 속는다.** 그래서 낱말이 아니라 바이트를 잰다.
//
// ⚠️ **문턱에 여유를 둔 이유** (창업자가 `check-mistakes` 에 직접 적어 둔 우려 그대로)
//    *"하루이틀 못 옮겼다고 배포를 막으면 급할 때 게이트를 꺼버리고, **꺼진 게이트는 없는 게이트다.**"*
//    → 🟡 경고를 «먼저» 주고, 🔴 는 한참 뒤에. 지금 값에서 여러 세션치 여유가 있다.
//
// 🧹 넘었을 때 **「크다」고만 하지 않는다** — «어디를 자를지»와 «자동으로 자르는 명령»까지 준다.
//    (뿌리 넷 중 하나가 *"정리하려면 150KB 를 읽어야 해서 아무도 시작을 못 했다"* 였다)
import { readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const APP = existsSync('hankki/docs') ? 'hankki' : '.'
const ROOT = APP === 'hankki' ? '.' : '..'

// ── 문턱 (바이트) ──────────────────────────────────────────
//   ⭐ 여기 숫자를 올리기 «전»에 `doc-trim.mjs` 를 먼저 돌릴 것. 문턱을 올리는 건 게이트를 끄는 것과 같다.
const 잴것 = [
  { 이름: 'HANDOVER.md', 길: join(ROOT, 'HANDOVER.md'), 경고: 80_000, 막음: 110_000,
    도구: 'node scripts/doc-trim.mjs        # 👀보기 →  --옮김 으로 실행' },
  { 이름: 'CLAUDE.md', 길: join(APP, 'CLAUDE.md'), 경고: 150_000, 막음: 200_000,
    도구: '핀·옛 버전 기록을 docs/ 로 옮긴다 (CLAUDE.md 맨 위 「색인」 참고)' },
]

const 킬로 = (n) => (n / 1000).toFixed(0) + 'KB'
let 죽음 = 0
let 경고 = 0     // ⚠️ 가 떴는데 맨 밑에 「둘 다 문턱 아래」라고 찍던 것을 막는다(첫 판이 그랬다)

console.log('\n📏 문서 크기 — 대화 창을 먹는가')

for (const t of 잴것) {
  if (!existsSync(t.길)) { console.log(`   ⚠️ ${t.이름} 이 없다 — 건너뛴다`); continue }
  const 글 = readFileSync(t.길, 'utf8')
  const 바이트 = Buffer.byteLength(글)
  const 줄 = 글.split('\n').length
  const 표 = 바이트 >= t.막음 ? '⛔' : 바이트 >= t.경고 ? '⚠️' : '✅'
  console.log(`   ${표} ${t.이름.padEnd(13)} ${바이트.toLocaleString().padStart(9)} B · ${String(줄).padStart(5)}줄   (경고 ${킬로(t.경고)} · 막음 ${킬로(t.막음)})`)

  if (바이트 < t.경고) continue
  경고++

  // ── 어디가 뚱뚱한지 찍어 준다 — 읽어 보지 않아도 알 수 있게 ──
  const 줄들 = 글.split('\n')
  const 자리 = []
  줄들.forEach((l, i) => { if (/^#{2,3} /.test(l)) 자리.push(i) })
  const 절 = 자리.map((s, k) => ({
    제목: 줄들[s].replace(/^#+ /, '').slice(0, 58),
    시작: s + 1,
    바이트: Buffer.byteLength(줄들.slice(s, 자리[k + 1] ?? 줄들.length).join('\n')),
  })).sort((a, b) => b.바이트 - a.바이트).slice(0, 5)
  console.log(`      가장 큰 절 다섯 —`)
  for (const x of 절) console.log(`        ${String(x.바이트).padStart(7)} B  ${x.시작}행  ${x.제목}`)
  console.log(`      👉 ${t.도구}`)

  if (바이트 >= t.막음) 죽음++
}

if (죽음) {
  console.log(`\n⛔ 문서 ${죽음}개가 막음 문턱을 넘었다 — 배포를 막는다.`)
  console.log('   📌 이건 「나중에」가 없다. 두면 다음 세션이 대화를 열자마자 창이 찬다.')
  console.log('   ⛔ 문턱 숫자를 올려서 통과시키지 말 것 — 그건 게이트를 끄는 것이다.')
  process.exit(1)
}
if (경고) {
  console.log(`\n⚠️ ${경고}개가 경고 문턱을 넘었다 — 아직 배포는 막지 않지만 **지금 덜어내는 게 맞다.**`)
  console.log('   📌 두면 다음 세션이 대화를 열자마자 창이 찬다. 하루 이틀이면 막음 문턱에 닿는다.')
  process.exit(0)
}
console.log('   ✅ 둘 다 문턱 아래')
process.exit(0)
