#!/usr/bin/env node
// 📉📊 «바뀐 것만 읽기» ＋ «계기판» 재현판 — 2026-09-04
//
// 📮 창업자 = *"바뀐 것만 읽기랑 계기판 만들어줘"*
//
// ⭐⭐ **이 판이 지키는 한 줄 = 「켜는 값이 «유저 수 × 레시피 수»로 늘지 않는다」.**
//    🔢 지금 = 켤 때마다 컬렉션 통째로. 255편이면 **255건**.
//       유저 1만 명이 하루 한 번 켜면 **하루 255만 건** — 파이어스토어 무료 읽기는 **하루 5만 건**이라
//       ⛔ **유저 200명쯤에서 닿는다.** 자동 받기를 켜는 순간 그게 현실이 된다(절대원칙 32).
//    ✅ 바뀐 것만 읽으면 평소 **1~2건**이다.
//
// ⛔⛔ **켜기 «전»에 해야 하는 일이다.** 켜고 나서 고치면 그 사이에 돈이 나간다.
//
// 🧪 재는 것 열 (설계 관문에서 세 각도로 나온 것 그대로)
//   ① 올릴 때 「고친때」를 문서 «바깥 칸»에 같이 올린다 (안 그러면 클라우드가 못 거른다)
//   ② 바뀐 게 없으면 읽기가 «1건» (meta 만)
//   ③ 한 편만 바뀌면 읽기가 «2건» (meta ＋ 그 한 편)
//   ④ ⭐**처음(마지막 받은 때가 없을 때)엔 통째로 읽는다** — 옛 문서엔 그 칸이 없어 걸러내면 «안 보인다»
//   ⑤ 마지막 받은 때를 «클라우드가 준 값»으로 적는다 (폰 시계를 안 믿는다)
//   ⑥ 계기판이 읽기·쓰기를 «세다» · ⑦ 달이 바뀌면 «따로» 센다
//   ⑧ 계기판이 실패해도 «동기화를 멈추지 않는다» · ⑨ 계기판에 제목·본문을 «안» 남긴다
//   ⑩ ⭐**계기판 숫자가 실제 부른 횟수와 «같다»** (틀린 계기판은 감보다 나쁘다)

let 나쁨 = 0
const 잰다 = (좋나, 이름, 덧 = '') => {
  if (!좋나) 나쁨++
  console.log(`  ${좋나 ? '✅' : '⛔'} ${이름}${덧 ? ` — ${덧}` : ''}`)
}

// ── 가짜 클라우드 — «읽은 문서 수»를 진짜로 센다 ─────────────────────────
const 문서들 = new Map()   // 길 → { j, t }
let 진짜읽기 = 0
const 가짜 = {
  async meta읽기 () { 진짜읽기++; return { at: '2026-09-04T00:00:00.000Z', 서버때: 7000 } },
  async 바뀐것읽기 (갈래, 언제부터) {
    const 나온것 = []
    for (const [길, v] of 문서들) {
      if (!길.startsWith(갈래 + '/')) continue
      // ⭐ 클라우드가 «걸러서» 준다 — 우리가 다 받아서 거르는 게 아니다(그럼 읽기가 안 준다)
      if (언제부터 != null && !(Number(v.t || 0) > 언제부터)) continue
      진짜읽기++
      나온것.push(JSON.parse(v.j))
    }
    return 나온것
  },
  async 통째로읽기 (갈래) {
    const 나온것 = []
    for (const [길, v] of 문서들) {
      if (!길.startsWith(갈래 + '/')) continue
      진짜읽기++
      나온것.push(JSON.parse(v.j))
    }
    return 나온것
  },
}
const 담기 = (갈래, id, 고친때) => 문서들.set(`${갈래}/${id}`, { j: JSON.stringify({ id, title: '편' + id, 고친때 }), t: 고친때 })

// 큰 창고 흉내 (계기판이 쓴다)
const 창고 = new Map()
const 가짜창고 = {
  async 넣기 (k, v) { 창고.set(k, JSON.parse(JSON.stringify(v))); return true },
  async 꺼내기 (k) { const v = 창고.get(k); return v === undefined ? null : JSON.parse(JSON.stringify(v)) },
  async 지우기 (k) { 창고.delete(k) },
  async 열쇠들 () { return [...창고.keys()] },
}
const 터지는창고 = { ...가짜창고, async 넣기 () { throw new Error('터짐') } }

let 모듈, 계기판
try {
  모듈 = await import('../src/syncPull.js')
  계기판 = await import('../src/syncMeter.js')
} catch {
  console.log('\n⛔⛔ `src/syncPull.js` · `src/syncMeter.js` 가 아직 없다 — **이 판이 먼저다.**\n')
  process.exit(1)
}
const { 바뀐것받기, 올릴칸만들기 } = 모듈
const { 세기, 읽기: 계기읽기, _창고물리기 } = 계기판
_창고물리기(가짜창고)

console.log('\n📉📊 바뀐 것만 읽기 ＋ 계기판\n')

// ① 올릴 때 고친때가 «바깥 칸»에 같이 간다
const 칸 = 올릴칸만들기({ id: 'u1', title: '김치', 고친때: 1234 })
잰다(칸?.t === 1234 && typeof 칸?.j === 'string',
  '① 올릴 때 「고친때」가 문서 «바깥 칸»(t)에 간다', `t=${칸?.t}`)

// ── 문서 다섯 편 (고친때 1000~5000)
for (let i = 1; i <= 5; i++) 담기('recipes', 'u' + i, i * 1000)
// ⛔⛔ ＋ **「t 가 «없는» 옛 문서」** — 이미 클라우드에 올라가 있는 것들이 전부 이 모양이다.
//    🧪 [2026-09-04] 처음엔 이걸 안 넣어서 «처음에도 걸러 읽게 고쳐도 판이 안 죽었다» — 헛돌던 칸이다.
//       실물에선 이게 「옛 레시피가 통째로 안 보인다」가 된다. 제일 무서운 자리다.
문서들.set('recipes/u-old', { j: JSON.stringify({ id: 'u-old', title: '옛 편' }) })

// ④ ⭐ 처음엔 통째로 읽는다
진짜읽기 = 0
const 첫번 = await 바뀐것받기(가짜, { 마지막받은때: null })
잰다(첫번.편들.length === 6, '④ ⭐ 처음엔 «통째로» 읽는다 — «t 없는 옛 문서»까지 다 온다', `${첫번.편들.length}편 (6이라야 맞다)`)
잰다(첫번.편들.some((x) => x.편.id === 'u-old'), '  ④-c ⛔«t 없는 옛 문서»가 안 빠진다 (빠지면 「레시피가 사라졌다」가 된다)')
잰다(첫번.통째로 === true, '  ④-b 「통째로 읽었다」를 알려준다')

// ⑤ 마지막 받은 때 = 클라우드가 준 값
잰다(첫번.마지막받은때 === 7000, '⑤ 마지막 받은 때를 «클라우드가 준 값»으로 적는다 (폰 시계를 안 믿는다)',
  String(첫번.마지막받은때))

// ② 바뀐 게 없으면 읽기 «1건» (meta 만)
진짜읽기 = 0
const 두번 = await 바뀐것받기(가짜, { 마지막받은때: 9000 })
잰다(두번.편들.length === 0 && 진짜읽기 === 1,
  '② 바뀐 게 없으면 읽기가 «1건» (meta 만)', `읽기 ${진짜읽기}건`)

// ③ 한 편만 바뀌면 읽기 «2건»
담기('recipes', 'u9', 9500)
진짜읽기 = 0
const 세번 = await 바뀐것받기(가짜, { 마지막받은때: 9000 })
잰다(세번.편들.length === 1 && 진짜읽기 === 2,
  '③ 한 편만 바뀌면 읽기가 «2건» (meta ＋ 그 편)', `읽기 ${진짜읽기}건 · ${세번.편들.length}편`)

// ⑥⑩ 계기판이 «실제 부른 횟수»와 같은 수를 센다
await 세기({ 읽기: 진짜읽기, 쓰기: 3 })
const 계 = await 계기읽기()
잰다(계.읽기 === 2 && 계.쓰기 === 3, '⑥⑩ 계기판 숫자가 «실제 부른 횟수»와 같다',
  `읽기 ${계.읽기} · 쓰기 ${계.쓰기}`)

// ⑦ 달이 바뀌면 따로 센다
await 세기({ 읽기: 5, 달: '2026-08' })
const 이번달 = await 계기읽기()
잰다(이번달.읽기 === 2, '⑦ 달이 바뀌면 «따로» 센다 (지난달 값이 안 섞인다)', `이번 달 읽기 ${이번달.읽기}`)

// ⑨ 계기판에 제목·본문을 안 남긴다
await 세기({ 읽기: 1, title: '항정살조림' })
잰다(!JSON.stringify([...창고.values()]).includes('항정살조림'),
  '⑨ ⛔계기판에 «제목»을 안 남긴다 (숫자만)')

// ⑧ 계기판이 실패해도 동기화를 멈추지 않는다
_창고물리기(터지는창고)
let 던졌나 = false
try { await 세기({ 읽기: 1 }) } catch { 던졌나 = true }
잰다(!던졌나, '⑧ 계기판이 실패해도 «동기화를 멈추지 않는다»', 던졌나 ? '⛔던졌다' : '조용히 넘어갔다')
_창고물리기(가짜창고)

console.log(나쁨 ? `\n⛔ ${나쁨}칸 실패 — 이걸 안 고치고 자동 받기를 켜면 유저 200명에서 무료치가 터진다\n`
  : '\n✅ 켜는 값이 «유저 수 × 레시피 수»로 안 는다 — 평소 읽기 1~2건 · 계기판이 숫자로 말한다\n')
process.exit(나쁨 ? 1 : 0)
