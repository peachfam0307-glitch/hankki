#!/usr/bin/env node
// 🗃🤖 「AI 가 성공했을 때만 보관함을 졸업한다」 재현판 — 2026-09-05 (창업자 확정)
//
// 📮 창업자 제보 = *"ai가 작동을안하는데도 **보관함에서 금방사라져버려. 읽기시작하면 바로 옮겨지는 듯**"*
// 📮 창업자 확정 = *"보관함은 **ai가 읽어서 성공했을때만 옮기고**,
//                  ai가 실패해서 **기본규칙이 적용되면 그대로 남게** 하자."*
//
// 🔢 **실물 표본 (2026-09-05 아침 · 창업자 캡처 6장)** — 같은 인스타 글을 «두 번» 담았다
//   · ①파서만  = 제목 「계속됩니다.. 커밍쑨」(앞 게시물 꼬리) · 재료에 「바닥 5중, 옆면 3중에…」(팬 광고문)
//   · ②AI 다듬기 = 제목 「얼큰 국물 파스타」 · 재료 16줄 정확 · 걸음 8개 · 「1스푼」→「1큰술」 단위 통일까지
//   ⭐ 즉 **AI 가 일하면 결과가 확연히 다르다.** 그런데 ①이 «AI 가 시작하기도 전에» 졸업해 버렸다.
//
// 🌲 **뿌리** = `store.jsx` 의 `다읽었나()` 는 **재료>=2 && 걸음>=2** 가 전부다.
//    ＝ 파서가 «장사말로» 2줄만 만들어도 그 순간 졸업한다. AI 는 그 «뒤»에 돈다.
//    ⛔ 그래서 AI 가 실패하거나 앱이 정리되면 **장사말 판이 조용히 정식 레시피가 된다.**
//
// ⭐⭐ **고침 = 잣대를 «둘로 가른다»** (숫자를 바꾼 게 아니다 · 절대원칙 34)
//   | 무엇 | 잣대 |
//   |---|---|
//   | **어디로 데려가나**(화면) | `다읽었나(parsed)` — ⛔지금 그대로 |
//   | **어디에 두나**(status)  | `다읽었나` **＋ AI 가 끝났나** |
//
// ⛔⛔ **「가두는 것」이 아니다 — 창업자가 2026-09-05 에 직접 바로잡았다:**
//    *"나는 **무조건 내보내라는 뜻이 아니었어**. 그때는 아예 보관함에서 안 나가고
//      최근저장에 반영이 안 되니까 물어본 거야."*
//    ＝ 2026-09-01 요구의 진짜 조건은 속도가 아니라 **「영영 안 나오는 상태를 만들지 마라」**.
//    ✅ 그래서 이 판은 **탈출구 셋이 살아 있는지**를 «같이» 잰다(④⑤⑥). 그게 이 판의 존재 이유다.
//
// 🧪 재는 것 — ⛔소스를 읽어서 «약속»을 잰다(실제 폰 판정은 창업자 몫).
//   ① 졸업(status:'sorted')이 «AI 끝남»에 걸려 있나
//   ② 규칙 파서 판(`채우기(기본)`)은 졸업을 «안» 시키나       ← 여기가 제보의 자리다
//   ③ AI 성공 판은 졸업을 «시키나»                          ← 이게 없으면 영영 안 나온다
//   ④ 🚪탈출구1 — 나중에 만회에 성공하면 상세 화면이 졸업시키나
//   ⑤ 🚪탈출구2 — 임시보관함의 「그대로 저장」이 살아 있나
//   ⑥ ⛔화면 잣대(`다읽었나(parsed)`)는 «안» 건드렸나        ← 2026-09-01 요구를 되돌리지 않는다
//   ⑦ ⛔올리기만 한다 — 상세 화면 만회가 이미 `sorted` 인 것을 내리지 않나
//   ⑧ ⛔잣대는 여전히 `다읽었나()` «한 곳»인가              ← 복사되면 그때부터 갈린다
//
// 실행: node scripts/_repro-보관함AI대기-0905.mjs   (exit 0 = 통과)
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

let 나쁨 = 0
const 잰다 = (좋나, 이름, 덧 = '') => {
  if (!좋나) 나쁨++
  console.log('  ' + (좋나 ? '✅' : '⛔') + ' ' + 이름 + (덧 ? ' — ' + 덧 : ''))
}

const 뿌리 = join(dirname(fileURLToPath(import.meta.url)), '..')
const 읽기 = (p) => readFileSync(join(뿌리, p), 'utf8')
// ⛔ 주석을 지우고 잰다 — 안 그러면 «설명하는 글»이 「고쳤다」로 읽힌다(가짜 초록불).
const 코드만 = (s) => s.split('\n').filter((줄) => !/^\s*(\/\/|\*|\/\*)/.test(줄)).join('\n')

const 앱 = 코드만(읽기('src/App.jsx'))
const 상세 = 코드만(읽기('src/screens/RecipeDetailScreen.jsx'))
const 보관함 = 코드만(읽기('src/screens/InboxScreen.jsx'))
const 가게 = 코드만(읽기('src/store.jsx'))

console.log('\n🗃🤖 보관함 졸업 — 「AI 가 읽어서 성공했을 때만」 (창업자 확정 2026-09-05)\n')

// ── ① 졸업이 «AI 끝남»에 걸려 있나 ────────────────────────────────────────
잰다(/AI끝남\s*&&\s*다읽었나\(r\)\s*\?\s*\{\s*status:\s*'sorted'/.test(앱),
  '① 🎓 졸업(status)이 «AI 끝남 ＋ 다읽었나» 둘을 «다» 본다',
  '⛔ 하나만 보면 장사말 2줄이 정식 레시피가 된다')

// ── ② 규칙 파서 판은 졸업을 «안» 시킨다 ───────────────────────────────────
//   ⭐ 잣대 = `채우기(기본)` 을 부르는 줄에 `AI끝남` 이 «없다».
//   ⛔ `채우기(기본, { AI끝남: true })` 로 새면 제보가 그대로 되살아난다.
const 파서판 = /채우기\(기본\)(?!\s*,)/.test(앱)
잰다(파서판, '② 📋 규칙 파서 판(`채우기(기본)`)은 «졸업 안 시킨다»',
  파서판 ? '안 시킨다 — 여기가 제보의 자리였다' : '⛔ 졸업시킨다 — AI 가 시작하기도 전에 나간다')

// ── ③ AI 성공 판은 졸업을 «시킨다» ────────────────────────────────────────
//   ⛔ 이게 빠지면 「영영 안 나오는 상태」가 된다 — 창업자가 제일 싫어하는 모양이다.
잰다(/채우기\(mergeTidy\([^)]*\)\s*,\s*\{\s*AI끝남:\s*true\s*\}\)/.test(앱),
  '③ 🤖 AI 가 성공한 판은 «졸업시킨다» (＝여기가 유일한 자동 출구)',
  '⛔ 없으면 영영 안 나온다')

// ── ④ 🚪탈출구1 — 나중에 만회해도 나오나 ─────────────────────────────────
//   📌 여기가 이번에 «같이» 고쳐야 했던 자리다. 안 고치면 AI 실패한 편이
//      나중에 만회에 성공해도 status 가 그대로라 보관함에 갇힌다.
잰다(/status\s*!==\s*'sorted'\s*&&\s*다읽었나\(/.test(상세) && /\.status\s*=\s*'sorted'/.test(상세),
  '④ 🚪 탈출구1 — 상세 화면이 «만회에 성공하면» 그때 졸업시킨다',
  '⛔ 없으면 AI 실패한 편이 갇힌다(2026-09-01 제보가 다른 문으로 되살아난다)')

// ── ⑤ 🚪탈출구2 — 유저 손으로 언제든 ─────────────────────────────────────
잰다(/status:\s*'sorted'/.test(보관함) && /그대로 저장|레시피로 저장/.test(읽기('src/screens/InboxScreen.jsx')),
  '⑤ 🚪 탈출구2 — 임시보관함의 「그대로 저장」이 살아 있다')

// ── ⑥ ⛔화면 잣대는 «안» 건드렸다 ────────────────────────────────────────
//   📮 창업자 2026-09-01 요구 = 「아예 보관함에서 안 나가고 최근저장에 반영이 안 된다」를 고치라는 것.
//   ⭐ 담을 때 «어디로 데려가나»는 그대로 `다읽었나(parsed)` 여야 한다.
잰다(/if\s*\(다읽었나\(parsed\)\)\s*rec\.status\s*=\s*'sorted'/.test(앱),
  '⑥ 🧭 담을 때 화면 잣대(`다읽었나(parsed)`)는 «그대로»다',
  '⛔ 여기까지 미루면 2026-09-01 제보가 그대로 되살아난다')

// ── ⑦ ⛔올리기만 한다 ────────────────────────────────────────────────────
//   ⭐ 상세 화면 만회가 이미 졸업한 것을 «내리면» 유저가 손으로 옮긴 게 도로 사라진다.
잰다(!/status:\s*'unsorted'/.test(상세),
  '⑦ ⬆️ 올리기만 한다 — 상세 화면이 이미 나간 것을 «되돌리지» 않는다')

// ── ⑧ ⛔잣대는 여전히 한 곳 ──────────────────────────────────────────────
//   📌 `store.jsx` 주석이 못 박아 둔 것 = 이 잣대가 복사되면 그때부터 화면마다 말이 갈린다.
const 정의수 = (가게.match(/export function 다읽었나/g) || []).length
잰다(정의수 === 1, '⑧ 📏 잣대 `다읽었나()` 정의는 «한 곳»뿐이다', '지금 ' + 정의수 + '곳')
잰다(/import\s*\{[^}]*다읽었나[^}]*\}\s*from\s*'\.\.\/store'/.test(상세),
  '⑧ 📏 상세 화면도 그 «한 곳»에서 가져다 쓴다 (복사하지 않았다)')

console.log(나쁨 ? '\n⛔ ' + 나쁨 + '칸 빨간불 — 장사말 판이 정식 레시피가 되거나, 영영 안 나온다\n'
  : '\n✅ AI 가 성공했을 때만 졸업한다 · 탈출구 셋 다 살아 있다\n')
process.exit(나쁨 ? 1 : 0)
