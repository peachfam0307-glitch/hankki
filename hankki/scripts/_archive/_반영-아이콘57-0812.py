줄.append('\n\n■ FoodIcon.jsx — ICON_RULES «맨 위»에 붙일 것 (구체 요리명)\n')
쓴규칙 = 0
for 옛, 새키, 이름, _, 낱말 in 결과:
    if not 낱말:
        continue
    쓴규칙 += 1
    # ⚠️ 띄어쓴 꼴을 «자동으로» 같이 넣는다 — 이름에 공백이 있으면 그 꼴도 들어가야 한다
    전부 = []
    for w in 낱말:
        전부.append(w)
    목록 = ', '.join(f"'{w}'" for w in dict.fromkeys(전부))
    줄.append(f'  [[{목록}], \'{새키}\'],')
줄.append(f'\n  (규칙 {쓴규칙}개 · 전용 그림이 이미 있어 «규칙 없이 픽커에만» 두는 것 {len(결과) - 쓴규칙}개)')

줄.append('\n\n■ FoodIcon.jsx — EXTRA_NAMES 에 붙일 것 (픽커 이름표)\n')
for 옛, 새키, 이름, _, 낱말 in 결과:
    if not 낱말 or 낱말[0] != 이름:      # 첫 낱말이 곧 이름이면 자동으로 잡힌다 → 안 적어도 된다
        줄.append(f"  {새키}: '{이름}',")

줄.append('\n\n■ FoodIcon.jsx — FOOD_ICON_GROUPS 에 그룹별로 붙일 것\n')
그룹별 = {}
for 옛, 새키, 이름, 그룹, _ in 결과:
    그룹별.setdefault(그룹, []).append((새키, 이름))
for 그룹, 것들 in 그룹별.items():
    키들 = ', '.join(f"'{k}'" for k, _ in 것들)
    이름들 = ' · '.join(n for _, n in 것들)
    줄.append(f'  [{그룹}]  {키들}')
    줄.append(f'      // {이름들}\n')

낼곳.write_text('\n'.join(줄), encoding='utf-8')
