바꿔('황태국', '재료', '멸치육수 1봉', '해물가루육수 1봉')
낱말('황태국', '순서', '야채육수 1봉, 멸치육수 1봉', '야채가루육수 1봉, 해물가루육수 1봉')

// ⑤ 마늘쫑장아찌 — *"레몬은 내가 못봤나봐 패스"* → ⛔손대지 않는다

// ⑥ 두부참치찌개 — *"올리고당7>5으로 바꾸자 단맛을 올리고당으로 가감"*
바꿔('두부참치찌개', '재료', '올리고당 7큰술', '올리고당 5큰술')
메모덧('두부참치찌개', '단맛은 올리고당으로 가감해요.')

// ⑦ 오이물김치 — *"(갈아만든배없으면 배즙)"*
바꿔('오이물김치', '재료', '갈아만든배 1컵', '갈아만든배 1컵 (없으면 배즙)')

// ⑧ 양념게장 — *"(초피없으면 멸치액젓)"*
바꿔('양념게장', '재료', '초피액젓 3큰술', '초피액젓 3큰술 (없으면 멸치액젓)')

// ⑨ 굴 매생이 떡국 — *"(파운더레시피)"*
//    ⭐ 어제 확정 *"전부 해물가루육수로"* 가 이 편만 빠져 있었다(검수에서 ✅였던 편이라 안 건드렸다)
바꿔('굴 매생이 떡국', '재료', '가루육수 1봉', '해물가루육수 1봉')
낱말('굴 매생이 떡국', '순서', '가루육수 1봉을 넣어', '해물가루육수 1봉을 넣어')
