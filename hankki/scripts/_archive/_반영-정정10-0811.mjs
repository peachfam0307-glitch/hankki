바꿔('목살조림', '재료', '아우노슈가 2큰술 (또는 설탕)', '아우노슈가 2큰술 (일반설탕 1과1/3큰술)') // 매콤 소스 쪽
바꿔('순살찜닭', '재료', '아우노슈가 2큰술 (또는 설탕)', '아우노슈가 2큰술 (일반설탕 1과1/3큰술)')
바꿔('비빔갈비찜', '재료', '아우노슈가 1큰술 (또는 설탕)', '아우노슈가 1큰술 (일반설탕 2/3큰술)')

// ③ 소고기 솥밥 — *"해물육수가루로"* → ⚠️광고가 붙는 이름 「해물가루육수」로 넣었다(물어볼 것)
바꿔('소고기 솥밥', '재료', '육수가루 1포', '해물가루육수 1포')
낱말('소고기 솥밥', '순서', '버섯과 육수가루를 넣어', '버섯과 해물가루육수를 넣어')

// ④ 황태국 — *"원래 야채가루육수1봉에 해물가루육수1봉이거든.
