//   ⭐ 어제 판(아티팩트)을 보고 창업자가 준 정정 10개.
//   ⛔ 「못 찾으면 죽는다」 — 옛 글자가 없으면 throw 해서 «조용히 안 바뀌는 것»을 막는다.
//      (writeFileSync 가 맨 끝이라 중간에 죽으면 파일이 한 글자도 안 바뀐다)
//
//   📌 환산 규칙 = 아우노 = 일반설탕 × 1.5  (src/data/basics.js 17줄 주석)
//      → 일반설탕 = 아우노 ÷ 1.5 · 아우노 2큰술 = 1과1/3큰술 · 아우노 1큰술 = 2/3큰술
//
//   ⛔⛔ 큐레이션 matches 는 «낱말 시작»으로만 걸린다(curation.js `startsWithAny`).
//      「해물가루육수」✅ · 「가루육수」✅ · 「육수가루」⛔ · 「해물육수가루」⛔
//      → 창업자가 말한 「해물육수가루」로 쓰면 육수 광고가 «끊긴다» → 「해물가루육수」로 넣고 물어본다.

import { readFileSync, writeFileSync } from 'node:fs'

const 파일 = new URL('../docs/_대기/레시피-정리-초안-2026-08-10.json', import.meta.url)
const arr = JSON.parse(readFileSync(파일, 'utf8'))
const by = Object.fromEntries(arr.map((r) => [r.title, r]))

const 한일 = []

const 칸 = (r, 이름) => (이름 === '재료' ? r.ingredients : r.steps)

// 재료·순서의 한 줄을 통째로 갈아끼운다 — 옛 줄이 없으면 죽는다
const 바꿔 = (제목, 종류, 옛, 새) => {
  const r = by[제목]
  if (!r) throw new Error(`「${제목}」 편이 없다`)
  const a = 칸(r, 종류)
  const i = a.findIndex((x) => x === 옛)
  if (i < 0) throw new Error(`${제목} ${종류}에 「${옛}」 없다 — 지금: ${JSON.stringify(a)}`)
  a[i] = 새
  한일.push(`${제목} · ${종류}${i + 1} : ${옛} → ${새}`)
}

// 한 줄 «안»의 낱말만 바꾼다(순서 문장처럼 긴 줄)
const 낱말 = (제목, 종류, 옛, 새) => {
  const r = by[제목]
  if (!r) throw new Error(`「${제목}」 편이 없다`)
  const a = 칸(r, 종류)
  const i = a.findIndex((x) => x.includes(옛))
  if (i < 0) throw new Error(`${제목} ${종류}에 「${옛}」 없다`)
  const 전 = a[i]
  a[i] = 전.split(옛).join(새)
  한일.push(`${제목} · ${종류}${i + 1} : …${옛}… → …${새}…`)
}

// 편 전체를 훑어 낱말을 바꾼다 — ⛔`orig`(창업자 원문)·`title`·`key` 는 «절대» 안 건드린다
const 전부 = (옛, 새) => {
  let n = 0
  for (const r of arr) {
    for (const 종류 of ['ingredients', 'steps']) {
      ;(r[종류] || []).forEach((x, i) => {
        if (x.includes(옛)) { r[종류][i] = x.split(옛).join(새); n++ }
      })
    }
    if ((r.memo || '').includes(옛)) { r.memo = r.memo.split(옛).join(새); n++ }
  }
  if (!n) throw new Error(`어디에도 「${옛}」 없다`)
  한일.push(`〈전수〉 ${옛} → ${새} · ${n}곳 (⛔orig 원문은 그대로)`)
}

const 메모덧 = (제목, 문장) => {
  const r = by[제목]
  if (!r) throw new Error(`「${제목}」 편이 없다`)
  if ((r.memo || '').includes(문장)) throw new Error(`${제목} 메모에 이미 「${문장}」 있다`)
  r.memo = (r.memo ? r.memo + '\n' : '') + 문장
  한일.push(`${제목} · 메모 ＋ ${문장}`)
}

