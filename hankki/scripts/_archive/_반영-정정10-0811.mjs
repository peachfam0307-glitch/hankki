// ⑩ 비빔갈비찜 — *"배농축액->갈아만든배로 (없으면 배즙)"*
바꿔('비빔갈비찜', '재료', '배농축액 2큰술 (배즙이나 갈아만든배도 좋아요)', '갈아만든배 2큰술 (없으면 배즙)')

// ⑪ 식용유 전수 → 올리브유
//    📮 창업자 2026-08-11 *"「식용유」는 ✅그대로 판정 받은 편들에도 있는데 안 건드렸어 — 이거 다 올리브유로 바꿔줘."*
//    ⛔ 맞는 지적이다 — 어제 나는 «✏️로 짚은 편»만 고쳤다. 그런데 지시는 «양념을 바꾸는 것»이라 편을 안 가린다.
//       ⭐ 「어느 편을 짚었나」가 아니라 「무엇을 바꾸라 했나」로 읽어야 했다.
