// 🐛 재현 — 「1/2컵」이 «혼자» 재료로 뜨는 것 (창업자 제보 2026-08-16)
//   📮 *"황태장아찌 요리시작 누르면 1/2컵이 줄바뀜으로 혼자 뜨는거"*
//   돌리기 = node hankki/scripts/_repro-분량만줄-0816.mjs
//   ⭐ 아래 ②③④ 는 «회귀 감시»다 — 고치다가 두 번 망가뜨린 자리라 같이 잰다.
import { parseRecipeText, mergeQtyOnlyIngredients } from '../src/parseRecipe.js'

let 실패 = 0
const 재다 = (이름, 원문, 검사) => {
  const r = parseRecipeText(원문, { fromOcr: true })
  const 말 = 검사(r)
  console.log(`\n● ${이름}  ${말 ? '❌ ' + 말 : '✅'}`)
  r.ingredients.forEach((x) => console.log('   - ' + x))
  if (말) 실패 += 1
}

// ① 창업자가 본 그 화면 — 「양조간장 (진간장)」 다음 줄에 분량만 남았다
재다(
  '① 황태장아찌 — 분량만 남은 줄',
  `📍 황태장아찌
재료: 황태채 360g, (맛술 1/2컵)
양념 : 고추장 2컵, 고춧가루 1/2컵, 양조간장 (진간장)
1/2컵
설탕 1/2컵, 매실청 1컵, 육수 1컵(멸치새우)
올리고당 1컵, 다진마늘 3스푼, 다진생강 1스푼
1 황태채 360g에 맛술 1/2컵을 부어 섞어두고`,
  (r) => {
    if (r.ingredients.some((x) => x.trim() === '1/2컵')) return '「1/2컵」이 아직 혼자 뜬다'
    if (!r.ingredients.some((x) => x.includes('양조간장') && x.includes('1/2컵'))) return '앞 재료에 안 붙었다'
    // 회귀 감시 — 뒤 줄들이 통째로 딸려 붙으면 안 된다
    if (!r.ingredients.some((x) => x.trim().startsWith('설탕'))) return '설탕이 앞줄에 딸려 붙었다(회귀)'
    if (!r.ingredients.some((x) => x.trim().startsWith('올리고당'))) return '올리고당이 딸려 붙었다(회귀)'
    return ''
  },
)

// ② 이름이 «한 글자»인 재료 — 붙으면 안 된다 (2차 회귀 자리)
재다(
  '② 전복솥밥 — 파 30g · 물 50ml 는 그대로',
  `❇ 맛간장 ❇
간장 3스푼
대게백간장 3스푼(생략가능)
파 30g
알룰로스 3스푼
통깨 1스푼
물 50ml
1. 전복 손질해서 준비`,
  (r) => {
    if (!r.ingredients.some((x) => x.trim() === '파 30g')) return '「파 30g」이 앞줄에 딸려 붙었다'
    if (!r.ingredients.some((x) => x.trim() === '물 50ml')) return '「물 50ml」가 앞줄에 딸려 붙었다'
    return ''
  },
)

// ③ 불릿 재료 뒤 분량 줄
재다(
  '③ 불릿 — 200g · 2큰술',
  `- 소고기
200g
- 간장
2큰술
- 대파 1대`,
  (r) => {
    if (r.ingredients.some((x) => /^(200g|2큰술)$/.test(x.trim()))) return '분량만 있는 줄이 혼자 떴다'
    if (!r.ingredients.some((x) => x.includes('소고기') && x.includes('200g'))) return '소고기에 안 붙었다'
    return ''
  },
)

// ④ 순서 안의 숫자 줄은 건드리지 않는다
재다(
  '④ 순서 구간 — 재료로 새지 않는다',
  `재료
- 감자 2개
만드는 법
1. 감자를 삶는다
10분
2. 으깨서 담는다`,
  (r) => (r.ingredients.length === 1 ? '' : '순서 구간의 줄이 재료로 샜다'),
)

// ⑤ 🚚 **이미 «저장된» 레시피** — 테스터 폰에 든 것도 고쳐져야 한다 (창업자 2026-08-16)
//    *"그 레시피는 테스터가 캡쳐해준거야. 근데도 고칠 수가 없다고?"*
const 이사검사 = (이름, 들어간것, 나와야할것) => {
  const 나온것 = mergeQtyOnlyIngredients(들어간것)
  const 같나 = JSON.stringify(나온것) === JSON.stringify(나와야할것)
  console.log(`\n● ${이름}  ${같나 ? '✅' : '❌'}`)
  나온것.forEach((x) => console.log('   - ' + x))
  if (!같나) { 실패 += 1; console.log('   기대 = ' + JSON.stringify(나와야할것)) }
}

이사검사(
  '⑤ 저장된 황태장아찌 — 「1/2컵」이 별개 재료로 들어 있다',
  ['재료: 황태채 360g, (맛술 1/2컵)', '양념 고추장 2컵', '고춧가루 1/2컵', '양조간장 (진간장)', '1/2컵', '설탕 1/2컵'],
  ['재료: 황태채 360g, (맛술 1/2컵)', '양념 고추장 2컵', '고춧가루 1/2컵', '양조간장 (진간장) 1/2컵', '설탕 1/2컵'],
)

이사검사(
  '⑥ 멀쩡한 기본 레시피는 «한 줄도» 안 건드린다',
  ['황태채 360g', '맛술 1/2컵', '[양념]', '고추장 2컵', '파 30g', '물 50ml'],
  ['황태채 360g', '맛술 1/2컵', '[양념]', '고추장 2컵', '파 30g', '물 50ml'],
)

이사검사(
  '⑦ 첫 줄이 분량만이면 붙일 데가 없으니 그냥 둔다',
  ['1/2컵', '고추장 2컵'],
  ['1/2컵', '고추장 2컵'],
)

console.log(`\n${실패 ? `❌ ${실패}개 실패` : '✅ 전부 통과'}`)
process.exit(실패 ? 1 : 0)
