// 🔬🔬 «남의 서비스에 붙기 전» 관문 — 절대원칙 37 (창업자 2026-09-04)
//
// 📮 창업자 = *"설계할때 제대로 리서치하고 검토하고 시작해 절대원칙이야"*
//           · *"설계는 촘촘하고 세밀하게, 리스크 고려해서 다각도 서치 검토 후 설계한다"*
//           · *"절대원칙이야 제일 중요한"* · *"**설계할때 읽고 시작 코드로 만들어서 박아둬**"*
//    ⭐ 마지막 한 줄이 이 파일이 있는 이유다 — **규칙으로 적지 말고 «막게» 만들라는 것.**
//       (창업자 2026-07-31 = *"규칙만 만들면 뭐해 안지키는데."* — 그래서 우리는 늘 장치로 간다)
//
// ⛔⛔ **왜 생겼나 — 2026-09-04 인스타 표지 뽑기에서 «같은 자리»를 세 번 틀렸다**
//    ⑴ *"인스타는 표지를 안 준다"* → 틀렸다(창업자가 경쟁 앱 화면으로 반증)
//    ⑵ 태그 «모양»에 맞춰 뽑기 → 인스타는 화면을 JS 로 그려서 못 집음
//    ⑶ 그래서 「cdninstagram 이면 다 좋다」로 **넓혔더니 로고를 집어 왔다**
//    ⭐ 셋 다 뿌리가 같다 = **그 서비스가 «실제로 어떻게 생겼는지»를 안 알아보고 만들었다.**
//       인스타는 사람이 올린 사진을 `scontent-…/v/t51.` 에, 화면 부품을 `static.…/rsrc.php/` 에 둔다.
//       **이 한 줄만 먼저 알았으면 세 번이 한 번이었다.**
//
// ⭐⭐ **제일 나쁜 것은 ⑶ 이다** — 안 뜨면 유저는 「안 뜨네」 하고 만다.
//    **엉뚱한 그림이 뜨면 «그게 그 요리인 줄» 안다.**
//    📌 넓게 잡는 건 실패를 없애는 게 아니라 **더 나쁜 실패로 바꾸는 것**이다.
//
// ═══ 쓰는 법 ═══════════════════════════════════════════════════
//   node hankki/scripts/design-check.mjs --붙는곳 "instagram.com" \
//     --모양     "사람이 올린 사진 = scontent-*.cdninstagram.com/v/t51.* · 서명이 붙고 며칠 뒤 만료" \
//     --닮은것   "화면 부품(로고) = static.cdninstagram.com/rsrc.php/* · 프로필 사진 = /t51.2885-19/" \
//     --바뀌는것 "태그 모양·클래스 이름은 수시로 바뀐다 / 도메인·경로 규칙은 잘 안 바뀐다" \
//     --막힘신호 "로그인 창(302·200인데 로그인 HTML) · 429 · 200인데 사진 주소 0개"
//
//   ✅ 통과하면 표식(`/tmp/hankki-설계-<붙는곳>`)이 생기고 훅이 비켜난다.
//   ⛔ 「모르겠다」·「확인 못 함」·「미확인」은 통과 못 한다 — 그게 이 관문이 막는 바로 그것이다.
//   ⛔ 네 칸 중 하나라도 비면 통과 못 한다. **짧게라도 «실제로 알아본 것»을 적는다.**
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const 인자 = process.argv.slice(2)
const 값 = (이름) => {
  const i = 인자.indexOf(`--${이름}`)
  return i >= 0 ? String(인자[i + 1] || '').trim() : ''
}

const 붙는곳 = 값('붙는곳')
const 칸들 = [
  ['모양', 값('모양'), '원하는 걸 «실제로 어떤 모양»으로 내주나 (주소 규칙·필드 이름·만료)'],
  ['닮은것', 값('닮은것'), '비슷하게 생겼지만 «다른 것» — 오탐 후보 (2026-09-04 엔 로고였다)'],
  ['바뀌는것', 값('바뀌는것'), '그쪽이 «바꿀 만한 것 / 잘 안 바꾸는 것» (바뀌는 것에 기대면 다음 달에 깨진다)'],
  ['막힘신호', 값('막힘신호'), '막힐 때 «어떤 신호»로 오나 (로그인 창? 빈 응답? 200인데 내용 없음?)'],
]

// ⛔ 「모른다」를 적어놓고 통과시키지 않는다 — 규칙 15 의 뿌리가 정확히 그것이었다
//    (*"확인 못 했다고 «내 손으로 적어놓고» 그 위에서 창업자를 움직였다"*)
const 모름 = /모르|미확인|확인\s*못|나중에|아마|추측|일단|TODO|\?\?/

if (!붙는곳) {
  console.log('⛔ --붙는곳 이 없다. 어느 서비스에 붙는지부터 적는다. (예: instagram.com)')
  process.exit(1)
}

let 나쁨 = 0
console.log(`\n🔬 «${붙는곳}» 에 붙기 전 — 네 가지를 알아봤나\n`)
for (const [이름, v, 뜻] of 칸들) {
  if (!v) { console.log(`⛔ --${이름} 이 비었다\n     ${뜻}`); 나쁨++; continue }
  if (모름.test(v)) { console.log(`⛔ --${이름} 에 «모른다»가 들어 있다 — 그건 알아본 게 아니다\n     ${v}`); 나쁨++; continue }
  if (v.length < 12) { console.log(`⛔ --${이름} 이 너무 짧다 — 한 낱말은 알아본 게 아니다\n     ${v}`); 나쁨++; continue }
  console.log(`✅ ${이름} — ${v}`)
}

if (나쁨) {
  console.log(`\n⛔ ${나쁨}칸이 비었다 — **아직 시작하지 않는다.**`)
  console.log('   📌 넓게 잡아놓고 되는지 보는 건 «실패를 더 나쁜 실패로 바꾸는 것»이다(절대원칙 37).')
  console.log('   🔎 알아보는 길 = WebSearch · 공식 문서 · 실물 응답 한 번 받아보기')
  console.log('   ⛔ 내가 못 여는 곳이면 «창업자에게 물어볼 문장»을 만들어 준다(규칙 15).\n')
  process.exit(1)
}

// 🚪 표식 = 훅이 이걸 보고 비켜난다. `/tmp` 라 컨테이너가 되감기면 저절로 사라진다(다시 알아본다).
const 표식 = join('/tmp', `hankki-설계-${붙는곳.replace(/[^\w.-]/g, '_')}`)
writeFileSync(표식, 칸들.map(([이름, v]) => `${이름}: ${v}`).join('\n') + `\n(${new Date().toISOString()})\n`)
console.log(`\n✅ 네 가지 다 적었다 — 시작해도 된다.`)
console.log(`   🚪 표식 = ${표식}`)
console.log('   ⛔ 그래도 «좁게» 시작한다 — 넓은 잣대는 틀린 답을 «맞다»고 말한다.\n')
process.exit(0)
