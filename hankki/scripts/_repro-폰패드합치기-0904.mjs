#!/usr/bin/env node
// ☁️🔀 폰↔패드 «합치기» 재현판 — 2026-09-04
//
// 📮 창업자 = *"폰에서 꾸민 것들, 추가한 것들 패드에 반영이 안되고 있어(자동으로)"*
//           ＋ *"시작하자 **이건 네가 우리앱을 책임지는거야. 이거 잘못되면 답이 없어**"*
//
// ⭐⭐ **이 판이 지키는 한 줄 = 「받기는 «지우지» 않는다」.**
//    지금 구조는 클라우드 판으로 **통째로 덮는다.** 그래서 안전장치 하나가 뚫리면 곧바로 사라진다.
//    🚨 2026-09-01 23:51 에 실제로 그랬다 — 창업자가 항정살조림을 담아 **열쇠가 5→4 로 깎였는데
//       잠시 뒤 레시피가 사라졌다.** 「돈은 썼는데 물건이 없는」 제일 나쁜 모양이다.
//       그 뒤로 `App.jsx` 에서 자동 받기를 `if (false)` 로 잠가 뒀다.
//    ⛔ **그 사고의 «원인»은 아직 확정 못 했다.** 그래서 이 판은 원인을 쫓지 않는다 —
//       **원인이 무엇이든 «잃지 않게»** 만드는지를 잰다(절대원칙 34 = 실패의 모양을 바꾼다).
//
// 📐 설계 전문 = `docs/폰패드-자동동기화-설계-2026-09-04.md` (다섯 번 흔든 기록 · 구멍 스무 개)
//
// 🧪 재는 것 여섯 — ⛔지금 코드로 돌리면 **①이 죽는다.** 그게 맞다(아직 안 만들었으니까).
//    ① ⭐**폰에만 있는 편이 살아남나** (＝9/1 사고 재현)
//    ② 폰에서 지운 편이 «되살아나지» 않나 (무덤)
//    ③ 장보기·냉장고가 통째로 덮이지 않나 (`name` 으로 합친다)
//    ④ **우리 기본 레시피**는 안 건드리나 (안 그러면 BASICS_VERSION 으로 바꾼 그림이 되돌아간다)
//    ⑤ 사진(`data:`)이 안 사라지나 — 클라우드엔 안 올리므로 «폰 것을 그 자리에 되돌려»야 한다
//    ⑥ 꾸미기와 본문을 **따로** 판정하나 (폰에서 꾸미고 패드에서 재료 고쳐도 둘 다 남아야 한다)
//
// ⛔ 이 판이 초록불이 되기 «전»에는 `App.jsx` 의 `if (false)` 를 풀지 않는다.
import { strict as assert } from 'node:assert'

// ── 폰 흉내 ──────────────────────────────────────────────────────────────
const 칸 = new Map()
globalThis.localStorage = {
  getItem: (k) => (칸.has(k) ? 칸.get(k) : null),
  setItem: (k, v) => 칸.set(k, String(v)),
  removeItem: (k) => 칸.delete(k),
}

let 나쁨 = 0
const 잰다 = (좋나, 이름, 덧 = '') => {
  if (!좋나) 나쁨++
  console.log(`  ${좋나 ? '✅' : '⛔'} ${이름}${덧 ? ` — ${덧}` : ''}`)
}

// ── 폰 · 패드가 각각 들고 있는 것 ────────────────────────────────────────
//   ⭐ 「같은 사람의 기기 둘」이다. 폰이 한 발 앞서 있다(방금 담았고 방금 꾸몄다).
const 사진 = 'data:image/png;base64,' + 'A'.repeat(2000)

const 폰 = () => ({
  recipes: [
    // ⓐ 우리 기본 레시피 — 앱에 딸려 오는 것. ⛔동기화가 건드리면 안 된다
    { id: 'basic-kongguksu', title: '콩국수', icon: 'gr_100' },
    // ⓑ ⭐방금 담은 것 — 패드엔 «없다». 9/1 에 사라진 그 자리다
    { id: 'u-hangjeong', title: '항정살조림', savedAt: 1000, 고친때: 3000 },
    // ⓒ 폰에서 «꾸민» 것 — 패드엔 꾸미기 없이 있다
    { id: 'u-kimchi', title: '김치찌개', image: 사진, decor: [{ id: 'd1', key: 'sk_05' }], 고친때: 3000 },
  ],
  // ⓕ ⭐일기 속지 사진 — 🔢 실측: 클라우드엔 «[null, null]» 로 담긴다(cloud.js 사진털기).
  //    그게 그대로 덮이면 사진이 «빈 칸»이 된다. 단순 사진 칸과 달리 «값이 있어서» 덮어친다.
  diary: [{ id: 'd1', 속지: [사진, 사진], 고친때: 3000 }],
  shoppingList: [{ name: '두부' }, { name: '대파' }],
  pantry: [{ name: '달걀' }],
})

const 패드 = () => ({
  recipes: [
    // ⛔⛔ 기본 레시피가 «패드에선 옛 그림»이다 — 오늘 BASICS_VERSION 111 로 갈아끼운 그 자리다.
    //    보호가 없으면 이게 폰의 새 그림을 덮어 «어제 준 사진»이 사라진다.
    //    🧪 [2026-09-04] 처음엔 양쪽을 같은 값으로 놔서 «보호를 빼도 판이 안 죽었다» — 헛돌던 칸이었다.
    { id: 'basic-kongguksu', title: '콩국수', icon: 'gr_OLD', 고친때: 9999 },
    // ⓓ 패드에서 «재료를 고친» 것 — 꾸미기는 없다. 폰 것과 «칸이 다르다»
    { id: 'u-kimchi', title: '김치찌개', ingredients: [{ name: '김치', qty: '한 컵' }], 고친때: 4000 },
    // ⓔ 폰에서 지운 편이 패드엔 아직 남아 있다 (무덤이 없으면 되살아난다)
    { id: 'u-zombie', title: '지운 레시피', 고친때: 1000 },
  ],
  diary: [{ id: 'd1', 속지: [null, null], 고친때: 4000 }],
  shoppingList: [{ name: '우유' }],
  pantry: [],
})

// 폰이 'u-zombie' 를 지웠다는 표시(무덤)
const 폰무덤 = [{ id: 'u-zombie', 갈래: 'recipes', 지운때: 5000 }]

// ── 합치기를 부른다 ──────────────────────────────────────────────────────
//   ⛔ 아직 안 만들었다 → 여기서 죽는 것이 «맞다»(규칙 12 = 옛 값으로 진짜 걸리는지 먼저 본다).
let 합치기
try {
  ({ 합치기 } = await import('../src/syncMerge.js'))
} catch {
  console.log('\n⛔⛔ `src/syncMerge.js` 가 아직 없다 — **이 판이 먼저다.** 만들고 나서 다시 돌린다.')
  console.log('   📐 무엇을 만들지 = docs/폰패드-자동동기화-설계-2026-09-04.md §3\n')
  process.exit(1)
}

console.log('\n☁️🔀 폰↔패드 합치기 — 「받기는 지우지 않는다」\n')
const 나온것 = 합치기({ 내것: 폰(), 받은것: 패드(), 무덤: 폰무덤 })
const 찾기 = (id) => (나온것.recipes || []).find((r) => r.id === id)

// ① ⭐ 9/1 사고 자리 — 폰에만 있던 것이 살아남나
잰다(!!찾기('u-hangjeong'), '⭐ 폰에만 있던 「항정살조림」이 살아남는다 (9/1 사고 자리)',
  찾기('u-hangjeong') ? '있다' : '⛔사라졌다')
// ①-b ⭐⭐ 「합치기」인지 「덮기」인지 «개수»로 못 박는다
//    🧪 [2026-09-04] 처음엔 ① 만 재서, 통째로 덮기로 되돌려도 판이 «안 죽었다».
//       내 편이 뒤에 얹혀 우연히 살아남았기 때문이다 — 그건 설계가 맞아서가 아니다.
//    ⛔ 그래서 «양쪽 것이 다 있나»를 센다. 덮기면 반드시 개수가 모자란다.
const 편수 = (나온것.recipes || []).length
잰다(편수 === 3, '  ①-b 양쪽 것이 «다» 있다 (덮은 게 아니라 합쳤다)', 편수 + '편 (기본1 ＋ 항정살 ＋ 김치 = 3)')

// ② 지운 것이 되살아나지 않나
잰다(!찾기('u-zombie'), '폰에서 지운 편이 «되살아나지» 않는다 (무덤)',
  찾기('u-zombie') ? '⛔되살아났다' : '없다(맞다)')

// ③ 장보기·냉장고는 이름으로 합쳐진다 (통째로 덮이면 폰 것이 사라진다)
const 장 = (나온것.shoppingList || []).map((x) => x.name).sort()
잰다(장.includes('두부') && 장.includes('대파') && 장.includes('우유'),
  '장보기가 «합쳐진다» (양쪽 것이 다 남는다)', 장.join('·') || '비었다')
잰다((나온것.pantry || []).some((x) => x.name === '달걀'), '냉장고 재료가 안 사라진다')

// ④ 우리 기본 레시피는 안 건드린다
const 기본 = 찾기('basic-kongguksu')
잰다(!!기본 && 기본.icon === 'gr_100', '우리 기본 레시피는 «그대로»다 (그림이 안 되돌아간다)')

// ⑤ 사진이 안 사라진다 — 클라우드엔 안 올라가므로 폰 것을 되돌려야 한다
잰다(찾기('u-kimchi')?.image === 사진, '폰에 있던 «사진»이 안 사라진다',
  찾기('u-kimchi')?.image ? '있다' : '⛔빈 칸이 됐다')

// ⑤-b ⭐ 일기 속지 사진이 «빈 칸»으로 안 덮인다 (클라우드는 [null,null] 로 준다)
const 속지 = (나온것.diary || []).find((d) => d.id === 'd1')?.속지 || []
잰다(속지[0] === 사진 && 속지[1] === 사진, '  ⑤-b 일기 속지 사진이 안 사라진다',
  속지[0] ? '있다' : '⛔빈 칸이 됐다')

// ⑥ ⭐ 칸별 판정 — 폰에서 꾸미고 패드에서 재료를 고쳤다. 둘 다 남아야 한다
const 김치 = 찾기('u-kimchi')
잰다(!!김치?.decor?.length, '  ⑥-a 폰에서 «꾸민 것»이 남는다')
잰다(!!김치?.ingredients?.length, '  ⑥-b 패드에서 «고친 재료»도 남는다 (칸별 판정)')

console.log(나쁨 ? `\n⛔ ${나쁨}칸 실패 — ⛔이 판이 초록불이 되기 전엔 자동 받기를 켜지 않는다\n`
  : '\n✅ 받기가 «지우지» 않는다 — 폰에만 있던 것도, 사진도, 꾸민 것도 살아남는다\n')
process.exit(나쁨 ? 1 : 0)
