// 🎃 레시피 목록 맨 위 = 핼러윈(10/16~10/30)엔 통단호박, 그 밖엔 꽃게탕 (창업자 2026-10-16)
import { seedRecipes, 정렬값, 지금맨위, 맨위고정 } from '../src/data/seed.js'
let 죽음 = 0
const 재다 = (n, ok) => { console.log(`${ok ? '✅' : '⛔'} ${n}`); if (!ok) 죽음++ }
const 첫째 = (오늘, 목록) => [...목록].sort((a, b) => 정렬값(b, 오늘) - 정렬값(a, 오늘))[0]?.id
const 새폰 = seedRecipes.filter((r) => !r.from || r.from <= '2026-10-16')
재다('10/15 = 꽃게탕', 지금맨위('2026-10-15') === 맨위고정)
재다('10/16 = 통단호박', 지금맨위('2026-10-16') === 'basic-tong-danhobak-cream-soup')
재다('10/30 = 통단호박', 지금맨위('2026-10-30') === 'basic-tong-danhobak-cream-soup')
재다('10/31 = 꽃게탕', 지금맨위('2026-10-31') === 맨위고정)
재다('새 폰 10/16 목록 첫째 = 통단호박', 첫째('2026-10-16', 새폰) === 'basic-tong-danhobak-cream-soup')
// 이미 깔린 폰 — 꽃게탕 savedAt 이 2099(옛 고정석)로 저장돼 있다
const 옛폰 = 새폰.map((r) => r.id === 맨위고정 ? { ...r, savedAt: Date.parse('2099-01-01T00:00:00') } : r)
재다('옛 폰 10/16 첫째 = 통단호박(꽃게탕 2099 가 안 이긴다)', 첫째('2026-10-16', 옛폰) === 'basic-tong-danhobak-cream-soup')
재다('옛 폰 10/31 첫째 = 꽃게탕(저절로 돌아온다)', 첫째('2026-10-31', 옛폰) === 맨위고정)
console.log(죽음 ? `\n⛔ ${죽음}칸` : '\n✅ 명절 맨 위 — 전부 통과'); process.exit(죽음 ? 1 : 0)
