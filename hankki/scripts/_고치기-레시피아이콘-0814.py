# 📮 창업자 확정(2026-08-13 작업복기 45줄) — *"정확하게 분은 못재 대강얼추비슷하게 고쳐"*
#    ⛔ 문서엔 「바꿨다」고 적혀 있는데 **코드는 안 바뀌어 있었다.** id 는 그대로 둔다(weekly.js·저장값이 흔들린다).
제목바꿈 = [('10분 버섯밥', '간단 버섯밥'), ('7분 우삼겹 갈비탕', '간단 우삼겹 갈비탕')]

바뀜, 못찾음 = [], []
for 제목, 옛, 새, 왜 in 고칠것:
    # ⭐ 제목 바로 아래 6줄 안의 icon 만 본다 — 파일 전체에서 `icon: 'fe_66'` 을 바꾸면 딴 편까지 바뀐다
    m = re.search(rf"(title: '{re.escape(제목)}'[^\n]*\n(?:[^\n]*\n){{0,6}}?\s*icon: ')({re.escape(옛)})(')", s)
    if not m:
        못찾음.append(f'{제목} (지금 {옛} 이 아니거나 제목이 다르다)')
        continue
    s = s[:m.start(2)] + 새 + s[m.end(2):]
    바뀜.append(f'  {제목:16} {옛:10} → {새:8} {왜}')

for 옛, 새 in 제목바꿈:
    n = s.count(f"title: '{옛}'")
    if n != 1:
        못찾음.append(f'제목 「{옛}」 이 {n}군데 (1군데여야 한다)')
        continue
    s = s.replace(f"title: '{옛}'", f"title: '{새}'")
    바뀜.append(f'  제목  「{옛}」 → 「{새}」')

# 🔢 BASICS_VERSION ＋1 — ⛔이걸 안 올리면 **이미 깔린 폰은 안 고쳐진다**(규칙 18 ⓙ)
m = re.search(r'export const BASICS_VERSION = (\d+)', s)
새판 = int(m.group(1)) + 1
s = s[:m.start(1)] + str(새판) + s[m.end(1):]
s = s.replace(
    f'export const BASICS_VERSION = {새판} //',
    f"export const BASICS_VERSION = {새판} // v{새판}: 🍱 붙는 그림 전수조사 — 딴 요리 그림이 붙어 있던 17편 고침"
    f"(두부참치찌개→순두부·꽃게찜/갈치조림/고등어조림/연근조림→목살조림에서 벗어남·나시고랭→볶음밥·양념게장·순살찜닭 등)"
    f" ＋ 그림이 아예 없어 도형으로 나가던 4편(꽃게탕·전찌개·대하소금구이·나물비빔밥)"
    f" ＋ 제목 「10분 버섯밥」→「간단 버섯밥」·「7분 우삼겹 갈비탕」→「간단 우삼겹 갈비탕」(2026-08-13 확정인데 코드에 안 들어와 있었다)."
    f" ⛔이 번호를 올려야 이미 깔린 폰이 고쳐진다 //", 1)

p.write_text(s)
print(f'✅ {len(바뀜)}군데 고침 · BASICS_VERSION → v{새판}\n')
print('\n'.join(바뀜))
if 못찾음:
    print(f'\n⛔ 못 찾은 것 {len(못찾음)}개 — 손으로 확인할 것')
    for x in 못찾음:
        print(f'   {x}')
