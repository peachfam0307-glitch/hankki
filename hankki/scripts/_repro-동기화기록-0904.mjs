#!/usr/bin/env node
// 📜 동기화 «기록» 재현판 — 2026-09-04
//
// 📮 창업자 = *"동기화 기록 만들어줘"*
//
// ⭐⭐ **이 판이 지키는 한 줄 = 「무엇이 언제 오갔는지 «반드시» 남는다」.**
//    🚨 2026-09-01 에 레시피가 사라졌을 때 **기록이 0이었다.** 그래서 「어느 길로 덮였나」를
//       끝내 확정 못 했고, 원인을 모르니 고칠 수도 없어 **자동 받기를 통째로 잠가 두었다.**
//    📌 기록이 있었으면 그날 밤에 끝났을 일이다. 그게 이 파일이 있는 이유다.
//
// 🧪 재는 것 여덟 (설계 관문에서 세 각도로 나온 것 그대로)
//   ① 오간 것을 남긴다(받음·합침·안 지움 개수) · ② 기기가 같이 남는다
//   ③ ⭐**실패도 «왜»까지 남긴다** — 성공만 남기면 정작 사고 난 날이 빈다
//   ④ ⭐**기록이 실패해도 «동기화를 멈추지 않는다»** — 기록 때문에 본 일이 죽으면 안 된다
//   ⑤ 50줄만 남기고 오래된 것부터 지운다 · ⑥ 최근 것이 «맨 앞»에 온다
//   ⑦ ⛔**레시피 제목·본문을 «안» 남긴다** — 개수만. 제목은 곧 개인정보다
//   ⑧ ⛔작은 서랍(localStorage)에 «안» 쓴다 — 창업자 폰이 이미 91%였다(9/2 사고)

let 나쁨 = 0
const 잰다 = (좋나, 이름, 덧 = '') => {
  if (!좋나) 나쁨++
  console.log(`  ${좋나 ? '✅' : '⛔'} ${이름}${덧 ? ` — ${덧}` : ''}`)
}

// ── 큰 창고 흉내 (되돌리기 판과 «같은 얼개») ─────────────────────────────
const 창고 = new Map()
const 가짜창고 = {
  async 넣기 (열쇠, 값) { 창고.set(열쇠, JSON.parse(JSON.stringify(값))); return true },
  async 꺼내기 (열쇠) { const v = 창고.get(열쇠); return v === undefined ? null : JSON.parse(JSON.stringify(v)) },
  async 지우기 (열쇠) { 창고.delete(열쇠) },
  async 열쇠들 () { return [...창고.keys()] },
}
const 터지는창고 = { ...가짜창고, async 넣기 () { throw new Error('창고 터짐') } }

let 서랍쓴횟수 = 0
const 칸 = new Map()
globalThis.localStorage = {
  getItem: (k) => (칸.has(k) ? 칸.get(k) : null),
  setItem: (k, v) => { 서랍쓴횟수++; 칸.set(k, String(v)) },
  removeItem: (k) => 칸.delete(k),
}

let 모듈
try { 모듈 = await import('../src/syncLog.js') } catch {
  console.log('\n⛔⛔ `src/syncLog.js` 가 아직 없다 — **이 판이 먼저다.**')
  console.log('   📐 무엇을 만들지 = docs/폰패드-자동동기화-설계-2026-09-04.md §3-ⓑ2\n')
  process.exit(1)
}
const { 적기, 읽기, 지우기, 한줄로, _창고물리기 } = 모듈
_창고물리기(가짜창고)

console.log('\n📜 동기화 기록 — 「무엇이 언제 오갔는지 반드시 남는다」\n')

// ① 오간 것을 남긴다
await 적기({ 한일: '받음', 기기: '패드', 받은것: 3, 합친것: 2, 지운것: 0 })
const 줄들1 = await 읽기()
잰다(줄들1.length === 1 && 줄들1[0].한일 === '받음' && 줄들1[0].받은것 === 3,
  '① 오간 것을 남긴다 (받음·합침·지움 개수)', 줄들1[0] ? `${줄들1[0].한일} ${줄들1[0].받은것}편` : '비었다')

// ② 기기 · 시각이 같이 남는다
잰다(줄들1[0]?.기기 === '패드' && !!줄들1[0]?.때, '② «어느 기기·언제»가 같이 남는다',
  줄들1[0] ? `${줄들1[0].기기} · ${줄들1[0].때?.slice(0, 16)}` : '')

// ③ ⭐ 실패도 «왜»까지 남는다 — 성공만 남기면 정작 사고 난 날이 빈다
await 적기({ 한일: '못받음', 왜: '양쪽이바뀜' })
const 줄들2 = await 읽기()
잰다(줄들2[0]?.한일 === '못받음' && 줄들2[0]?.왜 === '양쪽이바뀜',
  '③ ⭐ 실패도 «왜»까지 남는다', 줄들2[0]?.왜 || '⛔안 남았다')

// ⑥ 최근 것이 맨 앞
잰다(줄들2[0]?.한일 === '못받음' && 줄들2[1]?.한일 === '받음', '⑥ 최근 것이 «맨 앞»에 온다')

// ⑦ ⛔ 제목·본문은 안 남긴다 (개수만)
await 적기({ 한일: '받음', 받은것: 1, title: '항정살조림', 몰래: '내 일기 본문' })
const 글 = JSON.stringify(await 읽기())
잰다(!글.includes('항정살조림') && !글.includes('내 일기 본문'),
  '⑦ ⛔레시피 제목·본문을 «안» 남긴다 (개수만)',
  글.includes('항정살조림') ? '⛔제목이 새어 나갔다' : '개수만')

// ⑧ ⛔ 작은 서랍에 안 쓴다
잰다(서랍쓴횟수 === 0, '⑧ ⛔작은 서랍(localStorage)에 «안» 쓴다', `서랍 쓴 횟수 ${서랍쓴횟수}`)

// ⑤ 50줄 제한
for (let i = 0; i < 60; i++) await 적기({ 한일: '받음', 받은것: i })
const 줄들3 = await 읽기()
잰다(줄들3.length === 50, '⑤ 50줄만 남기고 오래된 것부터 지운다', `${줄들3.length}줄`)

// ④ ⭐ 기록이 실패해도 «던지지» 않는다 — 기록 때문에 동기화가 멈추면 안 된다
_창고물리기(터지는창고)
let 던졌나 = false
try { await 적기({ 한일: '받음', 받은것: 1 }) } catch { 던졌나 = true }
잰다(!던졌나, '④ ⭐ 기록이 실패해도 «동기화를 멈추지 않는다» (안 던진다)',
  던졌나 ? '⛔던졌다' : '조용히 넘어갔다')
_창고물리기(가짜창고)

// 지우기 (설정에서 「기록 비우기」)
await 지우기()
잰다((await 읽기()).length === 0, '  ＋ 기록을 비울 수 있다')

// ══ ⑨⑩ 🔍 [2026-09-04 신설] «막힌 이유»도 남고, 그게 «사람 말»로 읽히나 ══
//   📮 창업자 = *"기록 안보여 저절로 맞춘적이 없데"*
//   ⛔⛔ 그때 기록은 «성공»만 적고 있었다. 그래서 화면이 늘 비어 있었고,
//      「안 해봤다」인지 「하다 말았다」인지 아무도 몰랐다 — 9/1 에 원인을 못 찾은 그 구멍 그대로다.
//   ⭐ 그렇다고 «전부» 적으면 안 된다 — 앱을 켤 때마다 도는 길이라 늘 나는 이유로 50줄이 찬다.
//      그 잣대(`적을이유`)는 `cloud.js` 에 있다. 여기서는 «남은 것이 읽히나»를 잰다.
await 지우기()
await 적기({ 한일: '못올림', 왜: '아직안받았다' })
await 적기({ 한일: '못올림', 왜: '다른기기', 기기: 'abc123' })
const 막힌줄 = await 읽기()
잰다(막힌줄.length === 2, '⑨ 🔍 «막힌 이유»가 기록에 남는다', `${막힌줄.length}줄`)

const 말1 = 한줄로(막힌줄[1])
const 말2 = 한줄로(막힌줄[0])
잰다(/한 번도 안 가져왔/.test(말1), '⑩-a 「아직안받았다」가 사람 말로 읽힌다', 말1)
잰다(/다른 기기가 마지막/.test(말2), '⑩-b 「다른기기」가 사람 말로 읽힌다', 말2)
잰다(!말2.includes('abc123'), '⑩-c ⛔기기 이름(무작위 글자)은 «안» 찍는다', 말2)
await 지우기()


console.log(나쁨 ? `\n⛔ ${나쁨}칸 실패 — 기록이 없으면 다음에 또 «원인을 못 찾는다»\n`
  : '\n✅ 무엇이 언제 오갔는지 남는다 — 실패도 · 개수만 · 큰 창고에\n')
process.exit(나쁨 ? 1 : 0)
