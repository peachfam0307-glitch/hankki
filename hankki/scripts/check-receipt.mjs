// 📮📮 2026-08-15 창업자가 코스트코 영수증을 찍어 보내며 *"이 영수증 인식->새우 하나 인식됨"*
//    17품목 중 «하나»였다. 그리고 짚어줬다 —
//    *"참깨, 김, 가리비도 식재료인대 인식안됨. 원두, 해물파전, 해초샐러드, 찜닭도 음식인데 인식안됨"*
//
// ⭐⭐ 뿌리 = **어떤 영수증은 「이름 줄」과 「가격 줄」이 «따로»다**(코스트코 등).
//      청화볶음참깨                      ← 이름 (가격이 «없다»)
//      676498  1x  18,990  18,990 T      ← 바코드·수량·금액 (한글 이름이 «없다»)
//    우리는 「가격이 붙은 줄」만 후보로 봤으므로 **이름 줄이 통째로 버려졌다.**
//
// 🔢 결정적 증거 = 유일하게 걸린 「KS새우21-25 908G」는 «908» 이라는 숫자 때문에
//    «가격 줄로 오해받아» 통과한 것이다. **기능이 판단한 게 아니라 우연이었다.**
//    📌 그래서 「하나는 되니까 되긴 하는구나」로 넘기면 안 됐다.
//
// ⛔ 이 검사가 없으면 이 사고는 **조용히 되돌아온다** — 빌드도 스모크도 통과하고,
//    창업자가 마트에 다녀와 영수증을 찍어봐야만 드러난다.
import { extractReceiptItems } from '../src/receipt.js'

let bad = 0
const 검사 = (이름, 글자, 있어야, 없어야 = []) => {
  const 나온것 = extractReceiptItems(글자)
  const 빠짐 = 있어야.filter((w) => !나온것.some((x) => x.includes(w)))
  const 섞임 = 없어야.filter((w) => 나온것.some((x) => x.includes(w)))
  if (빠짐.length || 섞임.length) {
    bad++
    console.log(`  ⛔ ${이름}`)
    if (빠짐.length) console.log(`     못 뽑음: ${빠짐.join(' · ')}`)
    if (섞임.length) console.log(`     안 될 게 들어옴: ${섞임.join(' · ')}`)
    console.log(`     나온 것(${나온것.length}): ${나온것.join(' · ') || '(없음)'}`)
  } else {
    console.log(`  ✅ ${이름} — ${나온것.length}개`)
  }
}

