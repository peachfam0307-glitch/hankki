//    ⭐ 낱장 하나만 보면 못 잡는다. **120장을 다 겹친 판**을 만들어야 자리들이 한눈에 보인다.

const 파이썬 = `
import numpy as np
from PIL import Image, ImageDraw

W, H = 1080, 1920
FPS = 60
초 = 2.0
장수 = int(초 * FPS)          # 120
낼곳 = ${JSON.stringify(OUT)}
반짝들 = ${JSON.stringify(반짝들)}

# ✨✨ **「샤랄라」 층** (📮 창업자 = *"약간 샤랄라느낌있잖아 ㅋㅋ"*)
#    ⭐ 큰 별 열한 개만 있으면 «또박또박»하다 — 하나 켜지고 하나 꺼지는 게 세어진다.
#       샤랄라는 «세어지지 않는 것»이다. 그래서 작은 가루를 잔뜩, 짧게, 겹쳐 뿌린다.
#    ⛔ 아래 CTA 띠(y 1590~1840)엔 안 뿌린다 — 「Play스토어 다운로드」는 또렷해야 한다.
#    📌 자리는 «씨앗 고정» 난수다 — 다시 돌려도 같은 그림이 나와야 고칠 수 있다.
난 = np.random.RandomState(20260903)
가루들 = []
for _ in range(78):
    x = int(난.uniform(20, 1060))
    y = int(난.uniform(150, 1560))
    if 1590 <= y <= 1840:
        continue
    가루들.append((x, y,
                   int(난.uniform(22, 58)),        # 지름
                   float(난.uniform(0.0, 1.52)),   # 시작
                   float(난.uniform(0.22, 0.42)),  # 사는 길이
                   float(난.uniform(-16, 16))))    # 떠오르는 정도(위아래로 살짝)

# ── 반짝임 한 개를 «큰 타일 한 장»으로 미리 그려둔다 (장마다 줄여 쓴다)
T = 256
c = (T - 1) / 2.0
yy, xx = np.mgrid[0:T, 0:T].astype(float)
dx, dy = xx - c, yy - c
r = np.hypot(dx, dy)

# ⛔⛔⛔ **「빛나는 흰 별」은 이 시안에서 «안 보인다»** (2026-09-03 · 세 번 그려보고 알았다)
#    🔢 실측 = 반짝임을 놓을 자리들의 바탕 밝기가 **187~198 / 255**. 이미 밝다.
#       흰빛이 더할 수 있는 건 «60 남짓»뿐 — 밝은 것 위의 밝은 것은 없는 것과 같다.
#    ⛔ 후광을 깔아 봐도(살구빛 alpha 112) 「따뜻해졌다」 정도였지 «반짝»이 아니었다.
# ✅ 답 = **시안이 「선으로 그린 그림」이니 반짝임도 «테두리 있는 별»로 그린다.**
#    ⭐ 시안에 이미 있는 노란 별(≈742,480)이 정확히 그 문법이다 — 갈색 테두리 + 크림 속.
#       테두리는 «어둡다» → 바탕이 아무리 밝아도 읽힌다. 그리고 그림과 «같은 화풍»이 된다.
def 별점들(cx, cy, 큰, 작은, 각도):
    # 4각 반짝별 = 바깥 꼭짓점 4 + 사이 오목점 4 (작은/큰 이 작을수록 뾰족해진다)
    점 = []
    for i in range(8):
        th = np.radians(각도 + i * 45.0)
        R = 큰 if i % 2 == 0 else 작은
        점.append((cx + R * np.cos(th), cy + R * np.sin(th)))
    return 점

SS = 4                                   # 4배로 크게 그린 뒤 줄여야 테두리가 안 삐뚤다
TS = T * SS
큰별 = Image.new('RGBA', (TS, TS), (0, 0, 0, 0))
붓 = ImageDraw.Draw(큰별)
c2 = (TS - 1) / 2.0
바깥R = TS * 0.47
붓.polygon(별점들(c2, c2, 바깥R, 바깥R * 0.20, -90), fill=(138, 92, 58, 255))          # 테두리(갈색)
붓.polygon(별점들(c2, c2, 바깥R * 0.87, 바깥R * 0.155, -90), fill=(255, 250, 232, 255))  # 속(크림흰)
붓.polygon(별점들(c2, c2, 바깥R * 0.40, 바깥R * 0.09, -90), fill=(255, 236, 176, 255))   # 한가운데 살짝 노랑
타일이미지 = 큰별.resize((T, T), Image.LANCZOS)

# 별 «뒤»에 아주 옅은 살구빛 후광을 한 겹 — 별이 앉을 자리를 만들어 준다(이것만으론 부족했다)
#    ⛔ 회색·검정 후광은 안 된다. 파스텔 그림이 «때 탄 것»처럼 보인다.
후광밝 = np.exp(-(r / (T * 0.30)) ** 2)
후광 = np.zeros((T, T, 4), dtype=np.uint8)
후광[..., 0] = 255; 후광[..., 1] = 186; 후광[..., 2] = 108
후광[..., 3] = (후광밝 * 78).astype(np.uint8)
후광이미지 = Image.fromarray(후광, 'RGBA')

빈판 = Image.new('RGBA', (W, H), (0, 0, 0, 0))
살아있던최대 = 0
for f in range(장수):
    t = f / FPS
    장 = 빈판.copy()
    산것 = 0
    for (x, y, 지름, t0, 길이) in 반짝들:
        u = (t - t0) / 길이
        if u <= 0.0 or u >= 1.0:
            continue
        산것 += 1
        # 커졌다 작아지고 · 밝아졌다 어두워진다 (한 번에 사라지지 않게 사인 곡선)
        기세 = np.sin(np.pi * u)
        크기 = max(6, int(지름 * (0.42 + 0.58 * 기세)))
        투명 = 기세 ** 0.75
        비틀 = 26.0 * u                      # 조금씩 돌아 «살아 있게»
        # 후광 먼저 (별보다 1.35배 넓게) → 그 위에 별
        후크기 = int(크기 * 1.35)
        후 = 후광이미지.resize((후크기, 후크기), Image.LANCZOS)
        h = np.asarray(후).astype(float); h[..., 3] *= 투명
        장.alpha_composite(Image.fromarray(np.clip(h, 0, 255).astype(np.uint8), 'RGBA'),
                           (int(x - 후크기 / 2), int(y - 후크기 / 2)))
        조각 = 타일이미지.resize((크기, 크기), Image.LANCZOS).rotate(비틀, resample=Image.BICUBIC)
        a = np.asarray(조각).astype(float)
        a[..., 3] *= 투명
        조각 = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')
        장.alpha_composite(조각, (int(x - 크기 / 2), int(y - 크기 / 2)))
    # ── 샤랄라 가루 (작고 빠르게 · 후광 없이 별만)
    가루산것 = 0
    for (x, y, 지름, t0, 길이, 뜸) in 가루들:
        u = (t - t0) / 길이
        if u <= 0.0 or u >= 1.0:
            continue
        가루산것 += 1
        기세 = np.sin(np.pi * u)
        크기 = max(5, int(지름 * (0.35 + 0.65 * 기세)))
        조각 = 타일이미지.resize((크기, 크기), Image.LANCZOS).rotate(52.0 * u, resample=Image.BICUBIC)
        a = np.asarray(조각).astype(float)
        a[..., 3] *= 기세 ** 0.6
        조각 = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')
        장.alpha_composite(조각, (int(x - 크기 / 2), int(y - 크기 / 2 + 뜸 * u)))
    살아있던최대 = max(살아있던최대, 산것 + 가루산것)
    장.save(낼곳 + '/%03d.png' % f)

첫 = np.asarray(Image.open(낼곳 + '/000.png'))[..., 3].max()
끝 = np.asarray(Image.open(낼곳 + '/%03d.png' % (장수 - 1)))[..., 3].max()
print('큰 별', len(반짝들), '개 · 샤랄라 가루', len(가루들), '개')
print('장수', 장수, '· 한때 같이 켜진 최대', 살아있던최대, '개')
print('첫 장 알파 최대', 첫, '· 마지막 장 알파 최대', 끝, '→', '✅완전 투명(이어짐 안 보임)' if 첫 == 0 and 끝 == 0 else '⛔ 끝이 안 비었다 — 릴스가 돌 때 튄다')
`

