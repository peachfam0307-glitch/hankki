#!/usr/bin/env python3
# 📸 인스타 캡처 → 「공유 자리에 빨간 동그라미」 판 만들기 (2026-08-28)
#
# 📮 창업자 = *"고쳤어 **이걸로 스토어 스샷도 갈아줘.**"* (인스타 게시물의 식용유 → 올리브유)
#
# ⭐⭐ 왜 «합성»인가 — 원본 캡처 둘이 서로 반쪽씩만 쓸 만하다
#    · `2-인스타-깨끗`   = 본문(재료·만드는 법)이 다 보인다. ⛔그런데 도구 띠가 없다
#    · `1-인스타-도구띠` = 도구 띠(공유 단추)가 있다. ⛔그런데 **캡처 썸네일 작은 상자가 만드는 법을 가린다**
#      📮 창업자가 눈으로 잡았다 = *"만드는법을 캡쳐된 작은 상자가 가려."* (실물로 확인 = 다섯 걸음이 가려짐)
#    → 그래서 **깨끗판 위에 «도구 띠 부분만»** 오려 붙인다. 작은 상자는 그 띠보다 위라 안 딸려온다.
#
# ⛔ 이 판이 저장소에 «없어서» 오늘 다시 만들었다 — 지난번엔 scratchpad 에서 만들어 세션과 함께 날아갔다.
#    📌 절대원칙 30 = **판 생성기는 저장소에 둔다.** 결과물(PNG)만 저장소 밖에 둘 수도 있지만
#       이건 스토어에 나갈 재료라 저장소 안에 같이 둔다.
#
# 🔒 상단바는 «가림 판»을 쓴다 — 창업자 지시 *"내 개인정보랑 친구목록은 다 지워줘야해"*
#
# 실행: cd /home/user/hankki/hankki && python3 scripts/_판-인스타공유동그라미-0828.py
import sys
from pathlib import Path

from PIL import Image, ImageDraw

원본 = Path(__file__).resolve().parent.parent / 'design/promo/가져오기안내-원본캡처-2508'

깨끗 = 원본 / '2-인스타-깨끗-가림.png'
도구띠 = 원본 / '1-인스타-도구띠-가림.png'
낼것 = 원본 / '인스타-공유동그라미.png'
# ⭐ 동그라미 «없는» 판도 같이 낸다 — 릴스는 동그라미를 «맥박치게» 자기가 그린다(구운 그림이면 못 움직인다)
낼것_민판 = 원본 / '인스타-도구띠-합성.png'

# 📐 실측값(2026-08-28) — «도구띠 원본»(1080×2340) 안에서의 자리
띠_위, 띠_아래 = 2118, 2285   # 오려 붙일 도구 띠의 세로 범위
공유_x, 공유_y = 720, 2196     # 도구 띠 안 「공유」 단추 한가운데
반지름 = 92
선굵기 = 14

for p in (깨끗, 도구띠):
    if not p.exists():
        sys.exit(f'⛔ 재료가 없다 → {p}')

바탕 = Image.open(깨끗).convert('RGB')
띠원본 = Image.open(도구띠).convert('RGB')

if 바탕.width != 띠원본.width:
    sys.exit(f'⛔ 두 캡처 폭이 다르다 → 깨끗 {바탕.width} · 도구띠 {띠원본.width}')

# ✂️ 도구 띠를 오려서 «바탕 맨 아래»에 얹는다
#    ⛔ 「원본과 같은 y」에 붙이면 안 된다 — 깨끗판은 인사이트 줄 202px 을 덜어내 «더 짧다».
#       도구 띠는 화면 맨 아래에 뜨는 오버레이라 어느 판에서든 «바닥»에 있어야 맞다.
띠높이 = 띠_아래 - 띠_위
띠자리 = 바탕.height - 띠높이
바탕.paste(띠원본.crop((0, 띠_위, 바탕.width, 띠_아래)), (0, 띠자리))

# ⭕ 동그라미도 그만큼 따라 올라간다 — 손으로 옮겨 적지 않고 «계산»한다
cx = 공유_x
cy = 띠자리 + (공유_y - 띠_위)
r = 반지름
바탕.save(낼것_민판)
print(f'✅ {낼것_민판.name} · {바탕.size[0]}×{바탕.size[1]} (동그라미 없음 · 릴스용)')

# ⭕ 「여기를 누른다」 — 창업자 확정 = 글자 설명 대신 (빨간 동그라미)
동그라미판 = 바탕.copy()
d = ImageDraw.Draw(동그라미판)
d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=(214, 60, 60), width=선굵기)

동그라미판.save(낼것)
print(f'✅ {낼것.name} · {바탕.size[0]}×{바탕.size[1]} (스토어용)')

# 📮 릴스는 동그라미를 «맥박치게» 자기가 그린다 → 좌표를 «넘겨준다».
#    ⛔ 손으로 옮겨 적으면 다음에 원본이 바뀔 때 조용히 어긋난다(오늘 스토어 판이 그랬다).
import json

(원본 / '인스타-공유자리.json').write_text(
    json.dumps({'x': cx, 'y': cy, 'r': r, '판높이': 바탕.height}, ensure_ascii=False),
    encoding='utf-8',
)
print(f'   공유 자리 → x{cx} y{cy} r{r} (판 높이 {바탕.height})')

# 🔒 스스로 검사 — 붙인 띠가 진짜 들어갔나(도구 띠는 회색이라 바탕 흰색과 밝기가 다르다)
import numpy as np

a = np.asarray(바탕.convert('L'))
띠평균 = float(a[띠자리:띠자리 + 띠높이].mean())
바깥평균 = float(a[띠자리 - 120:띠자리 - 20].mean())
print(f'   도구 띠 밝기 {띠평균:.1f} ↔ 바로 위 {바깥평균:.1f}')
if abs(띠평균 - 바깥평균) < 4:
    sys.exit('⛔ 도구 띠가 안 붙은 것 같다 — 밝기 차이가 없다')

# 🔒 빨간 동그라미가 그려졌나
rgb = np.asarray(동그라미판)
칸 = rgb[cy - r - 20:cy + r + 20, cx - r - 20:cx + r + 20].astype(int)
빨강 = ((칸[:, :, 0] > 150) & (칸[:, :, 1] < 110) & (칸[:, :, 2] < 110)).sum()
print(f'   빨간 획 {빨강}px')
if 빨강 < 2000:
    sys.exit('⛔ 빨간 동그라미가 안 보인다')
