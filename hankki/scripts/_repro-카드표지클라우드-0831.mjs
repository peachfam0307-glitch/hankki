// 🧪 **진짜 JPEG 머리말을 만든다** — 세로를 읽어내는 코드를 시험하는 판이라 «모양이 맞아야» 한다.
//   FFD8(시작) → FFE0(APP0) → FFC0(SOF0 · 여기 세로·가로가 있다) → 채움 → FFD9(끝)
function 가짜JPEG (가로, 세로, 채움바이트 = 0) {
  const 머리 = [0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0, 1, 1, 0, 0, 1, 0, 1, 0, 0]
  const sof = [0xff, 0xc0, 0x00, 0x11, 0x08, (세로 >> 8) & 255, 세로 & 255, (가로 >> 8) & 255, 가로 & 255,
    3, 1, 0x22, 0, 2, 0x11, 1, 3, 0x11, 1]
  const 몸 = Buffer.alloc(채움바이트, 0x7f)
  const 끝 = [0xff, 0xd9]
  const buf = Buffer.concat([Buffer.from(머리), Buffer.from(sof), 몸, Buffer.from(끝)])
  return 'data:image/jpeg;base64,' + buf.toString('base64')
}

