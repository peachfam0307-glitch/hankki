// 매장 주소 줄 — "서울시 강남구 …", "역삼로 123" 같은 건 품목이 아니다.
// (대구·양구 같은 식품/지명 오탐을 막으려 '시+구' 조합이나 '로/길+숫자'만 주소로 본다)
const ADDR = /특별시|광역시|[가-힣]{2,}시\s+[가-힣]{2,}[구군]|[가-힣]{2,}[로길]\s?\d/

// 가격/수량처럼 보이는 숫자가 줄에 있는지 (영수증 품목 줄의 특징)
function hasPrice(line) {
  return /\d[\d,]{2,}/.test(line) || /\d+\s*원/.test(line)
}

// 📮📮 2026-08-15 창업자 *"이 영수증 인식->새우 하나 인식됨"* — 17품목 중 «하나».
// ⭐⭐ 원인 = **어떤 영수증은 「이름 줄」과 「가격 줄」이 따로다**(코스트코 등).
//      KS종이타월                      ← 이름 (가격이 «없다»)
//      1768085  1x  26,990  26,990 T   ← 바코드·수량·금액 (한글 이름이 «없다»)
//    우리는 「가격이 붙은 줄」만 후보로 봤으므로 **이름 줄이 통째로 버려졌다.**
// 🔢 결정적 증거 = 유일하게 걸린 「KS새우21-25 908G」는 «908» 이라는 숫자 때문에
//    가격 줄로 «오해받아» 통과한 것이다. 기능이 판단한 게 아니라 우연이었다.
// ✅ 그래서 「다음 줄이 가격 줄이면 이 줄은 이름이다」를 더한다.
//    ⛔ 「한글이 거의 없다」를 같이 본다 — 안 그러면 품목 줄끼리 물린다.
function isPriceOnlyLine(s) {
  if (!s) return false
  const hangul = (s.match(/[가-힣]/g) || []).length
  return hangul <= 1 && /\d{1,3}(?:,\d{3})+/.test(s)
}

// 줄에서 품목 이름만 남긴다 — 바코드·수량·단가·금액·기호를 걷어낸다.
function cleanItemName(line) {
  let s = ` ${line} `
  s = s.replace(/[₩*#]/g, ' ')
  s = s.replace(/\d{8,}/g, ' ') // 바코드
  s = s.replace(/[xX]\s*\d+/g, ' ') // 수량 배수 "x9"
  s = s.replace(/\d+\s*[xX]\b/g, ' ') // "9x"
  s = s.replace(/\d[\d,]*\s*원/g, ' ') // "2,980원"
  // 수량+단위 — 한글 단위(개·입·봉…)는 JS \b 가 안 걸리므로 경계 없이 제거
  s = s.replace(/\d+\s*(kg|g|ml|l|리터|봉지|봉|팩|입|매|병|캔|줄|장|포|구|호|인분|마리|손|단|알|쪽|개|말|미)/gi, ' ')
  s = s.replace(/[\d,]{3,}/g, ' ') // 남은 가격 "12,000" / "2980"
  s = s.replace(/[^가-힣A-Za-z%\s]/g, ' ') // 나머지 기호·낱숫자 제거
  s = s.replace(/(^|\s)[a-zA-Z](\s|$)/g, ' ') // 홀로 남은 라틴 한 글자(x 등)
  s = s.replace(/\s{2,}/g, ' ').trim()
  return s
}

// 한 글자쯤 잘못 읽힌 품목을 아는 식재료로 되돌린다 ("고주장"→"고추장", "달갈"→"달걀").
// 너무 짧은 단어는 오탐이 많아 3~6자만, 편집거리 1 이내만 스냅한다.
const SNAPPABLE = FOOD_WORDS.filter((w) => w.length >= 3)
function snapToFoodWord(tok) {
  if (tok.length < 3 || tok.length > 6) return null
  for (const w of SNAPPABLE) {
    if (Math.abs(w.length - tok.length) > 1) continue
    if (within1(tok, w)) return w
  }
  return null
}

export function extractReceiptItems(text) {
  const lines = String(text).split('\n').map((s) => s.trim()).filter(Boolean)
  const found = []
  const seen = new Set()
  const add = (name) => {
    const nm = name.trim()
    if (!nm || seen.has(nm)) return
    seen.add(nm)
    found.push(nm)
  }

  // 모바일 영수증은 헤더를 "합 계 · 면 세 물 품"처럼 한 글자씩 띄운다 —
  // 띄어쓰기를 지운 문자열로도 걸러야 SKIP/NONFOOD 정규식이 먹는다.
  const isSkippable = (s) => {
    const compact = s.replace(/\s+/g, '')
    return SKIP.test(compact) || NONFOOD.test(compact) || ADDR.test(s)
  }

  // 한 줄(품목명 후보)에서 식재료를 뽑아 담는다. 담았으면 true.
  // knownOnly = 「아는 식재료 낱말이 또렷이 있을 때만」 담는다(모르는 이름은 후보로도 안 올린다).
  //   → 아래 D) 갈래가 쓴다. 관문을 안 거친 줄이라 아무거나 담으면 확인 화면이 지저분해진다.
  const takeFrom = (raw, knownOnly) => {
    if (isSkippable(raw)) return false
    // 초고가 품목은 식재료가 아니다(가전 등) — 마트 식품은 개당 10만원을 넘지 않는다.
    // 쉼표로 끊은 '금액'만 본다(바코드 같은 긴 숫자는 가격이 아니므로 제외).
    const prices = (raw.match(/\d{1,3}(?:,\d{3})+/g) || []).map((n) => parseInt(n.replace(/,/g, ''), 10))
    if (prices.some((p) => p >= 100000)) return false
    // 1) 아는 식재료 단어가 있으면 대표 단어로 담는다(레시피 매칭에 유리).
    // ⭐⭐ 한 글자 낱말(김·무·굴·떡·게·콩·쌀·빵·깨·감·배·꿀)은 **뒤만 본다.**
    //    ⛔ 예전엔 앞뒤 둘 다 한글이 아니어야 걸렸는데, 상품명은 낱말을 이어 붙이므로
    //       「구운김밥**김**33GX7」의 「김」은 «앞»이 한글이라 영영 안 걸렸다.
    //       📮 창업자가 콕 짚은 그 「김」이다(*"참깨, 김, 가리비도 식재료인대 인식안됨"*).
    //    ✅ 「뒤가 한글이 아니다」 = 그 낱말로 «끝난다» = 그게 품목의 정체다.
    //       가래**떡** · 생**굴** · 강낭**콩** · 곶**감** · 참**게** 가 전부 이 규칙으로 살아난다.
    //    ⛔ 뒤가 한글이면 여전히 안 걸린다 — 「**김**치」·「**김**밥」·「**감**자」·「**배**추」·「**떡**볶이」처럼
    //       **다른 낱말의 첫 글자**인 경우다(그것들은 제 이름으로 사전에 따로 들어 있다).
    const matches = FOOD_WORDS.filter((w) => {
      if (w.length === 1) {
        // ⛔ 앞이 «숫자»면 수량 표현이다 — 「2배 적립」의 「배」를 과일로 보면 안 된다.
        if (ONECHAR_STRICT.has(w)) return new RegExp(`(^|[^가-힣])${w}([^가-힣]|$)`).test(raw)
        return new RegExp(`(^|[^0-9])${w}([^가-힣]|$)`).test(raw)
      }
      return raw.includes(w)
    })
    if (matches.length) {
      const claimed = []
      for (const w of matches.sort((a, b) => b.length - a.length)) {
        const i = raw.indexOf(w)
        if (i < 0) continue
        if (claimed.some(([s, e]) => i < e && i + w.length > s)) continue
        claimed.push([i, i + w.length])
        add(w)
      }
      return true
    }
    if (knownOnly) return false
    // 2) 아는 단어가 없어도 이름을 정리해 후보로 올린다.
    const name = cleanItemName(raw)
    // 한 글자 오독이면 아는 식재료로 되돌려 대표 단어로 담는다("고주장"→"고추장").
    const snap = name.split(' ').map(snapToFoodWord).find(Boolean)
    if (snap) { add(snap); return true }
    const hangul = (name.match(/[가-힣]/g) || []).length
    if (hangul >= 2 && name.length <= 16) { add(name); return true }
    return false
  }

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    if (isSkippable(line)) continue
    // A) 번호로 시작하는 품목 줄("01* 공심채", "1.삼겹살")은 가격이 다음 줄(바코드)에
    //    있어도 이름만으로 담는다. 구분자(*.))나 공백이 있어야 하므로 순수 바코드 줄
    //    ("2507281079179…")은 걸리지 않는다.
    const numbered = line.match(/^\d{1,2}(?:\s*[*.)]+|\s+)\s*(.+)/)
    if (numbered) { takeFrom(numbered[1]); continue }
    // B) 가격이 붙은 한글 품목 줄.
    if (hasPrice(line)) { takeFrom(line); continue }
    // C) ⭐ 가격이 «없어도» 「바코드·수량·금액」 줄과 **맞닿아 있으면** 이 줄이 품목 이름이다.
    //    (2026-08-15 창업자 영수증 — 17품목 중 하나만 걸리던 뿌리)
    //    ⭐⭐ **앞 줄도 본다** — 두 줄 구조는 「이름 → 가격 → 이름 → 가격」이라 «가격 줄 다음은 이름 줄»이다.
    //       ⛔ 다음 줄만 보면 **자르는 영역이 짧아 맨 아랫줄의 가격이 잘려 나갔을 때** 그 품목을 통째로 잃는다.
    //       🔢 전수 시험(자를 수 있는 351칸)에서 이 자리 하나 때문에 「구운김밥김」이 **25칸에서 안 잡혔다** —
    //          「김」은 한 글자라 앞뒤가 한글이면 사전에도 안 걸려서 D 갈래로도 못 건진다.
    //          📮 창업자가 어제 콕 짚은 그 「김」이다(*"참깨, 김, 가리비도 식재료인대 인식안됨"*).
    if (isPriceOnlyLine(lines[i + 1]) || isPriceOnlyLine(lines[i - 1])) { takeFrom(line); continue }
    // D) ⭐⭐⭐ 위 셋 다 아니어도 **아는 식재료 낱말이 또렷이 있으면** 담는다.
    //
    // 📮📮 2026-08-15 창업자 *"같은 영수증으로 영역을 다르게 찍었을 때 **최소 2개부터 최대 10개**
    //    인식까지 나와"* · *"인식율이 계속 달라져"* — 캡처 세 장이 4개·10개·4개였다.
    //
    // ⭐⭐ 뿌리 = **A·B·C 는 전부 「짝」에 매달려 있다.** 「이름 줄」과 「가격 줄」이 나란해야만 걸린다.
    //    그런데 자르는 영역이 조금만 달라지면 그 짝이 깨진다 —
    //      · 맨 아랫줄이 이름인데 그 아래 가격 줄이 잘려 나갔다        → C 실패
    //      · 가격 줄에 OCR 노이즈로 한글이 두 자 껴서 「가격 줄」로 안 보인다 → C 실패
    //      · 쉼표가 안 읽혀 「18990」이 되면 isPriceOnlyLine 이 못 알아본다  → C 실패
    //      · 이름은 이름끼리·가격은 가격끼리 몰려 읽혔다                 → C 실패
    //    🔢 실측(같은 품목·줄 모양만 다르게) = **10개 → 1 · 0 · 2 · 0.** 창업자가 본 흔들림 그대로다.
    //
    // ✅ 그래서 **짝을 안 본다** — 「참깨」·「원두」가 그 줄에 뻔히 적혀 있으면 그냥 담는다.
    //    자르는 위치가 어디든 그 줄만 살아 있으면 걸린다 = 결과가 흔들리지 않는다.
    // ⛔ 단 **아는 낱말이 있을 때만**(knownOnly). 모르는 이름까지 담으면 관문을 없앤 값으로
    //    확인 화면이 온통 잡음이 된다 — 관문의 «본래 역할»은 여기서만 남긴다.
    takeFrom(line, true)
  }
  return found
}
