// 영수증에서 무시할 줄 (합계·카드·매장·배송 정보 등)
const SKIP =
  /합계|총액|총\s*금액|부가세|과세|면세|카드|현금|결제|승인|포인트|적립|할인|쿠폰|거스름|받은|영수증|매장|지점|전화|사업자|대표|주소|번호|일시|바코드|교환|환불|감사합니다|배송|택배|봉투|무료|반품/

export function extractReceiptItems(text) {
  const lines = String(text).split('\n').map((s) => s.trim()).filter(Boolean)
  const found = []
  const seen = new Set()
  for (const line of lines) {
    if (SKIP.test(line)) continue
    // 이 줄에서 매치되는 단어들 — 한 글자 단어(무·김·배 등)는 다른 단어 속
    // 글자와 헷갈리기 쉬우니, 앞뒤가 한글이 아닐 때만 인정한다.
    const matches = FOOD_WORDS.filter((w) => {
      if (w.length === 1) return new RegExp(`(^|[^가-힣])${w}([^가-힣]|$)`).test(line)
      return line.includes(w)
    })
    // 같은 줄 안에서 겹치는 매치("대패삼겹살" → 대패삼겹+삼겹살)는 긴 것 하나만.
    const claimed = []
    for (const w of matches.sort((a, b) => b.length - a.length)) {
      const i = line.indexOf(w)
      if (i < 0) continue
      if (claimed.some(([s, e]) => i < e && i + w.length > s)) continue
      claimed.push([i, i + w.length])
      if (!seen.has(w)) {
        seen.add(w)
        found.push(w)
      }
    }
  }
  return found
}
