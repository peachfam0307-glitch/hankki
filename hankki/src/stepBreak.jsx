// ✂️· **걸음 글자는 「가운뎃점(·)에서」 줄이 바뀐다 — 항목 한가운데가 아니라** (창업자 확정 2026-09-01)
//
// 📮 창업자 원문 = *"2줄이 좋은데 **다진/ 마늘이네..**"* →
//    *"**3큰술 · 다진마늘이잖아. 그럼 다진마늘부터 줄이 바뀌어야지. ·를 기준으로**"*
//
// ⭐⭐ **창업자 규칙이 내 것보다 훨씬 낫다.** 나는 「다진·잘게·얇게 …」 꾸미는 말 «목록»을 만들려 했는데
//    (⛔손으로 만든 목록은 반드시 빠진다 — 이 저장소가 그걸로 여러 번 데었다),
//    창업자 규칙은 **구조**다: `·` 가 «항목 구분자»니 **한 항목은 통째로**, 끊을 거면 `·` 자리에서.
//
// ⛔⛔ **CSS 로는 못 한다** — `word-break: keep-all` 은 «낱말 안»만 지킨다.
//    「다진 마늘」은 띄어쓰기가 있는 두 낱말이라 브라우저가 거기서 끊는 게 «정상»이다.
//    그래서 **글자를 그릴 때 항목을 `nowrap` 으로 묶고 사이에 `<wbr>`(끊어도 되는 자리)** 를 넣는다.
//
// 🔢 **실측으로 정한 것 둘**(`scripts/_판-가운뎃점끊기-0901.mjs` · 964걸음 전수 · 패드 가로)
//    ⑴ ⛔**`·` 가 없는 걸음까지 묶으면 안 된다** — 첫 판이 문장 통째를 `nowrap` 으로 만들어
//       **964걸음 중 919개가 「1줄」이 되고 251개가 가로로 넘쳤다**(꺾일 자리가 아예 없어서).
//       → **조각이 둘 이상일 때만** 묶는다.
//    ⑵ ⛔**긴 조각도 묶으면 안 된다** — 「…을 섞어 소스를 만들어요.」 같은 꼬리를 묶으면 또 넘친다.
//       → **`항목최대` 자 이하만** 묶는다. 14자는 폰(338px·28px)에서도 한 줄에 들어가는 길이다.
//    ⭐ ＋ `·` 를 앞 조각 «끝»에 붙여 두니 **「·가 줄 머리에 오는」 흠도 같이 준다**(7 → 4군데).
//       그건 `styles.css` 요리모드 절에 *"고치려면 글 쪽을 손대야 해서 남겨 둔다"* 고 적어 둔 자리였다.
//
// ⛔ **글자를 바꾸지 않는다** — 넣는 것은 `<span>`·`<wbr>` 뿐이라 **읽히는 글은 한 글자도 안 달라진다.**
//    (레시피 «내용»을 고치는 게 아니므로 규칙 13 검수 대상이 아니다)
import { Fragment } from 'react'

// 🔢 이 길이를 넘는 조각은 안 묶는다 — 넘치는 것보다 갈리는 게 낫다
export const 항목최대 = 14

export function 항목묶어(글) {
  const t = String(글 ?? '')
  const 조각 = t.split('·')
  if (조각.length < 2) return t          // ⛔ `·` 가 없으면 손대지 않는다(지금까지와 똑같이 꺾인다)
  return 조각.map((c, i) => {
    const 끝아님 = i < 조각.length - 1
    const 몸 = c + (끝아님 ? '·' : '')
    return (
      <Fragment key={i}>
        {c.trim().length <= 항목최대 ? <span style={{ whiteSpace: 'nowrap' }}>{몸}</span> : 몸}
        {끝아님 ? <wbr /> : null}
      </Fragment>
    )
  })
}
