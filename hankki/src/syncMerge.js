// ☁️🔀 **합치기 — 「받기는 «지우지» 않는다」** (2026-09-04)
//
// 📮 창업자 = *"폰에서 꾸민 것들, 추가한 것들 패드에 반영이 안되고 있어(자동으로)"*
//           ＋ *"이건 네가 우리앱을 책임지는거야. 이거 잘못되면 답이 없어"*
//
// ⛔⛔ **왜 만드나 — 지금 「받기」는 «통째로 덮어쓰기»다.**
//    그래서 안전장치(`안올린변경있나`) 하나가 뚫리면 **곧바로 데이터가 사라진다.**
//    🚨 2026-09-01 23:51 에 실제로 그랬다 — 항정살조림을 담아 **열쇠가 5→4 로 깎였는데
//       레시피가 사라졌다.** 「돈은 썼는데 물건이 없는」 제일 나쁜 모양이다.
//    ⛔ **그 사고의 원인은 아직 확정 못 했다.** 그래서 원인을 쫓는 대신
//       **원인이 무엇이든 «잃을 수 없는» 모양**으로 바꾼다(절대원칙 34).
//
// ⭐⭐ **이 파일의 한 줄 = 「합치기는 늘 «더하기»만 한다」.**
//    지우는 일은 **오직 «무덤»이 시킬 때만** 한다. 무덤이 없으면 아무것도 안 지운다.
//    📌 그러면 최악이 「사라짐」 → **「지운 게 좀 남아 있음」**으로 내려간다.
//
// 📐 설계 전문(다섯 번 흔든 기록 · 구멍 스무 개) = `docs/폰패드-자동동기화-설계-2026-09-04.md`
// 🧪 이 파일을 지키는 판 = `scripts/_repro-폰패드합치기-0904.mjs`
//
// ⛔⛔ **여기서 하지 «않는» 것 — 일부러 안 한다**
//   · 클라우드를 부르지 않는다(순수 함수) → 판이 파이어베이스 없이 전부 돌릴 수 있다
//   · 화면을 안 건드린다 → 부르는 쪽이 «한 번에» 얹는다(반만 들어가는 일 방지 · 구멍 ⑦)
//   · **아무것도 저장하지 않는다** → 되돌리기 한 벌은 부르는 쪽이 «먼저» 떠 둔다

// 🕐 「나중에 고친 것이 이긴다」의 시각.
//   ⛔ `savedAt` 은 «처음 담은 때»라 판정에 쓰면 안 된다 — 고쳐도 안 바뀐다(구멍 ①).
//   ⚠️ 옛 데이터엔 `고친때` 가 «없다». 그땐 0 으로 본다 = **있는 쪽이 이긴다.**
//      ⭐ 둘 다 없으면(0 vs 0) **내 것을 지킨다** — 폰이 지금 손에 든 기기라 더 최근일 확률이 높고,
//         무엇보다 **잃지 않는 쪽**이다.
const 때 = (x) => Number(x?.고친때 || 0)

// 📷 사진은 클라우드에 «안» 올린다(창업자 확정 「글자부터」).
//   ⛔ 그래서 받은 판엔 사진 자리가 비어 있다 — 그대로 얹으면 **폰에 있던 사진이 빈 칸으로 덮인다.**
//   ✅ 받은 편에 사진이 없고 내 편에 있으면 **내 것을 그 자리에 되돌린다**(구멍 ④·⑤).
//   ⭐ 사진을 «보내는» 게 아니라 «안 지우는» 것이라 용량이 0이다.
const 사진인가 = (v) => typeof v === 'string' && v.startsWith('data:')

// 🧩 **칸별 판정** (구멍 ⑱ · 조사에서 나온 업계 함정)
//   폰에서 «꾸미고» 패드에서 «재료를 고치면», 편을 통째로 이기게 하면 한쪽이 통째로 날아간다.
//   ✅ 그래서 «칸마다» 본다 — 한쪽에만 있는 칸은 **그대로 살린다.**
//   ⛔ 양쪽에 «다 있는» 칸만 시각으로 가른다. 그게 진짜 부딪힘이다.
function 편합치기 (내편, 받은편) {
  if (!내편) return 받은편
  if (!받은편) return 내편
  const 내가최신 = 때(내편) >= 때(받은편)
  const 진자 = 내가최신 ? 받은편 : 내편
  const 이긴자 = 내가최신 ? 내편 : 받은편
  const 나온것 = { ...진자, ...이긴자 }

  for (const 칸이름 of Object.keys(진자)) {
    const 이긴값 = 이긴자[칸이름]
    const 진값 = 진자[칸이름]
    // ⭐ 이긴 쪽에 «그 칸이 없으면» 진 쪽 것을 살린다 — 그게 칸별 판정이다.
    if (이긴값 === undefined || 이긴값 === null) { 나온것[칸이름] = 진값; continue }
    // 📷 사진 지키기 — 이긴 쪽이 사진을 안 갖고 있으면(클라우드에서 온 판) 내 사진을 되돌린다
    if (사진인가(진값) && !사진인가(이긴값)) 나온것[칸이름] = 진값
    if (Array.isArray(이긴값) && Array.isArray(진값)) {
      // 🎨 꾸미기는 «비어 있으면 진 쪽 것을 살린다» — 클라우드 왕복에서 빈 배열로 오는 일이 있다
      if (이긴값.length === 0 && 진값.length) { 나온것[칸이름] = 진값; continue }
      // 📷📷 **[2026-09-04 · 판이 잡았다] 「사진 배열」이 `[null, null]` 로 온다.**
      //   🔢 실측 = `cloud.js` 의 `사진털기` 가 배열은 `map` 으로 훑어 **길이를 남기고 값만 undefined** 로
      //      만들고, JSON 을 거치며 **`null` 이 된다**. 일기 속지가 딱 그 모양이다.
      //   ⛔⛔ 단순 사진 칸(`image`)은 «칸이 통째로 빠져» 저절로 지켜졌는데, 배열은 «값이 있어서» 덮어쳤다.
      //      → 일기 속지 사진이 **빈 칸으로 사라진다.** 판을 세게 만들지 않았으면 못 봤을 자리다.
      //   ✅ 자리마다 본다 — 이긴 쪽이 빈 자리(null)면 **내 사진을 그 자리에 되돌린다.**
      나온것[칸이름] = 이긴값.map((v, i) => (
        (v === null || v === undefined) && 진값[i] !== undefined ? 진값[i] : v
      ))
    }
  }
  return 나온것
}

// 🗑 무덤 = 「이건 지웠다」는 표시. ⛔**지우는 일은 오직 이것만 시킨다.**
//   ⭐ 폰에만 두면 못 막는다(구멍 ⑤) — 패드가 자기 것을 올려 «되살리기» 때문이다.
//      그래서 무덤은 클라우드에도 올라간다(올리는 일은 `cloud.js` 몫).
const 무덤열쇠 = (t) => `${t.갈래 || 'recipes'}:${t.id}`

// 🍚 **우리 기본 레시피는 건드리지 않는다** (구멍 ⑰)
//   ⛔ 안 그러면 `BASICS_VERSION` 으로 바꾼 그림이 «옛 기기 것»으로 되돌아간다.
//      (오늘 실제로 그림 둘을 갈아끼웠다 — 그게 되돌아가면 창업자가 어제 준 사진이 사라진다)
//   ⭐ 잣대 = id 가 `basic-` 으로 시작하나. 앱이 이미 그 규칙으로 산다.
const 우리것인가 = (r) => typeof r?.id === 'string' && r.id.startsWith('basic-')

// 🔒 **잠긴 일기는 합치기에서 뺀다** (구멍 ⑮)
//   ⛔ 비번이 기기마다라, 받아온 잠긴 일기를 이 기기에서 못 열 수 있다.
//      그걸 섞으면 「사라졌다」로 보인다. 지금은 «내 것을 그대로 지킨다».
const 잠겼나 = (d) => !!(d?.locked || d?.잠김 || d?.enc)

// 📋 이름으로 맞추는 목록 — 장보기·냉장고·위시리스트 (구멍 ②)
//   ⭐ `store.jsx` 가 이미 «이름»으로 중복을 가른다 — 새 잣대를 만들지 않고 그걸 따른다.
//   ⛔ 통째로 덮으면 폰에서 담은 장보기가 패드 것으로 사라진다.
function 이름으로합치기 (내목록, 받은목록) {
  const 나온것 = []
  const 본이름 = new Set()
  for (const x of [...(내목록 || []), ...(받은목록 || [])]) {
    const 이름 = x?.name
    if (이름 == null) { 나온것.push(x); continue }
    if (본이름.has(이름)) continue
    본이름.add(이름)
    나온것.push(x)
  }
  return 나온것
}

/**
 * 폰에 있는 것과 클라우드에서 받은 것을 «합친다».
 *
 * @param 내것   지금 이 기기의 백업 모양
 * @param 받은것 클라우드에서 내려온 백업 모양
 * @param 무덤   [{ id, 갈래, 지운때 }] — ⛔지우는 일은 오직 이것만 시킨다
 * @returns 합쳐진 백업 모양 (⛔저장하지 않는다 — 부르는 쪽이 «한 번에» 얹는다)
 */
export function 합치기 ({ 내것, 받은것, 무덤 = [] } = {}) {
  const 내판 = 내것 || {}
  const 받은판 = 받은것 || {}
  const 무덤칸 = new Set((무덤 || []).map(무덤열쇠))

  const 목록합치기 = (갈래, 건드리지말것) => {
    const 자리 = new Map()
    for (const x of 내판[갈래] || []) if (x && x.id != null) 자리.set(String(x.id), x)
    for (const y of 받은판[갈래] || []) {
      if (!y || y.id == null) continue
      const id = String(y.id)
      const 내편 = 자리.get(id)
      // ⛔ 우리 기본 레시피 · 잠긴 일기는 «내 것을 그대로» 둔다
      if (건드리지말것 && 내편 && 건드리지말것(내편)) continue
      if (건드리지말것 && !내편 && 건드리지말것(y)) { 자리.set(id, y); continue }
      자리.set(id, 편합치기(내편, y))
    }
    // 🗑 무덤이 시킨 것만 지운다 — 그 밖엔 아무것도 안 지운다
    for (const id of [...자리.keys()]) if (무덤칸.has(`${갈래}:${id}`)) 자리.delete(id)
    return [...자리.values()]
  }

  return {
    ...받은판,
    ...내판,
    recipes: 목록합치기('recipes', 우리것인가),
    diary: 목록합치기('diary', 잠겼나),
    shoppingList: 이름으로합치기(내판.shoppingList, 받은판.shoppingList),
    pantry: 이름으로합치기(내판.pantry, 받은판.pantry),
    wishlist: 이름으로합치기(내판.wishlist, 받은판.wishlist),
    // 📁 폴더·프로필은 한 덩어리라 쪼갤 게 없다 — 내 것을 지킨다(잃지 않는 쪽)
    folders: 내판.folders !== undefined ? 내판.folders : 받은판.folders,
    profile: 내판.profile !== undefined ? 내판.profile : 받은판.profile,
  }
}

export const _내부 = { 편합치기, 이름으로합치기, 우리것인가, 잠겼나, 때, 사진인가 }
