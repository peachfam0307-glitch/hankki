export function 기본빼기(백업, 원본들) {
  const 원본 = new Map(원본들.map((r) => [r.id, r]))
  const 같나 = (r) => {
    const o = r && 원본.get(r.id)
    if (!o) return false
    const 칸 = new Set([...Object.keys(r), ...Object.keys(o)])
    for (const k of 칸) if (k !== 'savedAt' && JSON.stringify(r[k]) !== JSON.stringify(o[k])) return false
    return true
  }
  const 뺀것 = [], 남긴것 = []
  for (const r of 백업.recipes || []) (같나(r) ? 뺀것 : 남긴것).push(r)
  return { ...백업, _v: 3, recipes: 남긴것, _빠진기본: 뺀것.map((r) => r.id) }
}

// 🔢 백업에 든 레시피 «편 수» — 뺀 기본 레시피(번호만 든 것)까지 센다.
//   ⛔ `recipes.length` 만 세면 막 깐 폰 백업이 「레시피 0개」로 보인다 — 유저는 백업이 빈 줄 안다.
export const 백업편수 = (data) => (data?.recipes?.length || 0) + (Array.isArray(data?._빠진기본) ? data._빠진기본.length : 0)
