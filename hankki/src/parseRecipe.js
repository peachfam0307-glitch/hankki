    //      그대로 버린다(그건 제목이 아니라 꼬리표다). 태그가 둘 이상이면 예전 그대로.
    const 태그수 = (String(rawLine).match(/#[^\s#]+/g) || []).length
    //   ⚠️ 「첫 줄」은 «지금까지 담은 게 화면 찌꺼기뿐일 때»다 — 스크린샷은 맨 위가 늘 「KT 11:27」이라
    //      그걸 세면 진짜 첫 줄이 둘째가 되어 제목 가지가 영영 안 돈다(창업자 원문이 그 경우였다).
