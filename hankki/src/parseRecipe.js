  //       그래서 「*매운거 …추가」(재료 문단 끝) 뒤의 「■ 차돌 참나물양배추 파스타」(다음 문단 제목)가
  //       «줄바꿈으로 이어진 재료 설명»으로 오해돼 한 줄로 붙었다(창업자 실물).
