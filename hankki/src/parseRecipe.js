    //       그래서 「번호 걸음을 이미 봤나」와 «함께» 봐야 한다.
    const checkMark = /^\s*[✔☑✓✅]/.test(rawLine)
    // ※ [2026-09-01 · 창업자 판정 ⓐ] **「※」로 시작하는 줄은 «새 걸음»이 아니라 «앞 걸음의 곁말»이다.**
    //   📮 창업자 = *"ⓐ 걸음 1 아래 작은 곁말로 (요리모드에서 빈 칸이 안 생김"*
    //   ⛔ 삼치 원문의 「※무의 각진 모서리는 돌려깎기 했어요」가 **걸음 2번**이 되어
