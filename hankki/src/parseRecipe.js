const UNIT_TOKENS = new Set(['g', 'kg', 'ml', 'l', 'L', 'cc', 't', 'T', 'ts', 'tsp', 'tbsp', 'oz'])

// 🔗🔗 [2026-08-28] **OCR 이 재료 «두 줄»을 한 줄로 붙여 온다** — 그러면 한 칸에 두 재료가 들어간다.
//   📮 창업자 실물(공심채볶음 3:34) = 「아우노슈가 3/4작은술 (일반설탕 1/2작은술) 굴소스 1/2큰술」
//   📮 창업자 실물(골쫄면) = 「오이 1개 깻잎 10장 청양고추 5개」 — 세 재료가 한 칸에.
//   ⭐ 잣대 = **괄호 «밖»에 분량이 둘 이상이면 쪼갠다.**
//   ⛔⛔ 괄호 «안»의 분량은 세지 않는다 — 안 그러면 「아우노슈가 3/4작은술 (일반설탕 1/2작은술)」이
//      쪼개져 **없던 재료 「일반설탕」이 생긴다**. 그건 지금보다 나쁘다.
//   ⛔ 쪼갠 조각이 «전부 한글로 시작»해야만 쪼갠다 — 「우유 200ml 3팩」처럼 한 재료의 분량이
//      둘인 줄을 「우유 200ml」＋「3팩」으로 찢지 않으려고.
const ING_QTY_TOKEN =
  /\d+(?:\s*\/\s*\d+)?(?:[.,]\d+)?\s*(?:g|kg|ml|리터|cc|개|알|쪽|봉지|봉|모|장|대|톨|줄기|컵|큰\s?술|작은\s?술|스푼|티스푼|숟가락|숟갈|줌|꼬집|줄|캔|팩|조각|마리|공기|스틱)/gi
function splitMergedIng(s) {
  const 원 = String(s)
  if (!/[가-힣]/.test(원)) return [원]
  // 괄호 «안»을 같은 길이의 공백으로 덮는다 — 자리(index)가 원문과 어긋나면 안 되니까.
  let 깊이 = 0
  const 덮음 = [...원].map((c) => {
    if (c === '(' || c === '（') { 깊이++; return c }
    if (c === ')' || c === '）') { 깊이 = Math.max(0, 깊이 - 1); return c }
    return 깊이 > 0 ? ' ' : c
  }).join('')
  const 자리 = []
  ING_QTY_TOKEN.lastIndex = 0
  let m
  while ((m = ING_QTY_TOKEN.exec(덮음))) 자리.push(m.index + m[0].length)
  if (자리.length < 2) return [원]
  const 조각들 = []
  let 앞 = 0
  for (let i = 0; i < 자리.length - 1; i++) {
    let 끝 = 자리[i]
    // 분량 바로 뒤에 붙은 괄호(「1큰술 (대충 으깬 것)」)는 그 재료의 것이다 — 같이 데려간다.
    while (끝 < 원.length && /\s/.test(원[끝])) 끝++
    if (원[끝] === '(' || 원[끝] === '（') {
      let d = 0
      while (끝 < 원.length) { const c = 원[끝++]; if (c === '(' || c === '（') d++; else if (c === ')' || c === '）') { d--; if (d === 0) break } }
    }
    조각들.push(원.slice(앞, 끝).trim())
    앞 = 끝
  }
  조각들.push(원.slice(앞).trim())
  if (조각들.length < 2) return [원]
  if (!조각들.every((x) => /^[가-힣]/.test(x) && x.length >= 2)) return [원]
  // ⛔⛔ [2026-08-28 · 창업자가 물어서 잡았다] **「또는·혹은·대신」은 한 재료 «안»의 대체 안내다.**
  //   📮 창업자 *"이거 건드리면 기존에 쓰던 앱에서 사진 가져오기 기능이 엉망되는거 아니야?"*
  //      → 재보니 「멸치육수 500ml 또는 물 500ml」이 «두 재료»로 갈렸다. 요리책·손글씨 사진에
  //      흔한 말이라 그대로 나갔으면 사진 가져오기가 조용히 나빠졌다.
  //   ⭐ 뒤 조각이 이 말로 시작하면 통째로 안 쪼갠다 — 「물 500ml」만 따로 서면 «없던 재료»다.
  if (조각들.slice(1).some((x) => /^(또는|혹은|대신|아니면|내지|및|그리고)(\s|$)/.test(x))) return [원]
  return 조각들
}

// 특수문자·기호(외계어의 원인)를 제거 — 완성형 한글·영문·숫자 + 요리에 흔한 문장부호만 남긴다.
// 🌶🌶 **[2026-09-02 · 창업자 확정] 같은 글자가 세 번 넘게 이어지면 한 번으로 줄인다.**
//   📮 창업자 = *"제목이랑 후추추추추ㅋ"* — 사진에서 가져온 재료 줄이 **「후추추추추」** 였다.
//   ⭐ 이건 OCR 오독이 아니라 **원 글쓴이가 그렇게 쓴 것**(강조). 그래도 «재료 이름»으로는 못 쓴다 —
//      장보기 담기·검색이 낱말로 걸리는데 「후추추추추」로는 **「후추」 제품에 안 닿는다.**
//   ⛔ 원문을 잃지 않는다 — `rawText` 에 통째로 남는다(2026-08-22 부터). 여기서 줄이는 건 «보이는 줄»뿐이다.
//   🔢 **넣기 «전»에 우리 레시피 전수로 오탐을 쟀다** = 3,197줄 중 **0건**(3·4·5번 반복 전부 0).
//      그러니 이 규칙이 기존 레시피를 건드릴 일은 없다.
//   ⚠️ 정직하게 — 「팍팍팍」 같은 «맛깔나는 반복»도 「팍」이 된다. 창업자가 갈래 셋 중
//      「재료 줄에서만」이 아니라 **「정리한다」**를 골랐다(2026-09-02). 그 판정대로 재료·걸음 둘 다 적용.
//   ⛔ 한글 «한 글자»가 이어질 때만 본다 — 「아주아주」(두 글자 되풀이)·「ㅋㅋㅋ」(자모)는 안 건드린다.
export function collapseRepeatedSyllables(s) {
  return String(s).replace(/([가-힣])\1{2,}/g, '$1')
}

/** 🥄 「계량 기준」 줄 — 제목도 걸음도 아니고 «메모»다. 쓰는 곳이 둘(규칙 파서 · AI 결과)이라 여기 한 곳에 둔다.
 *   ⛔ 잣대가 둘로 갈리면 **규칙 파서는 걸러내는데 AI 판이 도로 얹는다**(창업자 폰이 그 상태였다). */
export const KIJUN_LINE = /(계량|계랑)[^\n]{0,10}기준/

function sanitize(s) {
  return String(s)
    // ⭐ [2026-08-28] 「·」를 살린다 — 창업자 실물(공심채볶음)에서 「국간장·일반 액젓」이
    //    「국간장 일반 액젓」이 되어 **두 가지 재료로 읽혔다**. 가운뎃점은 한국 레시피에서
    //    「이거 아니면 저거」·「A·B·C 를 섞어」로 늘 쓰는 글자다. 줄 «맨 앞»의 · 는
    //    LEAD_DECOR/JUNK_SYM 이 그대로 벗기니 불릿 오독은 안 늘어난다.
    .replace(/[^가-힣a-zA-Z0-9\s.,()/%°~:!+×·\-]/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .trim()
}

// 모음이 든 진짜 영어 단어가 있는지 — OCR 잡음(wWw, qL, eS 등)과 구분하는 기준.
function hasRealLatinWord(s, minLen = 3) {
  const words = String(s).match(/[a-zA-Z]+/g) || []
  return words.some((w) => w.length >= minLen && /[aeiouAEIOU]/.test(w))
}

// 줄 안의 깨진 조각(잡음 토큰)만 걷어낸다 — 낱자 영문, 구두점 조각 등.
// "양파 1개 eS" → "양파 1개"
function cleanTokens(line) {
  return line
    .split(/\s+/)
    .filter((tok) => {
      if (!/[가-힣a-zA-Z0-9]/.test(tok)) return false // 구두점만 남은 조각
      if (/^[a-zA-Z]+$/.test(tok)) {
        // 순수 영문 토큰: 단위이거나, 모음이 든 3자+ 진짜 단어만
        return UNIT_TOKENS.has(tok) || (tok.length >= 3 && /[aeiouAEIOU]/.test(tok))
      }
      return true
    })
    .join(' ')
    .trim()
}

// OCR 잡음(외계어) 줄 거르기 — 뜻있는 글자 비율이 낮거나, 온전한 단어가 하나도 없으면 버린다.
export function isGibberish(s) {
  const compact = s.replace(/\s/g, '')
  if (compact.length < 2) return true
  const good = (compact.match(/[가-힣a-zA-Z0-9]/g) || []).length
  if (good / compact.length < 0.6) return true
  if (!/[가-힣a-zA-Z]/.test(s) && !QTY.test(s) && compact.length > 3) return true
  // 온전한 한글 단어(2자+)도, 숫자도, 진짜 영어 단어도 없으면 잡음 (예: "wWw qL")
  if (compact.length > 3 && !/[가-힣]{2}/.test(compact) && !/\d/.test(compact) && !hasRealLatinWord(s)) return true
  return false
}

// ── 재료 줄 단위 오독 교정 ──
// OCR이 제일 자주 틀리는 T(큰술)·g(그램): 'T'를 7로, 'g'를 9로 읽는다.
// 재료 줄에서만, 오해 여지가 없는 모양일 때만 되돌린다(문장·날짜는 안 건드림).
const SEASONING =
  /간장|설탕|소금|고추장|된장|쌈장|고춧가루|후춧가루|후추|참기름|들기름|식초|맛술|미림|올리고당|물엿|꿀|굴소스|액젓|참치액|마요네즈|케첩|카레|깨|다진\s*마늘|생강|맛소금|다시다|연두|치킨스톡/
export function fixIngredientUnits(l) {
  let s = String(l)
  // 양념 + 한 자리 수 + 7 로 끝나면 → 큰술 (설탕 27 → 2큰술, 굴소스 1/27 → 1/2큰술)
  // 🥄 [창업자 확정 2026-09-03] 전엔 「$1T」였다 — **앱이 «직접» T 를 적고 있었다.**
  //   📮 *"우리 큰술 작은술 적는 거 있었잖아(레시피 붙여넣기로 정리할때) 거기도 바꿔줘"*
  //   ⭐ 아래 `단위통일()` 이 어차피 T 를 큰술로 고르지만, **여기서 적는 게 맞다** —
  //      고쳐야 할 것을 만들어 놓고 뒤에서 고치는 꼴이라, 순서가 바뀌면 조용히 새어 나간다.
  if (SEASONING.test(s)) s = s.replace(/(\d)7(?=\s|$)/g, '$1큰술')
  // '끝이 0·5인 수 + 9' 로 끝나면 → g (돼지고기 3009 → 300g, 떡 5009 → 500g)
  s = s.replace(/(\d{1,3}[05])9(?=\s|$)/g, '$1g')
  return s
}

// ── 🥄 단위를 «한 가지 말»로 (2026-09-03) ─────────────────────
// 📮 창업자 확정 = *"**큰술로 통일하자. 스푼 다 빼고**"*
//    그 앞 = *"스푼? 큰술? T 이거 앱에서 다 통일하자. 어떤건 T고 어떤건 큰술이고 헷갈려"*
//
// ⭐⭐ **「읽을 땐 다 받고, 저장할 땐 한 말로」** — 위 정규식들에서 「스푼·티스푼·T·t」를 «빼지 않는다».
//    유저가 붙여넣는 글에는 앞으로도 그 글자들이 들어온다. 못 읽으면 재료가 통째로 사라진다.
//    ⛔ 데이터만 고치면 **내일 담는 레시피에서 또 갈린다**(절대원칙 34 — 땜빵 금지).
//
// 🚨 순서가 «전부»다 —
//    ⑴ **「계량스푼」은 도구 이름**이라 먼저 빼둔다. 안 그러면 「계량큰술」이 된다.
//    ⑵ **「티스푼」이 「스푼」보다 «먼저»**다. 뒤에 하면 「티큰술」이 되고 **3배 틀린다.**
//    ⑶ 「스푼」은 «숫자가 붙었을 때만» 단위다. 「스푼으로 떠서」는 도구다 — 안 건드린다.
//
// ⚠️ 말 끝 고르기 — 「스푼」은 받침이 ㄴ, 「큰술」은 ㄹ 이라 **「으로」만 「로」로** 바뀐다.
//    ＋ T·t 를 쓴 사람은 「2t를」처럼 적기도 한다 → 「2작은술을」로 고른다.
const 계량자리표 = '계량스푼'
export function 단위통일 (줄) {
  let s = String(줄)
  if (!/스푼|[\dT t]/.test(s)) return s

  s = s.replace(/(계량|계랑)\s?스푼/g, 계량자리표)   // ⑴ 도구 이름은 지킨다
  s = s.replace(/티\s?스푼/g, '작은술')              // ⑵ 티스푼 먼저 (= 작은술)
  s = s.replace(/(\d)\s*T\b/g, '$1큰술')             // 1T · 1.5T · 0.3T
  s = s.replace(/(\d)\s*t\b/g, '$1작은술')           // 1t · 0.5t
  // ⑶ 숫자(분수·기호 포함) ＋ 스푼
  s = s.replace(/([\d½⅓⅔¼¾](?:[\d./\s]*[\d½⅓⅔¼¾])?)\s*스푼/g, '$1큰술')
  // 한글 수 ＋ 스푼
  s = s.replace(/한\s?스푼/g, '1큰술').replace(/반\s?스푼/g, '1/2큰술')
    .replace(/두\s?스푼/g, '2큰술').replace(/세\s?스푼/g, '3큰술')
  // 말 끝 고르기 (술 = ㄹ 받침)
  s = s.replace(/술으로/g, '술로').replace(/술를/g, '술을')
    .replace(/술가(?=\s|$|[,.·])/g, '술이').replace(/술는/g, '술은').replace(/술와/g, '술과')

  return s.split(계량자리표).join('계량스푼')
}

// ── 앞머리 OCR 잡음 제거 ──
// 불릿·아이콘을 오독한 조각(삐 · = · HE · Vv · Eel · \/^ · 를 …)이 유효한 한글 재료명
// 앞에 붙어 남는 경우가 많다("삐 선복 1<0", "= 쌀 450", "Vv Eel 토핑용"). 한글/숫자가
// 나오기 전까지의 '기호 덩어리 · 짧은 라틴 조각(단위 제외) · 대표 오독 한 글자'를 벗겨낸다.
const JUNK_SYM = /^[삐쁘=|/\\^<>~"'`_·•*■□▶►◆●○@©®№°§✓✔✅☑√✗✘☒▪▫◾◽◇◈✦✱＊①-⑳❶-❿➀-➉⓪]+/
// 숫자 뒤에 오면 '수량'이라 지우면 안 되는 단위들(번호 불릿과 구분).
const UNIT_AFTER = /^(?:스푼|큰술|작은술|티스푼|컵|공기|개|알|장|줌|톨|쪽|봉|캔|팩|모|줄|덩이|리터|ml|kg|cc|g)/
// 네모/핀 아이콘(■ 📌 ▪)이 오독되는 대표 글자들. tesseract가 매번 다르게 읽어(삐→뽀→뽀삐)
// 1~2글자 조합까지 잡는다. 단, '쌀·깨·꿀·짜장' 같은 진짜 재료는 이 집합에 없어 안전.
const JUNK_SYL = '를르롤삐쁘뽀빠뻐뿌쀼쁠삑뺴쀄삠'
const JUNK_TOK_OCR = new RegExp(`^(?:[${JUNK_SYL}]{1,2}|ㅂ|ㅃ|ㅉ|ㄲ|VE|Vv|EI|W|w)$`)
// 맨 앞에 홀로 올 수 있는 '진짜' 한 글자 재료·수식어 화이트리스트.
// OCR에서는 이 목록에 없는 한 글자가 줄 맨앞+뒤에 내용이 있으면 = 아이콘 오독으로 보고 버린다.
// (아이콘이 어떤 한글로 오독되든 다 걸러짐 — 목록에 없으니까)
const KEEP_1CHAR = new Set('물쌀깨꿀파콩무밥알면술김엿향잣팥쑥굴게차죽국떡묵밀순청홍생달참들표겨젓초씨쌈멸꿩닭소돼양'.split(''))
export function stripLeadingOcrJunk(line, fromOcr = false) {
  let s = String(line).trim()
  s = s.replace(JUNK_SYM, '').trim()
  if (fromOcr) {
    // 맨 앞 이모지(🍆✨🔥 등)와 변형선택자 제거
    s = s.replace(/^(?:[\u{1F000}-\u{1FAFF}☀-➿←-⇿⬀-⯿︀-️‍⃣]+\s*)+/u, '').trim()
    // 체크(✔️)가 한글에 붙어 라틴 조각(V·W 등)으로 오독된 것 제거: "V올리브유" → "올리브유"
    s = s.replace(/^[A-Za-z]{1,2}(?=[가-힣])/, '').trim()
    s = s.replace(JUNK_SYM, '').trim()
  }
  for (let i = 0; i < 3; i++) {
    const m = s.match(/^(\S+)\s+/)
    if (!m) break
    const tok = m[1]
    const rest = s.slice(m[0].length)
    const junk =
      JUNK_SYM.test(tok) ||
      (/^[A-Za-z]{1,3}$/.test(tok) && !/^(ml|g|kg|cc|ea|oz|l)$/i.test(tok)) ||
      (fromOcr && /^[A-Za-z]{4}$/.test(tok)) || // 긴 라틴 조각(AINE 등)도 OCR에선 잡음
      (fromOcr && /^[0OoＯ]$/.test(tok)) ||      // 불릿을 0·O 로 오독
      (fromOcr && /^[1-9]\d?$/.test(tok) && /^[가-힣]/.test(rest) && !UNIT_AFTER.test(rest)) || // 번호 불릿(③→3): 뒤가 단위 아닌 '재료명'이면 잡음
      (fromOcr && JUNK_TOK_OCR.test(tok)) ||
      (fromOcr && /^[가-힣]$/.test(tok) && !KEEP_1CHAR.has(tok)) // 화이트리스트에 없는 맨앞 한 글자 = 아이콘 오독
    if (!junk) break
    s = s.slice(m[0].length).replace(JUNK_SYM, '').trim()
  }
  return s
}

// 사용자가 직접 쓴 티가 나는 줄 — 이모지·기호(🔥★♥)나 온전한 한글 단어가 있으면
// 잡음 검사를 건너뛴다. (isGibberish 는 이모지를 '나쁜 글자'로 세기 때문)
const USER_SAFE = /[☀-➿⭐❤\u{1F000}-\u{1FAFF}]|[가-힣]{2}/u

// 메모 최종 청소 — 재료·순서와 겹치는 줄, 잡음 줄을 걷어낸다.
// 어떤 경로(OCR·공유·직접 입력)로 만들어진 메모든 저장·표시 전에 한 번 거르는 안전망.
// 짧은 줄(4자 미만)과 이모지·한글 문장은 사용자가 쓴 것일 수 있어 보존한다.
export function cleanMemo(memo, ingredients = [], steps = []) {
  const norm = (s) => String(s).replace(/\s+/g, ' ').trim()
  const taken = new Set([...ingredients, ...steps].map(norm))
  return String(memo || '')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => {
      if (!l) return false
      if (taken.has(norm(l))) return false
      const compact = l.replace(/\s/g, '')
      if (compact.length < 4) return true
      if (USER_SAFE.test(l)) return true
      return !isGibberish(l)
    })
    .join('\n')
}

// 사진(OCR)에서 온 텍스트의 메모 후보 — '깨끗한 문장'만 통과.
// 분류 안 된 찌꺼기가 메모에 흘러들지 않게 하는 마지막 관문.
export function isCleanMemoLine(s) {
  const compact = s.replace(/\s/g, '')
  if (compact.length < 9) return false // 진짜 팁은 문장 — 짧은 조각은 잡음
  const good = (compact.match(/[가-힣a-zA-Z0-9.,!?()%~:]/g) || []).length
  if (good / compact.length < 0.9) return false
  return /[가-힣]{2,}/.test(s) || hasRealLatinWord(s, 4)
}

// 문장으로 끝나는 줄은 제목이 아니다 ("추가해 총 사용했습니다" 같은 조각 방지)
// 니다(오독 포함)·~요 계열 어미, 또는 마침표·느낌표로 끝나면 문장으로 본다.
// 🙂🙂 [2026-08-28] 종결어미 «뒤»에 남은 것이 무엇이든 문장은 거기서 끝난다.
//    📮 창업자 실물(골쫄면) — 캡션 끝 😊 가 OCR 에서 「(」로 읽혔다.
//       그러면 「괄호가 안 닫혔다」로 판정돼 뒷줄을 통째로 빨아들여
//       제목이 「그릇만 먹어도 든든한 여름 면요리입니다( /골쫄면」이 됐다.
//    ✅ 앞머리를 LEAD_DECOR 로 «전부» 벗기듯, 꼬리 장식도 «전부» 무시한다.
const SENTENCE_END = /(니다|세요|어요|해요|져요|까요|네요|든요|께요|답니다)\s*[\p{P}\p{S}]*\s*$|[.!…]["')\]]*\s*$/u

// --- 재료 / 만드는 법(순서) 구분 ---
// 재료칸에 조리 문장이 섞이는 게 가장 큰 불편이라, 두 신호로 '순서 문장'을 가려낸다.
//  1) 조리 동작(활용형) — "볶고/넣어/끓인" 등. 재료명("김치볶음밥")엔 활용형이 없어 안 걸린다.
//  2) 평서형 종결 — "볶는다·끓인다·푼다·하세요·넣어요" 등.
// ⚠️ '푼'은 뺀다 — 제일 흔한 계량단위 '스푼'에 걸려 재료 줄(…3스푼)을 순서로 오분류함.
//    풀다(달걀 푼다)는 '풀어' + 종결어미(~다)로 이미 잡히므로 안전.
const STEP_VERB =
  // 🍳🍳 **[2026-09-04 · 창업자 실물] 「볶음」은 «동작»이 아니라 «음식 이름»이다.**
  //   📮 창업자 폰(인스타 닭한마리) = 「닭볶음탕용 닭 800g, 물 1.2L」이 **재료가 아니라 걸음으로** 갔다.
  //   🔎 실측 = 여기 맨 앞 「볶」 한 글자가 「닭**볶**음탕용」에 걸렸다.
  //   ⛔⛔ **바로 위 주석은 «틀린 말»이었다** — *"재료명(김치볶음밥)엔 활용형이 없어 안 걸린다"*.
  //      한 글자 「볶」이 있으니 볶음밥·제육볶음·닭볶음탕이 **전부 걸린다.**
  //      📌 적어둔 말과 코드가 갈려 있었고, 아무도 «무엇을 보는지»를 안 봤다(규칙 18 ⓘ).
  //   ✅ 「볶」 뒤에 «음»이 오면 이름이다 — 동작은 볶아·볶고·볶은·볶다 처럼 활용형으로 온다.
  //      (활용형 볶아·볶고는 아래 목록에 그대로 있다)
  //   ⛔ 목록을 넓히지도 좁히지도 않았다. **한 글자의 «잣대»만 고쳤다.**
  /(넣|볶(?!음)|끓|섞|부어|붓|풀|두르|둘러|구우|구워|구운|굽|익히|익혀|튀기|튀겨|삶|데치|데쳐|재우|재워|올려|얹|뿌려|졸이|졸여|우려|뒤집|비벼|담아|따라|헹궈|헹구|불려|불리|절이|절여|조리|조려|볶아|볶고|끓여|썰어|썰고|자르|잘라|다지|다져|버무|무쳐|무친|저어|저으|짜서|갈아|갈아서|말아|말고)/
// 수량·분량을 나타내는 표현 — 숫자가 없어도 재료로 본다("소금 약간", "애호박 반개")
const AMOUNT =
  /(\d|½|⅓|⅔|¼|¾|반\s?개|반\s?컵|반\s?쪽|약간|조금|적당량|적당히|넉넉|한\s?줌|두\s?줌|한\s?꼬집|한\s?스푼|한\s?방울|톨|줌|꼬집|방울)/

// 문장 종결(평서 ~다/~요/~라/~자, 또는 마침표)
const DECLARATIVE = /(다|요|죠|라|자|셈|봐)[.!~)"'\s]*$|[.!…]["')\]]*\s*$/
// 이 줄이 '만드는 법(순서)' 문장인가?
function looksLikeStep(l) {
  if (STEP.test(l)) return true // "1. …", "①…", "step 1"
  const hasVerb = STEP_VERB.test(l)
  const ends = DECLARATIVE.test(l)
  if (hasVerb && ends && l.length >= 6) return true // 짧은 조리 문장 ("밥을 넣고 볶는다")
  if (ends && l.length >= 8) return true // 종결형 문장이면 대체로 순서 ("오이는 어슷썬다")
  if ((hasVerb || ends) && l.length >= 16) return true // 긴 설명 문장
  return false
}

// 이 줄이 '재료' 항목인가? (분량 표현이 있고, 조리 문장은 아님)
function looksLikeIngredient(l, bullet) {
  if (l.length > 40) return false
  if (QTY.test(l)) return true
  if (bullet && /[가-힣]{2,}/.test(l)) return true
  if (AMOUNT.test(l) && /[가-힣]{2,}/.test(l)) return true
  return false
}

// ── 줄바꿈으로 잘린 문장 병합 (분류 전, 원문 줄 단위) ──
// 인스타 캡션 등은 한 문장이 여러 줄로 잘린다("…팬에" / "노릇노릇 굽는다").
// 앞줄이 '이어지는 중'(종결어미·문장부호로 안 끝나거나 괄호 안 닫힘·쉼표로 끝남)이고
// 뒷줄이 새 항목(불릿·번호·헤더)이 아니면 합쳐 원래 문장을 되살린다 → 재료/순서 분류가 정확해짐.
const WRAP_ENDPUNCT = /[.!?…]["'’)\]]*\s*$/
const WRAP_CONNECT = /(에|에서|에게|을|를|와|과|로|으로|의|도|만|고|며|서|여|게|면|지|랑|이랑|보다|처럼|든|거나|아서|어서|아|어)\s*$/
const WRAP_NEWITEM = /^\s*([-*•·▪◦‣●○✅✔☑✓]|[1-9]\d?\s*[.)]|[①-⑳❶-❿]|step\s*\d|스텝\s*\d)/i
// 다음 줄이 "3큰술"처럼 수량으로 시작 = 앞줄 재료(참기름)가 줄바꿈으로 잘린 것 → 이어붙임 신호.
const WRAP_STARTQTY = /^\s*\d+(?:[.,]\d+)?\s*(큰술|작은술|숟갈|숟가락|스푼|티스푼|컵|공기|줌|톨|알|장|개|쪽|봉|모|g|kg|ml|리터|l|T|t|cc|꼬집)/i
function isWrappedOpen(s) {
  const t = String(s).trim()
  if (!t) return false
  if (WRAP_ENDPUNCT.test(t) || SENTENCE_END.test(t)) return false // 문장으로 끝남 → 완결
  const opens = (t.match(/[(（]/g) || []).length
  const closes = (t.match(/[)）]/g) || []).length
  if (opens > closes) return true // 괄호 안 닫힘 → 확실히 이어짐
  if (/,\s*$/.test(t)) return true // 끝이 쉼표 → 목록/문장 계속
  return WRAP_CONNECT.test(t) // 연결어미·조사로 끝남
}
function mergeWrappedLines(lines) {
  const out = []
  for (const raw of lines) {
    const prev = out.length ? out[out.length - 1] : null
    // ⛔⛔ [2026-08-28] 여기 «불릿 목록»이 손으로 관리되던 게 사고의 뿌리였다.
    //    실측 = 한국 인스타 캡션에 흔한 장식 30개 중 **18개**(■ □ ◆ ◇ ▶ ▷ ◈ ▣ ◎ ★ ☆ ※ 🔸 🔹 📌 🍲 [ 【)
    //    가 목록에 없어서 아래 SEC_ING/SEC_STEP 방어막을 «못 넘고» 앞 문장에 붙었다.
    //    📮 창업자 실물(차돌 파스타) = 「남편이 오늘도 또 해먹자고 ■ 재료 (2-3인분 기준)」로 뭉쳐
    //       **재료 절이 한 번도 안 열렸고**, 그 바람에 분량 없는 재료(후추)가 통째로 사라졌다.
    //    ⛔ 바로 위 주석이 「[재료]·◆ 만드는 법 등 장식도 허용」이라 «적어만» 뒀는데 둘 다 죽어 있었다.
    //    ✅ 목록을 늘리지 않는다 — **앞머리 장식은 «전부» 벗긴다**(구두점·기호·이모지).
    //       숫자는 안 벗기므로 「1.」 같은 새 항목은 WRAP_NEWITEM 이 그대로 잡는다.
    const bare = stripLead(raw)
    const contQty = WRAP_STARTQTY.test(raw) && !WRAP_ENDPUNCT.test(String(prev || '')) && !SENTENCE_END.test(String(prev || ''))
    if (
      prev != null &&
      (isWrappedOpen(prev) || contQty) &&
      !WRAP_NEWITEM.test(raw) &&
      !SEC_ING.test(bare) &&
      !SEC_STEP.test(bare) &&
      // 🔤 «한글이 없는 짧은 잡음 줄»은 앞 문장에 붙이지 않는다 — 붙으면 지울 수가 없어진다.
      //    📮 창업자 실물(골쫄면) — 하단바를 읽은 「L4D TVHHE THIN」이 앞줄에 붙어 걸음이 됐다.
      //    ⛔⛔ 「길이 0」을 빼먹으면 «빈 줄»까지 걸려서 문단 이어붙이기가 통째로 죽는다
      //       (2026-08-28 에 실제로 그랬고 기존 ⭐2칸이 잡았다 — 빈 줄은 여기서 흡수되는 게 «정상»이다).
      !(String(raw).trim().length > 0 && String(raw).trim().length <= 24 && !/[가-힣]/.test(String(raw))) &&
      (prev + ' ' + raw).replace(/\s+/g, ' ').length <= 160
    ) {
      out[out.length - 1] = (prev + ' ' + raw).replace(/\s+/g, ' ').trim()
      continue
    }
    out.push(raw)
  }
  return out
}

