// 어떤 키가 «유료팩 것»인가.
//   ⭐ `packed` 명단이 있으면 **그 명단만** · 비어 있으면 접두어 전부(아직 안 골랐으니 안전하게).
export const paidPackOf = (key) => {
  const k = String(key)
  return PAID_PACKS.find((p) => (
    p.packed?.length ? p.packed.includes(k) : p.prefixes.some((pre) => k.startsWith(pre))
  )) || null
}

// 무료로 내보내도 되는 키인가 — ⛔**유료팩 컷이면 언제나 아니다.**
//   판매가 시작돼도 마찬가지다. 산 사람의 자물쇠 안에서만 열린다.
export const freeOk = (key) => !paidPackOf(key)
