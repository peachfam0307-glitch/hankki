// 어떤 키가 «유료팩 것»인가 — **접두어로 본다.** (`packed` 는 「팩에 뭐가 들었나」 기록용)
//   ⚠️ 접두어는 앱·카드에 겹치는 게 없는지 확인하고 적는다(2026-08-03 `pf_a` 사고).
export const paidPackOf = (key) => {
  const k = String(key)
  return PAID_PACKS.find((p) => p.prefixes.some((pre) => k.startsWith(pre))) || null
}

// 그 팩에서 «팩에 넣은» 컷인가 (기록·요약용)
export const isPacked = (key) => {
  const p = paidPackOf(key)
  return !!p && (p.packed || []).includes(String(key))
}

// 무료로 내보내도 되는 키인가.
//   ⛔ **기본은 「안 된다」** — 유료팩 접두어면 막는다. 판매가 시작돼도 마찬가지다
//      (산 사람의 자물쇠 안에서만 열린다 · *"카드에서라도 공유되면 한정판이 아니자나"*).
//   ✅ 예외는 딱 하나 — **`freed` 에 «적어둔» 컷.** 팩에 안 넣고 카드로 풀기로 한 것.
//   📌 «적어야 열린다»는 쪽이 안전하다. 반대로 하면 새 컷이 들어올 때마다 조용히 샌다.
export const freeOk = (key) => {
  const p = paidPackOf(key)
  return !p || (p.freed || []).includes(String(key))
}
