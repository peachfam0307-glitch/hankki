// 어떤 키가 «유료팩 것»인가 — **두 갈래로 본다.**
//   ① `packed` 에 «그 키가 그대로» 적혀 있나   ← 오늘 파는 컷
//   ② 접두어로 시작하나                        ← 그 식구로 «나중에» 들어올 컷까지 미리 차단
//
// ⛔⛔ 2026-08-03 에 잡은 구멍 — ①이 없었다.
//   추석 팩에 `cp_`·`ct_`·`cm_`·`cf2_`·`ci_` 31컷을 넣어놓고 **접두어를 안 적어서**
//   누수 검사가 그 31컷을 «유료팩 것»으로 아예 못 보고 있었다.
//   가을 팩의 `pf_02·04·08` 도 마찬가지인데, 이쪽은 **접두어를 못 적는다** —
//   `pf_` 로 시작하는 «무료» 앱 프레임이 46개나 있어서 통째로 막으면 앱이 깨진다.
//   📌 그래서 ①을 넣었다. **팩에 적힌 컷은 접두어와 무관하게 «언제나» 막힌다.**
//   ⚠️ 접두어는 앱·카드에 겹치는 게 없는지 확인하고 적는다(2026-08-03 `pf_a` 사고).
export const paidPackOf = (key) => {
  const k = String(key)
  return PAID_PACKS.find((p) => (p.packed || []).includes(k))
    || PAID_PACKS.find((p) => p.prefixes.some((pre) => k.startsWith(pre)))
    || null
}

// 그 팩에서 «팩에 넣은» 컷인가 (기록·요약용)
export const isPacked = (key) => {
  const p = paidPackOf(key)
  return !!p && (p.packed || []).includes(String(key))
}

// 무료로 내보내도 되는 키인가.
//   ⛔ **기본은 「안 된다」** — 유료팩 접두어면 막는다. 판매가 시작돼도 마찬가지다
//      (산 사람의 자물쇠 안에서만 열린다 · *"카드에서라도 공유되면 한정판이 아니자나"*).
//   ✅ 예외는 딱 하나 — **`freed` 에 «적어둔» 컷.** 팩에 안 넣고 카드로 풀기로 한 것.
//   📌 «적어야 열린다»는 쪽이 안전하다. 반대로 하면 새 컷이 들어올 때마다 조용히 샌다.
export const freeOk = (key) => {
  const p = paidPackOf(key)
  return !p || (p.freed || []).includes(String(key))
}
