// 🗓 「이번 주 픽」이 도는 규칙 — **순수 계산만** 담는다.
//
// ⚠️⚠️ **왜 `curation.js` 에서 갈라 냈나** — 그 파일은 `import.meta.glob`(Vite 전용)을 쓴다.
//    배포 게이트는 **노드만으로** 돌아야 하는데(2026-08-03·08-07 에 두 번 데였다),
//    노드가 그 파일을 열면 `glob is not a function` 으로 죽는다.
//    ⭐ 그래서 «돌리는 규칙»만 여기 두고 제품 목록은 **인자로 받는다** → 게이트가 그대로 검사할 수 있다.
//
// ⛔ 이 파일에 import 를 늘리지 말 것. 늘리는 순간 게이트가 또 못 읽는다.

// 에폭 주차 — 해가 바뀌어도 이어지고 매주 정확히 1씩 오른다.
// ⛔ 연중 주차로 세면 12월 말~1월 초에 튄다.
export const weekNo = (ymd) => Math.floor(Date.parse(`${ymd}T00:00:00Z`) / 604800000)

// 🆕 「새로 올린 것」으로 치는 기간 = **4주**.
//   ⭐ 날짜로 재니 **저절로 낡는다** — 손으로 `new: true` 를 지울 일이 없다(지우는 걸 잊으면 영영 새 것이 된다).
export const NEW_WEEKS = 4
export const 새것인가 = (since, today) =>
  !!(since && today && weekNo(today) - weekNo(since) >= 0 && weekNo(today) - weekNo(since) < NEW_WEEKS)

// 이번 주 픽 = ①이번 주 레시피가 쓰는 제품 ②**새로 올린 것** ③모자라면 주차로 밀어 채운다.
//   matched = ①의 결과(호출부가 넘긴다) · products = 전체 제품
//
// 🆕🆕 [창업자 2026-08-17] *"주부 장바구니 이번주 픽은 **새로 열린거 우선으로** 올려줘"*
//   ⭐⭐ 왜 필요한가 — 회전(`off`)은 **전체 목록을 한 바퀴 도는** 구조라, 새 제품을 올려도
//      그 차례가 오기까지 **몇 주~몇 달**이 걸린다. 창업자가 설명을 써서 올린 그 주에 안 뜨면
//      **「올린 보람」이 없다.** 그래서 새 것은 회전을 «건너뛰고» 앞에 선다.
//   ⏰ 4주가 지나면 저절로 회전 대열로 돌아간다(`새것인가`).
//
// ⭐⭐⭐ **순서 = ①새 것 → ②레시피가 쓰는 것 → ③회전.** 새 것이 «맨 앞»이다.
//   ⛔ 처음엔 ②를 앞에 뒀다(「이번 주 요리에 필요한 것이니 광고가 아니라 안내」라고 봤다).
//      **실물을 찍어 보니 틀렸다** — 새로 올린 올리고당이 **3번째**로 밀렸다(2026-08-17).
//   🔢 원인 = `picksForIngredients` 는 **제품 풀네임이 재료 글에 있으면 «항상 앞»**(direct)에 놓는데,
//      **「아우노슈가」가 레시피 91줄에 박혀 있다.** 그래서 그 제품은 **거의 매주 1번**이고 영영 안 바뀐다.
//      📮 창업자가 예전에 *"주부장바구니픽도 매주 꼭 바꿔줘"* 라고 한 그 자리가 여기서 막혀 있었다.
//   ✅ 그래서 새 것을 맨 앞으로. **②가 사라지는 게 아니라 한 칸 밀릴 뿐**이고(n=4),
//      새 것은 **4주만** 앞에 선 뒤 저절로 물러난다. 창업자 = *"새로 열린거 우선으로 올려줘"*.
// ⛔⛔⛔ **[2026-08-17 두 번째 고침] `matched` 도 «회전 대열»에 넣는다.**
//   📮 창업자 = *"**4주뒤는 하바티가 위에 서야지**"* — 내가 보여준 4주 뒤 순서가
//      「아우노슈가 → 올리고당 → 하바티」였고, **아우노슈가가 또 1번**이었다.
//   ⭐⭐ 뿌리 = `matched` 를 «그대로 앞에» 붙이면, 풀네임이 레시피에 박힌 제품은 **영영 1번**이다.
//      「아우노슈가」는 **91줄**에 박혀 있어서 4주 뒤에도, 1년 뒤에도 1번이다.
//      📌 새 것을 앞에 세운 건 «4주짜리 반창고»였을 뿐, 뿌리는 그대로였다.
//   ✅ 그래서 `matched` 를 회전 대열 **맨 앞쪽**에 넣고 «함께» 돌린다 —
//      ⑴ 이번 주 요리에 필요한 것이 여전히 앞쪽이고
//      ⑵ 매주 «다른 게» 1번에 온다(창업자 *"주부장바구니픽도 매주 꼭 바꿔줘"*)
export const pickRotate = ({ products = [], matched = [], today = '', n = 4 } = {}) => {
  const 담김 = new Set(matched.map((p) => p && p.name).filter(Boolean))
  const 안담김 = products.filter((p) => p && !담김.has(p.name))
  const 새것 = 안담김.filter((p) => 새것인가(p.since, today))
  // ⭐ 돌릴 것 = 「이번 주 레시피가 쓰는 것」 ＋ 나머지 전부. **새 것만 맨 앞 고정이고 그 밖엔 고정이 없다.**
  //   ⛔ 예전엔 `matched` 를 여기 «밖»에 두고 항상 앞에 붙였다 → 풀네임이 박힌 제품이 영영 1번이었다.
  const 돌릴것 = [...matched, ...안담김.filter((p) => !새것인가(p.since, today))]
  if (!돌릴것.length) return 새것.slice(0, n)
  // ⭐⭐ **한 주에 `n` 칸씩 민다** — 한 칸씩 밀면 4개 중 3개가 다음 주에도 그대로 남는다.
  //    창업자가 *"매주 꼭 바꿔줘"* 라고 한 건 «다른 게 뜬다»는 뜻이지 «하나만 바뀐다»가 아니다.
  //    🔢 실측 = 한 칸씩일 때 앞뒤 주가 3개씩 겹쳤다(2026-08-10 게이트 미리보기에서 드러났다).
  // ⚠️ `%` 는 음수에서 음수를 내니 한 번 더 더해 양수로 만든다(1970 이전 날짜·이상값 방어).
  const off = today ? ((((weekNo(today) * n) % 돌릴것.length) + 돌릴것.length) % 돌릴것.length) : 0
  return [...새것, ...돌릴것.slice(off), ...돌릴것.slice(0, off)].slice(0, n)
}
