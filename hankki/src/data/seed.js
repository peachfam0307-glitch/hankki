// 🕘🕘 [창업자 제보 2026-09-10] 「레시피가 최신순으로 안보이네? 최신 레시피가 제일 아래야」
//   ⛔⛔ 뿌리 = **「배열 순서」를 「저장한 시각」으로 삼았다.** 옛 공식 = Date.now() - i * 60000.
//      basics.js 는 레시피를 «뒤에» 쌓는데, 뒤일수록 i 가 커져 **더 옛날**로 찍혔다. 정확히 거꾸로다.
//      🔢 실측 = 콩국수 0번째 → 1등 · 꽃게탕 59번째 → 60등. **매주 넣는 새 레시피가 전부 맨 아래로 갔다.**
//   ✅ 진짜 「최신」의 근거는 「from」(그 편이 언제 열렸나)이다 — basics.js 가 이미 갖고 있다.
//      · from 있음 → 그 날짜   · from 없음(처음부터 있던 42편) → 아주 옛날(바닥)
//      · 같은 날 열린 것끼리는 **배열 앞이 위**다(i 초를 «뺀다»)
// 🕘🕘 [2026-09-12 창업자 폰 제보] *"15개레시피 또 거꾸로들어가있어 역순으로"* → *"역순으로 올라가는거 고쳐"*
//   ⛔⛔ 여기가 옛날엔 `+ i * 1000` 이었다 — **배열 «뒤»일수록 위**로 섰다.
//      📌 15편만의 일이 아니었다. **같은 날 열린 묶음이 전부 거꾸로**였다 —
//         8/17 묶음은 basics 차례가 「스무디 → … → 브로콜리 구이」인데 화면엔 브로콜리가 맨 위였다.
//   ✅ `- i * 1000` = **basics.js 에 적은 차례 그대로 위에서 아래로.** 사람이 적은 차례가 곧 화면 차례다.
//      ⛔ 배열을 뒤집어 두는 걸로 때우지 않는다 — 다음 사람이 「보기 좋게」 되돌리면 그 순간 또 깨진다.
//      🔢 i 는 최대 86초라 날짜 간격(하루)을 절대 못 넘는다 → 날짜 순서는 안 흔들린다.
//   ⛔ 「오늘」을 만들지 않는다 — 여기서 파싱하는 건 basics.js 에 «적힌» 날짜다(절대원칙 27 과 무관).
//   ⚠️ from 이 깨졌으면(NaN) 바닥으로 보낸다 — 깨진 값 하나가 목록 전체를 흔들면 안 된다.
// 📌📌 [창업자 확정 2026-09-10] 「샘플이 젤위여야지 꽃게탕고정으로」
//   ⭐ 왜 = 샘플은 «이렇게 꾸밀 수 있어요»를 보여주는 편이다. 새로 깐 사람이 맨 처음 보는 자리라야 값을 한다.
//      📮 그 앞 = 「시크릿모드로 유저가 보이는대로 들어갔거든. 근데 가을샘플이 아니고 콩국수가 바로 보이네;;」
//   ⛔ 샘플은 둘이다(콩국수=여름 · 꽃게탕=가을). 창업자가 «지금 철»인 꽃게탕을 고른 것이다.
//      👉 철이 바뀌어 새 샘플을 심으면 **이 줄의 id 만 바꾼다.** ⛔다른 곳은 안 건드린다.
//   ⚠️ 처음에 id 를 「basic-kkotgetang」으로 잘못 적었다(진짜는 basic-kkotge-tang).
//      그래서 아래 검사를 붙였다 — **없는 id 를 적으면 그 자리에서 죽는다.** 조용히 안 먹히는 게 제일 나쁘다.
export const 맨위고정 = 'basic-kkotge-tang'
const 바닥 = Date.parse('2020-01-01T00:00:00')
// 🔝 고정석 — 어떤 날짜보다도 위. 실제 날짜와 안 겹치게 아주 먼 미래로 둔다.
const 고정석 = Date.parse('2099-01-01T00:00:00')
export const 열린때 = (r, i = 0) => {
  if (r?.id === 맨위고정) return 고정석
  const t = r?.from ? Date.parse(r.from + 'T00:00:00') : NaN
  return (Number.isFinite(t) ? t : 바닥) - i * 1000
}

// 🔒 «없는 id 를 고정석에 적었나» — 손으로 적은 id 는 반드시 낡는다. 그때 조용히 안 먹히면 아무도 모른다.
//    ⛔ 죽이지는 않는다(앱이 안 뜨면 그게 더 큰 사고다) — 대신 검사판·개발 콘솔에 대고 소리친다.
if (맨위고정 && !basicRecipes.some((r) => r.id === 맨위고정)) {
  console.error('⛔ seed.js 맨위고정 = 「' + 맨위고정 + '」 인데 basics.js 에 그런 id 가 없다 — 샘플이 맨 위로 안 간다')
}

// 📅📅 [2026-09-12 창업자 폰 제보] *"날짜뭐야?"* · *"2020년?"* — 목록이 거의 다 「2020.01.01」이었다.
//   ⛔⛔ 뿌리 = **한 값을 두 일에 썼다.** `savedAt` 은 「줄 세우는 값」인데 화면 둘이 그걸
//      「저장 날짜」로 그대로 찍었다(MyRecipesScreen 의 칸 · RecipeDetailScreen 의 「… 저장」).
//      그래서 위 `바닥`(2020-01-01 · 맨 아래로 보내려고 고른 «가짜 시각»)이 유저 눈에 날짜로 새어 나왔다.
//   ✅✅ [창업자 확정 2026-09-12 「a」] **기본 레시피는 저장 날짜를 «안» 보여준다.**
//      ⭐ 왜 = 「저장」은 유저가 한 일이다. 앱에 처음부터 있거나 날짜가 돼서 열린 편은 **유저가 저장한 적이 없다.**
//         안 한 일에 날짜를 붙이니 그게 곧 2020.01.01 같은 거짓말이 됐다.
//      ⛔ 바닥 숫자를 「그럴듯한 날」로 바꿔 때우지 않는다 — 그건 더 그럴듯한 거짓말일 뿐이다(절대원칙 34).
//   ⭐ 판정은 **여기 한 곳**에서만 한다 — 화면마다 따로 판정하면 반드시 갈린다.
//      📌 유저가 기본 레시피를 «복사»해 담은 것은 새 id 라 `basic-` 이 아니다 → 진짜 저장 시각이 그대로 보인다.
export const 저장날짜보임 = (r) => !!r?.savedAt && !String(r?.id || '').startsWith('basic-')

export const seedRecipes = basicRecipes.map((r, i) => ({
  ...r,
  savedAt: 열린때(r, i),
}))

