// 🍚🍜 **종류** — 한 편이 「나라」와 「종류」 두 칩에 «둘 다» 뜨게 하는 자리
//
// 📮 창업자 확정 2026-09-14
//    · *"나라로 가자"* — 갈래(category)는 **나라**로만 (한식·중식·일식·양식·아시안)
//    · *"중복이어야 맞아"* — 한 편이 **나라 칩에도 종류 칩에도** 뜬다
//    · *"간식은 하나로 통일"* — 간식은 나라가 아니라 **종류**다
//    · *"전 튀김은 반찬으로. 고기요리도 반찬"* · *"찌개류는 찌개로 덮밥은 덮밥으로"*
//    · *"파스타는 면"* · *"김치 절임 무침 다 반찬으로"* · *"빵종류는 간식"*
//
// ⭐⭐ **왜 여기서 «계산»하나 — basics.js 에 박지 않는 이유**
//    ⓐ 201편에 손으로 박으면 **새로 들어오는 편은 또 빈 칸**이다. 창업자 = *"앞으로는 처음부터
//       갈래 나누는걸 바로 넣자"* → 계산하면 새 편도 **저절로** 갈린다.
//    ⓑ basics.js 의 `folder:` 줄은 서로 글자가 똑같아서(`folder: '한식',`) 130줄을 기계로 고치면
//       **엉뚱한 편을 집을 수 있다.** 실제로 계획을 재 보니 105줄이 「안 고유」였다.
//    ⛔ 대신 **글자 규칙은 틀린다** — 아래 `손으로` 가 그 증거다(「충무김밥 오징어무침」이
//       «김밥» 글자에 걸려 밥으로 갔다). 그래서 규칙보다 `손으로` 가 먼저 이긴다.

// ⛔ 칩은 이 여섯뿐이다. 여기 없는 이름은 칩이 되지 않는다.
//    📌 그 전엔 레시피에 적힌 folder 가 «칩을 저 혼자 만들었다» — 아무도 정한 적 없는
//       「국·탕·찌개」 칩이 2편짜리로 생겨 있었다. 이제 목록이 정하고, 게이트가 지킨다.
//   📮 창업자 2026-09-14 = *"소스는 따로 넣자. 소스만 필요할때도 있거든"* → 일곱 번째로 살렸다.
export const 종류들 = ['밥', '국', '면', '반찬', '간식', '샐러드', '소스']

// 🌏 갈래(category)는 **나라**뿐이다 (창업자 확정 2026-09-14 *"나라로 가자"*)
//    ⛔ 「간식」은 여기 없다 — 창업자 = *"간식은 하나로 통일"* → 간식은 **종류**다.
//    ⭐ 「기타」 = 나라를 댈 수 없는 것 (창업자 2026-09-14 *"기타에 넣던가"*)
//       요거트 아이스크림·슬러시·스무디처럼 «어느 나라 음식도 아닌» 편이 갈 곳이 필요하다.
export const 나라들 = ['한식', '중식', '일식', '양식', '아시안', '기타']

// 🗑 **폰에만 남아 있는 «옛 폴더» 이름** (창업자 확정 2026-09-14 *"그럼 다 빼야지"*)
//   ⛔⛔ 그 시절엔 «레시피에 적힌 folder 가 칩을 저 혼자 만들었다». 오늘 그 구조는 막았지만
//      **이미 폰에 저장된 목록(saved.folders)은 안 지워진다** — 가지무침이 안 바뀌던 것과 같은 뿌리(규칙 18ⓙ).
//   🔢 실측 2026-09-14 = 우리 씨앗(git 이력 전부)에 이 이름이 **한 편도 없다**.
//      창업자 폰엔 「소스 25 · 밥·면·덮밥 19 · 고기 21 · 해물 7 · 국·탕·찌개 10 · 반찬·기타 11」이 칩으로 떠 있었다.
//      📮 창업자 = *"나 기억안나는데 ???"* → 직접 만든 게 아니다. 옛 씨앗이 남긴 것이다.
//   ⭐⭐ **칩에서만 뺀다 — 그 폴더에 든 편은 사라지지 않는다.**
//      거르기가 「나라 이거나 폴더 이거나 종류」라서 그 편들은 나라 칩·종류 칩·「전체」에 그대로 뜬다.
//   ⛔ 이 목록은 «한 번 치우는 것»이라 낡지 않는다 — 오늘 이후로는 새로 생기지 않는다(칩 목록을 고정했다).
//   ⛔ 유저가 «직접 만든» 폴더는 여기 없으므로 그대로 살아 있다.
//   ⭐ 「소스」는 여기 «없다» — 창업자가 *"소스만 필요할때도 있거든"* 이라 종류로 살렸다.
export const 옛폴더이름 = ['밥·면·덮밥', '고기', '해물', '국·탕·찌개', '반찬·기타', '국·탕', '국물']

// ✋ 글자 규칙이 틀리게 집는 편 — 여기가 규칙보다 먼저다
const 손으로 = {
  '고구마 그라탕': '반찬', // 「탕」 글자에 걸려 국으로 갔다
  고구마맛탕: '간식', // 「맛탕」이 탕에 걸렸다
  // 📮 창업자 2026-09-14 = "소스는 따로 넣자" → 반찬에서 소스로 옮겼다
  '비빔밥 소스': '소스', // 「비빔밥」 글자에 걸려 밥으로 가던 것
  '고마다래 소스': '소스',
  달래장: '소스', // 밥·고기에 곁들이는 양념장이다 (⛔「장」으로 넓게 잡으면 간장게장이 딸려 온다)
  오징어누룽지: '국', // 📮 창업자 = *"누룽지는 탕"*
  '충무김밥 오징어무침': '반찬', // 「김밥」에 걸렸지만 무침이다
}

const 규칙 = [
  // 🥣 소스 (창업자 2026-09-14 *"소스는 따로 넣자. 소스만 필요할때도 있거든"*)
  //   ⛔⛔ **좁게 잡는다.** 「장」으로 잡으면 간장게장·새우장·양념게장·차돌된장이 딸려 온다(실측).
  //      「소스」로만 잡아도 «대파 소스 목살 덮밥»이 걸린다 — 그건 덮밥이다.
  //      ⭐ 넓게 잡는 건 실패를 없애는 게 아니라 «더 나쁜 실패»로 바꾸는 것이다(절대원칙 37).
  //   📌 그래서 «이름이 소스로 끝나는 것»만 본다. 늘려야 하면 창업자 판정을 받고 한 편씩 더한다.
  ['소스', /(?:소스|양념장)$/],
  ['샐러드', /샐러드|포케/],
  ['면', /파스타|국수|면$|면[^역]|냉면|칼국수|막국수|수제비|라자냐|팟타이|야끼우동|짬뽕/],
  ['국', /찌개|전골|탕$|탕[^수]|국$|국밥|미역국|떡국|곰탕|사브|샤브|누룽지탕|해장/],
  ['밥', /밥$|덮밥|비빔밥|솥밥|김밥|볶음밥|죽$|리조또/],
  ['간식', /아이스크림|스무디|슬러시|크루키|맛탕|크룽지|찰떡|요거트|떡볶이|샌드위치|타코|브리또|레터스랩/],
]

// 🍳 한 편의 «종류»를 고른다 — 어디에도 안 걸리면 **반찬**
//    📮 창업자 = *"전 튀김은 반찬으로. 고기요리도 반찬"* → 조림·볶음·구이·찜·전·튀김이 다 여기다.
export function 종류고르기(recipe) {
  const 제목 = (recipe && recipe.title) || ''
  if (손으로[제목]) return 손으로[제목]
  for (const [갈래, 규] of 규칙) if (규.test(제목)) return 갈래
  return '반찬'
}
