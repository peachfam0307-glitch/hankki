// 🔪 재료 한 줄 → 그 재료 손질법(없으면 null) · 레시피 재료 옆 「손질」 칩이 쓴다(창업자 2026-11-22 「레시피에서 손질법을 바로」)
//   ⭐ 「찾기」가 있는 칸만 잇는다 — 대파·양파처럼 자르기 팁은 거의 모든 레시피에 붙어 시끄러워진다
export function 손질찾기(재료 = '') {
  const 이름 = String(재료).replace(/^\[[^\]]*\]\s*/, '').split(/\s\d|\s\(/)[0]
  for (const g of PREP) for (const it of g.items) if (it.찾기 && it.찾기.test(이름)) return it
  return null
}
