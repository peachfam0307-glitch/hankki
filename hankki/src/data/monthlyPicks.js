// 🏅 「이달의 레꾸」 — 유저가 꾸민 레시피를 «달마다» 앱에 싣는 자리
//
// 📮 창업자 2026-09-13 = *"매달 한끼 레꾸자랑을 실을까.."* → **일회성 이벤트가 아니라 «매달 도는 코너»**
//    ＋ *"이달의 레꾸 좋아"*(이름 확정) ＋ *"앱에 자리만들고 홍보는 앱안 소식+인스타계정으로 둘다"*
//    ＋ *"9월에도 시험삼아 해볼까?"* → **9월 = 시험판 · 10월 할로윈 = 본판**
//
// ⛔⛔ **손으로 적은 목록은 반드시 낡는다** — 이 저장소에서 여러 번 데였다(스토어 스샷·릴리즈 판수·자산 개수).
//    그래서 **날짜가 열고 닫게** 만든다. `from`~`until` 이 지나면 저절로 사라진다.
//
// 📐 정한 것 (창업자 2026-09-13)
//    · 앱에 싣는 것 = **한 달에 3장** (가로로 민다)   · 인스타엔 «보낸 사람 전원»
//    · 이름은 **`@아이디 님`**                      · 「더보기」는 **안 만든다**(누를 데만 있고 갈 데가 없으면 더 나쁘다)
//
// ⚠️ **개인정보** — 아이디가 앱에 박힌다. 반드시 게시 동의를 받고 싣는다.
//    «내려달라» 하면 이 파일에서 지우고 배포하면 내려간다.
// ⚠️ **번들이 커진다** — 매달 3장이면 1년에 36장. 그래서 **`KEEP_MONTHS` 만큼만 남기고 덜어낸다.**
import { todayKST } from '../today.js'

// 🗓 몇 달치까지 앱에 남겨 두나 — 지난 건 덜어낸다(안 그러면 앱이 계속 무거워진다)
export const KEEP_MONTHS = 6

/**
 * 📣 접수 «중»인 회차 — 이게 있으면 칸이 「보내주세요」 얼굴로 뜬다.
 *    ⛔ 손으로 켜고 끄지 않는다 — `from`~`until` 날짜가 알아서 한다.
 */
export const ROUNDS = [
  // ⛔ [2026-09-13] 9월 시험판은 «접었다» — 창업자 = *"다음주가 추석이라.."*
  //    🔢 2026 추석 = **9/25(금) · 연휴 9/24~27**. 내가 잡았던 접수 마감(9/25)이 **추석 당일**이었다.
  //    📌 접수 기간 9/15~25 가 통째로 «추석 준비 주간»이라 참여도 판정도 어렵다.
  //    ⭐ 대신 생긴 2주 반을 «준비»에 쓴다 → 창업자 확정 = *"10월 하나로 가자"*
  {
    month: '2026-10',
    label: '10월',
    from: '2026-10-01',
    until: '2026-10-15',
    note: '할로윈 꾸미기로',
  },
]

/**
 * 🏅 이미 «실린» 것 — 창업자가 뽑은 뒤 여기에 넣는다.
 *    src: `src/assets/picks/` 에 넣은 그림 (⛔유저가 보낸 캡처 그대로가 아니라 «개인정보를 가린» 판)
 *    who: 인스타 아이디 (⛔ 「@」 는 화면에서 붙인다 — 여기엔 아이디만)
 * ⚠️ 지금은 비어 있다 — 9월 시험판이 아직 안 끝났다. 비면 화면이 「접수 중」 얼굴로 뜬다.
 */
export const PICKS = [
  // { month: '2026-09', who: '아이디', src: '/picks/2609-1.png', title: '콩국수' },
]

/** 📅 오늘 기준 «접수 중»인 회차 (없으면 null) */
export const openRound = (today = todayKST()) =>
  ROUNDS.find((r) => r.from <= today && today <= r.until) || null

/** 🏅 오늘 기준 «보여줄» 뽑힌 것 — 최근 달부터, `KEEP_MONTHS` 안의 것만 */
export const shownPicks = (today = todayKST()) => {
  const 자른달 = (() => {
    const [y, m] = today.slice(0, 7).split('-').map(Number)
    const t = m - KEEP_MONTHS
    const yy = y + Math.floor((t - 1) / 12)
    const mm = ((t - 1 + 12 * 100) % 12) + 1
    return `${yy}-${String(mm).padStart(2, '0')}`
  })()
  return PICKS.filter((p) => p.month >= 자른달).sort((a, b) => b.month.localeCompare(a.month))
}

/** 🗓 그달 라벨 — 「10월」처럼 */
export const labelOf = (month) => ROUNDS.find((r) => r.month === month)?.label || `${Number(month.slice(5, 7))}월`
