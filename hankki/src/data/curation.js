//
// ⛔⛔ **예전엔 `pick: true` 가 박힌 «두 개»를 그대로 보여줬다 — 매주는커녕 영영 안 바뀌었다.**
//    이름만 「이번 주 픽」이고 실제로는 「고정 둘」이었다. 창업자 확인 = *"예시야 된장."*
//
// ⭐⭐ **왜 「매주 손으로 바꾸기」로 안 만들었나** — 사람이 매주 하는 일은 반드시 빠진다.
