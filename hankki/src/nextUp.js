// 🍳 「다음에 뭐 할까」 — 홈 맨 위 한 줄이 상황을 보고 «할 일»을 꺼낸다
//
// 📮 창업자 2026-08-19 확정
//    · 갈래 = **ⓐ 한 자리에서 돌아가며** (*"a로 가자"*)
//    · 겉모습 = **㉯ 눈에 띄는 새 카드** (*"나도 나가 좋은데"*)
//    · 언제 = **ⓑ 다음 날부터** (*"ㅂ랑 ㉠으로 가자"*)
//    · 문구 = **㉠ 「다음엔 뭘 바꿔볼까요?」** ＋ 예시 “간장 반만”
//    · 여럿이면 = **가로로 밀어서 최대 3장** (*"레시피 오른쪽 스크롤해서 3개정도까지는 보이게?"*)
//    · 쓰고 나면 = **그 카드가 사라진다** (*"한줄남기기 마치면 그 창은 사라지게 하자"*)
//      ⭐ 저절로 된다 — `note` 가 채워지면 아래 조건에서 빠진다. 지우는 코드가 «없다».
//
// ⭐⭐ 왜 한 자리인가 = 셋이 다 「다음에 뭐 할까」라는 «같은 물음»의 답이다.
//    나란히 놓으면 서로 경쟁하고, 홈은 이미 카드가 다섯이다.
//
// 🔢 우리 앱 실측으로 뽑은 근거 (2026-08-19)
//    · 홈의 세 칸이 **전부 「이미 만든 것」만 본다** —
//      「오늘 뭐 해먹지」(냉장고→`cooked>0`) · 「자주 해먹는」(`cooked>0`) · 「최근 저장」(`savedAt`)
//      → **안 만든 레시피는 홈 어디에도 안 뜬다.** 저장할수록 파묻히는 구조였다.
//      ⭐ 리서치의 「저장한 것 중 15% 미만만 만들어진다」가 우리 앱에선 이 모양으로 있었다.
//    · `r.cookedAt`(마지막 만든 날)은 **저장은 되는데 아무 화면도 안 쓴다**
//    · 「만들었어요」가 만드는 일기가 `note: ''` 로 시작한다(`RecipeDetailScreen` onCook)
//      → 「한 줄 안 쓴 것」을 **새로 저장할 것 없이** 그대로 셀 수 있다
//
// ⛔ 톤 — 재촉·죄책감 금지(우리 원칙). 「3일째 요리 안 하셨어요」가 되면 안 된다.
//
// ⛔ 「만들었어요는 누르면 끝(토스트만)」 창업자 확정(2026-08-06)과 «안» 부딪힌다 —
//    그 확정은 «누른 직후에 폼을 안 띄운다»이고, ⓑ(다음 날부터)라서 **그날은 아예 조용하다.**
//    원래 설계가 *"남기고 싶은 사람은 자기가 원할 때 연다"* 였고 여기는 그 자리를 찾기 쉽게 할 뿐이다.

// ⏱ 「한 줄」을 묻는 창 — 어제부터 사흘 전까지
//    ⭐ 「어제부터」인 이유(창업자 ⓑ) = ⑴「누르면 끝」 확정을 온전히 지킨다
//       ⑵맛은 먹어봐야 안다(만든 직후엔 아직 안 먹었다) ⑶요리 직후는 상 차리고 먹고 치우느라 정신없다
//    ⛔ 손해가 없다 — 그날 밤 쓰고 싶으면 레시피 상세·일기 탭에서 언제든 쓴다. 이 카드는 «찾기 쉽게» 할 뿐이다.
const 한줄_묻기시작_일 = 1
const 한줄_유효기간_일 = 3
const 하루 = 24 * 60 * 60 * 1000

/**
 * 홈 맨 위에 꺼낼 것들 — «한 갈래»에서 최대 N개.
 * ⛔ 갈래를 섞지 않는다 — 「한 줄 남기기」와 「아직 안 해봤어요」가 나란히 밀리면
 *    무슨 줄인지 알 수 없다. 카드는 「지금 할 일 하나」를 말하는 자리다.
 * @returns {{갈래: string, 것들: object[]}|null}
 */
export function nextUpList(recipes = [], diary = [], now = Date.now(), 최대 = 3) {
  const 살아있는 = (recipes || []).filter((r) => r && r.status !== 'unsorted')
  const 찾기 = (id) => 살아있는.find((x) => x.id === id) || null

  // ── ① 한 줄 안 쓴 것 — 어제 ~ 사흘 전 (창업자 안 · 시간에 제일 민감하다) ──
  //    ⭐ 최근 것부터 — 오래된 건 이미 기억이 흐리다
  //    ⛔ **레시피가 아직 있는 것만** — 지우고 일기만 남은 항목을 꺼내면 눌러도 갈 데가 없다
  const 한줄없음 = (diary || [])
    .filter((d) => {
      if (!d || String(d.note || '').trim()) return false
      const 날 = 지난날(d.at, now)
      return 날 >= 한줄_묻기시작_일 && 날 <= 한줄_유효기간_일
    })
    .filter((d) => 찾기(d.recipeId))
    .sort((a, b) => (b.at || 0) - (a.at || 0))
    .slice(0, 최대)
  if (한줄없음.length) {
    return {
      갈래: '한줄',
      것들: 한줄없음.map((e) => ({
        키: 'n' + e.id,
        recipe: 찾기(e.recipeId),
        entry: e,
        라벨: 언제(e.at, now) + ' 만든 것',
        제목: e.title || 찾기(e.recipeId)?.title || '',
        // ㉠ 창업자 확정 — ⛔「도움이 돼요」는 막연해서 안 끌린다(창업자 판정)
        //    ⭐ 예시(“간장 반만”)가 붙어야 «뭘 쓸지»가 바로 떠오르고, 「한 줄이면 돼요」가 부담을 낮춘다
        이유: '다음엔 뭘 바꿔볼까요?',
        보기: '“간장 반만” 처럼 한 줄이면 돼요',
        단추: '한 줄 남기기',
      })),
    }
  }

  // ── ② 아직 안 해본 것 (A① · 15% 문제를 정면으로) ────────────────────
  //    ⭐ 오래 묵은 것부터 — 방금 저장한 건 아직 「안 해봤다」고 할 때가 아니다
  const 안해본것 = 살아있는
    .filter((r) => !(r.cooked > 0))
    .sort((a, b) => (a.savedAt || 0) - (b.savedAt || 0))
    .slice(0, 최대)
  if (안해본것.length) {
    return {
      갈래: '안해본것',
      것들: 안해본것.map((r) => ({
        키: 'u' + r.id,
        recipe: r,
        entry: null,
        라벨: '아직 안 해봤어요',
        제목: r.title || '',
        이유: '저장해두고 아직 한 번도 안 만든 거예요',
        보기: '',
        단추: null,
      })),
    }
  }

  // ── ③ 지난번 그거 (A② · `cookedAt` 이 여태 안 쓰이고 있었다) ──────────
  //    ⚠️ 실측 = 이 갈래는 «저장한 걸 전부 만들어본 사람»에게만 뜬다(시드 레시피가 많아 사실상 드물다).
  //       그래서 A② 의 본체는 이 카드가 아니라 「만든 요리」 화면 쪽이다 — 별개 일로 남겨 둔다.
  const 만든것 = 살아있는
    .filter((r) => r.cooked > 0 && r.cookedAt)
    .sort((a, b) => (b.cookedAt || 0) - (a.cookedAt || 0))
    .slice(0, 최대)
  if (만든것.length) {
    return {
      갈래: '지난번',
      것들: 만든것.map((r) => ({
        키: 'a' + r.id,
        recipe: r,
        entry: null,
        라벨: 언제(r.cookedAt, now) + ' 만든 것',
        제목: r.title || '',
        이유: '또 해볼까요?',
        보기: '',
        단추: null,
      })),
    }
  }

  // ⛔ 아무것도 없으면 «아무것도 안 그린다» — 빈 칸을 남기지 않는다(우리 규칙)
  return null
}

// 며칠 지났나 — ⛔ 시:분을 지우고 «날짜»로 센다.
//    안 그러면 밤 11시에 만든 것이 한 시간 뒤 「어제」가 되고, ⓑ(다음 날부터)가 새벽에 깨진다.
function 지난날(at, now) {
  if (!at) return 999
  return Math.floor((묶기(now) - 묶기(at)) / 하루)
}

// 「어제」·「3일 전」 — ⛔ 「3일째 안 하셨어요」로 읽히지 않게 «사실»만 적는다
function 언제(at, now) {
  if (!at) return '지난번에'
  const 날 = 지난날(at, now)
  if (날 <= 0) return '오늘'
  if (날 === 1) return '어제'
  if (날 === 2) return '그제'
  return `${날}일 전`
}

// 날짜만 남긴다(시:분을 지운다)
function 묶기(ms) {
  const d = new Date(ms)
  return new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime()
}
