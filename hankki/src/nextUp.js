// 🍳 「다음에 뭐 할까」 — 홈에서 한 자리가 상황을 보고 «하나»를 고른다
//
// 📮 창업자 2026-08-19 = *"a두가지는 오늘 해야하고"* ＋
//    *"b는 만들었어요누르고 한줄 넘 좋은데 **어떻게 어디서 누르게 하냐가 중요해.**
//      홈에 만들었는데 한줄 안쓴 레시피만 보여주게 한다거나.."*
//    → 갈래 판정 = **ⓐ 한 자리에서 돌아가며** (창업자 *"a로 가자"*)
//
// ⭐⭐ 왜 한 자리인가 = 셋이 다 「다음에 뭐 할까」라는 «같은 물음»의 답이다.
//    나란히 놓으면 셋이 서로 경쟁하고, 홈은 이미 길다(카드 다섯).
//
// 🔢 우리 앱 실측으로 뽑은 근거 (2026-08-19)
//    · 홈의 세 칸이 **전부 「이미 만든 것」만 본다** —
//      「오늘 뭐 해먹지」(냉장고→`cooked>0`) · 「자주 해먹는」(`cooked>0`) · 「최근 저장」(`savedAt`)
//      → **안 만든 레시피는 홈 어디에도 안 뜬다.** 저장할수록 파묻히는 구조였다.
//    · `r.cookedAt`(마지막 만든 날)은 **저장은 되는데 아무 화면도 안 쓴다**
//    · 「만들었어요」가 만드는 일기가 `note: ''` 로 시작한다(`RecipeDetailScreen` onCook)
//      → 「한 줄 안 쓴 것」을 **새로 저장할 것 없이** 그대로 셀 수 있다
//
// ⛔ 톤 — 재촉·죄책감 금지(우리 원칙). 「3일째 요리 안 하셨어요」가 되면 안 된다.
//    「이건 아직 안 해봤네요」 정도로 «권하지 않고 꺼내 놓기만» 한다.
//
// ⛔ 「만들었어요는 누르면 끝(토스트만)」 창업자 확정(2026-08-06)과 «안» 부딪힌다 —
//    그 확정은 «누른 직후에 폼을 안 띄운다»이고, 원래 설계가 *"남기고 싶은 사람은
//    자기가 원할 때 연다"* 였다. 여기는 그 「자기가 원할 때」를 **찾기 쉽게** 할 뿐이다.

// ⏱ 「한 줄」을 언제까지 물을까 — 기억이 살아 있는 동안만.
//    ⭐ 시간에 «민감한» 것이 먼저다: 어제 만든 것은 오늘 물어야 하고 사흘 뒤엔 늦다.
//       반대로 「아직 안 해본 것」은 언제 꺼내도 값이 안 준다.
const 한줄_유효기간_일 = 3

// 하루를 밀리초로
const 하루 = 24 * 60 * 60 * 1000

/**
 * 홈 한 자리에 꺼낼 «하나»를 고른다.
 * @param {object[]} recipes 저장된 레시피
 * @param {object[]} diary   요리 일기(「만들었어요」가 쌓는다)
 * @param {number}   now     지금(ms) — ⛔테스트가 시각을 넣을 수 있게 인자로 받는다
 * @param {number}   돌리기  「다른 것 보여줘」를 누른 횟수(같은 갈래 안에서 다음 것)
 * @returns {null | {갈래, recipe, entry, 라벨, 이유, 단추, 후보수}}
 */
export function pickNextUp(recipes = [], diary = [], now = Date.now(), 돌리기 = 0) {
  const 살아있는 = (recipes || []).filter((r) => r && r.status !== 'unsorted')
  const 고르기 = (목록) => (목록.length ? 목록[((돌리기 % 목록.length) + 목록.length) % 목록.length] : null)

  // ── ① 한 줄 안 쓴 것 (창업자 안 · 시간에 제일 민감하다) ─────────────
  //    ⭐ 최근 것부터 — 오래된 건 이미 기억이 흐리다
  //    ⛔ **레시피가 아직 있는 것만** — 지우고 나서 일기만 남은 항목을 꺼내면
  //       눌러도 갈 데가 없다(빈 화면). 「없는 것을 권하지 않는다」
  const 한줄없음 = (diary || [])
    .filter((d) => d && !String(d.note || '').trim() && now - (d.at || 0) <= 한줄_유효기간_일 * 하루)
    .filter((d) => 살아있는.some((x) => x.id === d.recipeId))
    .sort((a, b) => (b.at || 0) - (a.at || 0))
  if (한줄없음.length) {
    const e = 고르기(한줄없음)
    const r = 살아있는.find((x) => x.id === e.recipeId) || null
    return {
      갈래: '한줄',
      recipe: r,
      entry: e,
      라벨: 언제(e.at, now) + ' 만든 것',
      제목: e.title || r?.title || '',
      이유: '어땠어요? 한 줄만 남겨두면 다음에 도움이 돼요',
      단추: '한 줄 남기기',
      후보수: 한줄없음.length,
    }
  }

  // ── ② 아직 안 해본 것 (A① · 15% 문제를 정면으로) ────────────────────
  //    ⭐ 오래 묵은 것부터 — 방금 저장한 건 아직 「안 해봤다」고 할 때가 아니다
  const 안해본것 = 살아있는
    .filter((r) => !(r.cooked > 0))
    .sort((a, b) => (a.savedAt || 0) - (b.savedAt || 0))
  if (안해본것.length) {
    const r = 고르기(안해본것)
    return {
      갈래: '안해본것',
      recipe: r,
      entry: null,
      라벨: '아직 안 해봤어요',
      제목: r.title || '',
      이유: '저장해두고 아직 한 번도 안 만든 거예요',
      단추: null,
      후보수: 안해본것.length,
    }
  }

  // ── ③ 지난번 그거 (A② · `cookedAt` 이 여태 안 쓰이고 있었다) ──────────
  const 만든것 = 살아있는
    .filter((r) => r.cooked > 0 && r.cookedAt)
    .sort((a, b) => (b.cookedAt || 0) - (a.cookedAt || 0))
  if (만든것.length) {
    const r = 고르기(만든것)
    return {
      갈래: '지난번',
      recipe: r,
      entry: null,
      라벨: 언제(r.cookedAt, now) + ' 만든 것',
      제목: r.title || '',
      이유: '또 해볼까요?',
      단추: null,
      후보수: 만든것.length,
    }
  }

  // ⛔ 아무것도 없으면 «아무것도 안 그린다» — 빈 칸을 남기지 않는다(우리 규칙)
  return null
}

// 「어제」·「3일 전」 — ⛔ 「3일째 안 하셨어요」로 읽히지 않게 «사실»만 적는다
function 언제(at, now) {
  if (!at) return '지난번에'
  const 날 = Math.floor((묶기(now) - 묶기(at)) / 하루)
  if (날 <= 0) return '오늘'
  if (날 === 1) return '어제'
  if (날 === 2) return '그제'
  return `${날}일 전`
}

// 날짜만 남긴다(시:분을 지운다) — ⛔안 그러면 「23시에 만든 것」이 한 시간 뒤 「어제」가 된다
function 묶기(ms) {
  const d = new Date(ms)
  return new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime()
}
