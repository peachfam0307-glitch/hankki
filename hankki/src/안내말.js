import { KEY_NAME, KEY_UNIT } from './열쇠이름.js'

// ⛔ 이 파일은 «말»만 만든다 — 열쇠를 깎지도, 서버를 부르지도 않는다.
//    (tidy.js 에 두면 「열쇠를 두 곳에서 깎지 마라」 검사에 걸린다 — 뜻이 다른 걸 한 파일에 두지 않는다)

// 🔑🔑 **까닭 → 말** — 「어떤 오류에 어떤 안내」의 «유일한» 구현 [창업자 2026-09-09]
//   📮 창업자 = "어떤 오류에 어떤 안내가 들어가고 열쇠는 어떻게 되는지 세밀하게 설계해서 남겨"
//   📖 표 = docs/열쇠와안내-까닭별-2026-09-09.md
//
//   ⛔⛔ **말을 다른 곳에 또 적지 않는다** — 두 곳에 적으면 반드시 갈라진다.
//   ⛔ 「열쇠 안 썼어요」는 «안 깎인 것이 사실일 때»만 붙는다. 서버가 보낸 값으로만 판단한다.
//      그래서 «모름»(끊김)일 때는 열쇠 얘기를 통째로 뺀다 — 모르는 걸 안다고 말하는 게 최악이다.
export function 까닭말(왜, 앎 = true) {
  if (!앎) return { 머리: '연결이 끊겼어요', 몸: '잠시 뒤에 다시 해 주세요', 열쇠말: '' }
  switch (왜) {
    case '빈손':
      return { 머리: '글자가 안 보여요', 몸: '밝은 곳에서 다시 찍어 주세요', 열쇠말: '열쇠 안 썼어요' }
    case '전에읽음':
      return { 머리: '전에 읽은 사진이에요', 몸: '그대로 채웠어요', 열쇠말: '열쇠 안 썼어요' }
    case '처리중':
      return { 머리: '아직 읽는 중이에요', 몸: '조금 뒤에 다시 해 주세요', 열쇠말: '열쇠 안 썼어요' }
    case '구글실패':
      return { 머리: 'AI가 잠깐 안 돼요', 몸: '조금 뒤에 다시 해 주세요', 열쇠말: '열쇠 안 썼어요' }
    case 'rate_limited':
      return { 머리: '너무 빨라요', 몸: '1분 뒤에 다시 해 주세요', 열쇠말: '열쇠 안 썼어요' }
    case 'global_quota':
      return { 머리: '오늘은 여기까지예요', 몸: '내일 다시 열려요', 열쇠말: '열쇠 안 썼어요' }
    case 'user_quota':
      return { 머리: '열쇠를 다 썼어요', 몸: '다음 달에 다시 채워져요', 열쇠말: '' }
    default:
      // ⛔ 모르는 까닭이 와도 «막다른 길»이 되면 안 된다 — 열쇠 얘기는 안 하고 할 일만 말한다.
      return { 머리: '잘 안 됐어요', 몸: '조금 뒤에 다시 해 주세요', 열쇠말: '' }
  }
}

// 🤖 AI 다듬기가 «끝났을 때» 하얀 창에 남는 말 — 사라지기만 하면 됐는지 안 됐는지 모른다.
// 🙅 유저가 AI 동의 시트에서 「사용 안 함」을 고른 판 — 실패가 아니라 «선택»이다(2026-09-13 배포 검수).
export function 동의안함끝말() {
  return { 머리: 'AI 없이 정리했어요', 몸: '설정 → AI 다듬기 사용에서 언제든 켤 수 있어요', 열쇠말: '' }
}

export function 다듬기끝말(됐나, 꼬리 = '') {
  // 🔍 꼬리 = 모델·걸린 시간 — ⛔«창업자 폰에만» 붙는다(부르는 쪽이 tidyFounder 로 가른다).
  //   📮 창업자 2026-09-10 = *"갈색띠가 안떠 성공해도"* → 띠는 4.8초라 놓친다. 창은 닫을 때까지 남는다.
  return 됐나
    ? { 머리: '다 됐어요', 몸: '레시피에 올라갔어요' + 꼬리, 열쇠말: '' }
    : { 머리: 'AI 다듬기가 안 됐어요', 몸: '임시보관함에서 「AI로 다듬기」를 한 번 더 눌러 주세요' + 꼬리, 열쇠말: '열쇠 안 썼어요' }
}

// 🔑🔑 **「몇 개 남았나」를 말하는 «한 곳»** [창업자 2026-09-09]
//   📮 창업자 = "0개 남았어요가 무료랑은 안맞는 말이잖아"
//   ⛔ 옛 판 = 네 곳(KeyBadge·App·InboxScreen·EditorScreen)이 각자 「무료 열쇠 N개 남았어요」를 지었다.
//      N 이 0 이면 **「무료인데 왜 0이야?」**로 읽힌다 — 남은 걸 세는 말로 «없음»을 말할 수 없다.
//   ⭐ 0 은 「남은 수」가 아니라 «다른 사건»이다. 그래서 문장을 갈라 준다.
//   ⛔ 「무료」를 안 붙인다 — 유료를 켜도 이 말은 안 고쳐도 된다(창업자 확정 = ⓑ).
export function 남은열쇠말(left) {
  if (!left || left.무제한) return ''
  const n = Number(left.total)
  if (!Number.isFinite(n)) return ''
  if (n <= 0) return '열쇠를 다 썼어요 · 다음 달에 다시 채워져요'
  return `무료 ${KEY_NAME} ${n}${KEY_UNIT} 남았어요`
}
