const 계기열쇠 = '계기판'

let 붙은창고 = null
export function _창고물리기 (것) { 붙은창고 = 것 }
async function 창고 () {
  if (붙은창고) return 붙은창고
  const m = await import('./syncUndo.js')
  return m._창고()
}

// ⏰ 달을 가른다 — ⛔`cloud.js` 의 카운터와 «같은 잣대»(UTC)를 쓴다.
//   여기만 한국시간으로 바꾸면 달이 바뀌는 자정 무렵에 «다른 칸»을 읽어 0으로 보인다.
//   (그 함정은 `cloud.js` 의 `?quota=1` 자리에 이미 적혀 있다)
export const 이번달 = () => new Date().toISOString().slice(0, 7)

// ⛔ 허락한 칸만 — 「빼야 할 것을 지운다」가 아니라 «넣을 것만 받는다»
const 셀것 = ['읽기', '쓰기']

/** 부른 만큼 더한다. ⛔절대 던지지 않는다. */
export async function 세기 (것 = {}) {
  try {
    const 달 = 것.달 || 이번달()
    const 창 = await 창고()
    const 전부 = (await 창.꺼내기(계기열쇠)) || {}
    const 칸 = 전부[달] || {}
    for (const k of 셀것) {
      const v = Number(것[k] || 0)
      if (!v) continue
      칸[k] = Number(칸[k] || 0) + v
    }
    전부[달] = 칸
    // 🧹 석 달치만 둔다 — 계기판이 창고를 먹으면 그게 또 다른 벽이 된다
    const 달들 = Object.keys(전부).sort().reverse().slice(0, 3)
    const 남길것 = {}
    for (const d of 달들) 남길것[d] = 전부[d]
    await 창.넣기(계기열쇠, 남길것)
    return true
  } catch {
    // ⛔⛔ 여기서 던지면 동기화가 멈춘다. 계기판은 곁다리다.
    return false
  }
}

/** 이번 달(또는 고른 달) 숫자. 화면이 그대로 그린다. */
export async function 읽기 (달 = 이번달()) {
  try {
    const 전부 = (await (await 창고()).꺼내기(계기열쇠)) || {}
    const 칸 = 전부[달] || {}
    return { 달, 읽기: Number(칸.읽기 || 0), 쓰기: Number(칸.쓰기 || 0) }
  } catch { return { 달, 읽기: 0, 쓰기: 0 } }
}

// 🚦 **무료치에 얼마나 닿았나** — 「몇 %」로 말해야 사람이 판단한다.
//   🔢 파이어스토어 무료(하루) = 읽기 5만 · 쓰기 2만 · 저장 1GB
//   ⚠️ 이건 «한 사람» 몫이 아니라 **온 앱을 통틀어**다. 그래서 유저가 늘면 곧바로 닿는다.
export const 하루무료 = { 읽기: 50000, 쓰기: 20000 }

export function 몇퍼 (수, 한도) {
  if (!한도) return 0
  return Math.min(999, Math.round((Number(수 || 0) / 한도) * 100))
}

/** 한 줄로 — 설정 화면이 그대로 쓴다. */
export function 한줄로 ({ 읽기: r = 0, 쓰기: w = 0 } = {}) {
  return `이번 달 읽기 ${r.toLocaleString()}건 · 쓰기 ${w.toLocaleString()}건`
}

