// 유튜브·인스타그램 링크 → 앱 안에 띄울 수 있는 공식 임베드 주소로 변환.
// '영상 보면서 쓰기' — 위에 영상을 고정하고 아래에서 레시피를 적는 화면에 쓴다.
export function embedUrl(url = '') {
  const u = String(url)
  let m = u.match(/(?:youtube\.com\/watch\?.*v=|youtu\.be\/|youtube\.com\/shorts\/)([\w-]{6,})/)
  if (m) {
    // 🖼 [창업자 확정 2026-09-03] `thumb` = 영상 «그림»만 가져오는 주소.
    //   📮 창업자 = *"재생창은 보이게 하고 누르면 앱으로 가게해야지"*
    //             · *"우리앱에서 직접 재생만 안하면 되자나 미리보기정도는 보여줘도 되지"*
    //   ⭐⭐ 그림은 **임베드가 아니다** — 앱 안에서 «틀지» 않으므로 Developer Policies III.E.4.j
    //      (*"each YouTube video that it **embeds**"*)의 「영상마다 Made for Kids 확인」이 안 걸린다.
    //   ⛔ `src`(임베드 주소)는 남겨 둔다 — 편집 화면 「영상 보면서 쓰기」가 아직 쓴다.
    //      ⛔ 레시피 «상세»에선 `src` 를 쓰지 않는다. 거긴 `thumb` 만이다.
    //   🔢 `hqdefault` = 480×360. 그림이 없으면 화면에서 `onError` 로 그 칸을 통째로 감춘다.
    //
    // 🔒🔒 [창업자 확정 2026-09-04] `src` 는 **`youtube-nocookie.com`** 을 쓴다 — 「추적 끄기」
    //   📮 창업자 = *"아동용 영상이면 추적을 꺼야 하는데 안 끄고 있어 **이거는 문제되는거면 끄자**"*
    //   ⭐⭐ 왜 = Developer Policies III.E.4.j 는 「임베드하는 영상마다 Made for Kids 를 조회하고,
    //      MFK 면 **추적을 끄라**」고 한다. 우리는 그 조회를 아직 안 붙였다(＝어느 영상이 MFK 인지 모른다).
    //      → **모르면 «전부» 추적을 끈다.** 그러면 MFK 영상이 섞여 들어와도 지켜야 할 것은 지켜진다.
    //      📌 절대원칙 34 — 숫자를 넓힌 게 아니라 **실패의 «모양»을 바꿨다**:
    //         「모르는 영상에 추적이 켜진 채 나간다」 → 「모르는 영상도 추적이 꺼진 채 나간다」
    //   🔢 실측(2026-09-04 · 공식 도움말 ＋ 검색 다섯 곳 일치) — nocookie 가 «하는 일»
    //      ✅ 이 영상을 본 것이 유저의 유튜브 개인화에 안 쓰인다
    //      ✅ 광고가 붙어도 «비개인화» 광고로 나간다
    //      ⚠️ 다만 «추적 0»은 아니다 — 쿠키는 안 심지만 브라우저 저장소에 기기 식별자를 두고 IP 는 간다
    //   ⛔⛔ **그래서 이것이 「조회」를 대신하지 않는다.** 조문의 «의무»는 여전히 조회다.
    //      조회를 붙이는 일은 **창업자가 미뤘다(2026-09-04)** — 다시 볼 날은 아래 `recheck` 에 박아 뒀다.
    //   ⛔ 재생·전체화면·인라인은 그대로다(호스트만 바뀐다). 판이 이 주소를 글자로 붙들지 않는지 확인했다.
    return { type: 'youtube', id: m[1], src: `https://www.youtube-nocookie.com/embed/${m[1]}?playsinline=1`, thumb: `https://i.ytimg.com/vi/${m[1]}/hqdefault.jpg`, ratio: '16/9' }
  }
  m = u.match(/instagram\.com\/(?:[\w.]+\/)?(p|reel|reels|tv)\/([\w-]+)/)
  if (m) {
    const kind = m[1] === 'p' ? 'p' : 'reel'
  // ⛔⛔⛔ **[2026-09-04 · 닫혔다] 인스타 «표지 그림»은 못 가져온다. 다시 파지 말 것.**
  //   📮 창업자 = *"인스타는 유튜브처럼 미리보기 안돼??"* · *"다른앱들은 미리보기 되던데"*
  //   ✅ 끝까지 재봤다 — Cloudflare 워커(`hankki-preview`)를 만들어 창업자 폰에서 **일곱 번** 실측했다.
  //   🔢 **최종 실측 (판 0904-7)** — `www.instagram.com/reel/<번호>/` 와 `/embed/captioned/` 둘 다:
  //      · `200` (막힌 게 아니다 · 로그인벽=N)
  //      · 그런데 **제목이 그냥 "Instagram"** 이고 **embed 표식 없음**
  //      · 622KB 인데 글 안의 인스타 주소가 **전부 `static.cdninstagram.com/rsrc.php/…`**(＝화면 부품·로고)
  //      ⭐⭐ **＝ 서버가 받는 건 «빈 껍데기»다.** 글 내용도 사진 주소도 HTML 에 없고 JS 가 나중에 받아온다.
  //   ⛔ 그리고 Meta 가 **2025-11-03 부터** oEmbed 응답에서 `thumbnail_url` 을 뺐다(공식 = *"직접 만들어 쓰라"*).
  //      `/media/?size=l` 는 폐기됐고 로그인을 요구한다.
  //   ⛔ 남은 길 셋은 **전부 우리 원칙을 깬다** —
  //      진짜 브라우저를 서버에서 돌리기(요청마다 돈) · 내부 API(약관·수시로 막힘) · 유료 스크래핑(돈·약관)
  //      → 「앱이 폰 안에서 다 돈다」는 우리 최대 강점을 깬다(절대원칙 32).
  //   ✅ **그래서 인스타 편은 «문 한 줄»로 간다** — 표지 칸을 아예 안 그린다(`RecipeDetailScreen` 의 `표지보임`).
  //      ⛔ 우리 요리 사진을 그 자리에 깔지 않는다 — 「인스타에서 본 장면」으로 오해된다.
  //   📌 값을 치르고 배운 것 = 절대원칙 37(알아보고 시작한다)이 여기서 나왔다.
  //      ⛔ 다시 팔 거면 **위 실측부터 재현**할 것. 「해보면 되지 않을까」로 시작하지 말 것.
    // 🎞 `kind` 를 «내보낸다» — 화면이 「릴스로 보기」와 「원본 글 보기」를 가려 말하려면 이게 필요하다.
    //   ⛔ 「영상」이라고 뭉뜽그리면 사진 글(`p`)일 때 «거짓말»이 된다.
    //      눌러볼 이유를 만든다고 없는 것을 있다고 하면, 그건 미끼지 안내가 아니다.
    return { type: 'instagram', kind, id: m[2], src: `https://www.instagram.com/${kind}/${m[2]}/embed`, ratio: '4/5' }
  }
  return null
}

// 🔖🔖 [2026-09-04] SNS 표(▶ · 🔗)를 «두 화면»이 같은 자로 잰다 — 레시피 탭 ＋ 홈 SNS 상자.
//   📮 창업자 = *"왼쪽에 달지 않았어?? (레시피에는??)"* — 홈에도 같은 표를 달면서 잣대를 «베끼려» 했다.
//   ⛔⛔ 베끼면 반드시 갈린다 — v11.02 「책갈피」 이름이 일곱 곳에 흩어졌던 게 정확히 그 사고다.
//      그래서 잣대를 여기 «한 곳»에 두고 두 화면이 같이 부른다(CLAUDE.md 「같은 기능은 같은 이름」).
//
// ⑴ SNS에서 온 편인가 — 칩 개수·거르기·표 붙이기가 쓴다. 매체를 안 가린다(유튜브·인스타·앞으로 뭐든).
export const SNS인가 = (r) => !!(r?.sourceUrl || '').trim()
// ⑵ 앱에서 «재생»되는가 — ▶ 표가 쓴다. ⛔인스타는 재생이 안 되므로 ▶ 를 붙이지 않는다
//    (▶ 를 붙여 놓고 눌렀는데 안 나오면 그게 거짓말이다). 그 편은 🔗 로 「나가서 본다」를 말한다.
export const 영상인가 = (r) => embedUrl(r?.sourceUrl || '')?.type === 'youtube'

// ⑶🔖 **표에 무엇을 그릴까 — 한 곳에서 정한다** (창업자 2026-09-04)
//   📮 창업자 = *"인스타 로고라도 작은거 붙여서 식별이라도 하자."* ＋ *"유튜브는 그대로 영상미리보기 해놓고"*
//   ⛔ 그 전엔 인스타 편에 «일반 고리(link)» 표가 붙었다 — 그래서 **어디서 온 건지 알 수가 없었다.**
//      그 잣대(2026-09-03 확정)는 「재생되나」를 말하려던 것인데, 창업자가 원한 건 **「어디서 왔나」**다.
//   ✅ 그래서 표를 «매체»로 바꾼다 — 유튜브는 ▶ 붉은색(재생된다는 뜻이 그대로 살아 있다),
//      인스타는 **인스타 로고**. 둘 다 「어디서 왔나」를 말하고, 유튜브 쪽은 「재생된다」까지 말한다.
//   ⛔ 인스타에 ▶ 를 붙이지 않는다 — 눌렀는데 영상이 안 나오면 그게 거짓말이다.
//      (인스타 표지·영상은 서버로 못 가져온다 — 위 「닫혔다」 주석 참조)
//   ⭐ 세 화면(홈 SNS 상자 · 레시피 탭 · 상세 카드)이 이 한 곳을 부른다. 베끼면 반드시 갈린다.
export const SNS표 = (r) => {
  const e = embedUrl(r?.sourceUrl || '')
  if (e?.type === 'youtube') return { icon: 'youtube', color: '#e2352a', 뜻: 'play' }
  if (e?.type === 'instagram') return { icon: 'instagram', color: 'var(--brown)', 뜻: 'instagram' }
  // 앞으로 다른 데서 올 수도 있다 — 그땐 「나가서 본다」는 뜻의 고리로 남는다
  return { icon: 'link', color: 'var(--brown)', 뜻: 'link' }
}
