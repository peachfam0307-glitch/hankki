//
// 📮 창업자 = *"**해먹을 것 아니면 해볼 것 둘중에 하나.**"* ＋ *"책갈피는 **해볼 것 좋은게 같아 직관적이고.** 네 생각은?"*
//
// ⭐⭐⭐ **「해볼 것」으로 간다 — 창업자 감과 실측이 같은 곳을 가리켰다.**
//    결정타는 창업자가 이 이름 바꾸기를 «처음 꺼낸 이유» 그 자체다:
//    📮 *"**자주해먹는 것은 자주니까** 책갈피는 이름바꾸는 거 어떨지.."*
//    → 즉 **「자주(＝자주 해먹는 요리)」가 이미 «해먹」을 차지했으니 딴 말로 가자**는 것이었다.
//      그런데 **「해먹을 것」은 바로 그 말로 되돌아간다.** 피하려던 자리로 걸어 들어가는 셈이다.
//
// 🔢 **실측 — 「해먹」은 이미 화면에서 세 가지 뜻으로 쓰인다** (그래서 네 번째를 더하면 제일 겹치는 낱말이 된다)
//    · 홈 카드 **「오늘 뭐 해먹지?」**(두 곳) · 홈 카드 **「자주 해먹는 요리」** ·
//      도움말 *"일상에서 자주 해먹는 요리들이에요"* · 지금 책갈피 설명 *"해먹고 싶은 걸 꽂아두세요"* · *"같이 해먹자!"*
//    ⭐⭐ 그리고 **「자주」 칩은 이 칩 «바로 옆»에 선다**(`MyRecipesScreen` 필터 줄 = 전체 · 책갈피 · 자주 · 폴더…).
//       나란히 선 두 칩이 같은 낱말 뿌리를 나눠 쓰면 **한눈에 못 가른다.**
//
// ⚠️ **「해볼 것」에도 겹치는 자리가 있다 — 정직하게 적어 둔다**
//    홈 「다음에 뭐 할까」 카드의 **「아직 안 해봤어요」**(`nextUp.js:91`) · 「또 해볼까요?」(`:116`).
//    ⭐ 그래도 **「해먹을 것」쪽이 더 나쁘다 — «거리»가 다르다.**
//      · 해먹을 것 ↔ 자주(해먹는) = **같은 줄에 나란히 선 칩 둘** ＋ 같은 도움말 시트에 위아래로
//      · 해볼 것 ↔ 아직 안 해봤어요 = **다른 탭(홈)의 카드**
//      📌 한눈에 갈라야 하는 둘이 붙어 있을수록 겹침이 비싸다.
//
// ⭐ 덤 둘 = **두 글자 짧다**(칩 폭 실측 116px ↔ 132px · 필터 줄이 이미 빽빽하다) ·
//    **요리 말고 다른 것에도 걸친다**(창업자 2026-08-18 안 = 「해먹을 것, 맛있었던 것」처럼 유저가 이름표를 여럿 쓰는 것)
//
// ⛔⛔ **이름을 여기 «한 곳»에 두는 이유** — 이 자리는 벌써 **두 번** 이름이 바뀌었다
