//
// 📮 창업자 2026-09-01 = *"로그인화면에서 10개 주고 로그인하면 20개준다는 것도 안내붙였어? 스샷줘."*
//    ＋ *"그거 다하면 무료30개 제공(첫 유저 선물) 안내도 적어야 할 것 같아."*
//
// ⛔⛔ **부품으로 뺀 이유** — 그 전엔 선물 줄이 «첫 화면에만» 있었다.
//    그런데 첫 화면(CloudGate)은 **새로 깐 사람만** 본다 → 이미 쓰던 사람(창업자 포함)은
//    설정에서 시트를 열어도 **선물 얘기를 한 글자도 못 봤다.**
//    📌 **같은 안내가 두 화면에 있으면 부품으로 뺀다** — 복사하면 한쪽만 고쳐져 조용히 갈라진다
//       (KeyBadge 를 뺀 것과 같은 이유 · 2026-09-01 `_올릴판-worker.js` 가 하루 만에 갈라진 그 사고).
//
// ⛔ 숫자를 «글자로» 박지 않는다 — 서버가 준 두 상한을 읽는다(상한을 바꿔도 문구가 안 낡는다).
// ⛔ 유니코드 이모지 금지 — 우리 열쇠 그림만(절대원칙).
import { 무료열쇠상한, KEY_NAME, KEY_UNIT } from '../ocr'
import uiKeyOne from '../assets/ui/key_one.png'

export default function KeyGift() {
  const { 비로그인, 로그인, 더 } = 무료열쇠상한()
  return (
    <div className="cg-gift">
      <img src={uiKeyOne} alt="" aria-hidden="true" draggable={false} />
      <div>
        {/* ⭐ 「첫 가입 선물」을 첫 줄 머리로 올렸다 — 뒤에 붙이니 390px 에서 «세 줄»로 넘쳤다
            (규칙 21 로 찍어 보고 잡았다 · 창업자 *"구구절절 금지"*). */}
        <span>첫 가입 선물 · <b>{KEY_NAME} {로그인}{KEY_UNIT}</b></span>
        {/* ⭐ 「지금 몇 개 · 얼마나 더」를 같이 적는다 — 창업자가 콕 집은 자리다.
            그냥 「30개」만 적으면 이미 10개를 받은 사람이 «새로 30개»로 읽는다. */}
        <em>지금 {비로그인}{KEY_UNIT} · 로그인하면 {더}{KEY_UNIT}를 더 드려요</em>
      </div>
    </div>
  )
}
