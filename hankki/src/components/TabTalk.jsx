// 💬 탭 상단 「캐릭터 한마디」 — 상단바 바로 아래에 말풍선 한 줄.
//
// 📮 창업자 2026-08-21 = *"멘트넣는 건 좋은 것 같아. 심심하지 않고.."*
//    ＋ *"말풍선이면 캐릭터방향으로 풍선꼬리가 있어야해."*
//
// ⛔⛔ [창업자가 잡은 것] **홍보 문구를 앱에 그대로 옮기면 안 된다.**
//    📮 *"남의 요리책 말고. 무슨말일까 싶어.."*
//    ⭐ 홍보는 «대비·반전»이 먹힌다 — 맥락을 같이 주니까(사진·앞뒤 문장).
//       앱은 **한 줄로 뜻이 닫혀야** 한다. 매일 보고, 앞뒤가 없다.
//    ✅ 그래서 잣대 = **「한 줄로 뜻이 닫히나」**.
//       「한 권에 다 모았어」(홈쇼핑 시안에서 온 «비유») → **「여기에 다 모았어」**(창업자).
//       ⭐ 「여기에」는 «지금 보는 화면»을 그대로 가리켜 뜻이 즉시 닫힌다.
//
// 🎭 대사의 «주인» = 그 탭 상단바에 실제로 서 있는 애다 (소스로 확인, 짐작 아님)
//    · 레시피 = 🐻 꼬르곰 (`gom-header.png` · MyRecipesScreen.jsx)
//    · 일기   = 🐧 펭펭   (`wave/peng_nyam1.png` · 같은 파일 `view === 'log'`)
//    · 장보기 = 🐧 펭펭   (`wave/pn_shoplist.png` · ShopScreen.jsx)
//    · 홈     = 유저 아바타(캐릭터가 아니다) → 꼬리가 «내 얼굴»을 가리켜 혼잣말로 읽힌다
//    ⛔ 내가 처음에 「레시피=펭펭 · 장보기=꼬르곰」이라 적어뒀는데 둘 다 반대였다.
//
// ⛔ 대사는 한 탭에 «하나»만 둔다 — 여러 개를 돌리는 건 창업자 판정 대기.
//    (매일 바뀌면 재미있지만, 「어제 본 그 말」을 못 찾는 쪽이 더 크다)
//    · 레꾸자랑 = 🐻 꼬르곰 (`BragScreen.jsx` 상단바 · 실물 캡처로 확인 2026-08-24)
const 대사 = {
  home: '오늘 또 뭐 먹지?',
  myrecipes: '여기에 다 모았어.',
  log: '오늘도 한 끼 해냈다.',
  shop: '또 두부 샀네.',
  // 🎀 [2026-08-24] 레꾸자랑 — 여섯 탭 중 여기만 말풍선이 없었다(실물로 확인).
  //    ⭐ 잣대는 위와 같다: **「한 줄로 뜻이 닫히나」**. 「이건」이 «지금 고른 그 레시피»를 가리켜 즉시 닫힌다.
  //    ⏳ 문구는 창업자 판정 대기 — 시안은 `_판-자랑대사-0824.mjs` 로 실물에 얹어 찍는다.
  brag: '이건 자랑해야지.',
}

export default function TabTalk({ tab }) {
  const 말 = 대사[tab]
  if (!말) return null
  return (
    <div className="tab-talk">
      {/* ⛔ 읽어주는 도구엔 안 읽힌다 — 안내가 아니라 «분위기»다.
          탭 설명은 이미 세 겹으로 따로 있다(첫 방문 코치 · TabTips 「?」 · 화면 설명 줄). */}
      <span className="tab-talk-b" aria-hidden="true">
        {말}
        <i className="tab-talk-t" />
      </span>
    </div>
  )
}
