import { todayKST } from './today.js'

// 🗓🗓 **매주 무엇이 «무슨 요일»에 열리나 — 저장소에 여기 한 곳뿐이다.**
//
// 📮 창업자 2026-08-28 =
//    *"이번주 레시피랑 제철을 각각 다른요일에 오픈하면 어떨까.
//      **월요일날 오픈하면 일주일내내 앱이 변화가 없으니까. 나눠서 오픈하면 들어올 일이 생겨**
//      (예를 들어 월-이번주레시피 수-이번주제철 금-주부의 장바구니 이런 식으로. **요일도 딱 박고**)"*
//
// ⭐⭐ 창업자가 짚은 이유가 이 파일의 전부다 — 「무엇을 여느냐」가 아니라
//    **「몇 번 들어올 이유를 만드느냐」**. 셋이 다 월요일에 열리면 화요일부터 일요일까지
//    앱은 **아무것도 안 바뀐다.** 나누면 주 1회 → **주 3회**가 된다.
//
// 🔢 지금까지는 셋이 «전부» 월요일이었다 —
//    · 우리집레시피(`HOMEMADE`) · 이번 주 제철(`WEEKLY`) — 둘 다 `from` 이 그 주 «월요일»
//    · 주부의 장바구니 「이번 주 픽」 — `weekNo()` 가 주를 세는데 그 경계가 월요일이다
//
// ⭐⭐⭐ **데이터는 한 글자도 안 건드린다.** `from` 은 그대로 «월요일»로 두고
//    **고르는 순간의 「오늘」만 뒤로 민다.** 그러면 —
//      ⑴ `WEEKLY`(25주) · `HOMEMADE`(25주) 날짜를 다시 안 쓴다
//         (⛔ `HOMEMADE` 는 `_넣기-우리집36-0812.mjs` 가 다시 쓰는 자동 구역이라 손대면 안 된다)
//      ⑵ `basics.js` 의 레시피 `from` 과도 안 어긋난다 → 검수 게이트(`check-review`·
//         `release-calendar`)가 보는 값이 그대로다
//      ⑶ 요일을 바꾸고 싶으면 **아래 표 한 줄**만 고친다
//
// ⚠️ **「미룬다」는 뜻이지 「당긴다」가 아니다** — 수요일 갈래는 월·화엔 «지난주 것»이 그대로 보인다.
//    ⛔ 빈 자리를 만들지 않는다(우리 규칙). 바뀌는 날이 늦어질 뿐 비는 날은 없다.
//
// ⚠️ **첫 주만 한 번 「늦게 바뀐다」** — 이 판이 나가는 주에는 제철이 수요일에, 픽이 금요일에 바뀐다.
//    그 뒤로는 매주 같은 요일이라 유저가 리듬을 배운다(창업자 *"요일도 딱 박고"*).

// 🗓 요일 번호 = 월 1 · 화 2 · 수 3 · 목 4 · 금 5 · 토 6 · 일 7 (ISO)
//    ⛔ `Date.getDay()`(일=0) 와 헷갈리지 말 것 — 여기 숫자는 **「월요일에서 며칠 뒤인가」**로만 쓴다.
export const OPEN_DAY = {
  /** 🍳 우리집레시피 — **월요일**. 창업자 예시의 「이번주 레시피」다(홈 오른쪽 박스). */
  homemade: 1,
  /** 🥬 이번 주 제철 — **수요일**. 홈 왼쪽 박스(`WEEKLY`). */
  season: 3,
  /** 🛒 주부의 장바구니 「이번 주 픽」 — **금요일**. */
  pick: 5,
}

/** 사람이 읽는 요일 이름 — 안내 문구에 쓴다(⛔글자를 화면에 또 박지 말 것). */
export const DAY_NAME = { 1: '월요일', 2: '화요일', 3: '수요일', 4: '목요일', 5: '금요일', 6: '토요일', 7: '일요일' }
export const openDayName = (갈래) => DAY_NAME[OPEN_DAY[갈래] ?? 1] || '월요일'

const 하루 = 24 * 60 * 60000

/**
 * 그 갈래가 쓰는 「오늘」.
 *
 * 데이터의 `from` 은 «월요일»이므로, 열리는 요일만큼 **뒤로 민 날짜**로 비교하면
 * 그 요일이 되어야 새 줄이 열린다.
 *   예) 제철(수) · 9/07(월)자 줄 →
 *       9/07(월) 에는 밀린 날짜가 9/05 라 아직 지난 줄 · 9/09(수) 에 밀린 날짜가 9/07 → 열린다
 *
 * ⛔ 날짜 문자열은 `today.js` 만 만든다(절대원칙 27 · `check-kst` 게이트).
 *    여기서는 **`Date` 를 밀어서 넘기기만** 한다.
 */
export const openTodayKST = (갈래, now = new Date()) =>
  todayKST(new Date(now.getTime() - ((OPEN_DAY[갈래] ?? 1) - 1) * 하루))

/**
 * 같은 밀기를 **'YYYY-MM-DD' 문자열**에 적용한다.
 *
 * ⭐ 왜 따로 있나 — 「한끼 소식」(`whatsnew.js`)은 `Date` 가 아니라 «오늘 문자열»을 받아 돌고
 *    시험판도 그 문자열로 날짜를 흉내낸다. `Date` 로만 밀면 **소식과 홈이 서로 다른 날**을 본다
 *    (＝ 소식은 「열렸어요」라는데 홈엔 없는 상태 · 2026-08-12 에 실제로 났던 사고).
 * ⛔ 여기서도 날짜 문자열을 «직접» 만들지 않는다 — `todayKST` 에 밀어 넣기만 한다(절대원칙 27).
 */
/**
 * 🔁 **회전(주차)용 「오늘」** — 「이번 주 픽」처럼 `weekNo()` 로 도는 것에 쓴다.
 *
 * ⛔⛔ **`openTodayKST` 를 그대로 쓰면 «틀린다».** 그건 데이터의 `from`(＝월요일)을 기준으로 미는데,
 *    `weeklypick.js` 의 `weekNo()` 는 **에폭(1970-01-01)을 604800000ms 로 나눈다.**
 *    ⭐ **1970-01-01 은 목요일이다** → 회전이 바뀌는 경계가 «목요일»이지 월요일이 아니다.
 *    🔢 실제로 그래서 한 번 틀렸다(2026-08-28) — 월요일 기준으로 4일을 밀었더니
 *       픽이 **금요일이 아니라 «월요일»에** 바뀌었다. 재현판이 그 자리에서 잡았다.
 * ✅ 그래서 **목요일에서 얼마나 뒤인가**로 민다. 금요일이면 하루.
 */
const 에폭요일 = 4 // 1970-01-01 = 목요일
export const rotateTodayKST = (갈래, now = new Date()) =>
  todayKST(new Date(now.getTime() - ((((OPEN_DAY[갈래] ?? 1) - 에폭요일) % 7 + 7) % 7) * 하루))

/**
 * 거꾸로 — 데이터의 `from`(월요일)이 **실제로 열리는 날**.
 * ⭐ 「한끼 소식」이 「며칠 전에 열렸어요 / D-N」을 말할 때 쓴다.
 */
export const openedOn = (갈래, ymd) =>
  todayKST(new Date(Date.parse(`${ymd}T00:00:00Z`) - 9 * 60 * 60000 + ((OPEN_DAY[갈래] ?? 1) - 1) * 하루))

export const openYmd = (갈래, ymd) =>
  todayKST(new Date(Date.parse(`${ymd}T00:00:00Z`) - 9 * 60 * 60000 - ((OPEN_DAY[갈래] ?? 1) - 1) * 하루))
