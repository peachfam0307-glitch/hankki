// ⏰⏰⏰ **「오늘(KST)」을 만드는 곳 — 저장소에 여기 «하나»뿐이다.** (2026-08-17 창업자 절대원칙)
//
// 📮 창업자 원문 = *"한국시간은 정확하게 고쳐. **반복되지않게. 절대원칙. 강제할수있게 만들어**"*
//
// ⛔⛔⛔ **무슨 일이 있었나** — 2026-08-17 아침 8:01, 창업자 폰 홈에 「이번 주 제철 = 깻잎」(8/10 주차)이
//    떠 있었다. 8/17 주차 「여름 시원한 것」이 열렸어야 했는데 안 열렸다.
//    뿌리 = 날짜를 만드는 공식이 **네 곳에 흩어져 있었고 셋이 틀린 공식**이었다:
//      옛것 = `Date.now() + (9*60 + new Date().getTimezoneOffset()) * 60000`
//        · UTC 컨테이너(offset 0)  → +540분 → ✅ 맞다
//        · **KST 폰(offset −540)  → +0분  → UTC 그대로 → ⛔ 0~9시엔 «어제»**
//    ⭐ `Date.now()` 는 **이미 UTC 기준 숫자**이고 `toISOString()` 도 **UTC 로 찍는다.**
//       그러니 폰 오프셋을 더할 이유가 없다 — **그냥 +9시간.** 더하면 서로 «상쇄»된다.
//
// ⭐⭐ **왜 «한 곳»으로 모았나** — 공식이 흩어져 있으면 «한 곳만 고치고 끝났다고 말하게 된다.»
//    실제로 그랬다. 그리고 검사가 전부 UTC 컨테이너에서 도니 **넷 다 초록불**이었다.
//    이제 고칠 자리도 하나, 틀릴 자리도 하나다.
//
// 🔒 **강제 장치 = `scripts/check-kst.mjs`**(배포 게이트) —
//    이 파일 «밖»에서 날짜 문자열을 만들면 **배포가 막힌다.**
//    ＋ `scripts/_repro-KST날짜-0817.mjs` 가 **다섯 시간대에서 실제로 돌려** 값을 지킨다.
//
// ⚠️ **왜 `Intl`(`timeZone: 'Asia/Seoul'`)이 아닌가** — 그쪽도 맞는 답이지만 **엔진의 시간대 데이터**에
//    기댄다. 낮은 사양 안드로이드 웹뷰에서 데이터가 잘리면 **조용히 딴 값**이 나온다.
//    ⭐ 한국은 **1988년 이후 서머타임이 없어 UTC+9 고정**이라 산수 한 줄이 영원히 맞다.
//    (그래도 재현판이 `Intl` 로 «교차검증»한다 — 둘이 다르면 실패한다)

/** 오늘(KST)을 'YYYY-MM-DD' 로. `now` 는 시험할 때만 넣는다. */
export const todayKST = (now = new Date()) =>
  new Date(now.getTime() + 9 * 60 * 60000).toISOString().slice(0, 10)

/** 내일(KST). 「자동 공개 전날 검수」 게이트가 쓴다. */
export const tomorrowKST = (now = new Date()) =>
  new Date(now.getTime() + 33 * 60 * 60000).toISOString().slice(0, 10)
