export const BACKUP_STEPS = [5, 15]

// ⭐⭐ 「내 것」만 센다 — 기본 레시피는 빼고. (창업자 제보 2026-08-03)
//   *"설치한 사람 사진인데 «레시피 50개가 쌓였어요»는 뭐지?ㅡㅡ"*
