const read = (k) => { try { return localStorage.getItem(k) } catch { return null } }
const write = (k, v) => { try { localStorage.setItem(k, v) } catch { /* 저장 못 해도 앱은 돈다 */ } }
const drop = (k) => { try { localStorage.removeItem(k) } catch { /* noop */ } }

