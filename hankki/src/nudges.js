//   ⛔ 두 가지가 다 틀렸다 — ①아직 백업할 게 없다 ②「50개 쌓였어요」는 사실이 아니다(우리가 넣은 것).
//   ✅ 백업은 «잃으면 아까운 것»이 있을 때 권한다 =
