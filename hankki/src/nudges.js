//    *"옮긴 것 = thumb:'none' · decorBg:'sea' · 꾸미기 7컷(조각 이름 `nsg-`→`kgs-`)"* 라고 적혀 있다)
//    이 목록만 옛 id 를 들고 있었다 → **갓 깐 사람이 «1»부터 시작**했다.
//    🔢 백업 권유 문턱(10·30·60)도 그만큼 하나씩 당겨져 있었다. 리뷰 문턱을 2로 낮추자 드러났다
