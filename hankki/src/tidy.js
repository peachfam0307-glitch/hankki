// 🥄🥄 **AI 가 재료에서 «분량»을 떼어버린다 — 규칙 파서 것으로 되살린다** (창업자 제보 2026-08-31)
//
// 📮 창업자 = *"재료에 용량이 안떠"* (삼치간장조림 · 폰 캡처)
//
// 🔢 **실물로 갈랐다 — 파서가 아니라 AI 였다**
//    · 규칙 파서(같은 원문) = 「무 1/3개 · 식용유 2스푼 · 물 200ml …」 ✅
//    · 화면(AI 거친 판)      = 「무 · 식용유 · 물」 ⛔
//    · 그리고 걸음 말투가 「구워요」였다 — 그건 **AI 결과에만 나오는 말**이다(파서는 「구워줘요」).
