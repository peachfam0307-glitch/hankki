// 🧊 냉장고 재료 ↔ 레시피 재료 맞추기 — **여기 한 곳에서만** 판단한다.
//
// ⛔⛔ 왜 만들었나 (2026-08-10) — **같은 판단이 두 곳에 «따로» 적혀 있었고 둘 다 헐거웠다.**
//   ⒜ `HomeScreen.jsx` 「오늘 뭐 해먹지」 — 냉장고 이름의 «첫 낱말» 로 `ings.includes(k)`
//   ⒝ `PantryView.jsx` 「냉장고 파먹기」 — «풀네임» 으로 `ings.includes(p.name)`
//   ⒝는 더 나빴다 — 「돼지고기 앞다리살」이 「돼지고기 300g」에 **영영 안 걸린다.**
//   📌 한 곳만 고치면 나머지가 낡는다(코치 키·사진 자리·`ALL_PHOTO_FIELDS` 때와 같은 뿌리).
//
// 📊 **규칙은 짐작이 아니라 «재서» 골랐다** (`scripts/_measure-냉장고매칭-0810.mjs`)
//   시험 냉장고 22칸 × 기본 레시피 44편:
//   | 규칙 | 걸린 짝 | 낱말 «속»에서 |
//   |---|---:|---:|
//   | A 글자 포함(옛것) | 188 | **76** |
//   | B 낱말이 정확히 같을 때만 | 112 | 0 |
//   | **C ← 고른 것** | 146 | 34 |
//   ⭐ B 는 깨끗하지만 **「마늘 → 다진마늘」까지 버린다.**
//      C 는 그걸 26편 그대로 살리면서(A 대비 잃은 것 0편)
//      「무 → 풀무원·마무리·단무지」 5편 · 「파 → 스파게티·파마산·양파」 28편을 걷어낸다.
//      남은 34건은 「간장 → 진간장·국간장」처럼 **맞는 것**이다.
//
// ⭐ 규칙 C = **낱말 하나가 그 이름과 정확히 같거나, (2글자 이상이면) 그 이름으로 «끝나면» 맞다.**
//   한국어 합성어는 **핵심 명사가 뒤에 온다** — 「다진마늘」·「진간장」·「국물멸치」.
//   그래서 «끝»을 본다. 앞·가운데에서 걸리는 것(풀「무」원 · 「파」마산 · 단「무」지)은 거의 다 남이다.
//
// ⚠️⚠️ **1글자 이름은 «정확히 같을 때만»** 맞다. 「무」·「파」·「알」·「물」이 오추천의 대부분이었다
//   (실측 1글자 키 52건 → 15건). 1글자는 아무 낱말에나 들어가서 «끝»으로도 못 막는다(양「파」).
//
// ⛔ **아직 못 막는 구멍(정직하게 적어 둔다)** — 「두유」가 「노두유」에 걸린다(끝이 같다).
//   노두유(老抽)는 중국 진간장이지 두유가 아니다. 기본 레시피엔 없어서 지금은 안 터지지만,
//   유저가 직접 쓴 레시피엔 있을 수 있다. `curation.js` 는 방향이 반대라 «시작»으로 막았는데
//   여기는 「다진마늘」을 살려야 해서 같은 처방을 못 쓴다. **더 나은 수가 생기면 그때 고친다.**

// 재료 줄을 낱말로 쪼갠다 — `curation.js` 와 «같은» 구분자를 쓴다(따로 놀면 결과가 어긋난다).
export const ingredientTokens = (ingredients = []) =>
  (ingredients || []).flatMap((i) => String(i).split(/[\s,()·/]+/)).filter(Boolean)

// 냉장고 이름 → 맞출 «이름» 하나. 「돼지고기 앞다리살」 → 「돼지고기」
//   ⭐ 첫 낱말을 쓰는 이유 = 영수증·손입력은 뒤에 부위·용량이 붙는다(「소고기 국거리용」).
export const pantryKey = (name) => String(name || '').trim().split(/\s+/)[0]

// 이 낱말들 안에 그 재료가 있나
export const hasIngredient = (tokens, key) => {
  if (!key) return false
  return tokens.some((t) => t === key || (key.length >= 2 && t.endsWith(key)))
}

// 레시피 하나가 냉장고와 몇 개나 겹치나
export const countPantryHits = (recipe, pantry = []) => {
  const tokens = ingredientTokens(recipe?.ingredients)
  const seen = new Set()
  for (const p of pantry || []) {
    const k = pantryKey(p?.name)
    if (k && !seen.has(k) && hasIngredient(tokens, k)) seen.add(k)
  }
  return seen.size
}

// 🔢 추천 순서 점수
//   ⛔ 예전엔 «겹친 개수»만 봤다 → **재료가 많은 레시피가 늘 이겼다.**
//      실측: 냉장고 5칸에 「매운 소갈비찜(3/15 = 20%)」이 「초간단 순살 갈비찜(3/13 = 23%)」을 이겼다.
//      「냉장고 파먹기」인데 **더 많이 사야 하는 쪽**을 위로 올린 셈이다.
//   ⭐ 그래서 «개수»를 먼저 보고, **같은 개수면 «가진 비율»이 높은 쪽**(＝살 게 적은 쪽)이 이긴다.
//   ⛔ 비율«만» 쓰면 안 된다 — 재료 3개짜리에서 1개 걸린 것(33%)이
//      재료 12개에서 3개 걸린 것(25%)을 이겨 버린다. 1개 걸린 건 사실 아무 신호가 아니다.
export const pantryScore = (recipe, pantry = []) => {
  const n = countPantryHits(recipe, pantry)
  if (!n) return 0
  const total = (recipe?.ingredients || []).length || 1
  return n + n / total
}
