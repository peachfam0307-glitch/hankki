// 📉📉 **바뀐 것만 읽기 — 「켜는 값이 유저 수 × 레시피 수로 늘지 않는다」** (2026-09-04)
//
// 📮 창업자 = *"유저 늘어나서 만명이된다 쳐 그럼 동기화 터져?"*
//
// 🔢 **답 = 지금 그대로 켜면 «유저 200명»에서 터진다.** (실측 계산)
//   | | 지금(통째로) | 바뀐 것만 |
//   |---|---|---|
//   | 유저 200명 · 255편 | **51,200건/일** ⛔무료치(하루 5만) 초과 | 400건 |
//   | 유저 1만 명 · 255편 | **256만건/일** ⛔⛔ | 2만건 ✅ |
//   | 유저 1만 명 · **1000편** | **1,001만건/일** ⛔⛔ | **2만건** ✅ |
//   ⭐ 바뀐 것만 읽으면 **레시피가 몇 편이든 값이 안 는다.** 그래서 「나중에」가 아니라
//      **자동 받기를 켜기 «전»에** 해야 하는 일이다(절대원칙 32).
//
// ⛔⛔ **왜 지금 구조로는 못 하나 — 값이 «글자 덩어리 안»에 있다.**
//    지금 문서 = `{ j: '…JSON…', at, v, n레시피, n일기 }`.
//    `고친때` 가 그 `j` **안**에 있어서 클라우드가 «걸러줄 수가 없다».
//    ✅ 그래서 올릴 때 **`t`(고친때)를 문서 «바깥 칸»에 같이** 올린다. 그래야 `where('t','>',…)` 가 된다.
//
// ⚠️ **옛 문서엔 `t` 가 없다** — 걸러내면 «안 보인다»(사라진 것처럼 된다).
//    ✅ 그래서 **마지막 받은 때가 없으면 «통째로» 읽는다**(처음 한 번). 그 한 번은 지금과 같은 값이다.
//    📌 그 뒤부터 조금씩 — 이게 「모양을 바꾼다」이지 「숫자를 넓힌다」가 아니다(절대원칙 34).
//
// ⛔ **폰 시계를 안 믿는다** — 마지막 받은 때는 **클라우드가 준 값**으로 적는다.
//    폰 시계가 앞서 있으면 그 사이에 온 것을 영영 못 받는다.
//
// 🧪 판 = `scripts/_repro-바뀐것만-0904.mjs`

/**
 * 올릴 문서 한 개의 모양을 만든다.
 * ⭐ `j` = 지금까지 그대로(백업 JSON 한 덩어리 · 보험 ②를 안 깬다)
 * ⭐ `t` = **바깥 칸**으로 뺀 고친때. 이게 있어야 클라우드가 「그때 이후」를 걸러준다.
 *    ⛔ `j` 안의 값을 «복사»하는 것이라 두 곳이 갈릴 수 있다 —
 *       그래서 여기 한 곳에서만 만든다(부르는 쪽이 손으로 적지 않는다).
 */
export function 올릴칸만들기 (원소, 글 = null) {
  const j = 글 == null ? JSON.stringify(원소) : 글
  const t = Number(원소?.고친때 || 0)
  return t ? { j, t } : { j }
}

/**
 * 「그때 이후 바뀐 것」만 받아온다.
 *
 * @param 창구 클라우드 붙임 — { meta읽기, 바뀐것읽기(갈래, 언제부터), 통째로읽기(갈래) }
 *             ⭐ 이렇게 «갈아 끼울 수 있게» 두면 판이 파이어베이스 없이 전부 돌린다.
 * @param 마지막받은때 지난번에 받은 시각(클라우드가 준 값). 없으면 «통째로» 받는다.
 * @param 갈래들 기본 = 레시피·일기
 */
export async function 바뀐것받기 (창구, { 마지막받은때 = null, 갈래들 = ['recipes', 'diary'] } = {}) {
  const meta = await 창구.meta읽기()
  // ⭐ 마지막 받은 때 = **클라우드가 준 값**. 폰 시계를 안 쓴다.
  //    ⛔ 서버가 값을 안 주면 «갱신하지 않는다» — 엉뚱한 값을 적으면 그 뒤로 계속 어긋난다.
  const 새마지막 = meta?.서버때 != null ? Number(meta.서버때) : 마지막받은때

  const 통째로 = 마지막받은때 == null
  const 편들 = []
  for (const 갈래 of 갈래들) {
    const 온것 = 통째로
      ? await 창구.통째로읽기(갈래)
      : await 창구.바뀐것읽기(갈래, 마지막받은때)
    for (const x of 온것 || []) 편들.push({ 갈래, 편: x })
  }
  return { meta, 편들, 통째로, 마지막받은때: 새마지막 }
}

// 🚦 얼마나 읽었나 — 부르는 쪽이 계기판에 그대로 넘긴다.
//   ⭐ 「meta 1건 ＋ 편 N건」이 곧 읽기 건수다. 셈을 여기 한 곳에 둔다(두 곳에 적으면 갈린다).
export const 읽기건수 = ({ 편들 = [] } = {}) => 1 + 편들.length
