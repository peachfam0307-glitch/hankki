// 🪦🪦 **무덤 — 「지운 것은 다른 기기에서도 지워진 채로 있다」** (2026-09-04)
//
// 📮 창업자 = *"클라우드 무덤 만들어줘"*
//
// ⭐⭐ **왜 필요한가 — 합치기는 «절대 안 지우기» 때문이다.**
//    `syncMerge.js` 는 늘 «더하기»만 한다. 그게 「잃지 않는다」의 값이다.
//    ⛔ 그 대신 **지웠다는 표시가 없으면 좀비가 영원히 남는다** —
//       폰에서 지워도 패드가 자기 것을 올려 **되살린다.**
//    📌 그래서 무덤을 **폰이 아니라 «클라우드»에** 둔다. 폰에만 두면 다른 기기가 모른다.
//
// ⭐ **순서가 목숨이다 — 무덤을 «먼저» 쓰고, 그다음 문서를 지운다.**
//    뒤집으면 「지웠는데 지운 기록은 없는」 창이 생기고, 그 창에서 앱이 꺼지면
//    다른 기기가 그 편을 **되살린다.**
//    📌 `photoStore.js` 의 「창고에 먼저 넣고 서랍에서 뺀다」와 **같은 생각**이다.
//    ⛔ 무덤을 못 쓰면 **문서도 안 지운다** — 지금과 같아질 뿐 나빠지지 않는다.
//
// ⛔ **무덤에 제목·본문을 안 남긴다.** id 와 갈래와 지운때만. 무덤은 오래 남으므로
//    거기 제목이 들어가면 그게 곧 「지운 레시피 목록」이 된다.
//
// 🔢 **문서 «하나»에 통째로 담는다** — 무덤 한 줄 ≈ 80 B 라 1000편을 지워도 80 KB.
//    문서 한 개 상한(900 KB · `cloud.js` 한덩어리) 안이다.
//    ⭐ 그래서 **읽기가 1건**이다. 문서를 1000개로 쪼개면 켤 때마다 1000건을 읽는다(절대원칙 32).
//
// 🧪 판 = `scripts/_repro-클라우드무덤-0904.mjs` (10칸)

export const 무덤칸 = 'graves'
const 살려두는날 = 90   // ⭐90일 — 무덤이 성능을 먹는 건 업계가 이미 치른 값이다(조사 근거)

// 🧰 클라우드를 갈아 끼울 수 있게 — 판이 파이어베이스 없이 전부 돌린다.
let 붙은것 = null
export function _창고물리기 (것) { 붙은것 = 것 }
const 창 = () => {
  if (!붙은것) throw new Error('클라우드가 안 붙었다')
  return 붙은것
}

/**
 * 지운다 — ⭐**무덤을 «먼저» 쓰고, 그다음 문서를 지운다.**
 * @param 것들 [{ 갈래, id }]
 * @returns { 됐나, 왜? }  ⛔무덤을 못 쓰면 문서도 «안» 지운다
 */
export async function 묻기 (것들 = [], { 지운때 = Date.now() } = {}) {
  if (!것들.length) return { 됐나: true, 묻은것: 0 }
  try {
    const 옛것 = (await 창().읽기(무덤칸)) || []
    const 목록 = Array.isArray(옛것?.목록) ? 옛것.목록 : (Array.isArray(옛것) ? 옛것 : [])
    const 본것 = new Set(목록.map((x) => `${x.갈래}:${x.id}`))
    for (const x of 것들) {
      if (!x || x.id == null) continue
      const 열쇠 = `${x.갈래 || 'recipes'}:${x.id}`
      if (본것.has(열쇠)) continue
      // ⛔ id·갈래·지운때만. 제목은 «절대» 안 넣는다.
      목록.push({ 갈래: x.갈래 || 'recipes', id: String(x.id), 지운때 })
      본것.add(열쇠)
    }
    // ⭐ 여기서 던지면 아래 「지우기」가 «안» 돈다 — 그게 바라는 바다.
    await 창().쓰기(무덤칸, { 목록: 무덤청소(목록), at: new Date().toISOString() })
  } catch (e) {
    // ⛔⛔ **무덤을 못 썼으면 문서를 지우지 않는다.**
    //    지금과 같아질 뿐(＝클라우드에 남아 있음) 나빠지지 않는다.
    return { 됐나: false, 왜: (e && e.message) || '무덤을 못 썼다' }
  }

  // 🗑 이제 문서를 지운다 — 무덤이 이미 남았으므로 여기서 꺼져도 다른 기기가 안 되살린다.
  let 지운수 = 0
  for (const x of 것들) {
    try { await 창().지우기(`${x.갈래 || 'recipes'}/${x.id}`); 지운수++ } catch { /* 하나 못 지워도 나머지는 간다 */ }
  }
  return { 됐나: true, 묻은것: 것들.length, 지운것: 지운수 }
}

/** 다른 기기가 읽는다 — ⭐읽기 «1건». */
export async function 무덤읽기 () {
  try {
    const v = await 창().읽기(무덤칸)
    const 목록 = Array.isArray(v?.목록) ? v.목록 : (Array.isArray(v) ? v : [])
    return 무덤청소(목록)
  } catch { return [] }
}

/** 🧹 90일 지난 무덤은 버린다 — 안 그러면 무덤이 본체보다 커진다.
 *
 * ⛔⛔ **[2026-09-04 · 판이 잡았다] 「지운때」가 «두 가지 뜻»으로 쓰이고 있었다.**
 *   · 청소는 「진짜 시각(1757…)」으로 읽고 · 되살리기 판정(`무덤적용`)은 「그냥 커지는 수」로 읽는다.
 *   그래서 작은 수(예: 5000)로 묻으면 **방금 쓴 무덤이 «90일 지났다»로 곧바로 청소됐다.**
 *   ⭐ 이게 실물에서 나면 「지웠는데 다른 기기에서 되살아난다」가 된다 — 정확히 막으려던 그 사고다.
 *
 * ✅ 그래서 **「진짜 시각처럼 보이는 것」만 청소한다.**
 *    잣대 = 2001년 이후(1e12 넘는 수)라야 «시계에서 온 값»이다.
 *    그보다 작은 수는 «순서를 매기는 수»라 나이를 잴 수 없다 → **청소하지 않는다(안 지운다).**
 *    📌 잃지 않는 쪽으로 기운다 — 무덤이 좀 오래 남는 건 괜찮지만, 일찍 사라지면 좀비가 돌아온다.
 */
const 시계값인가 = (n) => Number(n) > 1e12
export function 무덤청소 (목록 = [], 이제 = Date.now()) {
  const 문턱 = 이제 - 살려두는날 * 24 * 3600 * 1000
  return (목록 || []).filter((x) => {
    const t = Number(x?.지운때 || 0)
    if (!시계값인가(t)) return true   // ⛔ 나이를 못 재면 «안 지운다»
    return t >= 문턱
  })
}

/**
 * ⭐⭐ **지운 뒤에 «다른 기기가 고쳤으면» 되살린다.**
 *   사람이 다시 손댄 것이 «더 최근 뜻»이다 — 지운때 < 고친때 면 그 편은 살린다.
 *   ⛔ 이게 없으면 「지웠다가 다시 쓴 레시피」가 영영 안 살아난다.
 *   📌 `syncMerge.js` 의 무덤 판정도 이 규칙을 그대로 따라야 한다(잣대가 갈리면 안 된다).
 */
export function 무덤적용 (목록 = [], 무덤 = [], 갈래 = 'recipes') {
  if (!무덤?.length) return 목록 || []
  const 표 = new Map()
  for (const g of 무덤) if ((g.갈래 || 'recipes') === 갈래) 표.set(String(g.id), Number(g.지운때 || 0))
  return (목록 || []).filter((x) => {
    const 지운때 = 표.get(String(x?.id))
    if (지운때 === undefined) return true
    // ⭐ 지운 «뒤»에 고쳤으면 살린다
    return Number(x?.고친때 || 0) > 지운때
  })
}

export const _내부 = { 살려두는날 }
