//    자동으로 안붙어."* → *"분류에 맞게 붙여줘. 이게 제목이 잘 안들어가면 아이콘도 이상한거 붙자나"*
//    → *"이거 예전 문서에 있을텐데.. 방법이 한번찾아봐"* ← **맞았다. 이미 있었다.**
//
// ⭐⭐ 뿌리 = **아이콘을 «글자를 읽기 전»에 정해서 박아버린다.**
//    `makeInboxRecipe()` 가 `icon: guessFoodIcon(title)` 로 굳히는데(ImportScreen.jsx),
//      · 앱에서 «사진 가져오기» = 그때 이미 OCR 이 끝나 제목이 진짜 이름 → 잘 붙는다
//      · SNS·갤러리 «공유»      = OCR 이 아직 안 돌아 제목이 빈 이름 → **'default'(빈 접시)로 굳는다**
//    그 뒤 `App.jsx` 가 OCR 결과로 제목을 채우는데 **아이콘은 안 고쳤다.**
//    화면(`Thumb.jsx`)은 `recipe.icon || guessFoodIcon(recipe.title)` 이라 —
//    **`icon` 에 값이 박혀 있으니 뒷쪽 자동찾기가 영영 안 돈다.**
//
// ⭐⭐ **「직접 고른 것은 안 덮는다」는 이미 정해져 있다** — `iconPicked` (v9.77 · 2026-08-05).
//    📮 그때 창업자 제보 = *"제목 육회로 바꿔도 아이콘 안 바뀜"* → 편집 화면이 이 규칙으로 산다:
//       `keepIcon = !!f.icon && (iconPicked || 제목그대로)` (EditorScreen.jsx)
//    🔒 `scripts/check-thumb.mjs` 가 그 규칙이 사라지면 배포를 막는다.
//    ⛔ 나는 처음에 「제목이 바뀌었나」로 «새 규칙»을 만들려 했다 — 창업자가 옛 문서를 찾아보라고
//       해서 이걸 발견했다. **같은 일에 규칙이 둘이면 한쪽을 고칠 때 다른 쪽이 낡는다.**
//
// ⛔⛔ **한 글자 낱말에만 걸린 매칭은 «OCR 이 읽은 제목»에는 안 쓴다.**
//    📮 창업자 = *"제목이 잘 안들어가면 아이콘도 이상한거 붙자나"* — 실물로 재보니 정확했다:
//       「게시물」 → 「물」에 걸려 **물 그림** · 「2:49 9 나였으면 다」 → 「면」에 걸려 **국수 그림**
//    🔢 한 글자 규칙은 21개(회·면·죽·쌀·밥·떡·빵·쌈·파·콘·콩·닭·굴·꿀·잼·귤·물·김·잣·국·탕).
//       사람이 «직접 친» 제목엔 필요하다(「떡」·「빵」). 그래서 **여기서만** 막는다 —
//       편집 화면에서 손으로 고친 제목은 그대로 한 글자도 쓴다(사람이 쓴 말은 믿는다).
//    ⛔ 재료·걸음까지 같이 보는 길은 «재보고 버렸다» — 탕수육 재료를 같이 넣으면
//       「양파」에 걸려 **재료 그림**이 붙는다. 지금보다 나쁘다.
//
// ⚠️ 이건 «앞으로 담는 것»만이다(규칙 18 ⓙ). 이미 담긴 골쫄면·부대찌개는 그대로다 —
//    옛것을 고칠지는 별개 판정이라 창업자에게 따로 묻는다.

// 📥 OCR 이 제목을 채운 뒤 아이콘을 다시 찾을까 — 찾으면 키, 아니면 null(안 건드림).
//   ⛔ `iconPicked` 가 참이면 **무조건** null — 창업자가 직접 고른 것이다(v9.77 규칙 그대로).
//   ⛔ 못 찾으면(default) null — 있던 것보다 나빠질 길을 아예 없앤다.
export function 공유아이콘(rec, 새제목, 찾기) {
  if (rec && rec.iconPicked) return null
  const b = String(새제목 || '').trim()
  if (!b) return null
  const k = 찾기(b)
  if (!k || k === 'default') return null
  return k === (rec && rec.icon) ? null : k
}
