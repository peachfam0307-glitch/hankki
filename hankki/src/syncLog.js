// 📜📜 **동기화 기록 — 「무엇이 언제 오갔는지 반드시 남는다」** (2026-09-04)
//
// 📮 창업자 = *"동기화 기록 만들어줘"*
//
// 🚨🚨 **왜 필요한가 — 기록이 «0» 이라서 원인을 못 찾았다**
//    2026-09-01 23:51 에 자동 받기가 방금 담은 레시피를 덮었다. 그런데 **무엇이 언제 오갔는지
//    아무 기록이 없어서** 「어느 길로 덮였나」를 끝내 확정하지 못했다.
//    → 원인을 모르니 고칠 수도 없어 **자동 받기를 통째로 잠가 두었다**(`App.jsx` 의 `if (false)`).
//    📌 기록이 있었으면 그날 밤에 끝났을 일이다.
//
// ⭐⭐ **이 파일의 규칙 둘 — 둘 다 «안 하는 것»이다**
//   ⛔ **개수만 남긴다. 레시피 제목·본문은 «절대» 안 남긴다.**
//      제목은 곧 개인정보고, 기록은 오래 남는다. 한 번 새면 되돌릴 수 없다.
//      ✅ 그래서 «허락한 칸»만 받는다(모르는 칸은 통째로 버린다). 막는 게 아니라 «못 들어오게» 만든다.
//   ⛔ **절대 던지지 않는다.** 기록이 실패해서 «동기화가 멈추는」 일은 없어야 한다.
//      기록은 곁다리다 — 곁다리가 본 일을 죽이면 안 된다.
//
// ⛔ 작은 서랍(localStorage)에 안 쓴다 — 창업자 폰이 이미 **91%(4.56MB/5MB)** 였다(2026-09-02 실측).
//    ✅ 되돌리기가 쓰는 **같은 창고**(`hankki-undo`)를 빌린다. 새 창고를 만들면 관리할 자리가 는다.
//    🔢 한 줄 ≈ 120 B × 50줄 ≈ **6 KB** — 폰 안에만 있어 **유저 수와 무관**하다.
//
// 🧪 판 = `scripts/_repro-동기화기록-0904.mjs` (9칸)

const 기록열쇠 = '기록'
const 줄수 = 50   // ⭐50줄만 — 무한히 쌓이면 창고를 먹는다(무덤이 성능을 먹는 것과 같은 성질)

// 🧰 창고는 되돌리기와 «같은 것»을 쓴다. 판이 갈아 끼울 수 있게 열어 둔다.
let 붙은창고 = null
export function _창고물리기 (것) { 붙은창고 = 것 }
async function 창고 () {
  if (붙은창고) return 붙은창고
  const m = await import('./syncUndo.js')
  // ⭐ `syncUndo` 가 들고 있는 진짜 창고를 그대로 쓴다 — 창고를 두 벌 열지 않는다.
  return m._창고()
}

// ⛔⛔ **허락한 칸만 통과시킨다.** 「빼야 할 것을 지운다」가 아니라 **「넣을 것만 받는다」**이다.
//   📌 지우는 쪽으로 만들면 칸이 늘 때마다 새는 구멍이 생긴다 —
//      `cloud.js` 의 사진털기가 「칸 이름으로 고르지 않는다」고 적어 둔 것과 같은 생각이다.
const 허락한칸 = ['한일', '왜', '기기', '받은것', '합친것', '지운것', '올린것', '되돌린것']

export async function 적기 (것 = {}) {
  try {
    const 줄 = { 때: new Date().toISOString() }
    for (const k of 허락한칸) {
      const v = 것[k]
      if (v === undefined || v === null) continue
      // ⭐ 글자는 짧게 자른다 — 「왜」에 긴 오류 글이 통째로 들어오면 그 안에 무엇이 섞일지 모른다
      줄[k] = typeof v === 'string' ? v.slice(0, 40) : (typeof v === 'number' ? v : String(v).slice(0, 40))
    }
    const 창 = await 창고()
    const 옛것 = (await 창.꺼내기(기록열쇠)) || []
    const 새것 = [줄, ...(Array.isArray(옛것) ? 옛것 : [])].slice(0, 줄수)
    await 창.넣기(기록열쇠, 새것)
    return true
  } catch {
    // ⛔⛔ **여기서 던지면 동기화가 멈춘다.** 기록은 곁다리다 — 조용히 넘어간다.
    return false
  }
}

/** 최근 것이 «맨 앞». 화면이 그대로 그린다. */
export async function 읽기 () {
  try {
    const v = await (await 창고()).꺼내기(기록열쇠)
    return Array.isArray(v) ? v : []
  } catch { return [] }
}

/** 설정에서 「기록 비우기」 */
export async function 지우기 () {
  try { await (await 창고()).지우기(기록열쇠) } catch { /* 못 지워도 치명적이지 않다 */ }
}

// 🗣 한 줄로 읽히게 — 설정 화면이 그대로 쓴다.
//   ⭐ 창업자가 원한 건 「기록이 있다」가 아니라 **「무슨 일이 있었는지 읽힌다」**이다.
export function 한줄로 (줄) {
  if (!줄) return ''
  const 어디 = 줄.기기 ? `${줄.기기}에서 ` : ''
  if (줄.한일 === '받음') {
    const 조각 = []
    if (줄.받은것) 조각.push(`${줄.받은것}편 받음`)
    if (줄.합친것) 조각.push(`${줄.합친것}편 합침`)
    if (줄.지운것) 조각.push(`${줄.지운것}편 지움`)
    return `${어디}${조각.join(' · ') || '바뀐 것 없음'}`
  }
  if (줄.한일 === '올림') return `${어디}${줄.올린것 || 0}편 올림`
  if (줄.한일 === '되돌림') return `되돌림 (${줄.되돌린것 || 0}편)`
  if (줄.왜) return `못 함 — ${줄.왜}`
  return 줄.한일 || ''
}

export const _내부 = { 허락한칸, 줄수, 기록열쇠 }
