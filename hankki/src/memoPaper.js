// 📌📌 「지난번 메모」 포스트잇이 쓸 «종이» — 목록과 고르는 법을 한 곳에 둔다.
//
// 📮 창업자 2026-08-20 = *"귀여운게 많아서 **포스트잇을 랜덤으로 붙이는거 어때?**"*
//    ✅ 판정 = **레시피마다 다르게** (같은 레시피는 늘 같은 종이) · **버릴 컷 없다 · 다 써도 된다**
//
// ⛔⛔ **「볼 때마다 바뀜」이 아니다** — 같은 레시피를 열 때마다 종이가 달라지면
//    어수선하고 「고장인가」로 읽힌다. 우리가 원하는 건 «다양한데 안 흔들리는 것».
//
// ⭐⭐ **왜 「저장」인가 — 「id 로 계산」만 하면 종이를 «추가»할 때 다 뒤바뀐다.**
//    해시 % 16 이던 것이 % 20 이 되면 **이미 쓴 메모의 종이가 전부 갈린다.**
//    유저 눈엔 「내 메모지가 왜 바뀌었지」가 된다. 창업자가 컷을 더 줄 가능성은 늘 높다.
//    ✅ 그래서 **메모를 만들 때 종이를 «적어 둔다»**(`store.jsx` `addDiary`).
//       ⛔ 이미 쓴 메모엔 그 값이 없다 → 그때만 아래 해시로 폴백한다.
//          그 메모들은 컷을 추가하면 갈리지만, **새로 쓰는 것부터는 안 갈린다.**
//
// ⛔ 여기 목록과 `Stickers.jsx` 의 `PHOTO_RATIO`·`BOX_PAD` 는 «같은 키»라야 한다.
//    어긋나면 종이가 안 뜬다 — `scripts/check-memopaper.mjs` 가 배포를 막는다.

export const MEMO_PAPERS = [
  'pn101', 'pn102', 'pn103', 'pn104',
  'pn201', 'pn202', 'pn203', 'pn204',
  'pn301', 'pn302', 'pn303', 'pn304',
  'pn401', 'pn402', 'pn403', 'pn404',
]

// 🎲 그 레시피의 종이 — «늘 같은 답»이 나온다(무작위가 아니라 「고정 랜덤」).
//    ⛔ `Math.random()` 을 쓰지 않는다 — 그건 「볼 때마다 바뀜」이고 창업자가 안 고른 쪽이다.
export function pickPaper(recipeId) {
  const s = String(recipeId || '')
  let h = 0
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0
  return MEMO_PAPERS[h % MEMO_PAPERS.length]
}
