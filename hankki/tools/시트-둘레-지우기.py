#!/usr/bin/env python3
# 🧽 그릇 둘레의 «흐린 빛무리»를 순백으로 지운다 — 자르기 «전»에 (2026-08-26 · 2판)
#
# 📮 창업자 = *"가위로 자른 것 같지않고 표면이 찢은것 같아보이는거는 고칠수 없는거야?"*
#            · *"바닥면쪽이 대부분 손으로 찢은거같아"* · *"원본으로 다시잘라 이렇게 땜빵하지말구."*
#
# ⭐⭐ **창업자 프롬프트는 잘못이 없다. 이름표도 문제가 아니다. 자르는 쪽 문제였다.**
#
# ⛔⛔ 뿌리 — 실측(구움찰떡 칸 · 굽 아래 세로 단면)
#     굽 몸통 `236 236 236 …` │ `191 190`(굽 바닥선) │ `218 224 … 244 **246 246** 248 250 253 254`
#     ⭐ `cut.py` 의 배경 문턱이 **246** 인데, 굽 «아래» 빛무리가 218 → 254 로 **서서히** 밝아져
#       **그 문턱이 빛무리 한가운데를 지난다** → 실루엣이 줄마다 1~2px 흔들리고,
#       흰 테는 실루엣을 «부풀려» 만들기 때문에 그 흔들림이 **계단**으로 확대된다.
#       그게 「손으로 찢은 것 같다」의 정체다.
#
# ✅ 그래서 몸통을 **`<246` 덩어리**로 잡는다 — **`cut.py` 문턱과 «똑같이».**
#   그러면 잘렸을 때의 경계가 내가 만든 덩어리 경계와 **정확히 일치**해서 흔들림이 0이 된다.
#
# ⛔⛔⛔ **1판이 저지른 사고 — 「진갈색 선(<200)을 따라 자르기」는 접시 «굽»을 통째로 먹었다.**
#   📮 창업자 = *"근데 접시를 많이 잘라먹은 듯..."* ·
#              *"좋다고 한것도 아랫부분없이 윗부분만 잘라놓은것들이 많아 찰떡이랑 쿠키같은."*
#   🔢 실측(구움찰떡) = 진갈색 선 덩어리 y168~**444** ／ 밝기 덩어리 y167~**485** → **45px 차이**
#      **창업자가 넣은 진갈색 윤곽선은 접시 «테두리»에만 있고 굽엔 없다.**
#      그런데 1판은 `선 넓이 ≥ 밝기 × 0.70` 이면 선을 썼고, 여기선 **84.6%** 라 통과했다.
#      → 굽 45px 이 「몸통 바깥」으로 판정돼 **순백으로 지워졌다.**
#   🔢 전수 = 108컷 중 **세로 10% 이상 잘린 것 30컷** · 5~10% 8컷.
#      창업자 판정도 그대로 나왔다 — 찰떡·쿠키·호떡·티라미수·팥빙수·팬케이크가 전부 「깨짐」.
#   📌 **넓이 비율로는 굽을 못 지킨다** — 굽은 넓이로 15%뿐이라 어떤 문턱을 잡아도 통과한다.
#      그래서 진갈색 선은 **아예 안 쓴다.**
#
# ⭐⭐ **＋ 그래서 도구가 스스로 잰다** — 몸통이 `<253` 덩어리보다 «많이» 짧으면 **죽는다.**
#   내가 세 번 헛짚은 뿌리가 「꺾임」만 재고 **「접시를 먹었나」를 안 잰 것**이라서다.
#   ⛔ 「규칙으로 적어두기」로는 안 된다 — 1판 주석에도 *"그림은 한 픽셀도 안 건드린다"* 라고
#      내 손으로 적어놓고 45px 을 먹었다.
#
# ⛔ `tools/cut.py` 는 손대지 않는다(창업자 절대원칙 2026-08-18).
# ⛔ 시트 «통째로» 하지 않는다 — 칸마다 몸통이 달라서 행×열을 «반드시» 준다.
#
# 씀:  python3 tools/시트-둘레-지우기.py <시트> <낼파일> <행> <열>
import os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

시트, 낼파일 = sys.argv[1], sys.argv[2]
행, 열 = int(sys.argv[3]), int(sys.argv[4])

몸통문턱 = 246   # ⛔ cut.py 의 배경 문턱과 «같아야» 한다. 다르면 그 차이만큼 경계가 흔들린다
빛무리끝 = 253   # 「진짜 그림이 어디까지인가」를 재는 눈 — 이보다 짧아지면 접시를 먹은 것이다
먹힘한계 = 0.08  # 몸통이 빛무리끝 덩어리보다 8% 넘게 짧으면 ⛔죽는다(1판 사고 = 13.8%)

im = Image.open(시트).convert('RGB')
a = np.asarray(im).astype(np.int16).copy()
mn = a.min(axis=2)
H, W = mn.shape
전체 = 0
죽음 = []
for r in range(행):
    for c in range(열):
        y0, x0 = r * H // 행, c * W // 열
        y1, x1 = (r + 1) * H // 행, (c + 1) * W // 열
        k = mn[y0:y1, x0:x1]
        칸 = r * 열 + c + 1

        def 덩어리(문턱, 닫기=7):
            f = ndimage.binary_fill_holes(ndimage.binary_closing(k < 문턱, np.ones((닫기, 닫기))))
            lab, n = ndimage.label(f)
            if not n:
                return None
            return lab == int(np.argmax(ndimage.sum(f, lab, range(1, n + 1)))) + 1

        몸 = 덩어리(몸통문턱)
        # ⛔⛔ 참고 문턱을 «박아 넣으면 안 된다» — 시트마다 배경 밝기가 다르다(실측).
        #   `c39e07e4`(구이 시트)는 **배경이 순백이 아니라 252~253** 이라 `<253` 덩어리가
        #   **배경을 통째로 잡아** 칸 전체(523px)가 「그림」이 되고, 멀쩡한 컷이 「34% 먹혔다」로 나왔다.
        #   ✅ 그래서 **배경을 안 잡는 제일 높은 문턱**을 칸마다 고른다 —
        #      덩어리가 «칸 가장자리에 닿으면» 그건 그림이 아니라 배경이다.
        #   ⛔ 「칸 가장자리에 닿나」만으로는 못 잡는다 — 배경 덩어리가 **3px 여백을 두고** 생겨서
        #      가장자리 검사를 빠져나갔다(실측 y3~525). ✅그래서 **몸통 대비 넓이**로도 거른다.
        #      배경을 삼키면 넓이가 훅 뛴다: 구움찰떡 **1.06배**(정상) ↔ 구이 시트 **1.64배**(삼킴).
        #      ⭐ 넓이 비율은 «칸 크기와 무관»해서 시트가 바뀌어도 안 낡는다.
        참고 = None
        if 몸 is not None:
            h, w = 몸.shape
            for t in (빛무리끝, 252, 251, 250, 248):
                d = 덩어리(t)
                if d is None:
                    continue
                띠 = np.zeros_like(d)
                띠[:5] = 띠[-5:] = True
                띠[:, :5] = 띠[:, -5:] = True
                if (d & 띠).any() or d.sum() > 몸.sum() * 1.3:
                    continue
                참고 = d
                break
        if 몸 is None or 참고 is None:
            continue

        # ⛔⛔ 「접시를 먹었나」 — 자르기 «전»에 여기서 잡는다
        m줄 = np.where(몸.any(axis=1))[0]
        c줄 = np.where(참고.any(axis=1))[0]
        m높, c높 = int(m줄[-1] - m줄[0] + 1), int(c줄[-1] - c줄[0] + 1)
        먹힘 = (c높 - m높) / max(1, c높)
        if 먹힘 > 먹힘한계:
            죽음.append(f'{칸}칸 세로 {먹힘:.1%}({c높}→{m높}px)')
            continue

        # ⛔ 3px 부풀려서 «가장자리 반투명 띠»는 남긴다 — 안 그러면 계단이 도로 생긴다
        지울 = (~ndimage.binary_dilation(몸, np.ones((3, 3)))) & (k < 255)
        n지 = int(지울.sum())
        if not n지:
            continue
        a[y0:y1, x0:x1][지울] = 255
        전체 += n지
        print(f'  {칸:02d}칸 — 몸통 y{m줄[0]}~{m줄[-1]}(먹힘 {먹힘:.1%}) · 둘레에서 지운 빛무리 {n지:,}px')

if 죽음:
    # ⛔ 조용히 넘기지 않는다 — 「고쳤다」고 말하게 된다
    print(f'⛔ {os.path.basename(시트)} — 접시를 먹었다: {" · ".join(죽음)}', file=sys.stderr)
    sys.exit(1)

os.makedirs(os.path.dirname(os.path.abspath(낼파일)), exist_ok=True)
Image.fromarray(a.astype(np.uint8)).save(낼파일)
print(f'✅ {os.path.basename(시트)} — 모두 {전체:,}px 지워 {낼파일} 로 냈다')
