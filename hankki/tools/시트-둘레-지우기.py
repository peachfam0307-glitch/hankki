#!/usr/bin/env python3
# 🧽 그릇 둘레의 «흐린 얼룩»을 순백으로 지운다 — 자르기 «전»에 (2026-08-26)
#
# 📮 창업자 = *"가위로 자른 것 같지않고 표면이 찢은것 같아보이는거는 고칠수 없는거야?"*
#            · *"바닥면쪽이 대부분 손으로 찢은거같아"* · *"원본으로 다시잘라 이렇게 땜빵하지말구."*
#            · *"다 네가 하란대로 추가해서 넣었는데 왜 매끈하지가 않은거야? 이름표를 뺄까?"*
#
# ⭐⭐ **창업자 프롬프트는 잘못이 없다. 이름표도 문제가 아니다. 자르는 쪽 문제였다.**
#
# ⛔⛔ 뿌리(실측 · 계란찜 칸 가운데 세로 단면)
#     … 195 194 203 138 **54** ← 여기가 진갈색 외곽선(＝접시 끝)
#     그 아래 → **244 · 248 · 246 · 250** · 253 · 254 …
#     ⭐ `cut.py` 의 배경 문턱이 **246** 이다. 즉 접시 바로 밑 네댓 줄이 **문턱을 걸치고 있다.**
#     → 실루엣이 줄마다 1~2px 씩 흔들리고, **흰 테는 그걸 «부풀려서» 만들기 때문에**
#       그 흔들림이 눈에 보이는 **계단**이 된다. 그게 「손으로 찢은 것 같다」의 정체다.
#
# ⛔ 내가 두 번 헛짚었다 (규칙 18 — «확인 방식»부터 의심할 것)
#   ⑴ *"그림자를 73px 이나 같이 자르고 있다"* → **closing 을 작게(5) 줘서 외곽선이 안 닫힌 탓**이었다.
#      제대로 닫으니(7) 문턱을 뭘로 잡든 몸통이 **2~3px 차이**뿐이다. 그림자 문제가 아니다.
#   ⑵ 자른 «뒤» 알파를 다듬는 판을 만들었다 → 창업자 = *"땜빵하지말구"*. 맞는 말이다.
#      **원본을 깨끗하게 해서 다시 자르는 게 맞다** — `시트-라벨지우기.py` 와 같은 자리의 일이다.
#
# ⭐ 하는 일 = 칸마다 **몸통 바깥**의 순백 아닌 얼룩을 **255 로** 지운다.
#   · 몸통 = `<250` 을 **7px 로 닫고 채운** 제일 큰 덩어리 → **접시 «안»이 통째로 들어온다**
#   · 지울 곳 = 그 몸통을 3px 부풀린 것의 **바깥**뿐 → **그림은 한 픽셀도 안 건드린다**
#   ⛔ 첫 판은 몸통을 「잉크(<200) 제일 큰 덩어리」로 잡았다가 **접시 «안»까지 지워** 얼룩덜룩해졌다.
#
# ⛔ `tools/cut.py` 는 손대지 않는다(창업자 절대원칙 2026-08-18).
# ⛔ 시트 «통째로» 하지 않는다 — 칸마다 몸통이 달라서 행×열을 «반드시» 준다.
#
# 씀:  python3 tools/시트-둘레-지우기.py <시트> <낼파일> <행> <열>
import os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

시트, 낼파일 = sys.argv[1], sys.argv[2]
행, 열 = int(sys.argv[3]), int(sys.argv[4])

im = Image.open(시트).convert('RGB')
a = np.asarray(im).astype(np.int16).copy()
mn = a.min(axis=2)
H, W = mn.shape
전체 = 0
for r in range(행):
    for c in range(열):
        y0, x0 = r * H // 행, c * W // 열
        y1, x1 = (r + 1) * H // 행, (c + 1) * W // 열
        k = mn[y0:y1, x0:x1]

        def 덩어리(문턱, 닫기=7):
            f = ndimage.binary_fill_holes(ndimage.binary_closing(k < 문턱, np.ones((닫기, 닫기))))
            lab, n = ndimage.label(f)
            if not n:
                return None
            return lab == int(np.argmax(ndimage.sum(f, lab, range(1, n + 1)))) + 1

        # ⭐⭐ **창업자가 그려 넣은 «진갈색 외곽선»을 따라 자른다** — 밝기 문턱이 아니라.
        #    밝기(<250)로 잡으면 그릇 밑 «흐린 빛무리»까지 몸통이 되고, 그 경계가 줄마다 흔들린다.
        #    🔢 실측 = 아래띠 «꺾임» 나박물김치 1.47 → **0.65** · 오이소박이 1.28 → **0.61** (절반)
        #    🔢 그리고 몸통이 실제로 짧아진다 — 나박물김치 y62~375 → y66~**327**(빛무리 48px)
        밝 = 덩어리(250)
        선 = 덩어리(200)
        if 밝 is None:
            continue
        # ⛔ 외곽선이 «닫혀 있을 때만» 쓴다 — 안 닫히면 채워지지 않아 몸통이 훅 작아진다
        몸 = 선 if (선 is not None and 선.sum() >= 밝.sum() * 0.70) else 밝
        if 선 is not None and 몸 is 밝:
            print(f'  ⚠️ {r * 열 + c + 1:02d}칸 — 진갈색 선이 안 닫혔다. 밝기로 잡는다')
        # ⛔ 3px 부풀려서 «가장자리 반투명 띠»는 남긴다 — 안 그러면 계단이 도로 생긴다
        지울 = (~ndimage.binary_dilation(몸, np.ones((3, 3)))) & (k < 255)
        n지 = int(지울.sum())
        if not n지:
            continue
        a[y0:y1, x0:x1][지울] = 255
        전체 += n지
        ys = np.where(몸.any(axis=1))[0]
        print(f'  {r * 열 + c + 1:02d}칸 — 몸통 y{ys[0]}~{ys[-1]} · 둘레에서 지운 얼룩 {n지:,}px')

os.makedirs(os.path.dirname(os.path.abspath(낼파일)), exist_ok=True)
Image.fromarray(a.astype(np.uint8)).save(낼파일)
print(f'✅ {os.path.basename(시트)} — 모두 {전체:,}px 지워 {낼파일} 로 냈다')
