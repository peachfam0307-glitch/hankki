#!/usr/bin/env python3
# 🍽 「접시 «굽»(바닥)만」 아주 살짝 눌러 준다 — 자르기 «전»에 쓰는 도구 (2026-08-26)
#
# 📮 창업자 = *"아랫부분이 깨진거많은데"* · *"무화과 김치 오이소박이 만두등등 깨졌어아래가"*
#            → *"접시바닥면만 어떻게 잘 해봐ㅠ"*
#
# ⛔⛔ 무슨 일이 나고 있었나 (실측)
#   `tools/cut.py` 는 **「밝으면 배경」**으로 본다. 그런데 **흰 접시의 굽이 250~253** 이라
#   배경과 같은 눈에 잡혀 함께 지워진다.
#   ⭐ 이 시트들은 접시 «위» 테두리가 진갈색이라 거긴 살고, **테두리가 없는 아래 굽만 죽었다.**
#
# ⛔ `tools/cut.py` 는 절대 안 건드린다(창업자 절대원칙 2026-08-18). 자르기 «전»에 원본을 살짝 눌러 둔다.
#
# ⛔⛔ 앞서 실패한 두 길 — 다시 밟지 말 것
#   ⑴ `tools/칸-접시테두리-그리기.py` 로 길잡이 선 → 바닥은 살았는데 **흰 테가 레이스처럼 물결쳤다**
#   ⑵ 그림 «전체»를 249 로 누르기 → 바닥은 살았는데 **딸기라떼 유리잔에 구멍**이 뚫렸다
#      (잔 «안» 우유의 순백(255)이 잔 테두리를 타고 바깥 배경과 이어져 배경으로 잡혔다)
#
# ⭐⭐ 그래서 «바닥 띠»에서만 누른다 — 창업자 말 그대로 **「접시 바닥면만」**.
#   · 칸마다 그림의 아래끝을 찾아 **아래 22% 띠**에서만 손댄다
#   · 잔 «안»의 흰 덩어리는 대개 그 띠보다 위에 있어 안 건드려진다
#   · 누르는 값도 250→249 **한 칸**이라 눈으로는 차이가 안 보인다(자르는 칼만 달라진다)
#
# ⛔ 시트 «통째로» 쓰지 않는다 — 칸마다 그림 높이가 달라 띠가 어긋난다. 행×열을 «반드시» 준다.
#
# 씀:  python3 tools/시트-접시굽-눌러주기.py <시트> <낼파일> <행> <열> [띠비율=0.22]
import os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

시트, 낼파일 = sys.argv[1], sys.argv[2]
행, 열 = int(sys.argv[3]), int(sys.argv[4])
띠 = float(sys.argv[5]) if len(sys.argv) > 5 else 0.22
# ⭐⭐ 236 = `cut.py` 가 «조각을 셀 때» 쓰는 문턱(`WHITE - 10`).
#    `--drop` 이 조각을 하나라도 버리면 **실루엣을 그 문턱으로 다시 짠다** → 이보다 밝은 곳이 통째로 깎인다.
#    ⛔ 접시의 밝은 바깥테·굽이 237~249 라 딱 여기서 「한 입 베어 문」 자국이 났다.
눌러서 = 236

im = Image.open(시트).convert('RGB')
a = np.asarray(im).astype(np.int16).copy()
H, W = a.shape[:2]
mn = a.min(axis=2)

전체눌림 = 0
for r in range(행):
    for c in range(열):
        y0, y1 = r * H // 행, (r + 1) * H // 행
        x0, x1 = c * W // 열, (c + 1) * W // 열
        칸 = mn[y0:y1, x0:x1]
        h, w = 칸.shape

        # ── ① 「확실한 잉크」로 몸통을 찾는다(<235). ⛔밝기만 보면 시트에 깔린 옅은 얼룩까지 그림이 된다
        잉크 = 칸 < 235
        lab, n잉크 = ndimage.label(잉크)
        if not n잉크:
            continue
        큰 = int(np.argmax(ndimage.sum(잉크, lab, range(1, n잉크 + 1)))) + 1
        씨앗 = lab == 큰

        # ── ② 그 잉크에 «이어진» 밝은 부분까지가 진짜 몸통이다 — 여기 접시 굽·바깥테가 들어 있다
        #    ⛔ 문턱 250 = `cut.py` 의 `WHITE(246)` 보다 넉넉히 위. 배경(253~255)은 안 들어온다
        몸통후보 = 칸 < 250
        lab2, _ = ndimage.label(몸통후보)
        몸통 = np.isin(lab2, np.unique(lab2[씨앗 & (lab2 > 0)]))

        줄 = np.where(몸통.any(axis=1))[0]
        위, 아래 = int(줄[0]), int(줄[-1])
        문턱 = 아래 - int(round((아래 - 위) * 띠))

        # ── ③ 바닥 띠에서만, 몸통인데 «칼이 조각 셀 때 쓰는 문턱(236)»을 넘는 픽셀을 235 로
        누를곳 = np.zeros_like(몸통)
        누를곳[문턱:아래 + 1] = 몸통[문턱:아래 + 1] & (칸[문턱:아래 + 1] >= 눌러서)
        n = int(누를곳.sum())
        if not n:
            continue
        sub = a[y0:y1, x0:x1]
        sub[누를곳] = np.minimum(sub[누를곳], 눌러서 - 1)
        전체눌림 += n
        print(f'  {r * 열 + c + 1:02d}칸 — 몸통 y{위}~{아래} · 띠 y{문턱}~{아래} · 누른 픽셀 {n}')

os.makedirs(os.path.dirname(os.path.abspath(낼파일)), exist_ok=True)
Image.fromarray(a.astype(np.uint8)).save(낼파일)
print(f'✅ {os.path.basename(시트)} — 모두 {전체눌림}픽셀 눌러 {낼파일} 로 냈다')
