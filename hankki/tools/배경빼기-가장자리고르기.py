#!/usr/bin/env python3
"""🖼 배경빼기 — «어느 가장자리에서 시작할지»를 고를 수 있는 판.

⛔⛔ 2026-08-20 사고: 5인 라인업에서 **꼬르곰 셰프모자 속이 통째로 뚫렸다.**
   📮 창업자 = *"꼬르곰 모자 잘렸엉"* — 「잘림」으로 보였지만 실은 **구멍**이었다.
   ⭐ 뿌리 = **모자가 프레임 위(y=0)에 닿아 있었다.**
      `배경빼기-한장.py` 는 「네 가장자리에서 연결된 흰색」을 배경으로 보는데,
      모자가 위에 닿으니 **모자 속 흰색이 바깥과 «이어진» 걸로 판정**돼 같이 빠졌다.
   📌 도구 주석에 *"셰프모자에 구멍이 뚫린다"* 라고 **이미 적혀 있었다.**
      적어둔 함정을 또 밟은 이유 = **그 함정이 「문턱을 잘못 잡을 때」만 난다고 생각했다.**
      진짜 조건은 **「그림이 가장자리에 닿을 때」**다. 문턱과 무관하다.

⭐ 그래서 이 도구는 **시작 가장자리를 고른다.**
   그림이 «위»에 닿아 있으면 위를 빼고 좌·우·아래에서만 flood 한다.
   → 위쪽 배경도 좌우를 타고 이어져 «그대로 빠지고», 모자 속만 살아남는다.
   (모자 외곽선이 담이 되어 flood 가 못 들어간다)

⛔ 이건 `tools/cut.py`(스티커 자르기 표준)와 «다른 일»이다 — cut.py 는 낱개로 쪼갠다.

쓰기:
  python3 tools/배경빼기-가장자리고르기.py <들어올그림> <내보낼PNG> \
      [--문턱 236] [--채도 22] [--가장자리 좌우아래]

  --가장자리 = 「위·아래·좌·우」 중 쓸 것만 이어 적는다 (기본 = 위아래좌우)
"""
import sys
import numpy as np
from PIL import Image
from scipy import ndimage

args = [a for a in sys.argv[1:] if not a.startswith('--')]
if len(args) < 2:
    print(__doc__)
    sys.exit(1)
src, dst = args[0], args[1]


def 옵션(이름, 기본):
    return sys.argv[sys.argv.index(이름) + 1] if 이름 in sys.argv else 기본


문턱 = int(옵션('--문턱', 236))
채도한도 = int(옵션('--채도', 22))
가장자리 = 옵션('--가장자리', '위아래좌우')

im = Image.open(src).convert('RGB')
a = np.asarray(im).astype(np.int16)
h, w = a.shape[:2]

밝기 = a.max(axis=2)
채도 = a.max(axis=2) - a.min(axis=2)
후보 = (밝기 >= 문턱) & (채도 <= 채도한도)

라벨, _ = ndimage.label(후보)
쓸라벨 = set()
if '위' in 가장자리:
    쓸라벨 |= set(라벨[0, :])
if '아래' in 가장자리:
    쓸라벨 |= set(라벨[-1, :])
if '좌' in 가장자리:
    쓸라벨 |= set(라벨[:, 0])
if '우' in 가장자리:
    쓸라벨 |= set(라벨[:, -1])
쓸라벨.discard(0)
배경 = np.isin(라벨, list(쓸라벨))

# 🧹 «갇힌 배경 잔재» 털기 — 캐릭터 사이에 둘러싸여 flood 가 못 들어간 흰 조각
#    ⛔ 2026-08-20 실측: 5인 마스터본에서 꼬르곰 다리 사이에 흰 조각이 남아
#       크림 배경 카드에 얹으니 «흰 얼룩»으로 떴다.
#    ⭐ 가르는 잣대 = **크기 «구간»**. 하한이 없으면 안 된다 —
#    ⛔⛔ 첫 판은 「상한 3000」만 뒀다가 **2564덩어리·18290px 를 털어 그림을 갉아먹었다.**
#       빨간 바탕에 얹으니 모자·앞치마·수건·뾰미 얼굴이 구멍 숭숭이었다.
#       📌 내 가정 「잔재는 작고 그림은 크다」가 틀렸다 —
#          **그림 «안»에도 작은 흰 하이라이트가 수천 개**다. 그게 다 걸렸다.
#    🔢 실측(5인 마스터본) = 얼룩 2261·1442·931px ↔ 하이라이트 수십~수백px ↔ 진짜 그림 4459px↑
#       → 「900~3000」 구간이 얼룩 셋만 집는다.
#    ⚠️ 「순백이면 배경」으로만 가르면 안 된다 — 모자 하이라이트도 순백이라 같이 먹는다.
#    ⛔⛔ 그리고 **크기 구간으로도 못 가른다** — 실측: 뾰미 «꼬리 흰 끝» 2237px ↔ 다리 사이 얼룩 1969px.
#       거의 같다. 📌 크기는 「그림이냐 배경이냐」를 모른다.
#    ✅ 그래서 **자리로 콕 집는다** — `--지울상자 x0,y0,x1,y1` (여러 개면 세미콜론으로)
#       그 상자 «안»의 순백 덩어리만 뺀다. 일회성이라 도구에 좌표를 박지 않고 명령줄로 준다.
상자들 = 옵션('--지울상자', '')
if 상자들:
    순백 = (~배경) & (a.min(axis=2) >= 250) & ((a.max(axis=2) - a.min(axis=2)) <= 4)
    지움 = np.zeros_like(순백)
    for 한상자 in 상자들.split(';'):
        x0, y0, x1, y1 = (int(v) for v in 한상자.split(','))
        틀 = np.zeros_like(순백)
        틀[y0:y1, x0:x1] = True
        지움 |= (순백 & 틀)
    if 지움.any():
        배경 = 배경 | 지움
        print(f'   🧹 상자 안 잔재 {int(지움.sum())}px 지웠다')
    else:
        print(f'   ⚠️ 상자 안에 지울 순백이 없다 — 좌표를 다시 볼 것')

# 알파를 «계산» — 배경 가장자리 2px 띠에서 부드럽게 (자르기 표준과 같은 생각)
알파 = np.where(배경, 0, 255).astype(np.uint8)
띠 = ndimage.binary_dilation(배경, iterations=2) & ~배경
if 띠.any():
    보이는 = 밝기[띠].astype(np.float32)
    비율 = np.clip((255.0 - 보이는) / max(1.0, 255.0 - 문턱), 0.0, 1.0)
    알파[띠] = (비율 * 255).astype(np.uint8)

out = np.dstack([np.asarray(im).astype(np.uint8), 알파])
Image.fromarray(out, 'RGBA').save(dst)

뺀비율 = 배경.sum() / (h * w) * 100
print(f'✅ {dst}')
print(f'   크기 {w}×{h} · 뺀 배경 {뺀비율:.1f}% · 시작 가장자리 「{가장자리}」 · 문턱 {문턱}/채도 {채도한도}')

# 🔎 스스로 검사 — 「가장자리에 닿은 그림」이 있으면 그쪽에서 flood 하면 안 된다고 알린다
그림 = ~배경
닿음 = {'위': int(그림[0].sum()), '아래': int(그림[-1].sum()), '좌': int(그림[:, 0].sum()), '우': int(그림[:, -1].sum())}
경고 = [k for k, v in 닿음.items() if v > 0 and k in 가장자리]
print(f'   가장자리에 닿은 그림 — ' + ' · '.join(f'{k} {v}px' for k, v in 닿음.items()))
if 경고:
    print(f'   ⚠️⚠️ 「{"·".join(경고)}」 쪽에 그림이 닿아 있는데 그 가장자리에서 flood 했다 —')
    print(f'         그 그림의 «흰 속»이 뚫렸을 수 있다. --가장자리 에서 빼고 다시 돌릴 것.')
if 뺀비율 > 85:
    print('   ⚠️ 너무 많이 뺐다 — 그림까지 먹었을 수 있다. 열어서 확인할 것.')
if 뺀비율 < 5:
    print('   ⚠️ 거의 안 뺐다 — 배경이 흰색이 아닐 수 있다. --문턱 을 낮춰 볼 것.')
