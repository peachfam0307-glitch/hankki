#!/usr/bin/env python3
"""🫧 홈 장식용 — 그림 «안»의 흰 면을 비운다(글자가 비쳐 보이게).

📮 창업자 2026-09-09 = *"이게 투명이야해. 배경이 하야니까 글자가 다 가려져서 이상해"*

════════ 무엇이 문제였나 ════════
흰 «테»를 벗겼는데도 거미줄이 글자를 덮었다. **테가 아니라 「안쪽」이 문제였다.**
🔢 실측(거미줄05) — 불투명한 면 128,873px 중 **거의 흰색이 37,776px = 29%**.
   거미줄이 「선」이 아니라 **크림색으로 꽉 찬 삼각형**으로 그려져 있다.
   ⛔ 홈 위에 얹으면 그 면이 글자를 통째로 가린다.

════════ 어떻게 비우나 ════════
⛔ 「흰 픽셀 지우기」로 딱 자르면 **테두리가 톱니**가 되고 옅은 음영이 뚝 끊긴다.
✅ **밝기를 그대로 투명도로 바꾼다** — 밝을수록 투명, 어두울수록 불투명.
   🔢 밝기 분포(거미줄05) = 180 아래 61,445 · 250 이상 27,605 → **두 무리가 뚜렷이 갈린다.**
   그래서 `200 이하 = 그대로 · 250 이상 = 완전히 투명 · 사이는 부드럽게`.
   ⭐ 이러면 거미줄 «실»과 이슬의 음영은 살고, 채워진 면만 사라진다. 계단도 안 진다.

⛔⛔ **아무 컷에나 쓰면 안 된다.** 구름·송편·달·곰펭은 «밝은 것이 곧 그림»이라 통째로 사라진다.
   그래서 파일을 «하나씩 지정»해서만 돌린다. 폴더 통째로 돌리는 길은 두지 않았다.

쓰기:
    python3 tools/홈장식-속비우기.py <컷.png> [<컷.png> …]   # 제자리에서 고친다
"""
import sys

import numpy as np
from PIL import Image

밝음 = 250   # 이보다 밝으면 완전히 투명
어두움 = 200  # 이보다 어두우면 그대로 둔다


def 비우기(path):
    im = Image.open(path).convert('RGBA')
    a = np.array(im).astype(float)
    mn = a[:, :, :3].min(axis=2)
    # 밝기 → 투명도. 200↓ = 1 · 250↑ = 0 · 사이는 직선으로 이어져 계단이 안 진다
    남길비율 = np.clip((밝음 - mn) / (밝음 - 어두움), 0.0, 1.0)
    전 = int((a[:, :, 3] > 200).sum())
    a[:, :, 3] = a[:, :, 3] * 남길비율
    후 = int((a[:, :, 3] > 200).sum())
    Image.fromarray(a.astype(np.uint8)).save(path)
    return f'불투명 {전} → {후} ({100 * 후 / max(1, 전):.0f}%)'


if __name__ == '__main__':
    for p in sys.argv[1:]:
        print(f'   {p.split("/")[-1]:18s} {비우기(p)}')
