#    ✅ 그래서 이 판은 **첫 1초를 «캐릭터»로** 바꾼다 — 뾰미 문방구 시안 크롭.
#       ⛔ 그 밖은 «한 가지만 바꾼다» 원칙대로 그대로 둔다(25초 안팎 · 끝을 처음과 잇기).
